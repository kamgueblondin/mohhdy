# ------------------------------------------------------------- sheet
SHEET_TYPES = ["<length>", "<length-percentage>", "<number>", "<integer>", "<angle>", "<time>", "<resolution>",
               "<transform-function>", "<transform-list>", "<url>", "<string>", "<image>", "<color>"]
INITIAL = {"<length>": "1px", "<length-percentage>": "1%", "<number>": "1", "<integer>": "1",
           "<angle>": "1deg", "<time>": "1s", "<resolution>": "1dppx", "<transform-function>": "scale(1)",
           "<transform-list>": "scale(1)", "<url>": "url(a.png)", "<string>": "'s'",
           "<image>": "linear-gradient(red, blue)", "<color>": "red", "<percentage>": "1%"}


def sheet_ok(v):
    """a value the sheet keeps as written: no ; } { or runs of spaces, no em
    family (not independent in an initial value)"""
    if any(c in v for c in ";{}\t\n\\") or "  " in v or v != v.strip():
        return False
    if any(c in v for c in "<>&"):
        return False
    return True


def write_sheet():
    rng = random.Random(SEED_SHEET)
    cases = []
    while len(cases) < 160:
        t = rng.choice(SHEET_TYPES)
        m = "" if t in ("<transform-list>", "<color>") else rng.choice(["", "", "+", "#"])
        syn = t + m
        alts = M.parse_syntax("'" + syn + "'")[1]
        inherits = rng.random() < 0.5
        vw, vh = rng.choice(VIEWPORTS)
        init = INITIAL[t]
        if rng.random() < 0.4:
            cand = list_value(rng, t, m, True) if m else value_for(rng, t, True)
            if (M.first_alt(alts, cand) and sheet_ok(cand) and not any(u in cand for u in ("em", "ex", "ch"))
                    and len(cand) < 90):
                init = cand
        init_b = M.compute(alts, init, (vw, vh)) or init
        vals = []
        for _ in range(2):
            good = rng.random() < 0.75
            v = list_value(rng, t, m, good) if m else value_for(rng, t, good)
            vals.append(v)
        if not all(sheet_ok(v) and v and len(v) < 100 for v in vals):
            continue
        child_own = rng.random() < 0.6
        simplified = [0]

        def bind(v, inherited):
            if M.first_alt(alts, v) is None:
                return inherited
            c = M.compute(alts, v, (vw, vh))
            if c is not None:
                simplified[0] += 1
                return c
            return v

        o_b = bind(vals[0], init_b)
        i_inh = o_b if inherits else init_b
        i_b = bind(vals[1], i_inh) if child_own else i_inh
        css = "@property --p { syntax: '%s'; inherits: %s; initial-value: %s } #o { --p: %s }" % (
            syn, "true" if inherits else "false", init, vals[0])
        if child_own:
            css += " #i { --p: %s }" % vals[1]
        if len(css) > 600:
            continue
        cases.append((css, vw, vh, o_b, i_b, init_b, simplified[0]))
    o = [HEADER % "Lot 95: registered values computed in the reader sheet with the page viewport",
         '#include "../../framework/unity.h"', "#include <string.h>", "#include <stdio.h>",
         '#include "wf_sitecss.h"', "",
         "static wf_site_t g_d;", "static char g_html[4096], g_t[256];", "",
         "static void prep(const char *css, int vw, int vh) {",
         "    snprintf(g_html, sizeof(g_html), \"<html><head><style>%s</style></head><body>\"",
         "             \"<div id=o><p id=i>i</p></div><p id=q>q</p></body></html>\", css);",
         "    TEST_ASSERT_EQUAL(0, wf_site_prepare_ext(&g_d, g_html, (int)strlen(g_html), vw, vh, 0, 0));",
         "    TEST_ASSERT_EQUAL(1, g_d.nprops);",
         "}", "",
         "static const char *nv(const char *id) {",
         "    int i;",
         "    for (i = 0; i < g_d.nnodes; i++)",
         "        if (!strcmp(g_d.node[i].id, id)) { const char *v = wf_site_node_var(&g_d, i, \"--p\"); "
         "return v ? v : \"(none)\"; }",
         "    return \"(no node)\";",
         "}", "",
         "static const char *tail(void) {",
         "    const char *s;",
         "    wf_site_props_text(&g_d, g_t, (int)sizeof(g_t));",
         "    s = strstr(g_t, \" simplified \");",
         "    return s ? s : \"\";",
         "}", ""]
    lines = []
    for css, vw, vh, ob, ib, qb, simp in cases:
        lines.append(["prep(%s, %d, %d);" % (cstr(css), vw, vh),
                      "TEST_ASSERT_EQUAL_STRING(%s, nv(\"o\"));" % cstr(ob),
                      "TEST_ASSERT_EQUAL_STRING(%s, nv(\"i\"));" % cstr(ib),
                      "TEST_ASSERT_EQUAL_STRING(%s, nv(\"q\"));" % cstr(qb),
                      "TEST_ASSERT_EQUAL_STRING(%s, tail());" % cstr(" simplified %d" % simp if simp else "")])
    names = chunks(o, "test_l95_sheet", lines, 1)
    finish(o, names, "test_lot95_sheet.c")
    return len(cases)


