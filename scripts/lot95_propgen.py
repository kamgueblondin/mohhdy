#!/usr/bin/env python3
"""Lot 95 test generator: @property limits (gap 2 of docs/lot94_plan.md)
and computed values (the rest of gap 3).

Writes four suites in tests/unit/userspace:
* test_lot95_syntax.c: syntax strings with up to ten alternatives, the six
  Lot 95 types (<url>, <image>, <resolution>, <transform-function>,
  <transform-list>, <string>) and the known faults; the code, the number
  of alternatives and each alternative (type, multiplier, keyword).
* test_lot95_match.c: values against a parsed syntax (match_prop) and
  against one type code (wf_cssprop_match) for the new types, lists and
  transform functions.
* test_lot95_compute.c: wf_cssprop_compute_ctx with and without a
  viewport: plain dimensions in every unit, calc() of lengths and
  percentages (known mixes), <integer> rounding, resolutions, lists and
  transform functions.
* test_lot95_sheet.c: the reader sheet (wf_site_prepare_ext): registered
  values computed where they are declared, inherited or not, with the
  page viewport, and the " simplified N" count.

Expectations come from scripts/lot95_propmodel.py, which shares no code
with userspace/wf_cssprop.c. Fixed seeds 9501 to 9504.

Run: python3 scripts/lot95_propgen.py
"""
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lot95_propmodel as M  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "tests", "unit", "userspace")
HEADER = "/* %s (generated by scripts/lot95_propgen.py; expectations from lot95_propmodel.py). */"
SEED_SYNTAX, SEED_MATCH, SEED_COMPUTE, SEED_SHEET = 9501, 9502, 9503, 9504
MULT = {"": 0, "+": 1, "#": 2}
NEW_TYPES = ["<url>", "<image>", "<resolution>", "<transform-function>", "<transform-list>", "<string>"]
OLD_TYPES = ["<length>", "<percentage>", "<length-percentage>", "<number>", "<integer>", "<color>", "<angle>",
             "<time>", "<custom-ident>"]
KEYWORDS = ["auto", "none", "small", "big", "x", "left-side", "_under", "-moz-thing", "a1", "stretch", "thin"]
VIEWPORTS = [(800, 600), (1280, 720), (375, 812), (1000, 1000), (640, 480)]


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\t", "\\t").replace("\n", "\\n") \
        .replace("\r", "\\r") + '"'


def rcase(rng, s):
    m = rng.randrange(3)
    if m == 0:
        return s
    if m == 1:
        return s.upper()
    return "".join(c.upper() if rng.random() < 0.3 else c for c in s)


def finish(o, names, fname):
    o += ["int main(void) {", "    unity_init();"]
    o += ["    RUN_TEST(%s);" % n for n in names]
    o += ["    unity_print_results();", "    unity_cleanup();", "    return unity_stats.tests_failed == 0 ? 0 : 1;",
          "}", ""]
    with open(os.path.join(OUT, fname), "w") as f:
        f.write("\n".join(o))


def chunks(o, prefix, lines_per_case, per):
    """group the cases' lines into test functions of `per` cases"""
    names = []
    for b in range(0, len(lines_per_case), per):
        name = "%s_%d" % (prefix, b // per)
        names.append(name)
        o.append("static void %s(void) {" % name)
        for lines in lines_per_case[b:b + per]:
            o += ["    " + x for x in lines]
        o += ["}", ""]
    return names


# ------------------------------------------------------------- syntax
def syntax_case(rng):
    """the text of a syntax string (the model says what it is)"""
    if rng.random() < 0.04:
        q = rng.choice(["'", '"'])
        return q + rng.choice(["*", " * "]) + q
    n = rng.choice([1, 1, 2, 3, 4, 5, 6, 7, 8, 8, 9, 10])
    texts = []
    for _ in range(n):
        r = rng.random()
        if r < 0.4:
            t = rng.choice(NEW_TYPES)
        elif r < 0.75:
            t = rng.choice(OLD_TYPES)
        else:
            t = rng.choice(KEYWORDS)
        m = rng.choice(["", "", "+", "#"])
        if t == "<transform-list>" and m and rng.random() < 0.6:
            m = ""
        texts.append(rcase(rng, t) + m)
    fault = rng.random()
    k = rng.randrange(n)
    if fault < 0.04:
        texts[k] = rcase(rng, rng.choice(sorted(M.RESERVED)))
    elif fault < 0.08:
        texts[k] = rng.choice(["<frequency>", "<flex>", "<transform>", "<urls>", "<image-set>", "<str>",
                               "<resolution >", "< url>", "<length-percentage>>", "1abc", "a.b", "a#b"])
    elif fault < 0.10:
        texts[k] = "abcdefghijklmnop"                       # 16 bytes: one too many
    elif fault < 0.12:
        texts[k] = "abcdefghijklmno"                        # 15 bytes: fits
    elif fault < 0.15:
        texts[k] = "<transform-list>" + rng.choice(["+", "#"])
    elif fault < 0.17:
        texts[k] = texts[k] + rng.choice(["+#", "#+", "++"])
    elif fault < 0.19:
        texts.append("")
    seps = [rng.choice(["|", " | ", "  |", "| ", "\t|\t"]) for _ in range(len(texts) - 1)]
    body = texts[0]
    for j in range(1, len(texts)):
        body += seps[j - 1] + texts[j]
    q = rng.choice(["'", '"'])
    return q + rng.choice(["", " "]) + body + rng.choice(["", " "]) + q


def write_syntax():
    rng = random.Random(SEED_SYNTAX)
    cases, seen = [], set()
    while len(cases) < 520:
        text = syntax_case(rng)
        if text in seen:
            continue
        seen.add(text)
        code, alts = M.parse_syntax(text)
        code = {"BAD": "WF_CSSPROP_BAD", "ANY": "WF_CSSPROP_ANY"}.get(code, code)
        lines = ["TEST_ASSERT_EQUAL(%s, wf_cssprop_syntax(%s, %d));" % (code, cstr(text), len(text)),
                 "TEST_ASSERT_EQUAL(%s, wf_cssprop_syntax_parse(%s, %d, &g_p));" % (code, cstr(text), len(text))]
        if alts is None:
            lines.append("TEST_ASSERT_EQUAL(0, g_p.nalt);")
        else:
            lines.append("TEST_ASSERT_EQUAL(%d, g_p.nalt);" % len(alts))
            for j, (t, m, ident) in enumerate(alts):
                lines.append("alt_is(%d, %s, %d, %s);" % (j, M.CODE[t], MULT[m], cstr(ident)))
        cases.append(lines)
    o = [HEADER % "Lot 95: @property syntax strings with up to eight alternatives and the Lot 95 types",
         '#include "../../framework/unity.h"', "#include <string.h>", '#include "wf_cssprop.h"', "",
         "static wf_cssprop_t g_p;", "",
         "static void alt_is(int k, int type, int mult, const char *ident) {",
         "    TEST_ASSERT_EQUAL(type, g_p.alt[k].type);",
         "    TEST_ASSERT_EQUAL(mult, g_p.alt[k].mult);",
         "    TEST_ASSERT_EQUAL_STRING(ident, g_p.alt[k].ident);",
         "}", ""]
    names = chunks(o, "test_l95_syntax", cases, 5)
    finish(o, names, "test_lot95_syntax.c")
    return len(cases)


# ------------------------------------------------------------- values
UNITS_OF = {"L": ["px", "in", "cm", "mm", "q", "pt", "pc", "em", "rem", "vw", "vh", "vmin", "vmax"],
            "P": ["%"], "A": ["deg", "grad", "rad", "turn"], "T": ["s", "ms"],
            "R": ["dppx", "x", "dpi", "dpcm"], "N": [""]}


def num(rng, small=False, integer=False, nonzero=False):
    """a number text: sign, up to 4 decimals (5 now and then)"""
    while True:
        w = rng.choice([0, 0, 1, 2, 3, 5, 10, 12, 45, 90, 96, 100, 180, 254, 360, 500, 1000, 1500])
        if not small and rng.random() < 0.06:
            w = rng.choice([20000, 99999, 100000, 150000, 2000000])
        if rng.random() < 0.3:
            w = rng.randrange(0, 400)
        t = str(w)
        if not integer and rng.random() < 0.4:
            d = rng.choice([1, 1, 2, 3, 4, 4, 5])
            t += "." + "".join(rng.choice("0123456789") for _ in range(d))
            if rng.random() < 0.1:
                t = t[t.index("."):] if w == 0 else t
        s = rng.choice(["", "", "", "-", "+"])
        if nonzero and M.raw_units(t)[0] == 0:
            continue
        return s + t


def dim(rng, kind, small=False):
    u = rng.choice(UNITS_OF[kind])
    return num(rng, small=small, integer=False) + u


def calc_text(rng, kinds, depth=0):
    """calc() of the given leaf kinds (+ and -), with * and / by numbers"""
    terms = []
    for k in kinds:
        t = dim(rng, k, small=True)
        r = rng.random()
        if r < 0.15:
            t = "%s * %s" % (t, num(rng, small=True))
        elif r < 0.25:
            t = "%s / %s" % (t, num(rng, small=True, nonzero=rng.random() < 0.9))
        elif r < 0.3:
            t = "%s * %s" % (num(rng, small=True), t)
        elif r < 0.36 and depth == 0:
            t = "(%s)" % calc_text(rng, [k, rng.choice([k, "L" if k in "LP" else k])], 1)[5:-1]
            if rng.random() < 0.5:
                t = "%s * %s" % (t, num(rng, small=True))
        terms.append(t)
    out = terms[0]
    for t in terms[1:]:
        out += rng.choice([" + ", " - "]) + t
    return "calc(" + out + ")"


def numeric(rng, kind):
    """a value of a numeric kind: a plain leaf or calc()"""
    if rng.random() < 0.55:
        if kind == "N0":
            return rng.choice(["0", "0.0", "+0", "-0", ".0"])
        return dim(rng, rng.choice("LP") if kind == "LP" else kind)
    if kind == "N0":
        return "calc(0)"
    if kind == "LP":
        ks = [rng.choice("LP") for _ in range(rng.choice([2, 2, 3]))]
        if "L" not in ks:
            ks[0] = "L"
        if "P" not in ks:
            ks[-1] = "P"
        return calc_text(rng, ks)
    return calc_text(rng, [kind] * rng.choice([1, 1, 2, 3]))


def url(rng, good=True):
    if good:
        k = rng.randrange(6)
        if k == 0:
            return "url(a.png)"
        if k == 1:
            return "url(%s)" % rng.choice(["https://x.example/i.png", "/img/b.gif", "c%20d.png", "e\\(f.png"])
        if k == 2:
            return "url('%s')" % rng.choice(["a b.png", "x(y).png", "q\\'r.png", ""])
        if k == 3:
            return 'url("%s")' % rng.choice(["a.png", "a'b.png", ""])
        if k == 4:
            return "url( %s )" % rng.choice(["a.png", "'a.png'"])
        return "url()"
    return rng.choice(["url(a b.png)", "url(a\"b)", "url(a", "uri(a.png)", "url(a(b).png)", "url('a.png)",
                       "url(\"a.png\" x)", "url", "url(a.png) x", "url('a'b')", "url(a.png)x", "src(a.png)"])


def string(rng, good=True):
    if good:
        return rng.choice(["'abc'", '"abc"', "''", '""', "'a b c'", "'a\"b'", '"a\'b"', "'a\\'b'", '"x\\"y"',
                           "'semi: colon'", "'\\\\'", "'(paren'"])
    return rng.choice(["'abc", "abc'", "'a'b'", '"a\\"', "'a' 'b'", "abc", "'x\"", "'a\\'", "\"a'"])


GRAD_BODIES = ["red, blue", "to right, red 10%, blue", "45deg, red, blue 3em", "circle, red, blue",
               "from 90deg, red, blue", "rgb(1, 2, 3), white", "red", "at 10px 20px, red, blue",
               "closest-side, red, (blue)"]


def image(rng, good=True):
    if good:
        if rng.random() < 0.25:
            return url(rng)
        g = rng.choice(M.GRADS)
        return g + rng.choice(GRAD_BODIES) + ")"
    k = rng.randrange(7)
    if k == 0:
        return rng.choice(M.GRADS) + ")"
    if k == 1:
        return rng.choice(M.GRADS) + " )"
    if k == 2:
        return rng.choice(M.GRADS) + "red, blue"
    if k == 3:
        return rng.choice(M.GRADS) + "red, blue) x"
    if k == 4:
        return rng.choice(["element(#a)", "image(a.png)", "image-set(a.png 1x)", "cross-fade(a, b)",
                           "linear-gradients(red, blue)", "gradient(red)", "-webkit-linear-gradient(red, blue)"])
    if k == 5:
        return url(rng, False)
    return rng.choice(M.GRADS) + "red, (blue)"


def targ(rng, kind, good=True):
    if good:
        if kind == "P":
            r = rng.random()
            if r < 0.4:
                return dim(rng, "L", small=True)
            if r < 0.65:
                return dim(rng, "P", small=True)
            if r < 0.75:
                return "0"
            return numeric(rng, rng.choice(["L", "P", "LP"]))
        if kind == "L":
            return "0" if rng.random() < 0.15 else numeric(rng, "L")
        if kind == "N":
            return num(rng, small=True) if rng.random() < 0.8 else calc_text(rng, ["N"])
        if kind == "S":
            r = rng.random()
            return num(rng, small=True) if r < 0.6 else dim(rng, "P", small=True) if r < 0.85 else \
                calc_text(rng, [rng.choice("NP")])
        r = rng.random()
        return rng.choice(["0", "-0", "0.0"]) if r < 0.15 else numeric(rng, "A")
    return {"P": rng.choice(["1deg", "red", "1s", "2", "auto", "calc(1px * 1px)"]),
            "L": rng.choice(["10%", "1deg", "3", "calc(1px + 2%)"]),
            "N": rng.choice(["1px", "10%", "1deg", "calc(1px)"]),
            "S": rng.choice(["1px", "1deg", "auto"]),
            "A": rng.choice(["1px", "10%", "1", "1s", "calc(0)"])}[kind]


def tfunc(rng, good=True):
    name = rng.choice(sorted(M.TFNS))
    lo, hi, kinds = M.TFNS[name]
    n = rng.randint(lo, hi)
    bad_kind = -1
    if not good:
        r = rng.random()
        if r < 0.3:
            n = rng.choice([x for x in (0, lo - 1, hi + 1, 7) if x >= 0 and not (lo <= x <= hi)])
        elif r < 0.75:
            bad_kind = rng.randrange(n)
        elif r < 0.85:
            return rng.choice(["translate(1px 2px)", "rotate(90deg", "rotate 90deg", "turn(90deg)",
                               "translate(1px,)", "translate(,1px)", "matrix3d(1, 0)", "scale()"])
        else:
            name = rng.choice(["transl", "rotate4d", "skewz", "translatew", "scalew", "matrix2"])
    args = []
    for k in range(n):
        kind = kinds[min(k, len(kinds) - 1)] if kinds else "N"
        args.append(targ(rng, kind, k != bad_kind))
    sep = rng.choice([", ", ",", " , ", ",  "])
    inner = sep.join(args)
    if rng.random() < 0.15:
        inner = " " + inner + " "
    return "%s(%s)" % (name, inner)


def tlist(rng, good=True):
    n = rng.choice([1, 1, 2, 2, 3, 4])
    fs = [tfunc(rng) for _ in range(n)]
    if not good:
        r = rng.random()
        if r < 0.4:
            fs[rng.randrange(n)] = tfunc(rng, False)
        elif r < 0.6:
            return ", ".join(fs) if n > 1 else "none"
        elif r < 0.8:
            fs[rng.randrange(n)] = rng.choice(["red", "1px", "url(a.png)", "calc(1px)", "var(--x)"])
        else:
            return ""
    sep = rng.choice([" ", " ", "  ", "\t", ""]) if n > 1 else " "
    return sep.join(fs)


def value_for(rng, t, good=True):
    """one item for a type (good: meant to match; the model decides)"""
    if t == "<url>":
        return url(rng, good)
    if t == "<string>":
        return string(rng, good)
    if t == "<image>":
        return image(rng, good)
    if t == "<transform-function>":
        return tfunc(rng, good)
    if t == "<transform-list>":
        return tlist(rng, good)
    if t == "<resolution>":
        if good:
            return numeric(rng, "R")
        return rng.choice(["1dp", "1dpx", "1px", "2", "calc(1dppx + 1px)", "1xx", "x"])
    if t == "<color>":
        return rng.choice(["red", "#abc", "#a1b2c3", "teal"]) if good else rng.choice(["#ab", "reddish", "1px"])
    if t == "<custom-ident>":
        return rng.choice(["foo", "a-b", "_x"]) if good else rng.choice(["inherit", "1a", "'q'"])
    if t == "kw":
        return rng.choice(KEYWORDS)
    kind = {"<length>": "L", "<percentage>": "P", "<length-percentage>": "LP", "<number>": "N",
            "<integer>": "N", "<angle>": "A", "<time>": "T"}[t]
    if not good:
        kind = rng.choice([k for k in ("L", "P", "A", "T", "R", "N") if k != kind])
    if t == "<integer>" and good and rng.random() < 0.6:
        return rng.choice(["", "-", "+"]) + str(rng.randrange(0, 2000))
    return numeric(rng, kind)


def list_value(rng, t, mult, good=True):
    n = rng.choice([1, 2, 2, 3, 4])
    its = [value_for(rng, t, good or rng.random() < 0.6) for _ in range(n)]
    if t in ("<transform-list>",):
        its = its[:1]
    if mult == "#":
        sep = rng.choice([", ", ",", " , "])
    else:
        sep = rng.choice([" ", "  ", "\t"])
    return sep.join(its)


def random_syntax(rng, want=None):
    """(text, alts) of a valid syntax with 1 to 8 alternatives"""
    while True:
        n = rng.choice([1, 1, 1, 2, 2, 3, 4, 6, 8])
        alts = []
        for j in range(n):
            if j == 0 and want:
                t = want
            else:
                r = rng.random()
                t = rng.choice(NEW_TYPES) if r < 0.45 else rng.choice(OLD_TYPES) if r < 0.8 else "kw"
            m = rng.choice(["", "", "", "+", "#"])
            if t == "<transform-list>":
                m = ""
            ident = rng.choice(KEYWORDS) if t == "kw" else ""
            alts.append((t, m, ident))
        text = "'" + " | ".join((a[2] if a[0] == "kw" else a[0]) + a[1] for a in alts) + "'"
        code, parsed = M.parse_syntax(text)
        if parsed:
            return text, parsed


def write_match():
    rng = random.Random(SEED_MATCH)
    cases, seen = [], set()
    while len(cases) < 1100:
        if rng.random() < 0.3:
            # one type code
            t = rng.choice(NEW_TYPES)
            v = value_for(rng, t, rng.random() < 0.55)
            if (t, v) in seen or len(v) > 120:
                continue
            seen.add((t, v))
            m = 1 if M.match_one(t, "", v) else 0
            cases.append(["TEST_ASSERT_EQUAL(%d, wf_cssprop_match(%s, %s));" % (m, M.CODE[t], cstr(v))])
            continue
        stext, alts = random_syntax(rng, rng.choice(NEW_TYPES + [None]))
        a = rng.choice(alts)
        good = rng.random() < 0.6
        v = list_value(rng, a[0], a[1], good) if a[1] else value_for(rng, a[0], good)
        if (stext, v) in seen or len(v) > 120 or not v.strip():
            continue
        seen.add((stext, v))
        m = 1 if M.first_alt(alts, v) is not None else 0
        cases.append(["TEST_ASSERT_EQUAL(%d, mp(%s, %s));" % (m, cstr(stext), cstr(v))])
    o = [HEADER % "Lot 95: values of the Lot 95 types, lists and transform functions against a syntax",
         '#include "../../framework/unity.h"', "#include <string.h>", '#include "wf_cssprop.h"', "",
         "static wf_cssprop_t g_p;", "",
         "static int mp(const char *syn, const char *v) {",
         "    memset(&g_p, 0, sizeof(g_p));",
         "    g_p.syntax = (unsigned char)wf_cssprop_syntax_parse(syn, (int)strlen(syn), &g_p);",
         "    if (g_p.syntax == WF_CSSPROP_BAD) return -1;",
         "    return wf_cssprop_match_prop(&g_p, v);",
         "}", ""]
    names = chunks(o, "test_l95_match", cases, 10)
    finish(o, names, "test_lot95_match.c")
    return len(cases)


# ------------------------------------------------------------- compute
COMPUTE_TYPES = ["<length>", "<length>", "<length-percentage>", "<length-percentage>", "<percentage>", "<number>",
                 "<integer>", "<integer>", "<angle>", "<time>", "<resolution>", "<resolution>",
                 "<transform-function>", "<transform-function>", "<transform-list>", "<transform-list>",
                 "<url>", "<string>", "<image>"]


def write_compute():
    rng = random.Random(SEED_COMPUTE)
    cases, seen = [], set()
    while len(cases) < 900:
        t = rng.choice(COMPUTE_TYPES)
        m = "" if t == "<transform-list>" else rng.choice(["", "", "", "+", "#"])
        alts = [(t, m, "")]
        if rng.random() < 0.25:
            o2 = rng.choice(OLD_TYPES + NEW_TYPES)
            if o2 != t:
                alts.insert(rng.randrange(2), (o2, "", ""))
        if rng.random() < 0.1:
            alts.insert(0, ("kw", "", rng.choice(KEYWORDS)))
        text = "'" + " | ".join((a[2] if a[0] == "kw" else a[0]) + a[1] for a in alts) + "'"
        code, parsed = M.parse_syntax(text)
        if not parsed:
            continue
        v = list_value(rng, t, m, True) if m else value_for(rng, t, rng.random() < 0.9)
        if rng.random() < 0.05:
            v = rng.choice(KEYWORDS)
        r = rng.random()
        vp = None if r < 0.3 else (0, 0) if r < 0.35 else rng.choice(VIEWPORTS)
        if len(v) > 110 or not v.strip() or (text, v, vp) in seen:
            continue
        e = M.compute(parsed, v, vp if vp != (0, 0) else None)
        if e is not None and len(e) > 100:
            continue          # far from the 127-byte edge (the hand tests take it)
        seen.add((text, v, vp))
        call = "cv(%s, %s, %s)" % (cstr(text), cstr(v), "0, 0, 0" if vp is None else "1, %d, %d" % vp)
        cases.append(["TEST_ASSERT_EQUAL_STRING(%s, %s);" % (cstr(e if e is not None else "KEEP"), call)])
    o = [HEADER % "Lot 95: computed values of registered values (wf_cssprop_compute_ctx)",
         '#include "../../framework/unity.h"', "#include <string.h>", '#include "wf_cssprop.h"', "",
         "static wf_cssprop_t g_p;", "static char g_o[128];", "",
         "static const char *cv(const char *syn, const char *v, int ctx, int vw, int vh) {",
         "    wf_cssprop_ctx_t c;",
         "    int r;",
         "    memset(&g_p, 0, sizeof(g_p));",
         "    g_p.syntax = (unsigned char)wf_cssprop_syntax_parse(syn, (int)strlen(syn), &g_p);",
         "    if (!g_p.syntax) return \"BAD SYNTAX\";",
         "    c.vw = vw; c.vh = vh;",
         "    r = wf_cssprop_compute_ctx(&g_p, v, ctx ? &c : 0, g_o, (int)sizeof(g_o));",
         "    if (!r) return g_o[0] ? \"KEEP BUT WRITTEN\" : \"KEEP\";",
         "    if (!strcmp(g_o, v)) return \"SAME BUT 1\";",
         "    return g_o;",
         "}", ""]
    names = chunks(o, "test_l95_compute", cases, 10)
    finish(o, names, "test_lot95_compute.c")
