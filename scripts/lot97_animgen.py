#!/usr/bin/env python3
"""Lot 97 test generator: easing, interpolation, the animation and
transition shorthands, animation timing and the reader sheet with
@keyframes, animation, transition and @starting-style on registered
custom properties.

Expectations come from scripts/lot97_animmodel.py (written from the rules
in docs/lot97_plan.md), not from the C sources:

* test_lot97_ease.c: wf_cssease_parse and wf_cssease_at;
* test_lot97_interp.c: wf_cssprop_interp;
* test_lot97_timing.c: wf_cssanim_parse, wf_csstrans_parse and
  wf_cssanim_progress;
* test_lot97_sheet.c: wf_site_prepare_ext after wf_site_set_time: the
  value of an animated or transitioned registered property on an element
  and on its child.

Run: python3 scripts/lot97_animgen.py
"""
