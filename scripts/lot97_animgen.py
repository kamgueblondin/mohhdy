OUT = os.path.join(ROOT, "tests", "unit", "userspace")
HEADER = "/* %s (generated by scripts/lot97_animgen.py; expectations from scripts/lot97_animmodel.py). */"
S = A.S
KIND = {"linear": 0, "bezier": 1, "steps": 2}
POS = {"end": 0, "start": 1, "none": 2, "both": 3}
DIRS = {"normal": 0, "reverse": 1, "alternate": 2, "alternate-reverse": 3}
FILLS = {"none": 0, "forwards": 1, "backwards": 2, "both": 3}


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def finish(o, names, fname):
    o += ["int main(void) {", "    unity_init();"]
    o += ["    RUN_TEST(%s);" % n for n in names]
    o += ["    unity_print_results();", "    unity_cleanup();", "    return unity_stats.tests_failed == 0 ? 0 : 1;",
          "}", ""]
    with open(os.path.join(OUT, fname), "w") as f:
        f.write("\n".join(o))


def chunks(o, prefix, cases, per):
    names = []
    for b in range(0, len(cases), per):
        name = "%s_%d" % (prefix, b // per)
        names.append(name)
        o.append("static void %s(void) {" % name)
        for lines in cases[b:b + per]:
            o += ["    " + x for x in lines]
        o += ["}", ""]
    return names


def dec(rng, lo, hi, places=4):
    """a decimal text in [lo, hi] (units) with up to `places` decimals"""
    v = rng.randrange(lo * 10 ** places, hi * 10 ** places + 1)
    p = rng.randrange(places + 1)
    v -= v % (10 ** (places - p))
    s = "-" if v < 0 else ""
    v = abs(v)
    w, f = divmod(v, 10 ** places)
    t = s + str(w)
    if f:
        t += "." + ("%0*d" % (places, f)).rstrip("0")
    return t


# ------------------------------------------------------------- easing
def ease_text(rng, good=True):
    k = rng.randrange(6)
    if k == 0:
        return rng.choice(["linear", "ease", "ease-in", "ease-out", "ease-in-out", "step-start", "step-end"])
    if k <= 2:
        xs = [dec(rng, 0, 1), dec(rng, -3, 3), dec(rng, 0, 1), dec(rng, -3, 3)]
        if not good:
            j = rng.randrange(5)
            if j == 0:
                xs[0] = rng.choice(["1.0001", "-0.1", "2"])
            elif j == 1:
                xs[3] = rng.choice(["100.0001", "-101", "250"])
            elif j == 2:
                xs = xs[:3]
            elif j == 3:
                xs[1] = rng.choice(["1px", "a", "", "50%"])
            else:
                xs.append("0")
        sep = rng.choice([",", ", ", " , "])
        return "cubic-bezier(" + sep.join(xs) + ")"
    n = rng.choice([1, 2, 3, 4, 5, 7, 10, rng.randrange(1, 10001)])
    pos = rng.choice([None, "jump-start", "jump-end", "jump-none", "jump-both", "start", "end"])
    if not good:
        j = rng.randrange(4)
        if j == 0:
            n = rng.choice([0, 10001, 99999])
        elif j == 1:
            pos = rng.choice(["middle", "jump", "both"])
        elif j == 2:
            return "steps(%d,)" % n
        else:
            return "steps(%d, end, end)" % n
    return "steps(%d%s)" % (n, "" if pos is None else ", " + pos)


EASE_C = ['#include "../../framework/unity.h"', "#include <string.h>", "#include <stdio.h>", '#include "wf_cssprop.h"', "",
          "static char g_t[96];", "static wf_cssease_t g_e;", "",
          "/* the parsed easing as \"kind pos n x1 y1 x2 y2\", BAD when refused */",
          "static const char *ez(const char *s) {",
          "    memset(&g_e, 0x5a, sizeof(g_e));",
          "    if (!wf_cssease_parse(s, (int)strlen(s), &g_e)) return \"BAD\";",
          "    snprintf(g_t, sizeof(g_t), \"%d %d %d %d %d %d %d\", g_e.kind, g_e.pos, g_e.n, g_e.x1, g_e.y1, g_e.x2, g_e.y2);",
          "    return g_t;",
          "}", "",
          "static int at(const char *s, int x, int before) {",
          "    if (!wf_cssease_parse(s, (int)strlen(s), &g_e)) return -999999;",
          "    return wf_cssease_at(&g_e, x, before);",
          "}", ""]


def ease_fields(e):
    if e[0] == "linear":
        return "0 0 1 0 0 0 0"
    if e[0] == "bezier":
        return "1 0 1 %d %d %d %d" % e[1:]
    return "2 %d %d 0 0 0 0" % (POS[e[2]], e[1])


def write_ease():
    rng = random.Random(9701)
    cases, worst = [], 0.0
    while len(cases) < 400:
        good = rng.random() < 0.8
        s = ease_text(rng, good)
        e = A.ease_parse(s)
        lines = ["TEST_ASSERT_EQUAL_STRING(%s, ez(%s));" % (cstr("BAD" if e is None else ease_fields(e)), cstr(s))]
        if e is not None:
            for _ in range(rng.randrange(1, 4)):
                x = rng.choice([0, S, rng.randrange(0, S + 1), rng.randrange(0, S + 1), rng.randrange(1, 10) * 1000])
                before = 1 if e[0] == "steps" and rng.random() < 0.3 else 0
                v = A.ease_at(e, x, bool(before))
                if e[0] == "bezier":
                    worst = max(worst, abs(v - A.bezier_true(e, x)))
                    assert abs(v - A.bezier_true(e, x)) <= 1.0, (s, x, v)
                lines.append("TEST_ASSERT_EQUAL(%d, at(%s, %d, %d));" % (v, cstr(s), x, before))
        cases.append(lines)
    o = [HEADER % "Lot 97: easing functions (wf_cssease_parse, wf_cssease_at)"] + EASE_C
    names = chunks(o, "test_l97_ease", cases, 10)
    finish(o, names, "test_lot97_ease.c")
    return len(cases), worst


# ------------------------------------------------------------- interpolation
def num_text(rng, kind):
    if kind == "L":
        return rng.choice([dec(rng, -300, 300) + "px", "0px", dec(rng, 0, 50, 2) + "px"])
    if kind == "P":
        return dec(rng, -100, 200) + "%"
    if kind == "LP":
        p, l = dec(rng, -100, 100, 2), dec(rng, 0, 200, 2)
        return "calc(%s%% %s %spx)" % (p, rng.choice(["+", "-"]), l)
    if kind == "N":
        return dec(rng, -1000, 1000)
    if kind == "I":
        return str(rng.randrange(-500, 501))
    if kind == "A":
        return dec(rng, -720, 720) + "deg"
    return dec(rng, 0, 30) + "s"


def colour_text(rng):
    k = rng.randrange(6)
    if k == 0:
        return rng.choice(sorted(A.NAMED) + ["transparent"])
    if k == 1:
        return "#" + "".join(rng.choice("0123456789abcdef") for _ in range(rng.choice([3, 4, 6, 8])))
    if k == 2:
        return "rgb(%d, %d, %d)" % tuple(rng.randrange(256) for _ in range(3))
    if k == 3:
        return "rgba(%d, %d, %d, %s)" % (rng.randrange(256), rng.randrange(256), rng.randrange(256), dec(rng, 0, 1, 2))
    if k == 4:
        return "rgb(%d %d %d / %s%%)" % (rng.randrange(256), rng.randrange(256), rng.randrange(256), rng.randrange(101))
    return rng.choice(["hsl(120, 50%, 50%)", "currentcolor"])


TYPE_KIND = {"<length>": "L", "<percentage>": "P", "<length-percentage>": "LPX", "<number>": "N", "<integer>": "I",
             "<angle>": "A", "<time>": "T", "<color>": "C", "<custom-ident>": "K"}


def value_of(rng, t):
    k = TYPE_KIND[t]
    if k == "C":
        return colour_text(rng)
    if k == "K":
        return rng.choice(["alpha", "beta", "gamma"])
    if k == "LPX":
        return num_text(rng, rng.choice(["L", "P", "LP"]))
    return num_text(rng, k)


def write_interp():
    rng = random.Random(9702)
    cases = []
    while len(cases) < 500:
        t = rng.choice(list(TYPE_KIND))
        m = rng.choice(["", "", "", "+", "#"])
        alts = [(t, m)]
        if rng.random() < 0.2:
            t2 = rng.choice(list(TYPE_KIND))
            if t2 != t:
                alts.append((t2, ""))
        text = "'" + " | ".join(a + b for a, b in alts) + "'"
        if rng.random() < 0.04:
            text = "'*'"
        code, parsed = P.parse_syntax(text)
        if not parsed and text != "'*'":
            continue

        def val():
            ty, mm = rng.choice(alts)
            if mm:
                n = rng.randrange(1, 4)
                return (", " if mm == "#" else " ").join(value_of(rng, ty) for _ in range(n))
            return value_of(rng, ty)
        a = val()
        b = val() if rng.random() < 0.85 else a
        if rng.random() < 0.3 and m:
            b = a.replace("1", "2", 1)
        tt = rng.choice([0, S, 5000, 4999, rng.randrange(0, S + 1), rng.randrange(0, S + 1), rng.randrange(-3000, 13001)])
        r, c = A.interp(None if text == "'*'" else parsed, a, b, tt)
        if r is None or len(r) >= 120:
            continue
        cases.append(["TEST_ASSERT_EQUAL_STRING(%s, ip(%s, %s, %s, %d, %d));" % (cstr(r), cstr(text), cstr(a), cstr(b), tt, c)])
    o = [HEADER % "Lot 97: interpolation of computed registered values (wf_cssprop_interp)",
         '#include "../../framework/unity.h"', "#include <string.h>", '#include "wf_cssprop.h"', "",
         "static wf_cssprop_t g_p;", "static char g_o[128];", "",
         "/* the interpolated text; the return code is checked against code */",
         "static const char *ip(const char *syn, const char *a, const char *b, int t, int code) {",
         "    memset(&g_p, 0, sizeof(g_p));",
         "    g_p.syntax = (unsigned char)wf_cssprop_syntax_parse(syn, (int)strlen(syn), &g_p);",
         "    if (!g_p.syntax) return \"BAD SYNTAX\";",
         "    if (wf_cssprop_interp(&g_p, a, b, t, g_o, (int)sizeof(g_o)) != code) return \"BAD CODE\";",
         "    return g_o;",
         "}", ""]
    names = chunks(o, "test_l97_interp", cases, 10)
    finish(o, names, "test_lot97_interp.c")
    return len(cases)


# ------------------------------------------------------------- timing
def time_text(rng, neg=False):
    if rng.random() < 0.5:
        v = rng.randrange(-5000 if neg else 0, 20001)
        return "%dms" % v
    return dec(rng, -5 if neg else 0, 20, 4) + "s"


def anim_item(rng, good=True):
    parts = []
    name = rng.choice(["k", "slide", "fade-in", "_x", "a1", "ease", "none", "paused"])
    parts.append(name)
    if rng.random() < 0.9:
        parts.append(time_text(rng))
    if rng.random() < 0.5:
        parts.append(time_text(rng, True))
    if rng.random() < 0.5:
        parts.append(ease_text(rng))
    if rng.random() < 0.5:
        parts.append(rng.choice(["infinite", "0", "1", "2", "2.5", "0.25", "3"]))
    if rng.random() < 0.4:
        parts.append(rng.choice(list(DIRS)))
    if rng.random() < 0.4:
        parts.append(rng.choice(list(FILLS)))
    if rng.random() < 0.2:
        parts.append(rng.choice(["running", "paused"]))
    if not good:
        parts.append(rng.choice(["-1s", "initial", "1s 2s 3s", "inherit", "1px", "-2", "steps(0)"]))
    rng.shuffle(parts)
    return " ".join(parts)


def trans_item(rng, good=True):
    parts = []
    if rng.random() < 0.8:
        parts.append(rng.choice(["--p", "--x", "all", "color", "none"]))
    if rng.random() < 0.9:
        parts.append(time_text(rng))
    if rng.random() < 0.5:
        parts.append(time_text(rng, True))
    if rng.random() < 0.5:
        parts.append(ease_text(rng))
    if rng.random() < 0.3:
        parts.append(rng.choice(["allow-discrete", "normal"]))
    if not good:
        parts.append(rng.choice(["-1s", "inherit", "1s 2s 3s", "2px", "--y"]))
    rng.shuffle(parts)
    return " ".join(parts)


def ease_c(e):
    return ease_fields(e)


def write_timing():
    rng = random.Random(9703)
    cases = []
    while len(cases) < 300:
        n = rng.choice([1, 1, 1, 2, 3, 5])
        good = rng.random() < 0.8
        if rng.random() < 0.6:
            v = ", ".join(anim_item(rng, good or k) for k in range(n))
            if rng.random() < 0.03:
                v = rng.choice(["k 1s,", ", k 1s", "k 1s,, j 2s", ""])
            got = A.anim_parse(v)
            lines = ["TEST_ASSERT_EQUAL(%d, anim(%s));" % (-1 if got is None else len(got), cstr(v))]
            for k, a in enumerate(got or []):
                lines.append("TEST_ASSERT_EQUAL_STRING(%s, afield(%d));" % (cstr("%s %d %d %d %d %d %d %s" % (
                    a["name"] or "-", a["dur"], a["delay"], a["iters"], DIRS[a["dir"]], FILLS[a["fill"]], int(a["paused"]),
                    ease_c(a["ease"]))), k))
                for _ in range(rng.randrange(1, 5)):
                    span = a["dur"] * (3 if a["iters"] < 0 else max(1, a["iters"] // S + 1)) + abs(a["delay"])
                    ms = rng.choice([0, a["delay"], a["delay"] + a["dur"], rng.randrange(0, span + 2),
                                     rng.randrange(0, span + 2), rng.randrange(0, 100000)])
                    ms = max(0, min(ms, A.MS_MAX))
                    pr = A.progress(a, ms)
                    lines.append("TEST_ASSERT_EQUAL_STRING(%s, prog(%d, %d));" % (
                        cstr("none" if pr is None else "%d %d" % (pr[0], int(pr[1]))), k, ms))
        else:
            v = ", ".join(trans_item(rng, good or k) for k in range(n))
            got = A.trans_parse(v)
            lines = ["TEST_ASSERT_EQUAL(%d, trans(%s));" % (-1 if got is None else len(got), cstr(v))]
            for k, t in enumerate(got or []):
                lines.append("TEST_ASSERT_EQUAL_STRING(%s, tfield(%d));" % (cstr("%s %d %d %d %s" % (
                    t["prop"] or "-", t["dur"], t["delay"], int(t["discrete"]), ease_c(t["ease"]))), k))
        cases.append(lines)
    o = [HEADER % "Lot 97: animation and transition shorthands and animation timing",
         '#include "../../framework/unity.h"', "#include <string.h>", "#include <stdio.h>", '#include "wf_cssprop.h"', "",
         "static wf_cssanim_t g_a[WF_CSSANIM_MAX];", "static wf_csstrans_t g_tr[WF_CSSANIM_MAX];", "static char g_t[160];", "",
         "static int anim(const char *v) { memset(g_a, 0x5a, sizeof(g_a)); return wf_cssanim_parse(v, g_a, WF_CSSANIM_MAX); }",
         "static int trans(const char *v) { memset(g_tr, 0x5a, sizeof(g_tr)); return wf_csstrans_parse(v, g_tr, WF_CSSANIM_MAX); }", "",
         "static const char *ez(const wf_cssease_t *e) {",
         "    static char b[64];",
         "    snprintf(b, sizeof(b), \"%d %d %d %d %d %d %d\", e->kind, e->pos, e->n, e->x1, e->y1, e->x2, e->y2);",
         "    return b;",
         "}", "",
         "static const char *afield(int k) {",
         "    const wf_cssanim_t *a = &g_a[k];",
         "    snprintf(g_t, sizeof(g_t), \"%s %d %d %d %d %d %d %s\", a->name[0] ? a->name : \"-\", a->dur, a->delay, a->iters,",
         "             a->dir, a->fill, a->paused, ez(&a->ease));",
         "    return g_t;",
         "}", "",
         "static const char *tfield(int k) {",
         "    const wf_csstrans_t *t = &g_tr[k];",
         "    snprintf(g_t, sizeof(g_t), \"%s %d %d %d %s\", t->prop[0] ? t->prop : \"-\", t->dur, t->delay, t->discrete, ez(&t->ease));",
         "    return g_t;",
         "}", "",
         "static const char *prog(int k, int ms) {",
         "    int p = -1, before = -1;",
         "    if (!wf_cssanim_progress(&g_a[k], ms, &p, &before)) return \"none\";",
         "    snprintf(g_t, sizeof(g_t), \"%d %d\", p, before);",
         "    return g_t;",
         "}", ""]
    names = chunks(o, "test_l97_timing", cases, 8)
    finish(o, names, "test_lot97_timing.c")
    return len(cases)


# ------------------------------------------------------------- the sheet
SHEET_TYPES = ["<length>", "<number>", "<percentage>", "<color>", "<angle>", "<integer>", "<length-percentage>",
               "<custom-ident>", "<length>+", "<color>#"]


def sheet_value(rng, t):
    if t.endswith("+") or t.endswith("#"):
        base = t[:-1]
        n = 2
        return (", " if t.endswith("#") else " ").join(value_of(rng, base) for _ in range(n))
    v = value_of(rng, t)
    if t == "<color>" and v.startswith(("hsl", "currentcolor")):
        v = "red"
    return v


def computed(alts, v):
    c = P.compute(alts, v, (640, 480))
    return v if c is None else c


def kf_case(rng):
    t = rng.choice(SHEET_TYPES)
    syn = "'%s'" % t
    _, alts = P.parse_syntax(syn)
    inherits = rng.random() < 0.5
    init = computed(alts, sheet_value(rng, t))
    own = sheet_value(rng, t) if rng.random() < 0.5 else None
    under = computed(alts, own) if own is not None else init
    offs = sorted(rng.sample([0, 2500, 5000, 7500, 10000, 3333, 6000], rng.randrange(1, 4)))
    frames, blocks = [], []
    for o in offs:
        v = sheet_value(rng, t)
        sel = "from" if o == 0 and rng.random() < 0.5 else "to" if o == 10000 and rng.random() < 0.5 else \
            ("%d%%" % (o // 100) if o % 100 == 0 else "%d.%02d%%" % (o // 100, o % 100))
        fe = None
        body = "--p: %s" % v
        if rng.random() < 0.2:
            fe_text = rng.choice(["linear", "ease-in", "steps(2)", "step-end"])
            fe = A.ease_parse(fe_text)
            body += "; animation-timing-function: %s" % fe_text
        blocks.append("%s { %s }" % (sel, body))
        frames.append((o, computed(alts, v), fe))
    dur = rng.choice([1000, 2000, 500, 3000])
    item = "k %dms" % dur
    e_text = rng.choice(["linear", "ease", "ease-in-out", "steps(4)", "cubic-bezier(0.1, 0.7, 1, 0.1)", None])
    if e_text:
        item += " " + e_text
    delay = rng.choice([0, 0, 250, -400, 1000])
    if delay:
        item += " %dms" % delay
    cnt = rng.choice([None, "infinite", "2", "1.5"])
    if cnt:
        item += " " + cnt
    d = rng.choice([None, "reverse", "alternate", "alternate-reverse"])
    if d:
        item += " " + d
    f = rng.choice([None, "forwards", "backwards", "both"])
    if f:
        item += " " + f
    an = A.anim_parse(item)[0]
    ms = rng.choice([0, rng.randrange(0, 4 * dur), rng.randrange(0, 4 * dur), dur // 2])
    # the model: frames with implicit ends from the underlying value
    fr = list(frames)
    if fr[0][0] > 0:
        fr.insert(0, (0, under, None))
    if fr[-1][0] < S:
        fr.append((S, under, None))
    pr = A.progress(an, ms)
    if pr is None:
        o_val = under
    else:
        p, before = pr
        j = 0
        while j + 2 < len(fr) and fr[j + 1][0] <= p:
            j += 1
        x = (20000 * (p - fr[j][0]) // (fr[j + 1][0] - fr[j][0]) + 1) // 2
        e = fr[j][2] or an["ease"]
        o_val = A.interp(alts, fr[j][1], fr[j + 1][1], A.ease_at(e, x, before))[0]
    i_val = o_val if inherits else init
    css = "@property --p { syntax: %s; inherits: %s; initial-value: %s } @keyframes k { %s } #o { animation: %s%s }" % (
        syn, "true" if inherits else "false", init, " ".join(blocks), item,
        "; --p: %s" % own if own is not None else "")
    return css, ms, o_val, i_val, int(pr is not None)


def trans_case(rng):
    t = rng.choice(SHEET_TYPES)
    syn = "'%s'" % t
    _, alts = P.parse_syntax(syn)
    init = computed(alts, sheet_value(rng, t))
    start = sheet_value(rng, t)
    end = sheet_value(rng, t) if rng.random() < 0.9 else start
    dur = rng.choice([0, 1000, 2000, 400])
    delay = rng.choice([0, 0, 300, -200])
    e_text = rng.choice(["linear", "ease", "steps(3, jump-both)", None])
    disc = rng.random() < 0.2
    item = "--p %dms" % dur + ("" if not delay else " %dms" % delay) + ("" if not e_text else " " + e_text) + \
        (" allow-discrete" if disc else "")
    if rng.random() < 0.15:
        item = item.replace("--p", "all")
    tr = A.trans_parse(item)[0]
    ms = rng.choice([0, rng.randrange(0, 3000), rng.randrange(0, 3000), 150])
    s_c, e_c = computed(alts, start), computed(alts, end)
    val, ran = e_c, 0
    if s_c != e_c and A.interp(alts, s_c, e_c, 5000)[1] == 2 or (s_c != e_c and tr["discrete"]):
        if tr["dur"] + tr["delay"] > 0:
            e = ms - tr["delay"]
            if e < tr["dur"]:
                ran = 1
                val = s_c if e < 0 else A.interp(alts, s_c, e_c, A.ease_at(tr["ease"], e * S // tr["dur"]))[0]
    css = "@property --p { syntax: %s; inherits: true; initial-value: %s } #o { --p: %s; transition: %s } " \
          "@starting-style { #o { --p: %s } }" % (syn, init, end, item, start)
    return css, ms, val, val, ran


def write_sheet():
    rng = random.Random(9704)
    cases = []
    while len(cases) < 160:
        css, ms, ov, iv, act = kf_case(rng) if rng.random() < 0.65 else trans_case(rng)
        if len(css) > 900 or ov is None or iv is None:
            continue
        cases.append(["prep(%s, %d);" % (cstr(css), ms),
                      "TEST_ASSERT_EQUAL_STRING(%s, nv(\"o\"));" % cstr(ov),
                      "TEST_ASSERT_EQUAL_STRING(%s, nv(\"i\"));" % cstr(iv),
                      "TEST_ASSERT_EQUAL(%d, g_d.prop_animated + g_d.prop_transitioned > 0);" % act])
    o = [HEADER % "Lot 97: animated and transitioned registered properties in the reader sheet",
         '#include "../../framework/unity.h"', "#include <string.h>", "#include <stdio.h>", '#include "wf_sitecss.h"', "",
         "static wf_site_t g_d;", "static char g_html[4096];", "",
         "static void prep(const char *css, int ms) {",
         "    wf_site_set_time(ms);",
         "    snprintf(g_html, sizeof(g_html), \"<html><head><style>%s</style></head><body>\"",
         "             \"<div id=o><p id=i>i</p></div><p id=q>q</p></body></html>\", css);",
         "    TEST_ASSERT_EQUAL(0, wf_site_prepare_ext(&g_d, g_html, (int)strlen(g_html), 640, 480, 0, 0));",
         "    wf_site_set_time(0);",
         "    TEST_ASSERT_EQUAL(1, g_d.nprops);",
         "}", "",
         "static const char *nv(const char *id) {",
         "    int i;",
         "    for (i = 0; i < g_d.nnodes; i++)",
         "        if (!strcmp(g_d.node[i].id, id)) { const char *v = wf_site_node_var(&g_d, i, \"--p\"); "
         "return v ? v : \"(none)\"; }",
         "    return \"(no node)\";",
         "}", ""]
    names = chunks(o, "test_l97_sheet", cases, 4)
    finish(o, names, "test_lot97_sheet.c")
    return len(cases)


