SPACES = ["srgb", "srgb-linear", "display-p3", "a98-rgb", "prophoto-rgb", "rec2020", "xyz", "xyz-d65", "xyz-d50"]


# ------------------------------------------------------------- colour texts
def alpha_part(rng):
    if rng.random() < 0.65:
        return ""
    return rng.choice([" / ", "/", " /", "/ "]) + G100.alpha_text(rng)


def pct_or(rng, lo, hi, plo, phi, places=4):
    k = rng.randrange(7)
    if k < 3:
        return dec(rng, lo, hi, places)
    if k < 5:
        return dec(rng, plo, phi, 2) + "%"
    if k == 5:
        return str(rng.randrange(lo, hi + 1))
    return rng.choice(["0", "0%", "100%", "50%", "-0", "+0.5", ".5", "1e1", "1E-1", "2.5e-2"])


def hue(rng):
    return G99.hue_text(rng) if rng.random() < 0.6 else G98.hue_text(rng)


def fname(rng, n):
    return G100.rcase(rng, n) if rng.random() < 0.2 else n


def lab_text(rng, good=True):
    k = rng.randrange(4)
    ok = k >= 2
    lch = k & 1
    L_ = pct_or(rng, -10, 110, -10, 110) if not ok else pct_or(rng, 0, 1, -10, 110)
    if ok:
        a = pct_or(rng, 0, 0, -120, 120) if rng.random() < 0.4 else dec(rng, -1, 1) if rng.random() < 0.3 else \
            "0." + "%04d" % rng.randrange(0, 5000) if rng.random() < 0.5 else "-0." + "%04d" % rng.randrange(0, 5000)
        c = pct_or(rng, 0, 0, -10, 130) if rng.random() < 0.4 else "0." + "%04d" % rng.randrange(0, 5000)
        b = "0." + "%04d" % rng.randrange(0, 5000) if rng.random() < 0.5 else "-0." + "%04d" % rng.randrange(0, 5000)
    else:
        a = pct_or(rng, -160, 160, -130, 130)
        b = pct_or(rng, -160, 160, -130, 130)
        c = pct_or(rng, -10, 230, -10, 160)
        if rng.random() < 0.05:
            a = rng.choice(["20000", "-12000", "9999.9999"])
    n = ["lab", "lch", "oklab", "oklch"][k]
    args = [L_, c, hue(rng)] if lch else [L_, a, b]
    sep = rng.choice([" ", " ", " ", "  ", "\t"])
    t = "%s(%s%s)" % (fname(rng, n), sep.join(args), alpha_part(rng))
    if rng.random() < 0.08:
        t = t.replace("(", "( ", 1).replace(")", " )")
    if not good:
        j = rng.randrange(10)
        t = ["%s(%s)" % (n, ", ".join(args)), "%s(%s)" % (n, " ".join(args[:2])),
             "%s(%s 1)" % (n, " ".join(args)), "%s(none %s)" % (n, " ".join(args[1:])),
             "%s(%spx %s)" % (n, args[0], " ".join(args[1:])), "%s(%s / 1 / 1)" % (n, " ".join(args)),
             "%sa(%s)" % (n, " ".join(args)), "%s(%s" % (n, " ".join(args)), "%s()" % n,
             "%s(%s %sdeg %s)" % (n, args[0], args[1], args[2])][j]
    return t


def color_text(rng, good=True):
    sp = rng.choice(SPACES)
    comps = [pct_or(rng, -1, 2, -20, 120) if rng.random() < 0.3 else dec(rng, 0, 1) for _ in range(3)]
    if rng.random() < 0.03:
        comps[0] = rng.choice(["150", "-101", "99.5"])
    if rng.random() < 0.15:
        sp = G100.rcase(rng, sp)
    sep = rng.choice([" ", " ", "  ", "\t"])
    t = "%s(%s%s%s%s)" % (fname(rng, "color"), rng.choice(["", "", "", " "]), sp, sep, sep.join(comps)) + ""
    t = t[:-1] + alpha_part(rng) + ")"
    if not good:
        j = rng.randrange(10)
        t = ["color(%s, %s)" % (sp, ", ".join(comps)), "color(%s %s)" % (sp, " ".join(comps[:2])),
             "color(%s %s 1)" % (sp, " ".join(comps)), "color(p3 %s)" % " ".join(comps),
             "color(%s)" % " ".join(comps), "color(%s %s / 1 / 1)" % (sp, " ".join(comps)),
             "color(--x %s)" % " ".join(comps), "color(%s %s" % (sp, " ".join(comps)), "color()",
             "color(%s %spx %s %s)" % (sp, comps[0], comps[1], comps[2])][j]
    return t


def new_colour(rng, good=True):
    return lab_text(rng, good) if rng.random() < 0.6 else color_text(rng, good)


def mixed(rng, good=True):
    """a new function inside color-mix(), with another colour"""
    a = new_colour(rng)
    b = new_colour(rng) if rng.random() < 0.5 else G100.simple_colour(rng)
    if rng.random() < 0.5:
        a, b = b, a
    pa = " " + G100.pct_text(rng) if rng.random() < 0.4 else ""
    return "color-mix(in srgb, %s%s, %s)" % (a, pa, b)


def any_new(rng):
    k = rng.randrange(10)
    if k < 6:
        return new_colour(rng, rng.random() < 0.85)
    if k < 8:
        return mixed(rng)
    return G100.any_colour(rng)


def model(fn, *args):
    """fn(*args), None for an unsure colour (the case is left out)"""
    try:
        return ("ok", fn(*args))
    except T.Unsure:
        return None


# ------------------------------------------------------------- color
def write_color():
    rng = random.Random(10101)
    cases, seen = [], set()
    fixed = ["lab(50 0 0)", "lab(100 0 0)", "lab(0 0 0)", "lch(50 0 0)", "oklab(1 0 0)", "oklab(0 0 0)",
             "oklch(0.7 0.1 120)", "lab(54.29 80.82 69.88)", "oklab(0.62796 0.22486 0.12585)",
             "color(srgb 1 0 0)", "color(srgb-linear 0.5 0.5 0.5)", "color(display-p3 1 0 0)",
             "color(a98-rgb 1 1 1)", "color(prophoto-rgb 0.5 0.5 0.5)", "color(rec2020 0.5 0.2 0.9)",
             "color(xyz 0.9505 1 1.089)", "color(xyz-d65 0.2 0.3 0.4)", "color(xyz-d50 0.9642 1 0.8249)",
             "lab(50% 50% -50%)", "lch(50% 100% 0.5turn)", "oklch(50% 100% 90deg / 50%)", "color(srgb 50% 0% 100% / 0.25)",
             "color(rec2020 0.01 0.02 0.03)", "color(display-p3 0.03 0.04 0.05)", "lab(none 0 0)", "lab(50, 0, 0)",
             "color(srgb, 1, 0, 0)", "color(p3 1 0 0)", "LAB(50 20 30)", "OkLch(0.5 0.2 200)", "Color(SRGB 1 1 1)"]
    for t in fixed:
        m = model(L.reader, t)
        assert m is not None, t
        seen.add(t)
        cases.append(["TEST_ASSERT_EQUAL_STRING(%s, rc(%s));" % (cstr(G100.rc_str(m[1])), cstr(t))])
    while len(cases) < 780:
        k = rng.randrange(10)
        if k < 7:
            t = any_new(rng)
        elif k == 7:
            t = rng.choice([" ", "\t", ""]) + new_colour(rng) + rng.choice(["", " ", ";", " !important", " x", ")"])
        elif k == 8:
            t = mixed(rng)
        else:
            t = new_colour(rng, False)
        if t in seen or len(t) > 200:
            continue
        seen.add(t)
        m = model(L.reader, t)
        if m is None:
            continue
        cases.append(["TEST_ASSERT_EQUAL_STRING(%s, rc(%s));" % (cstr(G100.rc_str(m[1])), cstr(t))])
    while len(cases) < 830:
        t = new_colour(rng) + rng.choice([";x", " ff", "0", ")", "!"])
        n = rng.choice([len(t) - 2, len(t) - 1, rng.randrange(1, len(t) + 1)])
        m = model(L.reader, t[:n])
        if m is None:
            continue
        cases.append(["TEST_ASSERT_EQUAL_STRING(%s, rcn(%s, %d));" % (cstr(G100.rc_str(m[1])), cstr(t), n)])
    for n in (126, 127, 128, 129):
        base = "lab(50 20 30)"
        t = base.replace(" 20", " " * (n - len(base) + 1) + "20")
        assert len(t) == n
        cases.append(["TEST_ASSERT_EQUAL_STRING(%s, rc(%s));" % (cstr(G100.rc_str(L.reader(t))), cstr(t))])
    o = [HEADER % "Lot 101: the reader colour (wf_cssprop_color): lab(), lch(), oklab(), oklch(), color()"] + \
        G98.IP_C + [
        "/* the reader colour of v[0..n) as \"#rrggbb alpha\", \"-\" when it is not one */",
        "static const char *rcn(const char *v, int n) {",
        "    unsigned int c = 0xdeadbeefu;",
        "    int a = -7, r = wf_cssprop_color(v, n, &c, &a);",
        "    if (!r) return c == 0xdeadbeefu && a == -7 ? \"-\" : \"WRITTEN\";",
        "    if (r != 1 || c > 0xffffffu || a < 0 || a > 255) return \"BAD CODE\";",
        "    snprintf(g_o, sizeof(g_o), \"#%06x %d\", c, a);",
        "    return g_o;",
        "}", "",
        "static const char *rc(const char *v) { return rcn(v, (int)strlen(v)); }", ""]
    o.insert(3, "#include <stdio.h>")
    names = chunks(o, "test_l101_color", cases, 12)
    finish(o, names, "test_lot101_color.c")
    return len(cases)


# ------------------------------------------------------------- mix
def reg_new(rng):
    k = rng.randrange(6)
    if k < 4:
        return new_colour(rng).lower()
    if k == 4:
        return mixed(rng).lower()
    return G100.reg_colour(rng)


def write_mix():
    rng = random.Random(10102)
    cases = []
    alts = L.ALTS

    def ok(v):
        m = model(A.colour_match, v)
        return m is not None and m[1] and len(v) < 128
    while len(cases) < 420:
        a, b = reg_new(rng), reg_new(rng)
        if not (ok(a) and ok(b)):
            continue
        tt = rng.choice([5000, rng.randrange(1, S), rng.randrange(1, S), 1, 9999, 2500])
        m = model(A.interp, alts, a, b, tt)
        if m is None or m[1][0] is None or len(m[1][0]) >= 160:
            continue
        r, c = m[1]
        cases.append(["TEST_ASSERT_EQUAL_STRING(%s, ip(%s, %s, %d, %d));" % (cstr(r), cstr(a), cstr(b), tt, c)])
    while len(cases) < 600:
        a, b = reg_new(rng), reg_new(rng)
        if not (ok(a) and ok(b)):
            continue
        m = model(M98.add, alts, a, b)
        if m is None or m[1][0] is None or len(m[1][0]) >= 160:
            continue
        r, c = m[1]
        cases.append(["TEST_ASSERT_EQUAL_STRING(%s, ad(%s, %s, %d));" % (cstr(r), cstr(a), cstr(b), c)])
    seen = set()
    while len(cases) < 760:
        v = (new_colour(rng, rng.random() < 0.6) if rng.random() < 0.8 else mixed(rng)).lower()
        if v in seen or len(v) >= 128:
            continue
        seen.add(v)
        m = model(A.colour_match, v)
        if m is None:
            continue
        cases.append(["TEST_ASSERT_EQUAL(%d, mt(%s));" % (int(bool(m[1])), cstr(v))])
    o = [HEADER % "Lot 101: lab(), lch(), oklab(), oklch() and color() in registered <color> values"] + \
        G98.IP_C + [
        "/* the interpolated text of two colours; the return code is checked */",
        "static const char *ip(const char *a, const char *b, int t, int code) {",
        "    if (!syn(\"'<color>'\")) return \"BAD SYNTAX\";",
        "    if (wf_cssprop_interp(&g_p, a, b, t, g_o, (int)sizeof(g_o)) != code) return \"BAD CODE\";",
        "    return g_o;",
        "}", "",
        "/* the sum text; the return code is checked */",
        "static const char *ad(const char *under, const char *v, int code) {",
        "    if (!syn(\"'<color>'\")) return \"BAD SYNTAX\";",
        "    if (wf_cssprop_add(&g_p, under, v, g_o, (int)sizeof(g_o)) != code) return \"BAD CODE\";",
        "    return g_o;",
        "}", "",
        "/* whether a '<color>' registration matches v */",
        "static int mt(const char *v) {",
        "    if (!syn(\"'<color>'\")) return -1;",
        "    return wf_cssprop_match_prop(&g_p, v) != 0;",
        "}", ""]
    names = chunks(o, "test_l101_mix", cases, 10)
    finish(o, names, "test_lot101_mix.c")
    return len(cases)


# ------------------------------------------------------------- timeline api
TL_NAMES = ["--t", "--u", "--v", "--scroller", "--a-b", "--x1", "--" + "y" * 29]
TL_BAD = ["-x", "-ab", "x--", "--", "t", "auto", "--" + "z" * 30, "1--", "--a.b", "--a(", "scroll()", "x y", "--t --u"]


def tl_value(rng, which):
    n = rng.choice([1, 1, 2, 3, 4, 5]) if rng.random() < 0.95 else 0
    items = []
    for _ in range(n):
        if which == 0:
            w = rng.choice(TL_NAMES + ["none", "NONE", "--T"]) if rng.random() < 0.88 else rng.choice(TL_BAD)
        elif which == 1:
            w = rng.choice(T.TL_AXES + ["BLOCK", "Y"]) if rng.random() < 0.88 else rng.choice(
                ["vertical", "horizontal", "--t", "block inline", "", "0"])
        else:
            w = rng.choice(TL_NAMES + ["none"]) if rng.random() < 0.9 else rng.choice(TL_BAD)
            if rng.random() < 0.6:
                w += " " + (rng.choice(T.TL_AXES) if rng.random() < 0.9 else rng.choice(["--t", "block x", "z"]))
            elif rng.random() < 0.05:
                w = rng.choice(T.TL_AXES) + " --t"
        items.append(w)
    sep = rng.choice([", ", ",", " , "])
    v = sep.join(items)
    if rng.random() < 0.05:
        v = rng.choice(["", " ", ",", v + ",", ", " + v, v + ", , --t"])
    return v


def tl_str(r):
    if r is None:
        return "-1"
    return "%d:%s" % (len(r), "".join(" %s/%d" % (n or "-", T.TL_AXES.index(a)) for n, a in r))


def write_tl():
    rng = random.Random(10103)
    cases = []
    which_c = ["WF_CSSTL_NAMES", "WF_CSSTL_AXES", "WF_CSSTL_SHORT"]
    kinds = ["names", "axes", "short"]
    while len(cases) < 420:
        w = rng.randrange(3)
        v = tl_value(rng, w)
        mx = rng.choice([4, 4, 4, 3, 2, 1, 8, 0])
        r = T.tl_list(kinds[w], v.lower().strip())
        if r is not None and len(r) > min(mx, 4):
            r = None
        if v != v.strip() or v == "":
            r = T.tl_list(kinds[w], v.lower().strip()) if v.strip() else None
            if r is not None and len(r) > min(mx, 4):
                r = None
            v = v.strip()
        cases.append(["TEST_ASSERT_EQUAL_STRING(%s, tp(%s, %s, %d));" % (cstr(tl_str(r)), which_c[w], cstr(v.lower()), mx)])
    while len(cases) < 560:
        nv = tl_value(rng, 0).lower().strip()
        av = tl_value(rng, 1).lower().strip() if rng.random() < 0.7 else None
        names = T.tl_list("names", nv) if nv else None
        axes = T.tl_list("axes", av) if av else None
        r = T.tl_coord(names, axes) if names else []
        cases.append(["TEST_ASSERT_EQUAL_STRING(%s, tc(%s, %s));" % (
            cstr(tl_str(r) if r else "0:"), cstr(nv), cstr(av) if av is not None else "0")])
    while len(cases) < 680:
        v = tl_value(rng, 2).lower().strip()
        r = T.tl_list("short", v) if v else None
        if not r:
            continue
        cap = rng.choice([128, 128, 64, 16, 8, 4, 2, 1])
        for ax in (0, 1):
            text = ", ".join((n or "none") if not ax else a for n, a in r)
            exp = "%d %s" % (len(text), text) if len(text) < cap else "0 "
            cases.append(["TEST_ASSERT_EQUAL_STRING(%s, tx(%s, %d, %d));" % (cstr(exp), cstr(v), ax, cap)])
    while len(cases) < 800:
        dur = rng.choice([0, 1, 1000, 2000, 500, rng.randrange(0, 100000), 100000000, 99999999, 33333])
        delay = rng.choice([0, 0, 500, -500, 1000, -1000, rng.randrange(-100000, 100000), 100000000, -100000000])
        iters = rng.choice([S, S, 2 * S, 5000, 0, -1, 3 * S, 12345, 100000 * S])
        prog = rng.choice([0, S, 5000, 2500, 7500, rng.randrange(0, S + 1), 1, 9999, -1, S + 1])
        a = {"dur": dur, "delay": delay, "iters": iters}
        r = T.scroll_ms(a, prog)
        cases.append(["TEST_ASSERT_EQUAL_STRING(%s, sm(%d, %d, %d, %d));" % (
            cstr("0 0" if r is None else "1 %d" % r), dur, delay, iters, prog)])
    o = [HEADER % "Lot 101: the scroll and view timeline lists and the scroll timeline time"] + [
        '#include "../../framework/unity.h"', "#include <string.h>", "#include <stdio.h>", '#include "wf_cssprop.h"', "",
        "static char g_o[256];", "static wf_csstl_t g_t[8];", "",
        "static const char *show(int n) {",
        "    int k, m;",
        "    if (n < 0) return \"-1\";",
        "    m = snprintf(g_o, sizeof(g_o), \"%d:\", n);",
        "    for (k = 0; k < n && m < (int)sizeof(g_o); k++)",
        "        m += snprintf(g_o + m, sizeof(g_o) - (size_t)m, \" %s/%d\", g_t[k].name[0] ? g_t[k].name : \"-\", g_t[k].axis);",
        "    return g_o;",
        "}", "",
        "/* wf_csstl_parse; items past the count stay untouched (all of them may\n * be written for an invalid list) */",
        "static const char *tp(int which, const char *v, int max) {",
        "    int n, k;",
        "    memset(g_t, 0x5a, sizeof(g_t));",
        "    n = wf_csstl_parse(which, v, g_t, max);",
        "    for (k = n < 0 ? 8 : n; k < 8; k++) if (g_t[k].axis != 0x5a) return \"WRITTEN\";",
        "    return show(n);",
        "}", "",
        "static const char *tc(const char *names, const char *axes) { return show(wf_csstl_coord(names, axes, g_t, 4)); }",
        "",
        "/* wf_csstl_text of the shorthand list v (names or axes) */",
        "static const char *tx(const char *v, int axes, int cap) {",
        "    static char t[256];",
        "    int n = wf_csstl_parse(WF_CSSTL_SHORT, v, g_t, 4), r;",
        "    memset(t, 'q', sizeof(t));",
        "    r = wf_csstl_text(g_t, n, axes, t, cap);",
        "    if (r != (int)strlen(t)) return \"BAD LENGTH\";",
        "    snprintf(g_o, sizeof(g_o), \"%d %s\", r, t);",
        "    return g_o;",
        "}", "",
        "static const char *sm(int dur, int delay, int iters, int prog) {",
        "    wf_cssanim_t a;",
        "    int ms = -7, r;",
        "    memset(&a, 0, sizeof(a));",
        "    a.dur = dur; a.delay = delay; a.iters = iters;",
        "    r = wf_cssanim_scroll_ms(&a, prog, &ms);",
        "    snprintf(g_o, sizeof(g_o), \"%d %d\", r, ms);",
        "    return g_o;",
        "}", ""]
    names = chunks(o, "test_l101_tl", cases, 12)
    finish(o, names, "test_lot101_tl.c")
    return len(cases)


