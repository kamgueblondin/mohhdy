def cur_word(rng):
    return rng.choice(["currentcolor", "currentColor", "CURRENTCOLOR", "currentcolor"])


def tree_colour(rng, prop):
    k = rng.randrange(12)
    if k < 4:
        v = new_colour(rng, rng.random() < 0.9)
    elif k < 6:
        v = cur_word(rng)
    elif k == 6 and prop == "color":
        v = rng.choice(["inherit", "unset"])
    elif k < 9:
        o = new_colour(rng) if rng.random() < 0.5 else G100.simple_colour(rng)
        items = [cur_word(rng) + (" " + G100.pct_text(rng) if rng.random() < 0.4 else ""), o]
        rng.shuffle(items)
        v = "color-mix(in srgb, %s, %s)" % tuple(items)
    elif k == 9:
        v = mixed(rng)
    else:
        v = G100.simple_colour(rng)
    return v if G100.css_ok(v) else "red"


