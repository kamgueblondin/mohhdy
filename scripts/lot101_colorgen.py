PROPS = ["color", "background-color"]
TLN = ["--t", "--u", "--v"]


def kf_value(rng):
    k = rng.randrange(10)
    if k < 4:
        return new_colour(rng).lower()
    if k < 6:
        return G100.simple_colour(rng)
    if k == 6:
        return "currentcolor"
    if k == 7:
        return "color-mix(in srgb, currentcolor, %s)" % G100.simple_colour(rng)
    return G100.reg_colour(rng)


def keyframes(rng, name):
    offs = sorted(set(rng.sample([0, 2500, 5000, 7500, 10000, 3333, 6000], rng.randrange(1, 4))))
    if rng.random() < 0.4:
        offs = [o for o in offs if o not in (0, S)] or [5000]
    blocks, frames = [], {p: [] for p in PROPS}
    for o in offs:
        decls = []
        for p in PROPS:
            if rng.random() < 0.65 or (p == "background-color" and not decls):
                v = kf_value(rng)
                if not G100.css_ok(v):
                    v = "red"
                decls.append((p, v))
        blocks.append("%s { %s }" % (G98.offset_sel(rng, o), "; ".join("%s: %s" % d for d in decls)))
        for p, v in decls:
            L.CUR = L.BLACK
            m = model(A.colour_match, v)
            L.CUR = None
            if m is None:
                return None
            if m[1] and len(v) < 128:
                frames[p].append((o, v, None, None))
    return "@keyframes %s { %s }" % (name, " ".join(blocks)), frames


def tl_decls(rng, root):
    d = []
    if rng.random() < (0.85 if root else 0.5):
        names = rng.sample(TLN, rng.choice([1, 1, 2]))
        if root and "--t" not in names and rng.random() < 0.6:
            names[-1] = "--t"
        if rng.random() < 0.15:
            names.append("none")
        if rng.random() < 0.5:
            items = []
            for n in names:
                ax = rng.choice(["", "", " block", " y", "", " inline", " x"] if root else ["", " y"])
                items.append(n + ax)
            d.append(("scroll-timeline", ", ".join(items)))
        else:
            d.append(("scroll-timeline-name", ", ".join(names)))
            if rng.random() < 0.5:
                d.append(("scroll-timeline-axis", ", ".join(rng.choice(["block", "y", "y", "block", "inline", "x"])
                                                           for _ in range(rng.choice([1, 2])))))
        if rng.random() < 0.08:
            d.append((rng.choice(["scroll-timeline", "scroll-timeline-name"]), rng.choice(["initial", "unset", "inherit",
                                                                                          "--t --u", "auto"])))
    if rng.random() < 0.25:
        n = rng.choice(TLN)
        d.append(rng.choice([("view-timeline", n + rng.choice(["", " block", " inline"])), ("view-timeline-name", n)]))
        if rng.random() < 0.3:
            d.append(("view-timeline-axis", rng.choice(["y", "inline"])))
    return d


def anim_decls(rng):
    out = []
    n = rng.choice([1, 1, 2])
    items = []
    for _ in range(n):
        it = "%s %s" % (rng.choice(["k", "k", "j"]), rng.choice(["1000ms", "2s", "500ms", "1s", "1000ms", "0s"] if rng.random() < 0.3 else ["1000ms", "2s", "1s"]))
        if rng.random() < 0.6:
            it += " linear"
        if rng.random() < 0.3:
            it += " " + rng.choice(["500ms", "-500ms", "1s", "250ms"])
        if rng.random() < 0.2:
            it += " " + rng.choice(["2", "infinite", "0.5", "3", "2", "0.5"])
        if rng.random() < 0.25:
            it += " " + rng.choice(["both", "forwards", "backwards"])
        if rng.random() < 0.15:
            it += " " + rng.choice(["reverse", "alternate"])
        items.append(it)
    out.append(("animation", ", ".join(items)))
    tl = [rng.choice(TLN + ["--t"] * 6 + ["auto", "none", "--nobody"]) for _ in range(rng.choice([1, 1, 2]))]
    out.append(("animation-timeline", ", ".join(tl)))
    if rng.random() < 0.2:
        out.append(("animation-composition", rng.choice(["add", "accumulate", "replace"])))
    return out


def scroll_case(rng):
    rules, tls = [], {}
    for el, root in (("html", True), ("body", False), ("#o", False)):
        p = 0.9 if root else 0.25
        d = tl_decls(rng, root) if rng.random() < p else []
        tls[el] = T.tl_cascade(d)
        bodyc = []
        if el == "body" and rng.random() < 0.4:
            bodyc = [("color", new_colour(rng).lower() if rng.random() < 0.5 else G100.simple_colour(rng))]
            if not G100.css_ok(bodyc[0][1]):
                bodyc = []
        if d or bodyc:
            rules.append((el, bodyc + d))
    kfs = {p: {} for p in PROPS}
    kf_rules = []
    for name in (("k", "j") if rng.random() < 0.35 else ("k",)):
        got = keyframes(rng, name)
        if got is None:
            return None
        text, fr = got
        kf_rules.append(text)
        for p in PROPS:
            kfs[p][name] = fr[p]
    own = {}
    for p in PROPS:
        if rng.random() < 0.45:
            v = new_colour(rng).lower() if rng.random() < 0.5 else G100.simple_colour(rng)
            if G100.css_ok(v) and v != "transparent":
                own[p] = v
    adecls = anim_decls(rng)
    anims = M99.coord(G99.cascade([(100, adecls)]))
    ms = rng.choice([0, 0, 500, 1500])
    pm = rng.choice([0, S, 5000, 2500, 7500, rng.randrange(0, S + 1), rng.randrange(0, 101) * 100])
    chain = [(tls["#o"], False), (tls["body"], False), (tls["html"], True)]
    body_col = [v for el, d in rules if el == "body" for p, v in d if p == "color"]
    try:
        L.CUR = L.BLACK
        body_t = L.paint_text(body_col[0]) if body_col else None
        par_eff = G100.cur_of(body_t) if body_t else L.BLACK
        out, n_anim, n_comp = [], 0, 0
        L.CUR = par_eff
        for p in PROPS:
            town = L.paint_text(own[p]) if p in own else None
            base = town if town is not None else (body_t or "#000000") if p == "color" else "transparent"
            cur, animated, composed = T.stack_tl(L.ALTS, anims, kfs[p], base, ms, pm, chain)
            n_comp += int(composed)
            final = town
            if animated:
                n_anim += 1
                t = L.paint_text(cur)
                if t:
                    final = t
            if final:
                out.append("%s:%s" % (p, final))
            if p == "color":
                L.CUR = G100.cur_of(final) if final else par_eff
        n_sc = T.n_scroll(anims, set(kfs["color"]), chain, ms, pm)
    except T.Unsure:
        return None
    finally:
        L.CUR = None
    o_decls = [("color" if p == "color" else p, v) for p, v in own.items()] + adecls
    rules.append(("#o", o_decls))
    css = " ".join(kf_rules) + " " + " ".join("%s { %s }" % (el, "; ".join("%s: %s" % x for x in d)) for el, d in rules)
    style = ' style="%s"' % ";".join(out) if out else ""
    return css, ms, pm, style, n_anim, n_comp, n_sc


