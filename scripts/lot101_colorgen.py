#!/usr/bin/env python3
"""Lot 101 test generator: lab(), lch(), oklab(), oklch() and color() in
the reader colour and in registered <color> values, currentcolor in the
reader paint, the scroll and view timeline properties, and colour
animations on the scroll timeline of the root element.

Expectations come from scripts/lot101_colormodel.py (written from the
rules in docs/lot101_plan.md and CSS Color 4) with
scripts/lot100_colormodel.py and the lot 97 to 99 animation models, not
from the C sources. A colour the float model cannot place on one side of
a rounding boundary (lot101_colormodel.Unsure) is left out.

* test_lot101_color.c: wf_cssprop_color on the new functions, alone and
  inside color-mix(), with their alpha, case, spaces and invalid forms;
* test_lot101_mix.c: wf_cssprop_interp, wf_cssprop_add and
  wf_cssprop_match_prop on registered <color> values written with them;
* test_lot101_tl.c: wf_csstl_parse, wf_csstl_coord, wf_csstl_text and
  wf_cssanim_scroll_ms;
* test_lot101_paint.c: wf_site_prepare: color, background-color and the
  background shorthand with currentcolor (alone, in color-mix(), inherit)
  on three levels, with the new functions;
* test_lot101_scroll.c: wf_site_prepare_ext after wf_site_set_time and
  wf_site_set_scroll: color and background-color keyframes on named scroll
  and view timelines (the written style, col_animated, anim_scroll).

Run: python3 scripts/lot101_colorgen.py
"""
