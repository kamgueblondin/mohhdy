#!/usr/bin/env python3
"""Lot 90 test generator (reader sheet: backgrounds, list images, font
lengths in px, long values).

Expectations come from this file, not from the C sources. Values are
built from a structure (an image list, a position pair, a font-size
expression) and the generator writes both the CSS text, with random case,
spacing and quoting, and the normal form or the px value the structure
stands for. Invalid values are made by a known fault (a gradient that is
not the last layer, a 45deg angle, five stops, left right ...), so the
expected answer is "refused" without parsing the text.

The rules modelled:
* url(): the quotes go, the case of the path stays, keywords are lower case.
* a gradient keeps its arguments, lower case, each run of spaces one space,
  joined with ", ".
* a position comes back as "X Y" (top -> center top, 10px -> 10px center,
  top left -> left top).
* a size of two autos is "auto"; a repeat of two equal words is one word,
  repeat no-repeat is repeat-x, no-repeat repeat is repeat-y.
* the background shorthand gives one item per layer in each list, the
  initial value (none, 0% 0%, auto, repeat) where the layer said nothing; a
  list is written only when some layer gave that part.
* font sizes: em and % against the parent, rem against the root (html)
  font size, keywords as CSS absolute sizes. A calc() with only em (or %)
  is kept as an em token, with only px as a px token (the engine resolves
  them); em mixed with px, or anything with rem, is resolved by the reader
  in px with integer thousandths (floor of the magnitude, sign after) and
  written with at most two decimals (half away from zero).

Run: python3 scripts/lot90_gen.py
"""
import os
import random

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "tests", "unit", "userspace")

HEADER = "/* %s (generated by scripts/lot90_gen.py; expectations from that model). */\n"


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def rcase(rng, s):
    """random case for a keyword"""
    m = rng.randrange(4)
    if m == 0:
        return s
    if m == 1:
        return s.upper()
    return "".join(c.upper() if rng.random() < 0.3 else c for c in s)


def sp(rng):
    return rng.choice([" ", " ", " ", "  ", "\t", " \t "])


# ---------------------------------------------------------------- colours
NAMES = ["black", "white", "red", "green", "blue", "yellow", "gray", "grey", "navy", "teal", "orange",
         "purple", "silver", "maroon", "lime"]
READER_NAMES = {"black": 0x000000, "white": 0xffffff, "red": 0xff0000, "green": 0x008000, "blue": 0x0000ff,
                "gray": 0x808080, "grey": 0x808080, "navy": 0x000080}


def hexs(rng, n):
    return "".join(rng.choice("0123456789abcdefABCDEF") for _ in range(n))


def colour(rng, reader=False):
    """(text, normal form for a gradient, reader rgb or None)"""
    k = rng.randrange(6 if not reader else 3)
    if k == 0:
        h = hexs(rng, 3)
        v = int("".join(c * 2 for c in h), 16)
        return "#" + h, ("#" + h).lower(), v
    if k == 1:
        h = hexs(rng, 6)
        return "#" + h, ("#" + h).lower(), int(h, 16)
    if k == 2:
        if reader:
            n = rng.choice(sorted(READER_NAMES))
            return rcase(rng, n), n, READER_NAMES[n]
        n = rng.choice(NAMES)
        return rcase(rng, n), n, READER_NAMES.get(n)
    if k == 3:
        h = hexs(rng, 8)
        return "#" + h, ("#" + h).lower(), None
    if k == 4:
        a, b, c = rng.randrange(256), rng.randrange(256), rng.randrange(256)
        seps = [rng.choice([",", ", ", " ,", " "]) for _ in range(2)]
        t = "rgb(%d%s%d%s%d)" % (a, seps[0], b, seps[1], c)
        norm = " ".join(t.split())
        return rcase(rng, "rgb") + t[3:], norm.lower(), None
    a, b, c = rng.randrange(256), rng.randrange(256), rng.randrange(256)
    t = "rgba(%d, %d, %d, 0.%d)" % (a, b, c, rng.randrange(10))
    return t, t, None


# ---------------------------------------------------------------- urls
URL_CH = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789._-/"


def url(rng, maxlen=30):
    n = rng.randrange(1, maxlen + 1)
    p = "".join(rng.choice(URL_CH) for _ in range(n))
    q = rng.randrange(5)
    if q == 0:
        t = "url(%s)" % p
    elif q == 1:
        t = "url(%s%s%s)" % (sp(rng), p, sp(rng))
    elif q == 2:
        t = 'url("%s")' % p
    elif q == 3:
        t = "url('%s')" % p
    else:
        t = "URL(%s)" % p
    return t, "url(%s)" % p


def bad_url(rng):
    k = rng.randrange(5)
    if k == 0:
        return "url(a b.png)"
    if k == 1:
        return "url(" + "x" * 101 + ")"
    if k == 2:
        return "url()"
    if k == 3:
        return "url(a;b)"
    return "url(\"a.png)"


# ---------------------------------------------------------------- lengths
def length(rng, pct=True, neg=True):
    k = rng.randrange(6)
    if k == 0:
        return "0", "0"
    v = rng.randrange(0, 2000)
    s = ("-" if neg and rng.random() < 0.2 and v else "") + str(v)
    if rng.random() < 0.3:
        s += "." + str(rng.randrange(1, 100)).rstrip("0") if rng.random() < 0.5 else "." + str(rng.randrange(1, 10))
    unit = "%" if (pct and rng.random() < 0.4) else rcase(rng, "px")
    t = s + unit
    return t, t.lower()


def bad_length(rng):
    return rng.choice(["10em", "1.234px", "12", "px", "10000px", "1e3px", "10 px", "--5px"])


# ---------------------------------------------------------------- positions
XK = ["left", "right", "center"]
YK = ["top", "bottom", "center"]


def position(rng):
    """(text, normal form)"""
    xl = rng.random() < 0.4
    yl = rng.random() < 0.4
    x = length(rng) if xl else (lambda k: (rcase(rng, k), k))(rng.choice(XK))
    y = length(rng) if yl else (lambda k: (rcase(rng, k), k))(rng.choice(YK))
    norm = x[1] + " " + y[1]
    forms = [x[0] + sp(rng) + y[0]]
    if not xl and not yl:
        forms.append(y[0] + sp(rng) + x[0])
    if y[1] == "center":
        forms.append(x[0])
    if x[1] == "center" and not yl:
        forms.append(y[0])
    return rng.choice(forms), norm


def bad_position(rng):
    return rng.choice(["left right", "top bottom", "10px left", "top 10px", "left center top", "middle",
                       "10em", "right right", "bottom top", "1.234px 0"])


def sizev(rng):
    k = rng.randrange(5)
    if k == 0:
        w = rng.choice(["cover", "contain", "auto"])
        return rcase(rng, w), w
    if k == 1:
        return rcase(rng, "auto") + sp(rng) + rcase(rng, "auto"), "auto"
    a = length(rng, neg=False) if rng.random() < 0.8 else (rcase(rng, "auto"), "auto")
    if k == 2:
        return a
    b = length(rng, neg=False) if rng.random() < 0.7 else (rcase(rng, "auto"), "auto")
    if a[1] == "auto" and b[1] == "auto":
        return a[0] + " " + b[0], "auto"
    return a[0] + sp(rng) + b[0], a[1] + " " + b[1]


def bad_size(rng):
    return rng.choice(["-10px", "cover auto", "contain contain", "10deg", "auto -1px", "1px 2px 3px", "big"])


REP1 = ["repeat", "no-repeat", "space", "round"]


def repeatv(rng):
    if rng.random() < 0.4:
        w = rng.choice(REP1 + ["repeat-x", "repeat-y"])
        return rcase(rng, w), w
    a, b = rng.choice(REP1), rng.choice(REP1)
    t = rcase(rng, a) + sp(rng) + rcase(rng, b)
    if a == b:
        return t, a
    if (a, b) == ("repeat", "no-repeat"):
        return t, "repeat-x"
    if (a, b) == ("no-repeat", "repeat"):
        return t, "repeat-y"
    return t, a + " " + b


def bad_repeat(rng):
    return rng.choice(["repeat-x repeat", "repeat-y no-repeat", "tile", "repeat repeat repeat", "norepeat"])


# ---------------------------------------------------------------- gradients
SIDES = ["top", "right", "bottom", "left"]
EXT = ["closest-side", "closest-corner", "farthest-side", "farthest-corner"]


def stop(rng):
    t, n, _ = colour(rng)
    if rng.random() < 0.5:
        v = rng.randrange(0, 101)
        p = str(v)
        if v < 100 and rng.random() < 0.3:
            p += "." + str(rng.randrange(10))
        return t + sp(rng) + p + "%", n + " " + p + "%"
    return t, n


def gradient(rng):
    radial = rng.random() < 0.4
    args = []
    if radial:
        if rng.random() < 0.6:
            words = []
            if rng.random() < 0.6:
                words.append(rng.choice(["circle", "ellipse"]))
            if rng.random() < 0.5:
                words.append(rng.choice(EXT))
            rng.shuffle(words)
            if not words or rng.random() < 0.5:
                pt, pn = position(rng)
                words += ["at", pt]
            t = sp(rng).join(rcase(rng, w) if w not in ("at",) else w for w in words)
            args.append((t, " ".join(t.lower().split())))
    else:
        k = rng.randrange(4)
        if k == 1:
            s = rng.choice(SIDES)
            t = "to" + sp(rng) + rcase(rng, s)
            args.append((t, "to " + s))
        elif k == 2:
            d = 90 * rng.randrange(-4, 5)
            t = "%ddeg" % d
            args.append((t, t))
        elif k == 3:
            q = rng.choice(["0turn", "0.25turn", "0.5turn", "0.75turn", "1turn", "1.5turn"])
            args.append((q, q))
    for _ in range(rng.randrange(2, 5)):
        args.append(stop(rng))
    name = "radial-gradient(" if radial else "linear-gradient("
    t = rcase(rng, name[:-1]) + "(" + ("," + sp(rng)).join(a[0] for a in args) + ")"
    n = name + ", ".join(a[1] for a in args) + ")"
    return t, n


def bad_gradient(rng):
    return rng.choice([
        "linear-gradient(45deg, red, blue)", "linear-gradient(red)", "linear-gradient(red, blue, green, navy, black)",
        "linear-gradient(to top left, red, blue)", "linear-gradient(red 101%, blue)", "linear-gradient(red 10px, blue)",
        "linear-gradient(bluish, red)", "repeating-linear-gradient(red, blue)", "radial-gradient(circle circle, red, blue)",
        "radial-gradient(at, red, blue)", "radial-gradient(circle 10px, red, blue)", "linear-gradient(0.3turn, red, blue)",
        "linear-gradient(90.5deg, red, blue)", "radial-gradient(at left right, red, blue)", "linear-gradient(red, blue",
        "linear-gradient((red, blue)", "conic-gradient(red, blue)"])


def image_item(rng, last):
    k = rng.randrange(3 if last else 2)
    if k == 0:
        return rcase(rng, "none"), "none"
    if k == 1:
        return url(rng)
    return gradient(rng)


def join_list(rng, items):
    return ("," + sp(rng)).join(items)


# ------------------------------------------------------------ suite: values
def gen_values(rng):
    cases = []   # (func, input, expected or None)
    for _ in range(160):
        n = rng.randrange(1, 5)
        items = [image_item(rng, i == n - 1) for i in range(n)]
        norm = ", ".join(i[1] for i in items)
        cases.append(("img", join_list(rng, [i[0] for i in items]), norm if len(norm) <= 127 else None))
    for _ in range(60):
        k = rng.randrange(4)
        if k == 0:
            n = rng.randrange(1, 4)
            items = [url(rng)[0] for _ in range(n)] + [gradient(rng)[0]]
            rng.shuffle(items)
            if items[-1].lower().startswith(("linear", "radial")):
                items.reverse()
            if items[-1].lower().startswith(("linear", "radial")):
                items.append("none")
            cases.append(("img", ", ".join(items), None))
        elif k == 1:
            cases.append(("img", ", ".join(["none"] * 5), None))
        elif k == 2:
            cases.append(("img", bad_gradient(rng), None))
        else:
            cases.append(("img", url(rng)[0] + ", " + bad_url(rng), None))
    for _ in range(150):
        n = rng.randrange(1, 5)
        items = [position(rng) for _ in range(n)]
        cases.append(("pos", join_list(rng, [i[0] for i in items]), ", ".join(i[1] for i in items)))
    for _ in range(40):
        n = rng.randrange(0, 3)
        items = [position(rng)[0] for _ in range(n)] + [bad_position(rng)]
        rng.shuffle(items)
        cases.append(("pos", ", ".join(items), None))
    for _ in range(110):
        n = rng.randrange(1, 5)
        items = [sizev(rng) for _ in range(n)]
        cases.append(("size", join_list(rng, [i[0] for i in items]), ", ".join(i[1] for i in items)))
    for _ in range(30):
        items = [sizev(rng)[0] for _ in range(rng.randrange(0, 3))] + [bad_size(rng)]
        rng.shuffle(items)
        cases.append(("size", ", ".join(items), None))
    for _ in range(100):
        n = rng.randrange(1, 5)
        items = [repeatv(rng) for _ in range(n)]
        cases.append(("rep", join_list(rng, [i[0] for i in items]), ", ".join(i[1] for i in items)))
    for _ in range(25):
        items = [repeatv(rng)[0] for _ in range(rng.randrange(0, 3))] + [bad_repeat(rng)]
        rng.shuffle(items)
        cases.append(("rep", ", ".join(items), None))
    for _ in range(40):
        if rng.random() < 0.3:
            cases.append(("limg", rcase(rng, "none"), "none"))
        else:
            t, n = url(rng)
            cases.append(("limg", t, n))
    for _ in range(15):
        cases.append(("limg", rng.choice([bad_url(rng), "linear-gradient(red, blue)", "url(a) url(b)", "nothing"]), None))
    for _ in range(60):
        t, n, _ = colour(rng)
        cases.append(("col", t, "1"))
    for c in ["#12", "#12345", "#ggg", "rgb(1, 2)", "rgb(1, 2, 3, 4, 5)", "bluish", "rgb(a, b, c)", "hsl(1, 2%, 3%)", "#", ""]:
        cases.append(("col", c, None))
    for _ in range(60):
        t, n = gradient(rng)
        cases.append(("grad", t, n if len(n) <= 127 else None))
    return cases


def write_values(rng):
    cases = gen_values(rng)
    o = [HEADER % "Lot 90: background and list image values in their normal form",
         '#include "../../framework/unity.h"', "#include <string.h>", '#include "wf_cssbg.h"', "",
         "static char g_o[WF_CSSBG_VAL];", "",
         "static const char *run(const char *f, const char *v) {",
         "    int r;",
         "    if (!strcmp(f, \"img\")) r = wf_cssbg_image(v, g_o, (int)sizeof(g_o));",
         "    else if (!strcmp(f, \"pos\")) r = wf_cssbg_position(v, g_o, (int)sizeof(g_o));",
         "    else if (!strcmp(f, \"size\")) r = wf_cssbg_size(v, g_o, (int)sizeof(g_o));",
         "    else if (!strcmp(f, \"rep\")) r = wf_cssbg_repeat(v, g_o, (int)sizeof(g_o));",
         "    else if (!strcmp(f, \"limg\")) r = wf_cssbg_list_image(v, g_o, (int)sizeof(g_o));",
         "    else if (!strcmp(f, \"grad\")) r = wf_cssbg_gradient(v, (int)strlen(v), g_o, (int)sizeof(g_o));",
         "    else { r = wf_cssbg_color(v, (int)strlen(v)); return r ? \"1\" : \"REFUSED\"; }",
         "    if (r <= 0) return g_o[0] ? \"REFUSED BUT WRITTEN\" : \"REFUSED\";",
         "    if (r != (int)strlen(g_o)) return \"BAD LENGTH\";",
         "    return g_o;",
         "}", ""]
    names = []
    per = 6
    for b in range(0, len(cases), per):
        name = "test_l90_val_%d" % (b // per)
        names.append(name)
        o.append("static void %s(void) {" % name)
        for f, v, e in cases[b:b + per]:
            o.append("    TEST_ASSERT_EQUAL_STRING(%s, run(%s, %s));" % (cstr(e if e is not None else "REFUSED"), cstr(f), cstr(v)))
        o.append("}")
        o.append("")
    o += ["int main(void) {", "    unity_init();"]
    o += ["    RUN_TEST(%s);" % n for n in names]
    o += ["    unity_print_results();", "    unity_cleanup();", "    return unity_stats.tests_failed == 0 ? 0 : 1;", "}", ""]
    open(os.path.join(OUT, "test_lot90_bgval.c"), "w").write("\n".join(o))
    return len(cases)


# ------------------------------------------------------- suite: shorthand
def shorthand_layer(rng, last, reader_colour=True):
    """components of one layer: returns (words text list, parts dict)"""
    comps = []
    parts = {}
    if rng.random() < 0.7:
        t, n = image_item(rng, last)
        comps.append([t])
        parts["image"] = n
    if rng.random() < 0.5:
        t, n = repeatv(rng)
        comps.append([t])
        parts["repeat"] = n
    if rng.random() < 0.6:
        t, n = position(rng)
        group = [t]
        parts["position"] = n
        if rng.random() < 0.5:
            st, sn = sizev(rng)
            group.append(rng.choice(["/", " / ", "/ ", " /"]) + st if True else st)
            parts["size"] = sn
        comps.append(["".join(group) if len(group) == 1 else group[0] + group[1]])
    if rng.random() < 0.2:
        comps.append([rcase(rng, rng.choice(["scroll", "fixed", "local"]))])
    if rng.random() < 0.2:
        b = rng.choice(["border-box", "padding-box", "content-box"])
        comps.append([rcase(rng, b)])
        parts["box"] = b          # Lot 91: one box keyword sets the origin and the clip
    if last and rng.random() < 0.6:
        t, n, v = colour(rng, reader=reader_colour)
        comps.append([t])
        parts["colour"] = (n, v)
    if not comps:
        t, n = url(rng)
        comps.append([t])
        parts["image"] = n
    rng.shuffle(comps)
    return sp(rng).join(c[0] for c in comps), parts


def shorthand_expect(layers):
    """Lot 91 (converted): None when the layers end with different origin
    or clip boxes (the engine has one of each per element): the shorthand
    is refused. Lot 90 accepted box keywords and passed nothing on."""
    out = {}
    for key, init in (("image", "none"), ("position", "0% 0%"), ("size", "auto"), ("repeat", "repeat")):
        if any(key in p for p in layers):
            out[key] = ", ".join(p.get(key, init) for p in layers)
    if "colour" in layers[-1]:
        out["colour"] = layers[-1]["colour"]
    boxes = set((p["box"], p["box"]) if "box" in p else ("padding-box", "border-box") for p in layers)
    if len(boxes) > 1:
        return None
    if any("box" in p for p in layers):
        origin, clip = boxes.pop()
        out["origin"], out["clip"] = origin, clip
    return out


def bad_shorthand(rng):
    k = rng.randrange(8)
    good = shorthand_layer(rng, True)[0]
    if k == 0:
        return "red url(a.png), " + good                     # colour not in the last layer
    if k == 1:
        return "url(a.png) url(b.png)"
    if k == 2:
        return "linear-gradient(red, blue), " + good          # gradient not last
    if k == 3:
        return "/ cover url(a.png)"
    if k == 4:
        return "no-repeat center repeat url(a.png)"
    if k == 5:
        return ", ".join(["url(a.png)"] * 5)
    if k == 6:
        return "url(a.png) center 10px 20px"
    return "url(a.png) red blue"


def write_sheet(rng):
    o = [HEADER % "Lot 90: the background shorthand split into its longhands, and the cascade of those longhands in the reader sheet",
         '#include "../../framework/unity.h"', "#include <string.h>", '#include "wf_sitecss.h"', '#include "wf_cssbg.h"', "",
         "static wf_site_t g_d;", "static char g_o[1400];", "static wf_cssbg_t g_bg;", "",
         "static const char *style_of(const char *html, const char *id) {",
         "    int i;",
         "    if (wf_site_prepare(&g_d, html, (int)strlen(html)) != 0) return \"PREPARE FAILED\";",
         "    g_o[0] = 0;",
         "    for (i = 0; i < g_d.nnodes; i++)",
         "        if (!strcmp(g_d.node[i].id, id)) { wf_site_style_attr(&g_d, g_d.node[i].start, g_o, (int)sizeof(g_o)); return g_o; }",
         "    return \"NO SUCH ID\";",
         "}", ""]
    names = []
    idx = 0
    # 1. wf_cssbg_shorthand directly
    for _ in range(170):
        n = rng.choice([1, 1, 2, 2, 3, 4])
        layers = [shorthand_layer(rng, i == n - 1, reader_colour=False) for i in range(n)]
        text = ("," + sp(rng)).join(l[0] for l in layers)
        exp = shorthand_expect([l[1] for l in layers])
        # Lot 91: refused too when the layers end in different boxes
        too_long = exp is None or any(len(v) > 127 for k, v in exp.items() if k != "colour")
        name = "test_l90_short_%d" % idx
        idx += 1
        names.append(name)
        o.append("static void %s(void) {" % name)
        if too_long:
            # a list longer than 127 bytes: refused, never cut
            o += ["    TEST_ASSERT_EQUAL(0, wf_cssbg_shorthand(%s, &g_bg));" % cstr(text),
                  "    TEST_ASSERT_EQUAL(0, g_bg.layers);", "}", ""]
            continue
        o.append("    TEST_ASSERT_EQUAL(1, wf_cssbg_shorthand(%s, &g_bg));" % cstr(text))
        o.append("    TEST_ASSERT_EQUAL(%d, g_bg.layers);" % n)
        for key, init, fld in (("image", "none", "image"), ("position", "0% 0%", "position"), ("size", "auto", "size"),
                               ("repeat", "repeat", "repeat"), ("origin", "padding-box", "origin"),
                               ("clip", "border-box", "clip")):
            if key in exp:
                o.append("    TEST_ASSERT_EQUAL(1, g_bg.has_%s);" % fld)
                o.append("    TEST_ASSERT_EQUAL_STRING(%s, g_bg.%s);" % (cstr(exp[key]), fld))
            else:
                o.append("    TEST_ASSERT_EQUAL(0, g_bg.has_%s);" % fld)
                o.append("    TEST_ASSERT_EQUAL_STRING(%s, g_bg.%s);" %
                         (cstr(init if fld in ("origin", "clip") else ", ".join([init] * n)), fld))
        o.append("    TEST_ASSERT_EQUAL_STRING(%s, g_bg.color);" % cstr(exp["colour"][0] if "colour" in exp else ""))
        o.append("}")
        o.append("")
    for _ in range(40):
        text = bad_shorthand(rng)
        name = "test_l90_short_%d" % idx
