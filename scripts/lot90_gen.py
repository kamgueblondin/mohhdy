def mul_milli(a, n):
    neg = (a < 0) != (n < 0)
    r = abs(a) * abs(n) // 1000
    return -r if neg else r


def div_milli(a, n):
    neg = (a < 0) != (n < 0)
    r = abs(a) * 1000 // abs(n)
    return -r if neg else r


def token(milli, unit):
    v = (abs(milli) + 5) // 10
    whole, frac = v // 100, v % 100
    s = ("-" if milli < 0 and v else "") + str(whole)
    if frac:
        s += "." + str(frac // 10)
        if frac % 10:
            s += str(frac % 10)
    return s + unit


def num_milli(s):
    if "." in s:
        a, b = s.split(".")
        b = (b + "000")[:3]
    else:
        a, b = s, "000"
    neg = a.startswith("-")
    a = a.lstrip("-") or "0"
    v = int(a) * 1000 + int(b)
    return -v if neg else v


class L:
    """a length term: number text and unit"""

    def __init__(self, num, unit):
        self.num, self.unit = num, unit

    def text(self):
        return self.num + self.unit

    def has(self):
        return {self.unit}

    def px(self, em, rem):
        n = num_milli(self.num)
        u = self.unit
        if u == "px":
            return n
        if u == "pt":
            return div_milli(mul_milli(n, 4000), 3000)
        if u == "em":
            return mul_milli(n, em)
        if u == "%":
            return mul_milli(int(n / 100), em)
        if u == "rem":
            return mul_milli(n, rem)
        raise AssertionError(u)

    def legacy(self):
        """(px part, em part) with rem at 16 px"""
        n = num_milli(self.num)
        u = self.unit
        if u == "px":
            return (n, 0)
        if u == "pt":
            return (div_milli(mul_milli(n, 4000), 3000), 0)
        if u == "rem":
            return (mul_milli(n, 16000), 0)
        if u == "em":
            return (0, n)
        if u == "%":
            return (0, int(n / 100))
        raise AssertionError(u)


class Add:
    def __init__(self, a, op, b):
        self.a, self.op, self.b = a, op, b

    def text(self):
        return "%s %s %s" % (self.a.text(), self.op, self.b.text())

    def has(self):
        return self.a.has() | self.b.has()

    def px(self, em, rem):
        x, y = self.a.px(em, rem), self.b.px(em, rem)
        return x + y if self.op == "+" else x - y

    def legacy(self):
        x, y = self.a.legacy(), self.b.legacy()
        if self.op == "+":
            return (x[0] + y[0], x[1] + y[1])
        return (x[0] - y[0], x[1] - y[1])


class Fn:
    def __init__(self, name, args):
        self.name, self.args = name, args

    def text(self):
        return "%s(%s)" % (self.name, ", ".join(a.text() for a in self.args))

    def has(self):
        s = set()
        for a in self.args:
            s |= a.has()
        return s

    def px(self, em, rem):
        v = [a.px(em, rem) for a in self.args]
        if self.name == "min":
            return min(v)
        if self.name == "max":
            return max(v)
        if self.name == "clamp":
            r = v[1]
            if v[2] < r:
                r = v[2]
            if v[0] > r:
                r = v[0]
            return r
        raise AssertionError

    def legacy(self):
        v = [a.legacy() for a in self.args]
        pxs = any(x[0] for x in v)
        ems = any(x[1] for x in v)
        if pxs and ems:
            return None
        k = 1 if ems else 0
        keys = [x[k] for x in v]
        if self.name == "min":
            i = min(range(len(v)), key=lambda j: (keys[j], j))
            # first of the smallest: C keeps the first unless a later one is strictly smaller
            best = 0
            for j in range(1, len(v)):
                if keys[j] < keys[best]:
                    best = j
            return v[best]
        if self.name == "max":
            best = 0
            for j in range(1, len(v)):
                if keys[j] > keys[best]:
                    best = j
            return v[best]
        r = v[1]
        if v[2][k] < r[k]:
            r = v[2]
        if v[0][k] > r[k]:
            r = v[0]
        return r


def calc_text(e):
    if isinstance(e, Fn):
        return e.text()
    return "calc(%s)" % e.text()


def rnum(rng, lo, hi, dec=True):
    v = rng.randrange(lo, hi)
    s = str(v)
    if dec and rng.random() < 0.4:
        s += "." + rng.choice(["5", "25", "75", "1", "2"])
    return s


def font_value(rng):
    """(css text, model) for a font-size declaration"""
    k = rng.randrange(10)
    if k == 0:
        return rng.choice(["small", "medium", "large", "x-large", "xx-small", "smaller", "larger"]), ("kw", None)
    if k == 1:
        n = rnum(rng, 8, 40)
        return n + "px", ("plain", L(n, "px"))
    if k == 2:
        n = rnum(rng, 0, 3)
        if num_milli(n) == 0:
            n = "1.5"
        return n + "em", ("plain", L(n, "em"))
    if k == 3:
        n = str(rng.randrange(50, 250))
        return n + "%", ("plain", L(n, "%"))
    if k == 4:
        n = rnum(rng, 0, 3)
        if num_milli(n) == 0:
            n = "1.25"
        return n + "rem", ("plain", L(n, "rem"))
    if k == 5:
        e = Add(L(rnum(rng, 0, 2), "em"), rng.choice(["+", "-"]), L(rnum(rng, 1, 9), "px"))
        return calc_text(e), ("calc", e)
    if k == 6:
        e = Add(L(rnum(rng, 0, 2), "rem"), "+", L(rnum(rng, 0, 9), "px"))
        return calc_text(e), ("calc", e)
    if k == 7:
        e = Fn("clamp", [L(rnum(rng, 0, 2), "rem"), L(rnum(rng, 1, 3), "em"), L(rnum(rng, 2, 4), "rem")])
        return calc_text(e), ("calc", e)
    if k == 8:
        e = Fn(rng.choice(["min", "max"]), [L(rnum(rng, 1, 3), "em"), L(rnum(rng, 10, 30), "px")])
        return calc_text(e), ("calc", e)
    e = Add(L(rnum(rng, 1, 2), "em"), "+", L(rnum(rng, 0, 1), "em"))
    return calc_text(e), ("calc", e)


KW = {"xx-small": 9000, "x-small": 10000, "small": 13000, "medium": 16000, "large": 18000, "x-large": 24000,
      "xx-large": 32000, "xxx-large": 48000}


def legacy_token(e):
    """the Lot 89 path: one part, rem at 16 px; None when it does not apply"""
    if "rem" in e.has():
        return None
    v = e.legacy()
    if v is None or (v[0] and v[1]):
        return None
    if v[1]:
        return token(v[1], "em"), ("em", v[1])
    return token(v[0], "px"), ("px", v[0])


def fsize_ok(tok):
    """the font-size bounds of a written token (fsize_tok)"""
    import re
    m = re.match(r"^(-?\d+)(?:\.(\d{1,2}))?(px|pt|em|rem|%)$", tok)
    if not m:
        return False
    v = int(m.group(1)) * 1000 + int((m.group(2) or "").ljust(3, "0"))
    mx = {"px": 96000, "pt": 72000, "em": 6000, "rem": 6000, "%": 600000}[m.group(3)]
    return 0 < v <= mx


def font_eval(text, model, parent, root, is_root):
    """(written token or None, the element's font size)"""
    rem = 16000 if is_root else root
    kind, e = model
    if kind == "kw":
        if text == "smaller":
            f = parent * 5 // 6
        elif text == "larger":
            f = parent * 6 // 5
        else:
            f = KW[text]
        return text, f
    if kind == "plain":
        if not fsize_ok(text):
            return None, parent
        v = e.px(parent, rem)
        f = v if 1 <= v <= 96000 else parent
        if e.unit == "rem" and rem != 16000:
            if 1 <= v <= 96000:
                return token(v, "px"), f
            return None, parent
        return text, f
    lt = legacy_token(e)
    if lt is not None:
        tok, (u, m) = lt
        if not fsize_ok(tok):
            return None, parent
        v = mul_milli(num_milli(tok[:-2]), parent) if u == "em" else num_milli(tok[:-2])
        return tok, (v if 1 <= v <= 96000 else parent)
    v = e.px(parent, rem)
    if 1 <= v <= 96000:
        return token(v, "px"), v
    return None, parent


