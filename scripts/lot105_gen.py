        "    wf_geom_box_t *b = &g_g.box[k];",
        "    memset(b, 0, sizeof(*b));",
        "    b->ok = 1; b->root = (unsigned char)root; b->bvert = (unsigned char)bvert;",
        "    b->b_off = b_off; b->b_size = b_size; b->i_off = i_off; b->i_size = i_size;",
        "    b->vp_b = vp_b; b->vp_i = vp_i; b->rg_b = rg_b; b->rg_i = rg_i;",
        "    g_g.n++;",
        "}", "",
        "/* its scroller mark, scroll offsets and own scroller state */",
        "static void geo2(int k, int sm, int sc_b, int sc_i, int sv, int s_vp, int s_sc, int s_rg) {",
        "    wf_geom_box_t *b = &g_g.box[k];",
        "    b->sm = sm; b->sc_b = sc_b; b->sc_i = sc_i; b->sv = (unsigned char)sv;",
        "    b->s_vp = s_vp; b->s_sc = s_sc; b->s_rg = s_rg;",
        "}", "",
        "static void prep3(const char *css, int ms, int pm, int gui, int with_geom) {",
