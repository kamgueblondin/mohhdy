#!/usr/bin/env python3
"""Lot 105 test generator: box scrollers as scroll and view timeline
sources and the GUI scroll position (the overflow and height cascade, the
reader sheet with box scroller geometry, the engine geometry of box
scrollers).

Expectations come from scripts/lot105_model.py (written from the rules in
docs/lot105_plan.md, CSS Overflow 3 and CSS Scroll-driven Animations 1)
with the lot 97 to 104 models, and for test_lot105_geom.c from the block
layout and box scrolling rules of the engine documented in lots 74 and
104 (no margin collapsing; a click on a scrollbar track at rel of its
height h scrolls to floor(range * rel / h)), not from the C sources. A
colour the float model cannot place on one side of a rounding boundary
(lot101_colormodel.Unsure), or a height near a px edge, is left out.

* test_lot105_overflow.c: overflow, overflow-x, overflow-y and height on
  the elements of a page (wf_site_box_scroller, wf_site_scroller_of, the
  height kept, the style the reader passes on for a box scroller a
  timeline reads);
* test_lot105_sheet.c: wf_site_prepare_ext after wf_site_set_geom,
  wf_site_set_scroll and wf_site_set_scroll_gui: colour keyframes on #i
  driven by scroll(), view() and named timelines with box scrollers (#o,
  #b) around it (the written styles, anim_scroll, anim_view, anim_box,
  anim_idle, geom_need, geom_used, geom_live);
* test_lot105_geom.c: we_geom_feed after the layout of stacked boxes and
  a box scroller scrolled by a click on its track, with the root scrolled
  (sv, sm, s_vp, s_sc, s_rg, sc_y).

Run: python3 scripts/lot105_gen.py
"""
