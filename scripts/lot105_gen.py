VW, VH = 320, 480


def geom_case(rng):
    """stacked boxes, one a box scroller with children scrolled by a click
    on its track, the root scrolled: the body html, the click, the root
    scroll and the expected boxes {mark: text}"""
    n = rng.randrange(1, 5)
    used = set()

    def mark():
        k = rng.randrange(0, 192)
        while k in used:
            k = rng.randrange(0, 192)
        used.add(k)
        return k
    sk = rng.randrange(n)
    html, exp, y, click, scr_text = [], {}, 0, None, None
    for j in range(n):
        s = G4.box_style(rng)
        bb = 2 * (s["p"] + s["b"])
        x0, w0 = s["ml"], VW - s["ml"] - s["mr"]
        top = y + s["mt"]
        m = mark() if rng.random() < 0.8 else None
        if j == sk:
            s["h"] = rng.choice([50, 100, 120, 200])
            sm = mark() if rng.random() < 0.75 else None
            sid = "wg%d" % sm if sm is not None else "sx"
            cy, kids, inner = 0, [], ""
            for _ in range(rng.randrange(1, 5)):
                c = G4.box_style(rng)
                c["p"] = c["b"] = 0
                c["h"] = rng.choice([20, 50, 100, 150, rng.randrange(0, 300)])
                cm = mark() if rng.random() < 0.85 else None
                ci = cy + c["mt"]
                kids.append((cm, c, ci))
                cy += G4.outer_h(c)
                inner += "<div%s style='%s'></div>" % (" id=wg%d" % cm if cm is not None else "", G4.css_of(c))
            crange = max(0, max(ci + c["h"] for _, c, ci in kids) - s["h"])
            track_h = s["h"] + 2 * s["p"]
            rel = rng.choice([0, track_h // 2, track_h - 1, rng.randrange(0, track_h)])
            tx = x0 + w0 - s["b"] - 6 + rng.randrange(0, 6)
            click = (tx, top + s["b"] + rel)
            sc = crange * rel // track_h if crange > 0 else 0
            for cm, c, ci in kids:
                if cm is not None:
                    cw = w0 - bb - c["ml"] - c["mr"]
                    exp[cm] = "0 1 %d+%d %d+%d vp %d/%d sc %d/0 rg %d/0 sv 0 sm %d own 0/0/0" % (
                        ci, c["h"], c["ml"], cw, s["h"], w0 - bb, sc, crange, (sm + 1) if sm is not None else 0)
            html.append("<div id=%s style='%s'>%s</div>" % (sid, G4.css_of(s, ";overflow:auto"), inner))
            if sm is not None:
                scr_text = (sm, top, s["h"] + bb, x0, w0, "sv 1 sm 0 own %d/%d/%d" % (s["h"], sc, crange))
            want_click = crange > 0
            click = (click, want_click, sc)
        else:
            html.append("<div%s style='%s'></div>" % (" id=wg%d" % m if m is not None else "", G4.css_of(s)))
            if m is not None:
                exp[m] = (top, s["h"] + bb, x0, w0, "sv 0 sm 0 own 0/0/0")
        y += G4.outer_h(s)
    page_h = y
    rg = max(0, page_h - VH)
    scroll = rng.choice([0, 0, 50, rg, rg // 2, rng.randrange(0, rg + 100)])
    sy = min(max(scroll, 0), rg)
    if scr_text:
        exp[scr_text[0]] = scr_text[1:]
    out = {}
    for m_, e in exp.items():
        if isinstance(e, tuple):
            out[m_] = "1 1 %d+%d %d+%d vp %d/%d sc %d/0 rg %d/0 %s" % (e[0], e[1], e[2], e[3], VH, VW, sy, rg, e[4])
        else:
            out[m_] = e
    return "".join(html), out, page_h, rg, click, scroll, sy


