# ------------------------------------------------------------- comparable arguments
def dom_lin(rng):
    """a leaf: whole px, whole percentages or both, small so that leaves
    are often comparable"""
    k = rng.randrange(5)
    if k == 0:
        return "%d%%" % rng.randrange(0, 60)
    if k == 1:
        return "%dpx" % rng.randrange(0, 80)
    if k == 2:
        return "calc(%d%% + %dpx)" % (rng.randrange(0, 60), rng.randrange(0, 80))
    if k == 3:
        return "calc(%d%% - %dpx)" % (rng.randrange(0, 60), rng.randrange(0, 80))
    return "%dem" % rng.randrange(1, 5)


def dom_val(rng, depth=0):
    k = rng.random()
    if depth >= 2 or k < 0.5:
        return dom_lin(rng)
    f = rng.choice(["min", "max", "min", "max", "clamp"])
    n = 3 if f == "clamp" else rng.choice([2, 3, 3, 4, 5])
    inner = "%s(%s)" % (f, ", ".join(dom_val(rng, depth + 1) for _ in range(n)))
    if k < 0.85:
        return inner
    if k < 0.93:
        return "calc(%s + %s)" % (inner, dom_lin(rng))
    return "calc(%s * %s)" % (inner, rng.choice(["2", "-1", "0.5", "3"]))


def write_dom():
    rng = random.Random(11202)
    cases, seen, mixed = [], set(), 0
    while len(cases) < 160:
        s = dom_val(rng, 0)
        if not s.startswith(("min(", "max(", "clamp(", "calc(")) or s in seen or len(s) > 120:
            continue
        seen.add(s)
        em, rem = rng.choice([10, 16, 20]), 16
        try:
            r = M9.math_box(s, em, rem, True)
            save = M11._Mix.op
            M11._Mix.op = M11._Mix.op_lot111
            try:
                old = M9.math_box(s, em, rem, True)
            finally:
                M11._Mix.op = save
        except UNSURE:
            continue
        if r == old and rng.random() < 0.85:
            continue            # mostly values where comparable leaves go
        if r is None:
            e = "-1 0 "
        elif r[0] == "px":
            e = "1 %d " % (r[1] * 1000)
        else:
            e = "2 0 " + r[1]
            mixed += 1
            G11.mix_check(s, r[1], em, rem)
        cases.append(["TEST_ASSERT_EQUAL_STRING(%s, mb(%s, %d, %d));" % (cstr(e), cstr(s), em * 1000, rem * 1000)])
    o = [HEADER % "Lot 112: comparable arguments of mixed min()/max() in wf_css_math_box"] + [
        '#include "../../framework/unity.h"', "#include <string.h>", "#include <stdio.h>", '#include "wf_cssmath.h"', "",
        "static char g_o[160];", "",
        "/* \"r px out\" of wf_css_math_box at 640 x 480 */",
        "static const char *mb(const char *s, int em, int rem) {",
        "    char out[64];",
        "    int px = -7, r = wf_css_math_box(s, 640, 480, em, rem, &px, out, (int)sizeof(out));",
        "    snprintf(g_o, sizeof(g_o), \"%d %d %s\", r, px, out);",
        "    return g_o;",
        "}", ""]
    names = chunks(o, "test_l112_dom", cases, 20)
    finish(o, names, "test_lot112_dom.c")
    return "%d (%d written)" % (len(cases), mixed)


