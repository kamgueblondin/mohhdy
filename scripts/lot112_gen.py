"""Lot 112 test generator: line-height passed to the engine (with
percentages and numbers in math functions, rlh, all, revert and
revert-layer, var()), comparable arguments of a mixed min()/max(), and
var() and math functions in opacity keyframes and @starting-style.

Expectations come from scripts/lot112_model.py with the lot 97 to 111
models (written from the specifications), not from the C sources. A value
the exact model cannot place (Unsure) is left out. The suites are kept
small: each case is one new behaviour.

* test_lot112_lh.c: the line heights the reader keeps, the line-height it
  passes the engine in the style attribute, and a box scroller height in
  lh and rlh;
* test_lot112_lflow.c: one-line paragraphs laid out by the engine, whose
  heights are the line heights the reader passed (or the engine's normal);
* test_lot112_dom.c: wf_css_math_box with comparable arguments in mixed
  min()/max() (dropped), checked against the engine's math as well;
* test_lot112_opk.c: opacity keyframes and @starting-style values with
  var() (the element's custom properties) and math functions;
* test_lot112_ckf.c: color and background-color keyframes with var() of
  the animated element (its own custom properties or inherited ones).

Run: python3 scripts/lot112_gen.py
"""
