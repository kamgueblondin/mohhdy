# ------------------------------------------------------ colour keyframes
CDEF = ["#ff0000", "#00ff00", "#0000ff", "#336699", "rgb(10 20 30)", "white", "#80808080", "12px", "nosuch",
        "rgb(200 100 0 / 50%)", "teal", "transparent"]
CKF = ["var(--c)", "var(--d)", "var(--c, #00ff00)", "var(--d, var(--c))", "var(--zz)", "var(--zz, #102030)",
       "#ffffff", "#000000", "var(--c) !important", "rgb(var(--n) 0 0)", "var(--c)var(--d)"]
NDEF = ["255", "128", "1px", "0"]


def ckf_case(rng):
    defs = []
    for el in ("body", "#o"):
        for name in ("--c", "--d"):
            if rng.random() < 0.45:
                defs.append((el, name, rng.choice(CDEF)))
        if rng.random() < 0.25:
            defs.append((el, "--n", rng.choice(NDEF)))
    env_by = {}
    for el, name, v in defs:
        env_by.setdefault(el, {})[name] = v
    # the element's custom properties: inherited from body, its own on top
    env = dict(env_by.get("body", {}))
    env.update(env_by.get("#o", {}))
    prop = rng.choice(G100.PROPS)
    own = None
    odecls = []
    if rng.random() < 0.5:
        own = rng.choice(["#000000", "#204060", "rgb(0 0 255)", "silver"])
        odecls.append((prop, own))
    offs = sorted(rng.sample([0, 5000, 10000, 2500], rng.randrange(1, 4)))
    blocks, frames = [], []
    for o in offs:
        v = rng.choice(CKF)
        blocks.append("%s { %s: %s }" % (G98.offset_sel(rng, o), prop, v))
        LC.CUR, cur = LC.BLACK, LC.CUR
        raw = M.col_frame(v, env, A97.colour_match)
        LC.CUR = cur
        if raw is not None:
            frames.append((o, raw, None, None))
    adecls = [("animation", rng.choice(["k 1s linear", "k 2s linear", "k 1s linear 250ms", "k 1s ease-in"]))]
    anims = M99.coord(G99.cascade([(100, adecls)]))
    odecls += adecls
    ms = rng.choice([0, 250, 500, 750, 1200, rng.randrange(0, 2000)])
    LC.CUR = LC.BLACK      # currentcolor in color is the parent's colour (black)
    town = LC.paint_text(own.lower()) if own else None
    base = town if town is not None else ("#000000" if prop == "color" else "transparent")
    final = town
    cur, animated, composed = LC.col_value(anims, {"k": frames}, base, ms, False)
    if animated:
        t = LC.paint_text(cur)
        if t:
            final = t
    LC.CUR = None
    blocks2 = ["%s { %s: %s }" % (el, n, v) for el, n, v in defs]
    blocks2.append("#o { %s }" % "; ".join("%s: %s" % d for d in odecls))
    rng.shuffle(blocks2)
    css = " ".join(["@keyframes k { %s }" % " ".join(blocks)] + blocks2)
    so = ' style="%s:%s"' % (prop, final) if final else ""
    return css, ms, so, int(animated)


