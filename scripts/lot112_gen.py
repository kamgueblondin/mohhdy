        "    snprintf(g_s, sizeof(g_s), \"%s %s %s\", a, b, c);",
        "    return g_s;",
        "}", "",
        "/* the height (px) in the style passed for the element with that id,",
        " * -1 when it has none */",
        "static int height_of(const char *id) {",
        "    int i, v = -1;",
        "    const char *h;",
        "    g_o[0] = 0;",
        "    for (i = 0; i < g_d.nnodes; i++)",
