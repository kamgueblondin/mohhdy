START = ["var(--a)", "var(--b)", "var(--u, 0.5)", "var(--u)", "calc(0.25 * 2)", "0", "min(20%, 0.4)"]


def opk_case(rng):
    env_by, defs = {}, []
    for el in ("body", "#o"):
        for name in ("--a", "--b"):
            if rng.random() < 0.4:
                v = rng.choice(ADEF)
                defs.append((el, name, v))
    for el, name, v in defs:
        env_by.setdefault(el, {})[name] = v
    env = dict(env_by.get("body", {}))
    env.update(env_by.get("#o", {}))
    rules, kfs, start, tl, anims = [], {}, None, [], []
    use_anim = rng.random() < 0.65
    odecls = []
    if rng.random() < 0.4:
        ov = rng.choice(["0.5", "var(--a)", "80%", "calc(0.3 + 0.3)"])
        odecls.append(("opacity", ov))
    if use_anim:
        offs = sorted(rng.sample([0, 5000, 10000, 2500], rng.randrange(1, 4)))
        blocks, frames = [], []
        for o in offs:
            v = rng.choice(OPK_VALS)
            blocks.append("%s { opacity: %s }" % (G98.offset_sel(rng, o), v))
            n = M.op_frame(v, env)
            if n is not None:
                frames.append((o, M10.op_text(n), None, None))
        rules.append("@keyframes k { %s }" % " ".join(blocks))
        kfs["k"] = frames
        adecls = [("animation", rng.choice(["k 1s linear", "k 2s linear", "k 1s linear 250ms", "k 1s ease-in"]))]
        anims = M99.coord(G99.cascade([(100, adecls)]))
        odecls += adecls
    else:
        sv = rng.choice(START)
        rules.append("@starting-style { #o { opacity: %s } }" % sv)
        got = M11.op_value(sv, env)
        if got is not None and got[0] != 3:
            start = got[1]
        tdecls = [("transition", rng.choice(["opacity 1s linear", "opacity 2s linear", "all 1s ease-in"]))]
        tl = M98.coord(False, G98.cascade(False, [(100, tdecls)]))
        odecls += tdecls
    ms = rng.choice([0, 250, 500, 750, 1200, rng.randrange(0, 2000)])
    own_t = [v for p, v in odecls if p == "opacity"]
