#!/usr/bin/env python3
"""Lot 69: generate the native square-cell bitmap fonts used by the desktop
renderer at 1.5x, 2x, 3x and 4x (cells 12, 16, 24 and 32 px; the 8x8 font
stays for 1x), ASCII 32..126, from IBM Plex Mono Medium (SIL Open Font
License 1.1, Copyright IBM Corp.). Each glyph is drawn at 4x resolution,
stretched to the square cell (the desktop keeps the 8x8 cell metrics, so a
cell is as wide as it is high), area-averaged and thresholded. The result
is a rasterised derivative; the OFL notice is kept in the header.
  python3 scripts/gen_bitmap_font.py FONT.ttf kernel/gfx_font_hd.h
"""
import sys
from PIL import Image, ImageDraw, ImageFont

CELLS = [12, 16, 24, 32]
OVER = 4


def glyph(font, code, cell, size):
    big = cell * OVER
    img = Image.new("L", (big * 2, big * 2), 0)
    d = ImageDraw.Draw(img)
    d.text((big // 2, int(big * 1.62)), chr(code), fill=255, font=font, anchor="ls")
    # the 8x8 cell layout: ink from about 1/8 to 7/8 vertically
    top, bottom = int(big * 0.62), int(big * 1.62) + int(big * 0.22)
    # horizontal: the font advance (0.6 em) stretched to the cell, 1/16 margin
    adv = font.getlength("M")
    x0 = big // 2 - int(adv * 0.04)
    x1 = big // 2 + int(adv * 1.04)
    crop = img.crop((x0, top, x1, bottom)).resize((cell, cell), Image.BOX)
    rows = []
    for y in range(cell):
        bits = 0
        for x in range(cell):
            if crop.getpixel((x, y)) >= 100:
                bits |= 1 << x
        rows.append(bits)
    return rows


def main():
    path = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else "kernel/gfx_font_hd.h"
    lines = [
        "/* gfx_font_hd.h - Lot 69: native square-cell bitmap fonts for the",
        " * desktop at 1.5x/2x/3x/4x (12, 16, 24, 32 px), ASCII 32..126.",
        " * Generated by scripts/gen_bitmap_font.py from IBM Plex Mono Medium,",
        " * Copyright IBM Corp., SIL Open Font License 1.1 (rasterised",
        " * derivative). Bit x of row y is pixel (x, y), bit 0 = left. */",
        "#ifndef GFX_FONT_HD_H",
        "#define GFX_FONT_HD_H",
        "#include <stdint.h>",
    ]
    for cell in CELLS:
        size = int(cell * OVER * 1.0)
        font = ImageFont.truetype(path, size)
        ctype = "uint16_t" if cell <= 16 else "uint32_t"
        lines.append("static const %s gfx_font_hd%d[95][%d] = {" % (ctype, cell, cell))
        for code in range(32, 127):
            g = glyph(font, code, cell, size)
            c = chr(code)
            tag = c if c not in "\\*/" else "0x%02x" % code
            lines.append("    {" + ",".join("0x%x" % v for v in g) + "}, /* %s */" % tag)
        lines.append("};")
    lines += ["#endif", ""]
    with open(out, "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
