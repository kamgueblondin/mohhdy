def none_or(rng, t, p):
    return "none" if rng.random() < p else t


def miss_colour(rng):
    """a colour with missing or powerless components for the new spaces"""
    k = rng.randrange(8)
    p = 0.4
    if k == 0:
        return "hsl(%s %s %s)" % (none_or(rng, G98.hue_text(rng), p), none_or(rng, G98.sl_text(rng), p),
                                  none_or(rng, G98.sl_text(rng), p))
    if k == 1:
        return "hwb(%s %s%% %s%%)" % (none_or(rng, G98.hue_text(rng), p), none_or(rng, str(rng.randrange(0, 101)), p),
                                      none_or(rng, str(rng.randrange(0, 101)), p))
    if k == 2:
        return "lch(%s %s %s)" % (none_or(rng, num(rng, 0, 100, 2), p), none_or(rng, num(rng, 0, 120, 2), p),
                                  none_or(rng, num(rng, 0, 360, 2), p))
    if k == 3:
        return "oklch(%s %s %s)" % (none_or(rng, num(rng, 0, 1), p), none_or(rng, num(rng, 0, 0.3), p),
                                    none_or(rng, num(rng, 0, 360, 2), p))
    if k == 4:
        return rng.choice(["lab", "oklab"]) + "(%s %s %s)" % tuple(
            none_or(rng, x, p) for x in ([num(rng, 0, 100, 2), num(rng, -80, 80, 2), num(rng, -80, 80, 2)]
                                         if rng.random() < 0.5 else [num(rng, 0, 1), num(rng, -0.2, 0.2),
                                                                     num(rng, -0.2, 0.2)]))
    if k == 5:
        # greys: powerless hues
        g = rng.choice(["white", "black", "grey", "#777", "rgb(10 10 10)", "hsl(120 0% 40%)", "hwb(200 60% 40%)",
                        "lch(50 0 120)", "oklch(0.5 0 30)", "oklch(0.5 0.000003 30)", "lch(50 0.001 30)",
                        "transparent"])
        return g
    if k == 6:
        return G102.none_text(rng)
    return G100.simple_colour(rng)


def miss_mix(rng, depth=0):
    sp = rng.choice(POLAR + ["lab", "oklab", "srgb-linear", "xyz", "display-p3", "srgb"])
    h = " %s hue" % rng.choice(M.HUES) if sp in POLAR and rng.random() < 0.4 else ""

    def item():
        c = miss_mix(rng, depth + 1) if depth < 1 and rng.random() < 0.15 else miss_colour(rng)
        if rng.random() < 0.3:
            c += " " + G100.pct_text(rng)
        return c
    return "color-mix(in %s%s, %s, %s)" % (sp, h, item(), item())


