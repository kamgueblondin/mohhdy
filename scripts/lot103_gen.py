def num(rng, lo, hi, places=4):
    """a decimal text in [lo, hi] with up to `places` decimals"""
    q = 10 ** places
    v = rng.randrange(int(round(lo * q)), int(round(hi * q)) + 1)
    if rng.random() < 0.2:
        v -= v % (q // 100 or 1)
    s = "-" if v < 0 else ""
    w, f = divmod(abs(v), q)
    t = s + str(w)
    if f:
        t += "." + ("%0*d" % (places, f)).rstrip("0")
    return t


def gamut_text(rng):
    """a colour of the Lot 101 functions, biased to the sRGB edge"""
    k = rng.randrange(9)
    al = G101.alpha_part(rng) if rng.random() < 0.3 else ""
    if k == 0:
        return "oklch(%s %s %s%s)" % (num(rng, 0, 1), num(rng, 0, 0.4), num(rng, 0, 360, 2), al)
    if k == 1:
        return "oklab(%s %s %s%s)" % (num(rng, 0, 1), num(rng, -0.4, 0.4), num(rng, -0.4, 0.4), al)
    if k == 2:
        return "lch(%s %s %s%s)" % (num(rng, 0, 100, 2), num(rng, 0, 150, 2), num(rng, 0, 360, 2), al)
    if k == 3:
        return "lab(%s %s %s%s)" % (num(rng, 0, 100, 2), num(rng, -125, 125, 2), num(rng, -125, 125, 2), al)
    if k == 4:
        sp = rng.choice(WIDE)
        return "color(%s %s %s %s%s)" % (sp, num(rng, -0.1, 1.1), num(rng, -0.1, 1.1), num(rng, -0.1, 1.1), al)
    if k == 5:
        # an sRGB-edge colour of a wide space: one component 0 or 1
        sp = rng.choice(["display-p3", "rec2020", "a98-rgb", "prophoto-rgb"])
        c = [num(rng, 0, 1) for _ in range(3)]
        c[rng.randrange(3)] = rng.choice(["0", "1"])
        return "color(%s %s%s)" % (sp, " ".join(c), al)
    if k == 6:
        # slightly outside: a small chroma beyond typical sRGB, or L near 0 / 1
        return "oklch(%s %s %s%s)" % (rng.choice([num(rng, 0, 0.05), num(rng, 0.95, 1), num(rng, 0.3, 0.9)]),
                                      num(rng, 0.1, 0.35), num(rng, 0, 360, 2), al)
    if k == 7:
        return "oklch(%s %s %s%s)" % (rng.choice(["0", "1", "0.5", "100%", "0%"]), num(rng, 0, 0.5),
                                      rng.choice(["0", "90", "180", "270", "29.23", "142.5", "264.05"]), al)
    return G101.new_colour(rng)


def simple(rng):
    k = rng.randrange(10)
    if k < 4:
        return G100.simple_colour(rng)
    if k < 7:
        return gamut_text(rng)
    if k < 9:
        return G102.none_text(rng)
    return rng.choice(["transparent", "white", "black", "grey", "red", "blue", "lime", "#000", "rgb(0 0 0 / 0)"])


def head(rng, good=True):
    sp = rng.choice(SPACES)
    t = "in " + sp
    if sp in POLAR and rng.random() < 0.5:
        t += " %s hue" % rng.choice(M.HUES)
    if rng.random() < 0.1:
        t = G100.rcase(rng, t)
    if rng.random() < 0.1:
        t = t.replace(" ", rng.choice(["  ", "\t", " \t "]))
    if not good:
        t = rng.choice(["in hsv", "in srgb longer hue", "in lab shorter hue", "in xyz increasing hue",
                        "in oklch longer", "in oklch hue longer", "in lch shorter hue x", "in xyz-d60",
                        "in", "in oklch, longer hue", "oklch", "in hsl hue", "in hwb clockwise hue",
                        "in display-p3-linear", "in rgb", "in lch longer hues", "in rec-2020",
                        "in hsl increasing  hue  hue", "in shorter hue oklch"])
    return t


def mix_text(rng, depth=0, good=True):
    def item():
        c = mix_text(rng, depth + 1) if depth < 2 and rng.random() < 0.15 else simple(rng)
        if rng.random() < 0.35:
            pc = G100.pct_text(rng)
            return c + " " + pc if rng.random() < 0.5 else pc + " " + c
        return c
    return "color-mix(%s, %s, %s)" % (head(rng, good), item(), item())


# ------------------------------------------------------------- suites
RC_C = [
    "/* the reader colour of v as \"#rrggbb alpha\", \"-\" when it is not one */",
    "static const char *rc(const char *v) {",
    "    static char b[64];",
    "    unsigned int c = 0xdeadbeefu;",
    "    int a = -7, r = wf_cssprop_color(v, (int)strlen(v), &c, &a);",
    "    if (!r) return c == 0xdeadbeefu && a == -7 ? \"-\" : \"WRITTEN\";",
    "    if (r != 1 || c > 0xffffffu || a < 0 || a > 255) return \"BAD CODE\";",
    "    snprintf(b, sizeof(b), \"#%06x %d\", c, a);",
    "    return b;",
    "}", ""]
IP_FNS = [
    "static const char *ip(const char *a, const char *b, int t, int code) {",
    "    if (!syn(\"'<color>'\")) return \"BAD SYNTAX\";",
    "    if (wf_cssprop_interp(&g_p, a, b, t, g_o, (int)sizeof(g_o)) != code) return \"BAD CODE\";",
    "    return g_o;",
    "}", "",
    "static int mt(const char *v) {",
    "    if (!syn(\"'<color>'\")) return -1;",
    "    return wf_cssprop_match_prop(&g_p, v) != 0;",
    "}", ""]


def rc_file(name, title, cases, prefix):
    o = [HEADER % title] + G98.IP_C + RC_C
    o.insert(3, "#include <stdio.h>")
    names = chunks(o, prefix, cases, 12)
    finish(o, names, name)


