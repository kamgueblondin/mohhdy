def write_sheet():
    """the Lot 101 reader paint cases (currentcolor in a tree) with the
    Lot 103 colours in place of the Lot 101 ones"""
    rng = random.Random(10304)
    old = G101.new_colour

    def colour(r, good=True):
        k = r.randrange(10)
        if k < 4:
            return gamut_text(r)
        if k < 8:
            return mix_text(r, 1)
        return miss_mix(r, 1)
    G101.new_colour = colour
    cases = []
    try:
        while len(cases) < 300:
            got = G101.paint_case(rng)
            if got is None or not got[0]:
                continue
            css, out = got
            if len(css) > 1000:
                continue
            cases.append(["prep(%s, 0);" % cstr(css)] +
                         ["TEST_ASSERT_EQUAL_STRING(%s, style_of(\"%s\"));" % (cstr(out[el]), el)
                          for el in ("b", "o", "i")])
    finally:
        G101.new_colour = old
    o = [HEADER % "Lot 103: the reader paint with gamut-mapped colours and color-mix() in other spaces"] + \
        G101.TREE_HEAD
    names = chunks(o, "test_l103_sheet", cases, 6)
    finish(o, names, "test_lot103_sheet.c")
    return len(cases)


if __name__ == "__main__":
    a = write_gamut()
    b = write_mix()
    c = write_hue()
    d = write_sheet()
    print("gamut %d, mix %d, hue %d, sheet %d" % (a, b, c, d))
