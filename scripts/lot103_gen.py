def model(fn, *args):
    try:
        return ("ok", fn(*args))
    except T.Unsure:
        return None


def rc_case(t):
    m = model(L.reader, t)
    if m is None:
        return None
    return "TEST_ASSERT_EQUAL_STRING(%s, rc(%s));" % (cstr(G100.rc_str(m[1])), cstr(t))


