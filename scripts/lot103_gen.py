"""Lot 103 test generator: gamut mapping of out-of-sRGB colours,
color-mix() in the CSS Color 5 spaces with the hue methods, and the
analogous sets of missing components (the reader colour, registered
<color> values, interpolation and the reader paint).

Expectations come from scripts/lot103_model.py (written from CSS Color 4
sections 12 and 13, CSS Color 5 and docs/lot103_plan.md) with the lot 97
to 102 models, not from the C sources. A colour the float model cannot
place on one side of a decision or rounding boundary
(lot101_colormodel.Unsure) is left out.

* test_lot103_gamut.c: wf_cssprop_color on lab(), lch(), oklab(),
  oklch() and color() inside, near and far outside sRGB;
* test_lot103_mix.c: wf_cssprop_color on color-mix() in every space and
  hue method (nested mixes, percentages, invalid heads);
* test_lot103_hue.c: missing and powerless components in mixes,
  wf_cssprop_interp and wf_cssprop_match_prop with the new mixes;
* test_lot103_sheet.c: wf_site_prepare_ext: the reader paint (color,
  background-color, currentcolor in a tree) with these colours.

Run: python3 scripts/lot103_gen.py
"""
