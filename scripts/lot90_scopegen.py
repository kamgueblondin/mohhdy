#!/usr/bin/env python3
"""Lot 90: generated @scope proximity and selector-list suite.

Independent model of the CSS Cascade 6 scoping proximity as wf_sitecss
implements it after Lot 90: among matching rules of equal importance,
origin, layer and specificity, the rule whose scoping root is fewer
generations up from the element wins; generations are counted up to
WF_SITE_SCOPE_HOPS (14), farther roots tie with a root 14 up; an unscoped
rule has infinite hops and loses to any scoped one; ties go to the later
rule. A start list keeps WF_SITE_SCOPE_ALTS (6) selectors; the rest are
dropped.

Writes tests/unit/userspace/test_lot90_scopegen.c (seed 9007).
"""
import os
import random

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "tests", "unit", "userspace", "test_lot90_scopegen.c")
HOPS = 14
ALTS = 6


def chain(n, classes):
    """n nested divs, div k gets classes.get(k); a p inside the last one."""
    o = ""
    for k in range(n):
        c = classes.get(k)
        o += "<div class=%s>" % c if c else "<div>"
    o += "<p id=t>t</p>"
    o += "</div>" * n
    return o


def prox(n, k):
    hops = n - k
    return 15 - min(hops, HOPS)


def main():
    rng = random.Random(9007)
    cases = []
    colours = set()

    def colour():
        while True:
            c = rng.randrange(1, 0xffffff)
            if c not in colours:
                colours.add(c)
                return c

    # A: two scoped rules
    for _ in range(160):
        n = rng.randint(2, 22)
        a, b = rng.sample(range(n), 2)
        ca, cb = colour(), colour()
        first_a = rng.random() < 0.5
        ra = "@scope (.sa) { p { color: #%06x } }" % ca
        rb = "@scope (.sb) { p { color: #%06x } }" % cb
        css = ra + " " + rb if first_a else rb + " " + ra
        pa, pb = prox(n, a), prox(n, b)
        if pa != pb:
            exp = ca if pa > pb else cb
        else:
            exp = cb if first_a else ca
        cases.append((css, chain(n, {a: "sa", b: "sb"}), exp))
    # B: scoped against unscoped, either order
    for _ in range(50):
        n = rng.randint(1, 22)
        a = rng.randrange(n)
        cs, cu = colour(), colour()
        rs = "@scope (.sa) { p { color: #%06x } }" % cs
        ru = "p { color: #%06x }" % cu
        css = ru + " " + rs if rng.random() < 0.5 else rs + " " + ru
        cases.append((css, chain(n, {a: "sa"}), cs))
    # C: start lists of 1..8 selectors, the root is one of them
    for _ in range(90):
        k = rng.randint(1, 8)
        n = rng.randint(1, 10)
        at = rng.randrange(n)
        pick = rng.randrange(k)
        c = colour()
        sel = ", ".join(".l%d" % j for j in range(k))
        css = "@scope (%s) { p { color: #%06x } }" % (sel, c)
        exp = c if pick < ALTS else None
        cases.append((css, chain(n, {at: "l%d" % pick}), exp))

    o = ["/* Generated by scripts/lot90_scopegen.py (seed 9007): @scope proximity",
         " * up to 14 generations and start lists of six selectors. Do not edit. */",
         '#include "../../framework/unity.h"',
         '#include "../../../userspace/wf_sitecss.h"',
         "#include <string.h>",
         "#include <stdio.h>",
         "",
         "static wf_site_t g_d;",
         "",
         "/* the colour of #t, -1 when no rule set it, -2 when prepare failed */",
         "static int colour_of(const char *css, const char *body) {",
         "    static char html[4096];",
         "    int i, n = snprintf(html, sizeof(html), \"<html><head><style>%s</style></head><body>%s</body></html>\", css, body);",
         "    if (n <= 0 || n >= (int)sizeof(html) || wf_site_prepare(&g_d, html, n) != 0) return -2;",
         "    for (i = 0; i < g_d.nnodes; i++)",
         "        if (strcmp(g_d.node[i].id, \"t\") == 0) return g_d.node[i].color_set ? (int)g_d.node[i].color : -1;",
         "    return -2;",
         "}",
         ""]
    names = []
    per = 10
    for t in range(0, len(cases), per):
        name = "test_l90_scope_%d" % (t // per)
        names.append(name)
        o.append("static void %s(void) {" % name)
        for css, body, exp in cases[t:t + per]:
            o.append("    TEST_ASSERT_EQUAL(%d, colour_of(\"%s\",\n        \"%s\"));" %
                     (exp if exp is not None else -1, css, body))
        o.append("}")
        o.append("")
    o.append("int main(void) {")
    o.append("    unity_init();")
    for n in names:
        o.append("    RUN_TEST(%s);" % n)
    o += ["    unity_print_results();", "    unity_cleanup();",
          "    return unity_stats.tests_failed == 0 ? 0 : 1;", "}", ""]
    open(OUT, "w").write("\n".join(o))
    print("scope cases %d tests %d" % (len(cases), len(names)))


if __name__ == "__main__":
    main()
