#!/usr/bin/env python3
"""Lot 92 test generator: CSS math functions in the reader (abs, sign,
round, mod, rem, the trigonometric functions) and the computed value of
registered properties (calc() and friends simplified).

Expectations come from this file, not from the C sources. Each case is a
tree (a sum, a product, a function with its arguments, a number with its
unit); the text is written from the tree with random case and spacing and
the answer is computed on the tree with exact fractions (Python's
fractions.Fraction), so the C parser has to find the same structure.

Rules modelled (CSS Values 4, restricted to what the reader keeps):
* types: number, length, percentage, length-percentage (a length mixed
  with a percentage), angle, time. + and - need one type (a length and a
  percentage give length-percentage) and white space on both sides; *
  needs a number on one side, / a number on the right.
* calc(x); min() and max() take one or more values of compatible types,
  clamp() three; abs(x) keeps the type; sign(x) is a number; round()
  takes an optional strategy (nearest, up, down, to-zero) then A and B of
  one type, B left out only when A is a number (B = 1); mod(A, B) and
  rem(A, B) take two values of one type; sin, cos, tan take a number or an
  angle and give a number; asin, acos, atan take a number and give an
  angle; atan2 takes two values of one type and gives an angle. Anything
  else (pow, exp, an identifier, a missing argument) is invalid.
  Lot 93 (converted): the trigonometric functions are simplified, with
  the values of scripts/lot93_mathmodel.py; pow(A, B), log(A, B),
  hypot(A, B) and the constants pi, e, infinity and nan are valid numbers
  (exp() and sqrt() with two arguments and -pi stay invalid). A case whose
  exact value lies too near a rounding boundary for the 62-bit C side
  (lot93_mathmodel.Ambiguous) is dropped after its text is written, so the
  random sequence of the other cases does not change.
* values: each value is kept in 1/10000 of its canonical unit (px, deg, s,
  %, or a number). A literal is rounded half away from zero at its fourth
  decimal; units: in = 96px, cm = 4800/127 px, mm = 480/127 px, q = 120/127
  px, pt = 4/3 px, pc = 16px, grad = 9/10 deg, turn = 360deg, rad =
  1800000000/31415927 deg, ms = 1/1000 s; each conversion and each * and /
  rounds half away from zero; a value past 100000 units is not known.
  Relative lengths (em, rem, ex, ch, vw, vh, vmin, vmax), a mix of length
  and percentage, a division or a round()/mod()/rem() step of zero are
  typed but not known (Lot 92 also kept the trigonometric functions).
* round(): nearest rounds half toward +infinity, up toward +infinity, down
  toward -infinity, to-zero toward zero, to a multiple of |B|. mod() takes
  the sign of B (A - B floor(A / B)), rem() the sign of A (A - B trunc(A / B)).
* computed value of a registered property: the first alternative of its
  syntax that the value matches must be one numeric type without a
  multiplier and the value known; <integer> rounds half toward +infinity.
  Otherwise the text is kept.

Run: python3 scripts/lot92_mathgen.py
"""
import os
import random
import sys
from fractions import Fraction as F

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lot93_mathmodel as M93  # noqa: E402  (Lot 93: trigonometric values)

AMBIG = [False]   # set when a case met lot93_mathmodel.Ambiguous

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "tests", "unit", "userspace")
HEADER = "/* %s (generated by scripts/lot92_mathgen.py; expectations from that model). */\n"
SEED_TYPE = 9201
SEED_EVAL = 9202
SEED_COMPUTE = 9203
SEED_SHEET = 9204

S = 10000
LIM = 10 ** 9
N, L, P, LP, A, T = "N", "L", "P", "LP", "A", "T"
CODE = {N: "WF_CSSPROP_NUMBER", L: "WF_CSSPROP_LENGTH", P: "WF_CSSPROP_PERCENT", LP: "WF_CSSPROP_LENPCT",
        A: "WF_CSSPROP_ANGLE", T: "WF_CSSPROP_TIME", None: "WF_CSSPROP_BAD"}
NUM = {N: 5, L: 2, P: 3, LP: 4, A: 8, T: 9, None: 0}
CANON = {N: "", L: "px", P: "%", A: "deg", T: "s"}
UNITS = {
    L: [("px", F(1)), ("in", F(96)), ("cm", F(4800, 127)), ("mm", F(480, 127)), ("q", F(120, 127)),
        ("pt", F(4, 3)), ("pc", F(16))],
    A: [("deg", F(1)), ("grad", F(9, 10)), ("turn", F(360)), ("rad", F(1800000000, 31415927))],
    T: [("s", F(1)), ("ms", F(1, 1000))],
}
RELATIVE = ["em", "rem", "ex", "ch", "vw", "vh", "vmin", "vmax"]


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\t", "\\t") + '"'


def rcase(rng, s):
    m = rng.randrange(5)
    if m == 0:
        return s.upper()
    if m == 1:
        return "".join(c.upper() if rng.random() < 0.5 else c for c in s)
    return s


def rha(x):
    """round half away from zero to an integer"""
    if x >= 0:
        return int((x + F(1, 2)).__floor__())
    return -int((-x + F(1, 2)).__floor__())


def floor(x):
    return int(x.__floor__())


def trunc(x):
    return int(x) if x >= 0 else -int(-x)


def fits(v):
    if isinstance(v, tuple):
        return all(fits(x) for x in v)
    return v is not None and -LIM <= v <= LIM


def parts(t, v):
    """Lot 95 (converted): (percent, px) of a known L, P or LP value"""
    if t == LP:
        return v
    return (v, 0) if t == P else (0, v)


def tadd(a, b):
    if a is None or b is None:
        return None
    if a == b:
        return a
    if a in (L, P, LP) and b in (L, P, LP):
        return LP
    return None


def known(t, v):
    """Lot 95 (converted): a length mixed with a percentage is known as the
    pair (percent, px) (Lot 92: never known)"""
    return t is not None and v is not None and (t != LP or isinstance(v, tuple))


def fmt(v, t):
    if t == LP:
        p, x = v
        return "calc(%s %s %s)" % (fmt(p, P), "-" if x < 0 else "+", fmt(abs(x), L))
    sign = "-" if v < 0 else ""
    v = abs(v)
    whole, frac = divmod(v, S)
    s = sign + str(whole)
    if frac:
        s += "." + ("%04d" % frac).rstrip("0")
    return s + CANON[t]


# ------------------------------------------------------------ the tree
# a node is a dict: kind (leaf, sum, prod, paren, fn), text written by
# write(), and the model's (type, value) by evaluate()

def sp(rng, need=False):
    if need:
        return rng.choice([" ", " ", "  ", "\t", " \t "])
    return rng.choice(["", "", "", " ", "  ", "\t"])


def number_text(rng, mag, decimals):
    """(text, exact value)"""
    whole = rng.randrange(0, mag + 1)
    frac = rng.randrange(0, 10 ** decimals) if decimals else 0
    neg = rng.random() < 0.25
    if decimals:
        digits = str(frac).rjust(decimals, "0")
        if whole == 0 and rng.random() < 0.3:
            body = "." + digits
        else:
            body = str(whole) + "." + digits
        val = F(whole) + F(frac, 10 ** decimals)
    else:
        body = str(whole)
        val = F(whole)
    if neg:
        return "-" + body, -val
    if rng.random() < 0.05:
        return "+" + body, val
    return body, val


def leaf(rng, t):
    mag = rng.choice([3, 9, 9, 40, 40, 250, 2000])
    if rng.random() < 0.04:
        mag = rng.choice([150000, 999999])
    dec = rng.choice([0, 0, 1, 2, 3, 4, 5])
    text, val = number_text(rng, mag, dec)
    raw = rha(val * S)
    v = raw if -LIM <= raw <= LIM else None
    if t == N:
        return {"kind": "leaf", "text": text, "t": N, "v": v}
    if t == P:
        return {"kind": "leaf", "text": text + "%", "t": P, "v": v}
    if t == L and rng.random() < 0.07:
        u = rng.choice(RELATIVE)
        return {"kind": "leaf", "text": text + rcase(rng, u), "t": L, "v": None}
    u, fac = rng.choice(UNITS[t]) if rng.random() < 0.6 else UNITS[t][0]
    cv = None
    if v is not None:
        cv = rha(v * fac)
        if not fits(cv):
            cv = None
    return {"kind": "leaf", "text": text + rcase(rng, u), "t": t, "v": cv}


def atom(rng, t, depth):
    """a leaf, a parenthesised sum or a function, of type t"""
    r = rng.random()
    if depth <= 0 or r < 0.45:
        if t == LP:
            return leaf(rng, rng.choice([L, P]))
        return leaf(rng, t)
    if r < 0.6:
        inner = sum_node(rng, t, depth - 1)
        return {"kind": "paren", "inner": inner}
    return fn_node(rng, t, depth - 1)


def prod_node(rng, t, depth):
    """a product chain of type t (left to right)"""
    items = [atom(rng, t, depth)]
    ops = []
    for _ in range(rng.choice([0, 0, 1, 1, 2])):
        op = rng.choice("*/")
        if op == "*" and rng.random() < 0.5:
            # a number on the left: put it first by swapping
            items.insert(0, atom(rng, N, depth - 1))
            ops.insert(0, "*")
            continue
        ops.append(op)
        d = atom(rng, N, depth - 1)
        if op == "/" and d["kind"] == "leaf" and d["v"] == 0 and rng.random() < 0.8:
            d = atom(rng, N, depth - 1)
        items.append(d)
    if len(items) == 1:
        return items[0]
    return {"kind": "prod", "items": items, "ops": ops}


def sum_node(rng, t, depth):
    n = rng.choice([1, 1, 2, 2, 3])
    items, ops = [], []
    for k in range(n):
        tt = t
        if t == LP:
            tt = rng.choice([L, P, LP]) if k else rng.choice([L, P])
        items.append(prod_node(rng, tt, depth))
        if k:
            ops.append(rng.choice("+-"))
    if n == 1:
        return items[0]
    return {"kind": "sum", "items": items, "ops": ops}


def fn_node(rng, t, depth):
    choices = ["calc", "calc", "min", "max", "clamp", "abs", "round", "round", "mod", "rem"]
    if t == N:
        choices += ["sign", "sign", rng.choice(["sin", "cos", "tan"])]
    if t == A:
        choices += [rng.choice(["asin", "acos", "atan", "atan2"])]
    name = rng.choice(choices)
    args, strategy = [], None
    if name in ("calc", "abs"):
        args = [sum_node(rng, t, depth)]
    elif name in ("min", "max"):
        args = [sum_node(rng, t, depth) for _ in range(rng.choice([1, 2, 2, 3, 4]))]
    elif name == "clamp":
        args = [sum_node(rng, t, depth) for _ in range(3)]
    elif name == "round":
        if rng.random() < 0.5:
            strategy = rng.choice(["nearest", "up", "down", "to-zero"])
        if t == N and rng.random() < 0.4:
            args = [sum_node(rng, N, depth)]
        else:
            args = [sum_node(rng, t, depth), sum_node(rng, t, depth)]
    elif name in ("mod", "rem"):
        args = [sum_node(rng, t, depth), sum_node(rng, t, depth)]
    elif name == "sign":
        args = [sum_node(rng, rng.choice([N, L, P, A, T]), depth)]
    elif name in ("sin", "cos", "tan"):
        args = [sum_node(rng, rng.choice([N, A]), depth)]
    elif name in ("asin", "acos", "atan"):
        args = [sum_node(rng, N, depth)]
    elif name == "atan2":
        tt = rng.choice([N, L, A, T])
        args = [sum_node(rng, tt, depth), sum_node(rng, tt, depth)]
    return {"kind": "fn", "name": name, "args": args, "strategy": strategy}


def write(rng, n):
    k = n["kind"]
    if k == "leaf":
        return n["text"]
    if k == "paren":
        return "(" + sp(rng) + write(rng, n["inner"]) + sp(rng) + ")"
    if k == "prod":
        s = write(rng, n["items"][0])
        for op, it in zip(n["ops"], n["items"][1:]):
            s += sp(rng) + op + sp(rng) + write(rng, it)
        return s
    if k == "sum":
        s = write(rng, n["items"][0])
        for op, it in zip(n["ops"], n["items"][1:]):
            s += sp(rng, True) + op + sp(rng, True) + write(rng, it)
        return s
    parts = [write(rng, a) for a in n["args"]]
    if n.get("strategy"):
        parts.insert(0, rcase(rng, n["strategy"]))
    inner = ("," + sp(rng)).join(parts) if not n.get("raw_args") else n["raw_args"]
    return rcase(rng, n["name"]) + "(" + sp(rng) + inner + sp(rng) + ")"


def evaluate(n):
    """(type, value or None); type None when invalid"""
    k = n["kind"]
    if k == "leaf":
        return n["t"], n["v"]
    if k == "paren":
        return evaluate(n["inner"])
    if k == "prod":
        t, v = evaluate(n["items"][0])
        for op, it in zip(n["ops"], n["items"][1:]):
            ut, uv = evaluate(it)
            if t is None or ut is None:
                return None, None
            if op == "*":
                nt = ut if t == N else (t if ut == N else None)
                if nt is None:
                    return None, None
                if v is None or uv is None:
                    v = None
                elif isinstance(v, tuple) or isinstance(uv, tuple):
                    # Lot 95 (converted): a mix scales both parts
                    x, f = (v, uv) if isinstance(v, tuple) else (uv, v)
                    v = tuple(rha(F(y) * f / S) for y in x)
                else:
                    v = rha(F(v) * uv / S)
                t = nt
            else:
                if ut != N:
                    return None, None
                if v is None or uv is None or uv == 0:
                    v = None
                elif isinstance(v, tuple):
                    v = tuple(rha(F(y) * S / uv) for y in v)
                else:
                    v = rha(F(v) * S / uv)
            if not fits(v):
                v = None
        return t, v
    if k == "sum":
        t, v = evaluate(n["items"][0])
        for op, it in zip(n["ops"], n["items"][1:]):
            ut, uv = evaluate(it)
            nt = tadd(t, ut)
            if nt is None:
                return None, None
            if v is not None and uv is not None and nt == t == ut and nt != LP:
                v = v + uv if op == "+" else v - uv
                if not fits(v):
                    v = None
            elif v is not None and uv is not None and nt == LP:
                # Lot 95 (converted): a length and a percentage give a known mix
                a, b = parts(t, v), parts(ut, uv)
                v = tuple(x + y if op == "+" else x - y for x, y in zip(a, b))
                if not fits(v):
                    v = None
            else:
                v = None
            t = nt
        return t, v
    return eval_fn(n)


def lp_args(name, args):
    """Lot 95 (converted): a mix argument is known only inside calc()"""
    if name == "calc":
        return args
    return [(t, None if t == LP else v) for t, v in args]


def eval_fn(n):
    name, args = n["name"], lp_args(n["name"], [evaluate(a) for a in n["args"]])
    if not args or any(a[0] is None for a in args):
        return None, None
    t = args[0][0]
    for a in args[1:]:
        t = tadd(t, a[0])
        if t is None:
            return None, None
    same = all(a[0] == args[0][0] for a in args) and args[0][0] != LP
    allv = same and all(a[1] is not None for a in args)
    vals = [a[1] for a in args]
    if name == "calc":
        if len(args) != 1:
            return None, None
        return args[0]
    if name in ("min", "max"):
        return t, ((min if name == "min" else max)(vals) if allv else None)
    if name == "clamp":
        if len(args) != 3:
            return None, None
        return t, (max(vals[0], min(vals[1], vals[2])) if allv else None)
    if name == "abs":
        if len(args) != 1:
            return None, None
        tt, v = args[0]
        return tt, (abs(v) if v is not None else None)
    if name == "sign":
        if len(args) != 1:
            return None, None
        tt, v = args[0]
        if not known(tt, v):
            return N, None
        return N, (S if v > 0 else -S if v < 0 else 0)
    if name == "round":
        how = n.get("strategy") or "nearest"
        if len(args) == 1:
            if t != N:
                return None, None
            a, b = args[0], (N, S)
        elif len(args) == 2:
            a, b = args
        else:
            return None, None
        if not (known(a[0], a[1]) and b[1] is not None and a[0] == b[0] and b[1] != 0):
            return t, None
        step = abs(b[1])
        q = F(a[1], step)
        if how == "up":
            k = -floor(-q)
        elif how == "down":
            k = floor(q)
        elif how == "to-zero":
            k = trunc(q)
        else:
            k = floor(q + F(1, 2))
        v = k * step
        return t, (v if fits(v) else None)
    if name in ("mod", "rem"):
        if len(args) != 2:
            return None, None
        a, b = args
        if not (known(a[0], a[1]) and b[1] is not None and a[0] == b[0] and b[1] != 0):
            return t, None
        q = F(a[1], b[1])
        k = floor(q) if name == "mod" else trunc(q)
        v = a[1] - b[1] * k
        return t, (v if fits(v) else None)
    # Lot 93 (converted): the trigonometric functions are simplified
    if name in ("sin", "cos", "tan"):
        if len(args) != 1 or t not in (N, A):
            return None, None
        return N, amb(lambda: M93.trig(name, t == A, vals[0]))
    if name in ("asin", "acos", "atan"):
        if len(args) != 1 or t != N:
            return None, None
        return A, amb(lambda: M93.arc(name, vals[0]))
    if name == "atan2":
        if len(args) != 2:
            return None, None
        return A, (amb(lambda: M93.atan2(vals[0], vals[1])) if allv else None)
    return None, None


def amb(f):
    """f() of the Lot 93 model; None and AMBIG set near a boundary"""
    try:
        return f()
    except M93.Ambiguous:
        AMBIG[0] = True
        return None


def wrap_fn(rng, t, depth):
    """a whole value: a function at the top"""
    return fn_node(rng, t, depth)


# ---------------------------------------------------------- invalid ones
def broken(rng):
    """(text, reason): values that are not valid math functions"""
    k = rng.randrange(18)
    a = lambda t: write(rng, leaf(rng, t))  # noqa: E731
    if k == 0:
        return "calc(%s + %s)" % (a(L), a(A)), "length + angle"
    if k == 1:
        return "calc(%s * %s)" % (a(L), a(L)), "length * length"
    if k == 2:
        return "calc(%s / %s)" % (a(N), a(L)), "divided by a length"
    if k == 3:
        return "round(%s)" % a(rng.choice([L, A, T, P])), "round of a dimension without B"
    if k == 4:
        return rcase(rng, "round") + "(%s)" % rng.choice(["up", "down", "nearest", "to-zero"]), "a strategy alone"
    if k == 5:
        return "round(%s, %s, %s)" % (rng.choice(["sideways", "half", "ceil"]), a(N), a(N)), "an unknown strategy"
    if k == 6:
        return rcase(rng, rng.choice(["mod", "rem"])) + "(%s)" % a(L), "one argument"
    if k == 7:
        return rcase(rng, rng.choice(["mod", "rem"])) + "(%s, %s, %s)" % (a(L), a(L), a(L)), "three arguments"
    if k == 8:
        return rcase(rng, rng.choice(["mod", "rem", "atan2"])) + "(%s, %s)" % (a(L), a(A)), "two types"
    if k == 9:
        return rcase(rng, rng.choice(["sign", "abs", "sin", "asin"])) + "()", "no argument"
    if k == 10:
        return rcase(rng, rng.choice(["abs", "sign", "sin", "cos"])) + "(%s, %s)" % (a(N), a(N)), "two arguments"
    if k == 11:
        return rcase(rng, rng.choice(["sin", "cos", "tan"])) + "(%s)" % a(rng.choice([L, T, P])), "trig of a length"
    if k == 12:
        return rcase(rng, rng.choice(["asin", "acos", "atan"])) + "(%s)" % a(rng.choice([A, L])), "arc of a dimension"
    if k == 13:
        # Lot 93 (converted): pow, log and hypot of two numbers are numbers
        nm = rng.choice(["pow", "exp", "log", "sqrt", "hypot"])
        return rcase(rng, nm) + "(%s, %s)" % (a(N), a(N)), ("valid" if nm in ("pow", "log", "hypot") else "two arguments")
    if k == 14:
        return rcase(rng, rng.choice(["abs", "round", "mod"])) + "(%s+%s)" % (a(L), a(L)), "no spaces around +"
    if k == 15:
        # Lot 93 (converted): pi, e, infinity and nan are numbers; -pi is not a constant
        c = rng.choice(["pi", "e", "infinity", "nan", "-pi"])
        return "calc(%s)" % c, ("valid" if c != "-pi" else "not a constant")
    if k == 16:
        return rcase(rng, rng.choice(["abs", "sign", "clamp"])) + "(%s" % a(N), "unbalanced"
    return "atan2(%s)" % a(N), "atan2 with one argument"


def write_type():
    rng = random.Random(SEED_TYPE)
    cases = []
    for _ in range(560):
        t = rng.choice([N, N, L, L, P, LP, A, A, T])
        n = wrap_fn(rng, t, rng.choice([1, 2, 2, 3]))
        tt, _ = evaluate(n)
        cases.append((write(rng, n), tt))
    for _ in range(280):
        text, why = broken(rng)
        cases.append((text, N if why == "valid" else None))
    rng.shuffle(cases)
    o = [HEADER % "Lot 92: the types of abs, sign, round, mod, rem and the trigonometric functions",
         '#include "../../framework/unity.h"', "#include <string.h>", '#include "wf_cssprop.h"', ""]
    names, per = [], 6
    for b in range(0, len(cases), per):
        name = "test_l92_mtype_%d" % (b // per)
        names.append(name)
        o.append("static void %s(void) {" % name)
        for text, tt in cases[b:b + per]:
            o.append("    TEST_ASSERT_EQUAL(%s, wf_cssprop_math_type(%s));" % (CODE[tt], cstr(text)))
        o.append("}")
        o.append("")
    finish(o, names, "test_lot92_mathtype.c")
    return len(cases)


def expect_eval(tt, v):
    if tt is None:
        return "BAD"
    if not known(tt, v):
        return "T%d KEEP" % NUM[tt]
    return "T%d %s" % (NUM[tt], fmt(v, tt))


def write_eval():
    rng = random.Random(SEED_EVAL)
    cases = []
    for _ in range(1500):
        t = rng.choice([N, N, L, L, L, P, A, A, T, T])
        n = wrap_fn(rng, t, rng.choice([0, 0, 1, 1, 2]))
        AMBIG[0] = False
        tt, v = evaluate(n)
        text = write(rng, n)
        if len(text) > 200 or AMBIG[0]:
            continue
        cases.append((text, expect_eval(tt, v)))
