# ------------------------------------------------------------- compute
SYN_TYPES = [("<length>", L), ("<percentage>", P), ("<length-percentage>", LP), ("<number>", N),
             ("<integer>", "I"), ("<angle>", A), ("<time>", T)]
OTHER_ALTS = ["auto", "none", "<color>", "<custom-ident>"]


def alt_matches(at, tt):
    """a numeric alternative against the type of a math value"""
    if at == L:
        return tt == L
    if at == P:
        return tt == P
    if at == LP:
        return tt in (L, P, LP)
    if at in (N, "I"):
        return tt == N
    return at == tt


def syntax(rng):
    """(text, [(type or None for a non-numeric one, mult)])"""
    alts = []
    for _ in range(rng.choice([1, 1, 2, 2, 3, 4])):
        if rng.random() < 0.2:
            alts.append((rng.choice(OTHER_ALTS), None, ""))
        else:
            name, t = rng.choice(SYN_TYPES)
            mult = rng.choice(["", "", "", "", "", "", "+", "#"])
            alts.append((name, t, mult))
    text = "'" + (" | ".join(a[0] + a[2] for a in alts)) + "'"
    return text, alts


def compute_model(alts, tt, v):
    for name, at, mult in alts:
        if at is None or not alt_matches(at, tt):
            continue
        # Lot 95 (converted): a list alternative computes its items too (a
        # single math value is a list of one item); Lot 92 kept lists
        if not known(tt, v):
            return None
        if at == "I":
            k = floor(F(2 * v + S, 2 * S))
            return fmt(k * S, N)
        return fmt(v, tt)
    return None


def write_compute():
    rng = random.Random(SEED_COMPUTE)
    cases = []
    while len(cases) < 900:
        stext, alts = syntax(rng)
        if len(set(a[0] for a in alts)) != len(alts):
            continue
        r = rng.random()
        if r < 0.85:
            t = rng.choice([N, N, L, L, P, LP, A, T])
            numeric = [a[1] for a in alts if a[1] is not None]
            if numeric and rng.random() < 0.75:
                t = {"I": N, LP: rng.choice([L, P, LP])}.get(numeric[0], numeric[0])
            n = wrap_fn(rng, t, rng.choice([0, 0, 0, 1]))
            AMBIG[0] = False
            tt, v = evaluate(n)
            text = write(rng, n).lower()
            if tt is None or len(text) >= 63 or AMBIG[0]:
                continue
            e = compute_model(alts, tt, v)
        else:
            text = rng.choice(["12px", "3", "auto", "1.5s", "90deg", "50%", "red"])
            e = None
        cases.append((stext, text, e if e is not None else "KEEP"))
    o = [HEADER % "Lot 92: computed values of registered math values (wf_cssprop_compute)",
         '#include "../../framework/unity.h"', "#include <string.h>", '#include "wf_cssprop.h"', "",
         "static wf_cssprop_t g_p;", "static char g_o[64];", "",
         "static const char *cv(const char *syn, const char *v) {",
         "    int r;",
         "    memset(&g_p, 0, sizeof(g_p));",
         "    g_p.syntax = (unsigned char)wf_cssprop_syntax_parse(syn, (int)strlen(syn), &g_p);",
         "    if (!g_p.syntax) return \"BAD SYNTAX\";",
         "    r = wf_cssprop_compute(&g_p, v, g_o, (int)sizeof(g_o));",
         "    if (!r) return g_o[0] ? \"KEEP BUT WRITTEN\" : \"KEEP\";",
         "    return g_o;",
         "}", ""]
    names, per = [], 6
    for b in range(0, len(cases), per):
        name = "test_l92_compute_%d" % (b // per)
        names.append(name)
        o.append("static void %s(void) {" % name)
        for st, text, e in cases[b:b + per]:
            o.append("    TEST_ASSERT_EQUAL_STRING(%s, cv(%s, %s));" % (cstr(e), cstr(st), cstr(text)))
        o.append("}")
        o.append("")
    finish(o, names, "test_lot92_compute.c")
