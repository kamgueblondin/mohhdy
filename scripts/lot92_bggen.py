#!/usr/bin/env python3
"""Lot 92 test generator: linear-gradient angles in radians in the reader,
and registered angles (computed by the reader, Lot 92) used as a gradient
angle.

Expectations come from this file, not from the C sources. A radian value
is built from a number of quarter turns k and an offset in degrees, then
written with 0 to 5 decimals; the answer is computed in floating point
from the written text (180 / pi from Python's math module):

* a radian angle is taken when it has at most two integer digits and four
  decimals, no '+', and its value in degrees is within half a degree of a
  multiple of 90 with at most 40 quarter turns; it is written back as that
  whole number of degrees ("1.5708rad" -> "90deg", "-0rad" -> "0deg");
  any other radian value refuses the gradient. Values whose distance to
  the half degree is under 0.001 degree are not generated (the C side
  uses pi / 2 = 1.5707963 and 0.5deg = 0.0087266 rad).
* deg, turn and grad stay as Lot 91 had them (scripts/lot91_bggen.py).
* in the reader sheet, background-image and the background shorthand
  pass the normal form; a registered '<angle>' whose value is a math
  function is computed in deg (Lot 92) and the gradient then takes it
  when it is a whole multiple of 90deg (at most 3600), like a written
  angle; an unregistered one keeps its text and the gradient is refused.

Run: python3 scripts/lot92_bggen.py
"""
import math
import os
import random
from fractions import Fraction as F

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "tests", "unit", "userspace")
HEADER = "/* %s (generated by scripts/lot92_bggen.py; expectations from that model). */\n"
SEED_RAD = 9211
SEED_SHEET = 9212

NAMED = ["red", "blue", "green", "black", "white", "navy", "teal", "lime", "gray", "orange"]


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\t", "\\t") + '"'


def rcase(rng, s):
    m = rng.randrange(4)
    if m == 0:
        return s.upper()
    if m == 1:
        return "".join(c.upper() if rng.random() < 0.5 else c for c in s)
    return s


def sp(rng):
    return rng.choice(["", " ", " ", "  ", "\t"])


def colour(rng):
    k = rng.randrange(3)
    if k == 0:
        return rng.choice(NAMED)
    if k == 1:
        return "#" + "".join(rng.choice("0123456789abcdef") for _ in range(rng.choice([3, 6])))
    return "rgb(%d, %d, %d)" % (rng.randrange(256), rng.randrange(256), rng.randrange(256))


def stops(rng):
    n = rng.choice([2, 2, 3, 4])
    out = []
    for _ in range(n):
        c = colour(rng)
        if rng.random() < 0.3:
            c += " %d%%" % rng.randrange(101)
        out.append(c)
    return out


def rad_text(rng):
    """(text, degrees or None, skip)"""
    k = rng.randrange(-44, 45)
    off = rng.choice([0.0, 0.0, rng.uniform(-0.45, 0.45), rng.uniform(-0.6, 0.6), rng.uniform(-3, 3)])
    deg = 90 * k + off
    r = deg * math.pi / 180.0
    dec = rng.choice([0, 1, 2, 3, 4, 4, 4, 5])
    text = ("%." + str(dec) + "f") % abs(r)
    if dec and text.startswith("0.") and rng.random() < 0.2:
        text = text[1:]
    neg = r < 0 and float(text) != 0.0 or (r < 0 and rng.random() < 0.5)
    if neg:
        text = "-" + text
    return text, dec


def rad_model(text, dec):
    body = text.lstrip("-")
    whole = body.split(".")[0]
    if len(whole) > 2 or dec > 4:
        return None, False
    r = float(text)
    deg = r * 180.0 / math.pi
    k = round(deg / 90.0)
    dist = abs(deg - 90 * k)
    if abs(dist - 0.5) < 0.001:
        return None, True
    if dist > 0.5 or abs(k) > 40:
        return None, False
    return "%ddeg" % (90 * k), False


def norm_words(text):
    return " ".join(text.split()).lower()


def gradient_case(rng):
    while True:
        text, dec = rad_text(rng)
        deg, skip = rad_model(text, dec)
        if not skip:
            break
    t = text + rcase(rng, "rad")
    st = stops(rng)
    src = rcase(rng, "linear-gradient(") + sp(rng) + ("," + sp(rng)).join([t] + st) + sp(rng) + ")"
    if deg is None:
        return src, None
    normal = "linear-gradient(" + ", ".join([deg] + [norm_words(s) for s in st]) + ")"
    if len(normal) > 127:
        return src, None
    return src, normal


def bad_case(rng):
    k = rng.randrange(8)
    st = ", ".join(stops(rng))
    if k == 0:
        a = "+1.5708rad"
    elif k == 1:
        a = "1.rad"
    elif k == 2:
        a = "157.0796rad"           # three integer digits
    elif k == 3:
        a = rng.choice(["1rad", "0.7854rad", "2.3562rad", "0.5rad"])
    elif k == 4:
        a = "1.5708 rad"
    elif k == 5:
        a = rng.choice(["rad", "-rad", ".rad"])
    elif k == 6:
        a = "1.5708rads"
    else:
        a = "64.4026rad"            # 41 quarter turns
    return "linear-gradient(%s, %s)" % (a, st), None


def write_rad():
    rng = random.Random(SEED_RAD)
    cases = []
    for _ in range(460):
        cases.append(("grad",) + gradient_case(rng))
    for _ in range(80):
        cases.append(("grad",) + bad_case(rng))
    # through the image list: url layers, then the gradient last
    for _ in range(120):
        g, n = gradient_case(rng)
        urls = ["url(i%d.png)" % rng.randrange(100) for _ in range(rng.randrange(0, 3))]
        text = ("," + sp(rng)).join(urls + [g])
        normal = None if n is None else ", ".join(urls + [n])
        if normal is not None and len(normal) > 127:
            normal = None
        cases.append(("img", text, normal))
    o = [HEADER % "Lot 92: linear-gradient angles in radians, written back as whole degrees",
         '#include "../../framework/unity.h"', "#include <string.h>", '#include "wf_cssbg.h"', "",
         "static char g_o[WF_CSSBG_VAL];", "",
         "static const char *run(const char *f, const char *v) {",
         "    int r;",
         "    if (!strcmp(f, \"img\")) r = wf_cssbg_image(v, g_o, (int)sizeof(g_o));",
         "    else r = wf_cssbg_gradient(v, (int)strlen(v), g_o, (int)sizeof(g_o));",
         "    if (r <= 0) return g_o[0] ? \"REFUSED BUT WRITTEN\" : \"REFUSED\";",
         "    if (r != (int)strlen(g_o)) return \"BAD LENGTH\";",
         "    return g_o;",
         "}", ""]
    names, per = [], 6
    for b in range(0, len(cases), per):
        name = "test_l92_rad_%d" % (b // per)
        names.append(name)
        o.append("static void %s(void) {" % name)
        for f, v, e in cases[b:b + per]:
            o.append("    TEST_ASSERT_EQUAL_STRING(%s, run(%s, %s));" % (cstr(e if e is not None else "REFUSED"), cstr(f), cstr(v)))
        o.append("}")
        o.append("")
    finish(o, names, "test_lot92_bgrad.c")
    return len(cases)


# ------------------------------------------------------------ the sheet
def angle_math(rng):
    """(text, degrees as a Fraction): a math value of whole quarter turns
    or not, with exact units the reader converts without rounding"""
    k = rng.randrange(-8, 9)
    form = rng.randrange(5)
    if form == 0:
        return "calc(%dturn / 4)" % k, F(90 * k)
    if form == 1:
        return "calc(%ddeg * 3)" % (30 * k), F(90 * k)
    if form == 2:
        return "calc(%dgrad + %dgrad)" % (50 * k, 50 * k), F(90 * k)
    if form == 3:
        d = rng.choice([45, 30, 10])
        return "calc(%ddeg + %ddeg)" % (90 * k, d), F(90 * k + d)
    return "max(%ddeg, %ddeg)" % (90 * k, 90 * k - 90), F(90 * k)


def deg_text(d):
    if d.denominator == 1:
        return "%ddeg" % d.numerator
    return None


def bg_accepts(d):
    return d.denominator == 1 and d.numerator % 90 == 0 and abs(d.numerator) <= 3600


def write_sheet():
    rng = random.Random(SEED_SHEET)
    cases = []
    for _ in range(100):
        g, n = gradient_case(rng)
        if rng.random() < 0.5:
            css = "#t { background-image: %s }" % g
        else:
            css = "#t { background: %s }" % g
        exp = "" if n is None else ' style="background-image:%s"' % n
        cases.append((css, exp))
    for _ in range(100):
        text, d = angle_math(rng)
        registered = rng.random() < 0.7
        st = ", ".join(stops(rng))
        css = ("@property --a { syntax: '<angle>'; inherits: false; initial-value: 0deg } " if registered else "")
        css += "#t { --a: %s; background-image: linear-gradient(var(--a), %s) }" % (text, st)
        if registered and bg_accepts(d):
            normal = "linear-gradient(%s, %s)" % (deg_text(d), norm_words(st))
            exp = ' style="background-image:%s"' % normal if len(normal) <= 127 else ""
        else:
            exp = ""
        cases.append((css, exp))
    o = [HEADER % "Lot 92: radian and computed angles of linear-gradient in the reader sheet",
         '#include "../../framework/unity.h"', "#include <string.h>", "#include <stdio.h>",
         '#include "wf_sitecss.h"', "",
         "static wf_site_t g_d;", "static char g_html[4096], g_o[1400];", "",
         "static const char *st(const char *css) {",
         "    int i;",
         "    snprintf(g_html, sizeof(g_html), \"<html><head><style>%s</style></head><body><div id=t>t</div></body></html>\", css);",
         "    if (wf_site_prepare(&g_d, g_html, (int)strlen(g_html)) != 0) return \"PREPARE FAILED\";",
         "    g_o[0] = 0;",
         "    for (i = 0; i < g_d.nnodes; i++)",
         "        if (!strcmp(g_d.node[i].id, \"t\")) wf_site_style_attr(&g_d, g_d.node[i].start, g_o, (int)sizeof(g_o));",
         "    return g_o;",
         "}", ""]
    names, per = [], 5
    for b in range(0, len(cases), per):
        name = "test_l92_bgsheet_%d" % (b // per)
        names.append(name)
        o.append("static void %s(void) {" % name)
        for css, e in cases[b:b + per]:
            o.append("    TEST_ASSERT_EQUAL_STRING(%s, st(%s));" % (cstr(e), cstr(css)))
        o.append("}")
        o.append("")
    finish(o, names, "test_lot92_bgsheet.c")
    return len(cases)


def finish(o, names, fname):
    o += ["int main(void) {", "    unity_init();"]
    o += ["    RUN_TEST(%s);" % n for n in names]
    o += ["    unity_print_results();", "    unity_cleanup();", "    return unity_stats.tests_failed == 0 ? 0 : 1;", "}", ""]
    open(os.path.join(OUT, fname), "w").write("\n".join(o))


if __name__ == "__main__":
    a = write_rad()
    b = write_sheet()
    print("bgrad %d, bgsheet %d" % (a, b))
