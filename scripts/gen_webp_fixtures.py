#!/usr/bin/env python3
"""Lot 73: writes tests/unit/userspace/imgdec_webp_samples.h (WebP
lossless fixtures and the expected RGBA pixels).

The files are encoded by Pillow's libwebp (lossless, exact) with images
chosen to make the encoder use every VP8L tool: predictor, cross color
and subtract green transforms (smooth gradients), color indexing with
1, 2, 4 and 8 bit packing (2, 4, 16 and 40 colors), the color cache
and backward references (repeated tiles), meta prefix codes (a large
mixed image at method 6) and alpha. The expected pixels are Pillow's own
decode. A lossy file, an animated file and a VP8X file with EXIF are
added for the container paths. Pillow and libwebp versions change the
bytes, so the header is generated once and committed."""
import io
import random
from PIL import Image

OUT = "tests/unit/userspace/imgdec_webp_samples.h"


def enc(img, **kw):
    b = io.BytesIO()
    img.save(b, "WEBP", **kw)
    return b.getvalue()


def gradient(w, h):
    im = Image.new("RGB", (w, h))
    im.putdata([((x * 255) // (w - 1), (y * 255) // (h - 1), ((x + y) * 7) & 255) for y in range(h) for x in range(w)])
    return im


def palette(w, h, n, seed):
    r = random.Random(seed)
    cols = [(r.randrange(256), r.randrange(256), r.randrange(256)) for _ in range(n)]
    im = Image.new("RGB", (w, h))
    im.putdata([cols[r.randrange(n)] for _ in range(w * h)])
    return im


def tiles(w, h):
    r = random.Random(7)
    tile = [(r.randrange(256), r.randrange(256), r.randrange(256)) for _ in range(5 * 3)]
    im = Image.new("RGB", (w, h))
    im.putdata([tile[(y % 3) * 5 + (x % 5)] for y in range(h) for x in range(w)])
    return im


def alpha(w, h):
    r = random.Random(3)
    im = Image.new("RGBA", (w, h))
    im.putdata([(x * 20 & 255, y * 30 & 255, r.randrange(4) * 60, (x * y * 9) & 255) for y in range(h) for x in range(w)])
    return im


def mixed(w, h):
    r = random.Random(11)
    im = Image.new("RGB", (w, h))
    px = []
    for y in range(h):
        for x in range(w):
            if x < w // 2:
                px.append(((x * 9) & 255, (y * 5) & 255, (x * y) & 255))
            elif y < h // 2:
                px.append((r.randrange(256), r.randrange(256), r.randrange(256)))
            else:
                px.append([(255, 0, 0), (0, 0, 255), (250, 250, 250)][(x // 3 + y // 2) % 3])
    im.putdata(px)
    return im


SAMPLES = [
    ("grad", gradient(16, 12), dict(lossless=True, exact=True, method=4)),
    ("pal2", palette(9, 3, 2, 1), dict(lossless=True, exact=True)),
    ("pal4", palette(13, 7, 4, 2), dict(lossless=True, exact=True)),
    ("pal16", palette(11, 5, 16, 3), dict(lossless=True, exact=True)),
    ("pal40", palette(10, 6, 40, 4), dict(lossless=True, exact=True)),
    ("tiles", tiles(32, 9), dict(lossless=True, exact=True, method=6)),
    ("alpha", alpha(10, 10), dict(lossless=True, exact=True)),
    ("mixed", mixed(64, 48), dict(lossless=True, exact=True, method=6, quality=100)),
    ("fast", mixed(24, 20), dict(lossless=True, exact=True, method=0, quality=0)),
]


def carray(name, data):
    lines = ["static const unsigned char %s[%d] = {" % (name, len(data))]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join("0x%02x" % v for v in data[i:i + 16]) + ",")
    lines.append("};")
    return lines


def main():
    out = ["/* Generated by scripts/gen_webp_fixtures.py (Lot 73). Do not edit. */"]
    for name, im, kw in SAMPLES:
        data = enc(im, **kw)
        assert data[12:16] == b"VP8L", name
        dec = Image.open(io.BytesIO(data)).convert("RGBA")
        out += carray("webp_%s" % name, data)
        out += carray("webp_%s_rgba" % name, dec.tobytes())
        out.append("#define WEBP_%s_W %d" % (name.upper(), im.width))
        out.append("#define WEBP_%s_H %d" % (name.upper(), im.height))
    lossy = enc(gradient(16, 12), quality=50)
    assert lossy[12:16] == b"VP8 "
    out += carray("webp_lossy", lossy)
    frames = [gradient(8, 8), palette(8, 8, 3, 9)]
    b = io.BytesIO()
    frames[0].save(b, "WEBP", save_all=True, append_images=frames[1:], lossless=True, duration=50)
    assert b.getvalue()[12:16] == b"VP8X"
    out += carray("webp_anim", b.getvalue())
    exif = Image.Exif()
    exif[0x010E] = "lot73"
    ex = enc(palette(6, 4, 3, 5), lossless=True, exact=True, exif=exif.tobytes())
    assert ex[12:16] == b"VP8X"
    out += carray("webp_vp8x", ex)
    out += carray("webp_vp8x_rgba", Image.open(io.BytesIO(ex)).convert("RGBA").tobytes())
    open(OUT, "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
