#!/usr/bin/env python3
"""Lot 90: generated suite for the public suffix rules of wf_regdom.c.

The rule list is read from userspace/wf_regdom.c (it is the data under
test); the algorithm is the Public Suffix List one, written here from the
PSL format description (publicsuffix.org/list): a domain matches a rule
when the rule's labels equal its rightmost labels, "*" matching any one
label; an exception rule (!) wins and the public suffix is the rule
without its leftmost label; otherwise the matching rule with the most
labels wins; with none, the rule "*" (the TLD). The registrable domain is
the public suffix plus one label; a host that is a public suffix has none.

Writes tests/unit/userspace/test_lot90_psl.c. Deterministic (seed 9006).
"""
import os
import random
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "userspace", "wf_regdom.c")
OUT = os.path.join(ROOT, "tests", "unit", "userspace", "test_lot90_psl.c")


def rules():
    text = open(SRC).read()
    body = text[text.index("k_suffix[] = {"):text.index("0\n};")]
    return re.findall(r'"([^"]+)"', body)


RULES = rules()


def matches(rule, labels):
    r = rule.split(".")
    if len(r) > len(labels):
        return False
    tail = labels[len(labels) - len(r):]
    return all(a == "*" or a == b for a, b in zip(r, tail))


def public_suffix(host):
    labels = host.split(".")
    exc = [r[1:] for r in RULES if r.startswith("!") and matches(r[1:], labels)]
    if exc:
        best = max(exc, key=lambda r: len(r.split(".")))
        return ".".join(best.split(".")[1:])
    best = None
    for r in RULES:
        if r.startswith("!"):
            continue
        if matches(r, labels) and (best is None or len(r.split(".")) > len(best.split("."))):
            best = r
    n = len(best.split(".")) if best else 1
    return ".".join(labels[len(labels) - n:])


def regdom(host):
    labels = host.split(".")
    if len(labels) < 2:
        return None
    ps = public_suffix(host)
    n = len(ps.split("."))
    if n >= len(labels):
        return None
    return ".".join(labels[len(labels) - n - 1:])


def is_suffix(host):
    labels = host.split(".")
    if len(labels) == 1:
        return True
    return public_suffix(host) == host


def cstr(s):
    return '"' + s + '"'


def label(rng):
    alpha = "abcdefghijklmnopqrstuvwxyz0123456789"
    n = rng.randint(1, 8)
    s = "".join(rng.choice(alpha) for _ in range(n))
    return s


def host_from(rng, rule):
    base = rule.lstrip("!")
    parts = [label(rng) if p == "*" else p for p in base.split(".")]
    extra = [label(rng) for _ in range(rng.choice([0, 1, 1, 2, 3]))]
    host = ".".join(extra + parts)
    if rng.random() < 0.2:
        host = "".join(c.upper() if rng.random() < 0.3 else c for c in host)
    return host


def main():
    rng = random.Random(9006)
    cases = []
    # every rule at least once, then random ones
    for r in RULES:
        cases.append(host_from(rng, r))
    for _ in range(300):
        cases.append(host_from(rng, rng.choice(RULES)))
    for _ in range(60):
        cases.append(".".join(label(rng) for _ in range(rng.randint(1, 4))) + "." + rng.choice(["com", "org", "fr", "mu", "io"]))
    seen = set()
    o = ["/* Generated by scripts/lot90_pslgen.py (seed 9006): the public suffix",
         " * rules of wf_regdom.c against the PSL algorithm. Do not edit by hand. */",
         '#include "../../framework/unity.h"',
         "#include <string.h>",
         '#include "wf_regdom.h"',
         "",
         "static char g_o[WF_REGDOM_MAX];",
         "",
         "static const char *rd(const char *h) {",
         "    if (wf_regdom(h, g_o, (int)sizeof(g_o)) != 0) return \"NONE\";",
         "    return g_o;",
         "}",
         ""]
    names = []
    chunk = []
    for h in cases:
        if h in seen or len(h) >= 95:
            continue
        seen.add(h)
        low = h.lower()
        exp = regdom(low)
        chunk.append("    TEST_ASSERT_EQUAL_STRING(%s, rd(%s));" % (cstr(exp if exp else "NONE"), cstr(h)))
        chunk.append("    TEST_ASSERT_EQUAL(%d, wf_regdom_is_suffix(%s));" % (1 if is_suffix(low) else 0, cstr(low)))
        if len(chunk) >= 40:
            name = "test_l90_psl_%d" % len(names)
            names.append(name)
            o.append("static void %s(void) {" % name)
            o += chunk
            o.append("}")
            o.append("")
            chunk = []
    # same-site pairs under wildcards and exceptions
    pairs = [("x.a.b.ck", "y.a.b.ck", 1), ("a.b.ck", "c.b.ck", 0), ("www.ck", "x.www.ck", 1),
             ("x.city.kawasaki.jp", "city.kawasaki.jp", 1), ("a.ward.kawasaki.jp", "b.ward.kawasaki.jp", 0),
             ("x.a.ward.kawasaki.jp", "y.a.ward.kawasaki.jp", 1), ("a.myschool.sch.uk", "b.myschool.sch.uk", 0),
             ("x.a.myschool.sch.uk", "y.a.myschool.sch.uk", 1), ("me.github.io", "you.github.io", 0),
             ("www.example.co.mu", "login.example.co.mu", 1)]
    if chunk:
        name = "test_l90_psl_%d" % len(names)
        names.append(name)
        o.append("static void %s(void) {" % name)
        o += chunk
        o.append("}")
        o.append("")
    name = "test_l90_psl_pairs"
    names.append(name)
    o.append("static void %s(void) {" % name)
    for a, b, same in pairs:
        ra, rb = regdom(a), regdom(b)
        exp = 1 if (a == b or (ra is not None and ra == rb)) else 0
        assert exp == same, (a, b)
        o.append("    TEST_ASSERT_EQUAL(%d, wf_regdom_same_site(%s, %s));" % (exp, cstr(a), cstr(b)))
    o.append("}")
    o.append("")
    o.append("int main(void) {")
    o.append("    unity_init();")
    for n in names:
        o.append("    RUN_TEST(%s);" % n)
    o += ["    unity_print_results();", "    unity_cleanup();",
          "    return unity_stats.tests_failed == 0 ? 0 : 1;", "}", ""]
    with open(OUT, "w") as f:
        f.write("\n".join(o))
    print("psl hosts %d rules %d" % (len(seen), len(RULES)))


if __name__ == "__main__":
    main()
