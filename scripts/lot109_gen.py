@contextlib.contextmanager
def reuse(mod, seed, fname, title, old, new, patches, keep=None):
    """run an older writer of module mod with seed, its file fname, its
    header title and its test names old* renamed new*, the first keep
    cases only, with the module attributes in patches replaced
    meanwhile"""
    class _R:
        Random = staticmethod(lambda _seed: random.Random(seed))
    saved = {k: getattr(mod, k) for k in list(patches) + ["random", "finish", "chunks"]}

    def fin(o, names, _f):
        o[0] = HEADER % title
        finish(o, names, fname)
    for k, v in patches.items():
        setattr(mod, k, v)
    mod.random, mod.finish = _R, fin
    mod.chunks = lambda o, prefix, cases, per: chunks(o, prefix.replace(old, new), cases[:keep], per)
    try:
        yield
    finally:
        for k, v in saved.items():
            setattr(mod, k, v)


# ------------------------------------------------------------- values
FONT_U = ["ex", "ch", "lh"]
LEN_U = ["px", "em", "rem", "vh", "vw", "ex", "ch", "lh", "pt", "pc"]


def num(rng, frac=0.4):
    if rng.random() < frac:
        return "%d.%s" % (rng.randrange(0, 40), rng.choice(["5", "25", "75", "125", "2"]))
    return "%d" % rng.randrange(0, 60)


def length(rng):
    return num(rng) + rng.choice(LEN_U)


def pct(rng):
    return rng.choice(["%d%%" % rng.randrange(0, 101), "%s%%" % num(rng, 0.3)])


def lin(rng):
    """a sum with a percentage and a length (either may be left out)"""
    k = rng.randrange(8)
    if k == 0:
        return pct(rng)
    if k == 1:
        return length(rng)
    if k == 2:
        return "calc(%s %s %s)" % (pct(rng), rng.choice("+-"), length(rng))
    if k == 3:
        return "calc(%s %s %s)" % (length(rng), rng.choice("+-"), pct(rng))
    if k == 4:
        return "calc(%s * %s)" % (pct(rng), rng.choice(["2", "0.5", "1.5", "3", "0.25"]))
    if k == 5:
        return "calc((%s + %s) / %s)" % (pct(rng), length(rng), rng.choice(["2", "4", "5", "8"]))
    if k == 6:
        return "calc(%s * (%s - %s))" % (rng.choice(["2", "0.5", "3"]), pct(rng), length(rng))
    return "calc(%s - %s + %s)" % (pct(rng), length(rng), pct(rng))


def box_math(rng):
    """a math function with a percentage, ex, ch or lh; some refused"""
    k = rng.random()
    if k < 0.35:
        v = lin(rng)
        return v if v.startswith("calc(") else "calc(%s)" % v
    if k < 0.75:
        f = rng.choice(["min", "max", "min", "max", "clamp"])
        n = 3 if f == "clamp" else rng.choice([2, 2, 3])
        return "%s(%s)" % (f, ", ".join(lin(rng) for _ in range(n)))
    if k < 0.9:
        return "calc(%s %s %s)" % (num(rng) + rng.choice(FONT_U), rng.choice("+-"),
                                    rng.choice([length(rng), num(rng) + rng.choice(FONT_U)]))
    return rng.choice(["calc(min(50%, 10px) + 1px)", "min(min(10%, 1lh), 2px)", "min(50%, 2)", "calc(50% * 2%)",
                       "calc(3000px + 1%)", "calc(2001% + 1ex)", "max(10%, 1lh) * 2", "calc(1ex + 1)",
                       "clamp(10%, 2ch)", "calc(10% / 0)", "min(10%, 1q)", "calc(1ex+1lh)"])


