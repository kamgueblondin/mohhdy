    while len(cases) < 200:
        ndiv = rng.randrange(1, 5)
        divs = []
        for i in range(ndiv):
            decls = []
            for j in range(rng.randrange(0, 4)):
                p = rng.choice(["height", "height", "min-height", "max-height"])
                v = tall_value(rng)
                if v == "auto" and p != "height":
                    continue
                decls.append((p, v))
            divs.append(decls)
        sheet = rng.random() < 0.5
        if sheet:
            css = "body { margin: 0 } " + " ".join("#d%d { %s }" % (i, "; ".join("%s: %s" % pv for pv in d))
                                                   for i, d in enumerate(divs) if d)
            body = "".join("<div id=d%d></div>" % i for i in range(ndiv))
            html = "<html><head><style>%s</style></head><body>%s</body></html>" % (css, body)
        else:
            body = "".join("<div id=d%d%s></div>" % (i, " style='%s'" % ";".join("%s:%s" % pv for pv in d) if d else "")
                           for i, d in enumerate(divs))
            html = "<body style='margin:0'>%s</body>" % body
        if html in seen or len(html) > 600:
            continue
        seen.add(html)
        got = M.tall_layout(divs)
        lines = ["lay(%s);" % cstr(html)]
        for i, (h, y) in enumerate(got):
            lines.append("TEST_ASSERT_EQUAL(%d, nd(\"d%d\")->h);" % (h, i))
            lines.append("TEST_ASSERT_EQUAL(%d, nd(\"d%d\")->y);" % (y, i))
        cases.append(lines)
    o = [HEADER % "Lot 109: heights, min-heights and max-heights past 2000 px (parse_height, up to WE_LAYOUT_MAX) in "
                  "style attributes and sheets, stacked"] + [
        '#include "../../framework/unity.h"', "#include <string.h>", '#include "webeng.h"', "",
        "static we_doc_t g_doc;", "static we_node_t g_none;", "",
        "static void lay(const char *html) {",
        "    TEST_ASSERT_EQUAL(0, we_parse(&g_doc, html, (int)strlen(html)));",
        "    TEST_ASSERT_EQUAL(0, we_style(&g_doc));",
        "    TEST_ASSERT_EQUAL(0, we_layout_viewport(&g_doc, 640, 480));",
        "}", "",
        "static const we_node_t *nd(const char *id) {",
        "    int i;",
        "    for (i = 0; i < (int)g_doc.nnodes; i++)",
        "        if (!strcmp(g_doc.nodes[i].id, id)) return &g_doc.nodes[i];",
        "    g_none.h = g_none.y = -1;",
        "    return &g_none;     /* -1: no such node */",
        "}", ""]
    names = chunks(o, "test_l109_tall", cases, 10)
    finish(o, names, "test_lot109_tall.c")
    return len(cases)


