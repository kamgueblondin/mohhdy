def kws_of(f, sp):
    if f == "color":
        return ("x", "y", "z") if sp.startswith("xyz") else ("r", "g", "b")
    return M.REL_KW[f]


def rel_arg(rng, f, sp, pos):
    kws = kws_of(f, sp)
    kw = kws[pos] if rng.random() < 0.75 else rng.choice(list(kws) + ["alpha"])
    k = rng.random()
    if k < 0.35:
        return kw
    if k < 0.8:
        big = f in ("rgb", "hsl", "hwb", "lab", "lch") or (f == "oklch" and kws[pos] == "h")
        n = rng.choice(["10", "20", "1", "45", "100"]) if big else rng.choice(["0.1", "0.05", "0.2", "0.5"])
        e = rng.choice(["calc(%s + %s)", "calc(%s - %s)", "calc(%s * 2)", "calc(%s / 2)", "calc(%s * 0.5 + %s)",
                        "calc(%s)", "calc(%s + 10%%)"])
        return e % ((kw, n) if e.count("%s") == 2 else (kw,))
    lk = f if f != "color" else ("xyz" if sp.startswith("xyz") else "rgbsp")
    return rng.choice(LITS[lk])


def rel_origin(rng, depth):
    k = rng.random()
    if k < 0.1 and depth < 2:
        return rel_colour(rng, depth + 1, True)
