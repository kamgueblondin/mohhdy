def rel_colour(rng, depth=0, good=False):
    name, f = rng.choice(NAMES)
    if rng.random() < 0.05:
        name = name.upper()
    sp = rng.choice(M.COLOR_SP) if f == "color" else ""
    args = [rel_arg(rng, f, sp, p) for p in range(3)]
    k = rng.random()
    alpha = "" if k < 0.6 else " / " + rng.choice(["alpha", "0.5", "50%", "calc(alpha / 2)", "none", "1"])
    v = "%s(from %s %s%s%s)" % (name, rel_origin(rng, depth), sp + " " if sp else "", " ".join(args), alpha)
    if not good and rng.random() < 0.12:
        b = rng.randrange(6)
        if b == 0 and sp:
            v = v.replace(" %s " % sp, " %s " % rng.choice(["lab", "hsl", "oklch", "srgbx", "xyz-d60"]), 1)
        elif b == 1:
            v = v[:-1] + " %s)" % args[0]
        elif b == 2:
            v = v.replace(" " + args[2] + alpha + ")", alpha + ")", 1)
        elif b == 3:
            v = v.replace("(from ", "(", 1)
        elif b == 4:
            v = v.replace(" %s" % args[0], ", %s" % args[0], 1)
        else:
            v = v[:-1] + " / 1 / 1)"
    return v


def expect_rel(v):
    r = M.rel_rgba(v)
    if r is None:
        return "0"
    ch, al = r
    rgb = 0
    for c in ch:
        rgb = rgb * 256 + (c + S // 2) // S
    return "1 %06x %d" % (rgb, (al * 255 + S // 2) // S)


