FLOW_C = r'''#include "../../framework/unity.h"
#include <string.h>
#include <stdio.h>
#include "webeng.h"
#include "wf_html.h"

static we_doc_t g_doc;
static char g_html[8192], g_out[65536], g_o[512];

/* the page: #p (a box scroller #j reads) holds #o (one #i reads),
 * reduced by the reader and laid out at 640 x 480; the reader's style
 * of #o into g_o */
static void flow(const char *css) {
    wf_html_stats_t st;
    int n;
    const char *s, *e;
    snprintf(g_html, sizeof(g_html), "<html><head><style>@keyframes k { from { color: #000000 } to { color: "
             "#ffffff } } %s #i, #j { animation: k 1s linear; animation-timeline: scroll(nearest) }</style></head>"
             "<body><main><div id=p><p id=j>j</p><div id=o><p id=i>i</p><p>a</p><p>b</p></div></div></main>"
             "</body></html>", css);
    wf_html_set_sitecss(1);
    n = wf_html_reduce(g_html, (int)strlen(g_html), 0, g_out, (int)sizeof(g_out), &st);
    wf_html_set_sitecss(0);
    TEST_ASSERT_TRUE(n > 0);
    TEST_ASSERT_EQUAL(0, we_parse(&g_doc, g_out, n));
    TEST_ASSERT_EQUAL(0, we_style(&g_doc));
    TEST_ASSERT_EQUAL(0, we_layout_viewport(&g_doc, 640, 480));
    g_o[0] = 0;
    s = strstr(g_out, "<p>j</p><div style=\"");
    if (s) {
        s += 20;
        e = strchr(s, '"');
        if (e && e - s < (int)sizeof(g_o)) { memcpy(g_o, s, (size_t)(e - s)); g_o[e - s] = 0; }
    }
}

/* the height of the k-th box scroller along y */
static int sh(int k) {
    int i;
    for (i = 0; i < (int)g_doc.nnodes; i++)
        if ((g_doc.nodes[i].overflow_scroll & 2) && !k--) return g_doc.nodes[i].h;
    return -1;
}
'''

OUTER = ["300px", "200px", "240px", "150px", "400px", "20lh", "25ch", "40ex", "12.5em", "320px", "250px"]


def write_flow():
    rng = random.Random(10904)
    cases = []
    while len(cases) < 160:
        outer = rng.choice(OUTER)
        ob = M.math_box(outer)
        basis = M7.math_floor(ob[1])
        decls = [("height", box_math(rng) if rng.random() < 0.85 else pct(rng))]
        if rng.random() < 0.3:
            decls.append(("max-height", box_math(rng)))
        if rng.random() < 0.3:
            decls.append(("min-height", box_math(rng)))
        try:
            got = [(p, M7.height_val(v, p == "max-height")) for p, v in decls]
            got = [(p, M7.box_len(hv, 16, 16) if hv else None) for p, hv in got]
            for p, v in decls:
                M.math_box(v, 16, 16, True)         # Unsure when a step is cut
        except (M.Unsure, M7.Unsure):
            continue
        if got[0][1] is None:
            continue
        txt = {p: M7.box_text(r) for p, r in got if r is not None}
        h = M.engine_px(txt["height"], basis)
        if "max-height" in txt:
            h = min(h, M.engine_px(txt["max-height"], basis))
        if "min-height" in txt:
            h = max(h, M.engine_px(txt["min-height"], basis))
        if h > 2000:
            continue
        sty = "overflow-y:auto" + "".join(";%s:%s" % (p, txt[p]) for p in ("height", "max-height", "min-height")
                                          if p in txt)
        css = "#p { overflow: auto; height: %s } #o { overflow: auto; %s }" % (outer, "; ".join(
            "%s: %s" % d for d in decls))
        cases.append(["flow(%s);" % cstr(css), "TEST_ASSERT_EQUAL_STRING(%s, g_o);" % cstr(sty),
                      "TEST_ASSERT_EQUAL(%d, sh(0));" % basis, "TEST_ASSERT_EQUAL(%d, sh(1));" % h])
    o = [HEADER % "Lot 109: percentage expressions of the reader laid out against the containing block"] + \
        FLOW_C.split("\n")
    names = chunks(o, "test_l109_flow", cases, 8)
    finish(o, names, "test_lot109_flow.c")
    return len(cases)


