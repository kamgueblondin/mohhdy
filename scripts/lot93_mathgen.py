def write_powlog():
    rng = random.Random(SEED_POW)
    cases = []
    while len(cases) < 1100:
        k = rng.random()
        if k < 0.3:
            r = rng.random()
            if r < 0.4:
                base = small_num(rng, -4, 12, rng.choice([0, 1, 1, 2, 4]))
            elif r < 0.5:
                base = small_num(rng, -0.5, 0.5, rng.choice([1, 2, 4]))
            elif r < 0.6:
                base = {"kind": "leaf", "text": rng.choice(["0", "1", "-1", "0.0001", "10000", "e", "pi"]), "t": N}
                base["v"] = {"0": 0, "1": S, "-1": -S, "0.0001": 1, "10000": 10 ** 8, "e": 27183, "pi": 31416}[base["text"]]
            else:
                base = num_leaf(rng)
            r = rng.random()
            if r < 0.5:
                ex = small_num(rng, -9, 13, 0)
            elif r < 0.7:
                ex = small_num(rng, -2, 2, rng.choice([1, 2]))
            elif r < 0.8:
                ex = small_num(rng, -200, 200000, 0)
            else:
                ex = num_leaf(rng)
            n = {"kind": "fn", "name": "pow", "args": [base, ex], "strategy": None}
        elif k < 0.45:
            r = rng.random()
            if r < 0.3:
                w = rng.randint(0, 300)
                arg = {"kind": "leaf", "text": str(w * w) if rng.random() < 0.5 else str(G.F(w * w, 100)), "t": N}
                arg["text"] = arg["text"] if "/" not in arg["text"] else ("%.2f" % (w * w / 100.0))
                arg["v"] = G.rha(G.F(arg["text"]) * S)
            else:
                arg = LOT92_LEAF(rng, N) if r < 0.8 else num_leaf(rng)
            n = {"kind": "fn", "name": "sqrt", "args": [arg], "strategy": None}
        elif k < 0.65:
            tt = rng.choice([N, L, L, P, A, T])
            items = [LOT92_LEAF(rng, tt) for _ in range(rng.choice([1, 2, 2, 2, 3, 4]))]
            if rng.random() < 0.1 and tt == L:
                items.append(LOT92_LEAF(rng, P))
            n = {"kind": "fn", "name": "hypot", "args": items, "strategy": None}
        elif k < 0.85:
            r = rng.random()
            a = small_num(rng, -1, 1000, rng.choice([0, 1, 2, 4])) if r < 0.6 else LOT92_LEAF(rng, N)
            args = [a]
            if rng.random() < 0.55:
                r = rng.random()
                if r < 0.5:
                    b = {"kind": "leaf", "text": rng.choice(["2", "10", "e", "0.5", "1", "0", "-2", "16", "1.0001"]), "t": N}
                    b["v"] = M.CONST.get(b["text"].lower()) if b["text"] == "e" else G.rha(G.F(b["text"]) * S)
                else:
                    b = small_num(rng, 0, 30, rng.choice([0, 1, 3]))
                args.append(b)
            n = {"kind": "fn", "name": "log", "args": args, "strategy": None}
        else:
            r = rng.random()
            a = small_num(rng, -14, 13, rng.choice([0, 1, 2, 4])) if r < 0.8 else LOT92_LEAF(rng, N)
            n = {"kind": "fn", "name": "exp", "args": [a], "strategy": None}
        tree_case(rng, n, "powlog", cases)
    write_ev_suite("test_lot93_powlog.c", "Lot 93: pow, sqrt, hypot, log and exp simplified",
                   "test_l93_powlog", cases)
    return len(cases)


