def broken93(rng):
    """(text, type or None): values around the Lot 93 functions"""
    a = lambda t: G.write(rng, LOT92_LEAF(rng, t))  # noqa: E731
    k = rng.randrange(16)
    if k == 0:
        nm = rng.choice(["pow", "log"])
        return rcase(rng, nm) + "(%s, %s)" % (a(rng.choice([L, A, T, P])), a(N)), None
    if k == 1:
        nm = rng.choice(["sqrt", "exp", "log"])
        return rcase(rng, nm) + "(%s)" % a(rng.choice([L, A, T, P])), None
    if k == 2:
        nm = rng.choice(["sqrt", "exp"])
        return rcase(rng, nm) + "(%s, %s)" % (a(N), a(N)), None
    if k == 3:
        return rcase(rng, "pow") + "(%s)" % a(N), None
    if k == 4:
        nm = rng.choice(["pow", "log"])
        return rcase(rng, nm) + "(%s, %s, %s)" % (a(N), a(N), a(N)), None
    if k == 5:
        nm = rng.choice(["pow", "sqrt", "hypot", "log", "exp"])
        return rcase(rng, nm) + "()", None
    if k == 6:
        t1, t2 = rng.sample([N, L, A, T], 2)
        return rcase(rng, "hypot") + "(%s, %s)" % (a(t1), a(t2)), None
    if k == 7:
        return rcase(rng, "hypot") + "(%s, %s)" % (a(L), a(P)), LP
    if k == 8:
        c = rng.choice(["-pi", "-e", "pi-1", "2pi", "pie", "e2", "pi_", "--pi", "- infinity", "nan-"])
        return "calc(%s)" % c, None
    if k == 9:
        c = rng.choice(CONSTANTS + ["PI", "E", "NaN", "-INFINITY", "Infinity"])
        return rcase(rng, rng.choice(["calc", "abs", "sign", "sqrt", "exp"])) + "(%s)" % c, N
    if k == 10:
        c = rng.choice(CONSTANTS)
        t = rng.choice([L, A, T, P])
        return "calc(%s * %s)" % (c, a(t)), t
    if k == 11:
        c = rng.choice(CONSTANTS)
        return "calc(%s + %s)" % (c, a(rng.choice([L, A, T]))), None
    if k == 12:
        return rng.choice(["pi", "e", "infinity", "nan", "pow", "sqrt(4"]), None
    if k == 13:
        nm = rng.choice(["pow", "log", "hypot"])
        return rcase(rng, nm) + "(%s,%s)" % (a(N), a(N)), N
    if k == 14:
        t = rng.choice([L, A, T, P, N])
        return rcase(rng, "hypot") + "(%s)" % a(t), t
    return rcase(rng, rng.choice(["sin", "cos", "tan"])) + "(%s)" % rng.choice(CONSTANTS), N


def write_mtype():
    rng = random.Random(SEED_TYPE)
    cases = []
    for _ in range(520):
        t = rng.choice([N, N, N, L, P, LP, A, A, T])
        n = G.wrap_fn(rng, t, rng.choice([1, 2, 2, 3]))
        G.AMBIG[0] = False
        tt, _ = G.evaluate(n)
        cases.append((G.write(rng, n), tt))
    for _ in range(280):
        text, tt = broken93(rng)
        cases.append((text, tt))
    rng.shuffle(cases)
    o = [HEADER % "Lot 93: the types of pow, sqrt, hypot, log, exp and the constants",
         '#include "../../framework/unity.h"', "#include <string.h>", '#include "wf_cssprop.h"', ""]
    names, per = [], 8
    for b in range(0, len(cases), per):
        name = "test_l93_mtype_%d" % (b // per)
        names.append(name)
        o.append("static void %s(void) {" % name)
        for text, tt in cases[b:b + per]:
            o.append("    TEST_ASSERT_EQUAL(%s, wf_cssprop_math_type(%s));" % (G.CODE[tt], cstr(text)))
        o.append("}")
        o.append("")
    G.finish(o, names, "test_lot93_mtype.c")
    return len(cases)


