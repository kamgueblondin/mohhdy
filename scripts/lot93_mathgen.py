# ------------------------------------------------------------ compute
def write_compute():
    rng = random.Random(SEED_COMPUTE)
    cases = []
    while len(cases) < 520:
        stext, alts = G.syntax(rng)
        if len(set(x[0] for x in alts)) != len(alts):
            continue
        t = rng.choice([N, N, N, L, P, A, A, T])
        numeric = [x[1] for x in alts if x[1] is not None]
        if numeric and rng.random() < 0.9:
            t = {"I": N, LP: rng.choice([L, P])}.get(numeric[0], numeric[0])
        n = fn_node93(rng, t, rng.choice([0, 0, 1]))
        if n["name"] in ("calc", "min", "max", "clamp", "abs", "round", "mod", "rem", "sign"):
            continue
        G.AMBIG[0] = False
        tt, v = G.evaluate(n)
        text = G.write(rng, n).lower()
        if G.AMBIG[0]:
            drop("compute")
            continue
        if tt is None or len(text) >= 63:
            continue
        e = G.compute_model(alts, tt, v)
        cases.append((stext, text, e if e is not None else "KEEP"))
    o = [HEADER % "Lot 93: computed values of registered values using the Lot 93 functions",
         '#include "../../framework/unity.h"', "#include <string.h>", '#include "wf_cssprop.h"', "",
         "static wf_cssprop_t g_p;", "static char g_o[64];", "",
         "static const char *cv(const char *syn, const char *v) {",
         "    int r;",
         "    memset(&g_p, 0, sizeof(g_p));",
         "    g_p.syntax = (unsigned char)wf_cssprop_syntax_parse(syn, (int)strlen(syn), &g_p);",
         "    if (!g_p.syntax) return \"BAD SYNTAX\";",
         "    r = wf_cssprop_compute(&g_p, v, g_o, (int)sizeof(g_o));",
         "    if (!r) return g_o[0] ? \"KEEP BUT WRITTEN\" : \"KEEP\";",
         "    return g_o;",
         "}", ""]
    names, per = [], 8
    for b in range(0, len(cases), per):
        name = "test_l93_compute_%d" % (b // per)
        names.append(name)
        o.append("static void %s(void) {" % name)
        for st, text, e in cases[b:b + per]:
            o.append("    TEST_ASSERT_EQUAL_STRING(%s, cv(%s, %s));" % (cstr(e), cstr(st), cstr(text)))
        o.append("}")
        o.append("")
    G.finish(o, names, "test_lot93_compute.c")
    return len(cases)


# ------------------------------------------------------------ sheets
def has_relative(n):
    k = n["kind"]
    if k == "leaf":
        low = n["text"].lower()
        return any(low.endswith(u) for u in G.RELATIVE)
    if k == "paren":
        return has_relative(n["inner"])
    kids = n.get("items") or n.get("args") or []
    return any(has_relative(c) for c in kids)


def sheet_value93(rng):
    """(text, kind, type, value): a Lot 93 math value without relative units"""
    while True:
        t = rng.choice([N, N, L, P, A, A, T])
        n = fn_node93(rng, t, 0)
        if n["name"] in ("calc", "min", "max", "clamp", "abs", "round", "mod", "rem", "sign") and rng.random() < 0.8:
            continue
        if has_relative(n):
            continue
        text = " ".join(G.write(rng, n).lower().split()).replace("( ", "(").replace(" )", ")")
        G.AMBIG[0] = False
        tt, v = G.evaluate(n)
        if G.AMBIG[0]:
            drop("sheet")
            continue
        if tt is None or len(text) > 50:
            continue
        return text, "math", tt, v


def write_sheet():
    rng = random.Random(SEED_SHEET)
    cases = []
    while len(cases) < 120:
        sname, st = rng.choice(G.SHEET_TYPES)
        inherits = rng.random() < 0.5
        init = G.INITIAL[st]
        init_b = init
        simplified = 0
        if rng.random() < 0.3:
            text, kind, it, iv = sheet_value93(rng)
            want = {L: L, P: P, LP: L, N: N, "I": N, A: A, T: T}[st]
            if it != want and not (st == LP and it in (L, P)):
                continue
            init = text
            init_b = G.sheet_computed(st, text, "math", it, iv)
        vals = [sheet_value93(rng) for _ in range(2)]
        child_own = rng.random() < 0.6

        def bind(val, inherited):
            nonlocal simplified
            text, kind, ptype, v = val
            if G.sheet_match(st, kind, ptype):
                b = G.sheet_computed(st, text, kind, ptype, v)
                # Lot 95 (converted): counted when the computed text differs
                if b != text:
                    simplified += 1
                return b
            return inherited

        o_b = bind(vals[0], init_b)
        i_inh = o_b if inherits else init_b
        i_b = bind(vals[1], i_inh) if child_own else i_inh
        css = "@property --p { syntax: '%s'; inherits: %s; initial-value: %s } #o { --p: %s }" % (
            sname, "true" if inherits else "false", init, vals[0][0])
        if child_own:
            css += " #i { --p: %s }" % vals[1][0]
        cases.append((css, o_b, i_b, init_b, simplified))
    o = [HEADER % "Lot 93: registered values with the Lot 93 functions computed in the reader sheet",
         '#include "../../framework/unity.h"', "#include <string.h>", "#include <stdio.h>",
         '#include "wf_sitecss.h"', "",
         "static wf_site_t g_d;", "static char g_html[4096], g_t[256];", "",
         "static void prep(const char *css) {",
         "    snprintf(g_html, sizeof(g_html), \"<html><head><style>%s</style></head><body>\"",
         "             \"<div id=o><p id=i>i</p></div><p id=q>q</p></body></html>\", css);",
         "    TEST_ASSERT_EQUAL(0, wf_site_prepare(&g_d, g_html, (int)strlen(g_html)));",
         "    TEST_ASSERT_EQUAL(1, g_d.nprops);",
         "}", "",
         "static const char *nv(const char *id) {",
         "    int i;",
         "    for (i = 0; i < g_d.nnodes; i++)",
         "        if (!strcmp(g_d.node[i].id, id)) { const char *v = wf_site_node_var(&g_d, i, \"--p\"); return v ? v : \"(none)\"; }",
         "    return \"(no node)\";",
         "}", "",
         "static const char *tail(void) {",
         "    const char *s;",
         "    wf_site_props_text(&g_d, g_t, (int)sizeof(g_t));",
         "    s = strstr(g_t, \" simplified \");",
         "    return s ? s : \"\";",
         "}", ""]
    names = []
    for k, (css, ob, ib, qb, simp) in enumerate(cases):
        name = "test_l93_sheet_%d" % k
        names.append(name)
        o.append("static void %s(void) {" % name)
        o.append("    prep(%s);" % cstr(css))
        o.append("    TEST_ASSERT_EQUAL_STRING(%s, nv(\"o\"));" % cstr(ob))
        o.append("    TEST_ASSERT_EQUAL_STRING(%s, nv(\"i\"));" % cstr(ib))
        o.append("    TEST_ASSERT_EQUAL_STRING(%s, nv(\"q\"));" % cstr(qb))
        o.append("    TEST_ASSERT_EQUAL_STRING(%s, tail());" % cstr(" simplified %d" % simp if simp else ""))
        o.append("}")
        o.append("")
    G.finish(o, names, "test_lot93_propsheet.c")
    return len(cases)


