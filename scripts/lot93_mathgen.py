#!/usr/bin/env python3
"""Lot 93 test generator: the CSS math functions the reader now
simplifies (sin, cos, tan, asin, acos, atan, atan2, pow, sqrt, hypot,
log, exp) and the constants e, pi, infinity, -infinity and nan.

Expectations come from scripts/lot93_mathmodel.py (60-digit decimal
arithmetic and exact integers, no code shared with the C) and, for the
trees around them, from the Lot 92 model (scripts/lot92_mathgen.py: sums,
products, calc, min, max, clamp, abs, sign, round, mod, rem, the units and
their 1/10000 steps). This file adds the Lot 93 functions and constants
to that tree: G.fn_node, G.eval_fn and G.leaf are replaced here (the Lot 92
generator itself is not changed by that).

A case whose exact value lies within lot93_mathmodel.MARGIN of a rounding
boundary is dropped (and counted): the 62-bit C side may round it either
way. Suites:
  test_lot93_trig.c      the trigonometric functions on leaves and short sums
  test_lot93_powlog.c    pow, sqrt, hypot, log, exp
  test_lot93_mtype.c     types: valid trees with the new functions and
                         constants, and values that are not valid
  test_lot93_nested.c    random trees mixing Lot 92 and Lot 93 functions
  test_lot93_compute.c   computed values of registered properties
  test_lot93_propsheet.c registered values computed in the reader sheet

Run: python3 scripts/lot93_mathgen.py
"""
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lot92_mathgen as G  # noqa: E402
import lot93_mathmodel as M  # noqa: E402

OUT = G.OUT
HEADER = "/* %s (generated by scripts/lot93_mathgen.py; expectations from lot93_mathmodel.py). */\n"
SEED_TRIG = 9301
SEED_POW = 9302
SEED_TYPE = 9303
SEED_NEST = 9304
SEED_COMPUTE = 9305
SEED_SHEET = 9306
S = G.S
N, L, P, LP, A, T = G.N, G.L, G.P, G.LP, G.A, G.T
DROPPED = {}

cstr, rcase, fmt, sp = G.cstr, G.rcase, G.fmt, G.sp


# ------------------------------------------------------------ the tree
LOT92_LEAF = G.leaf
LOT92_FN = G.fn_node
LOT92_EVAL = G.eval_fn
CONSTANTS = ["e", "pi", "infinity", "-infinity", "nan"]


def leaf93(rng, t):
    """a Lot 92 leaf, or (numbers) a constant"""
    if t == N and rng.random() < 0.12:
        c = rng.choice(CONSTANTS)
        text = rcase(rng, c) if c != "nan" else rng.choice(["nan", "NaN", "NAN"])
        return {"kind": "leaf", "text": text, "t": N, "v": M.CONST[c]}
    return LOT92_LEAF(rng, t)


def small_num(rng, lo, hi, dec):
    """(text, value in 1/10000) of a number in [lo, hi] with dec decimals"""
    q = 10 ** dec
    k = rng.randint(int(lo * q), int(hi * q))
    v = G.rha(G.F(k, q) * S)
    if not G.fits(v):
        v = None                     # past 100000 units: not known
    neg = k < 0
    k = abs(k)
    w, f = divmod(k, q)
    text = str(w) + ("." + str(f).rjust(dec, "0") if dec else "")
    if neg:
        text = "-" + text
    return {"kind": "leaf", "text": text, "t": N, "v": v}


def fn_node93(rng, t, depth):
    """a Lot 92 function node, or one of Lot 93"""
    choices = ["lot92"] * 5
    if t == N:
        choices += ["sin", "cos", "tan", "pow", "pow", "sqrt", "log", "log", "exp", "hypot"]
    elif t == A:
        choices += ["asin", "acos", "atan", "atan2", "atan2"]
    else:
        choices += ["hypot", "hypot"]
    name = rng.choice(choices)
    if name == "lot92":
        return LOT92_FN(rng, t, depth)
    sub = lambda tt: G.sum_node(rng, tt, depth)  # noqa: E731
    if name in ("sin", "cos", "tan"):
        tt = rng.choice([N, A, A])
        args = [sub(tt)]
    elif name in ("asin", "acos"):
        args = [small_num(rng, -1.05, 1.05, rng.choice([1, 2, 4])) if rng.random() < 0.6 else sub(N)]
    elif name == "atan":
        args = [sub(N)]
    elif name == "atan2":
        tt = rng.choice([N, L, L, P, A, T])
        args = [sub(tt), sub(tt)]
    elif name == "pow":
        base = small_num(rng, -3, 6, rng.choice([0, 1, 2])) if rng.random() < 0.6 else sub(N)
        if rng.random() < 0.5:
            ex = small_num(rng, -6, 8, 0)
        elif rng.random() < 0.5:
            ex = small_num(rng, -3, 3, rng.choice([1, 2]))
        else:
            ex = sub(N)
        args = [base, ex]
    elif name == "sqrt":
        args = [sub(N)]
    elif name == "log":
        a = small_num(rng, -1, 500, rng.choice([0, 2])) if rng.random() < 0.5 else sub(N)
        args = [a]
        if rng.random() < 0.5:
            args.append(small_num(rng, 0, 20, rng.choice([0, 1])) if rng.random() < 0.7 else sub(N))
    elif name == "exp":
        args = [small_num(rng, -13, 13, rng.choice([0, 2, 4])) if rng.random() < 0.6 else sub(N)]
    else:  # hypot
        k = rng.choice([1, 2, 2, 3, 4])
        args = [sub(t if t != LP else rng.choice([L, P])) for _ in range(k)]
    return {"kind": "fn", "name": name, "args": args, "strategy": None}


def eval_fn93(n):
    name = n["name"]
    if name not in ("pow", "sqrt", "hypot", "log", "exp"):
        return LOT92_EVAL(n)
    args = G.lp_args(name, [G.evaluate(a) for a in n["args"]])
    if not args or any(a[0] is None for a in args):
        return None, None
    t = args[0][0]
    for a in args[1:]:
        t = G.tadd(t, a[0])
        if t is None:
            return None, None
    vals = [a[1] for a in args]
    same = all(a[0] == args[0][0] for a in args) and args[0][0] != LP
    if name == "hypot":
        return t, (G.amb(lambda: M.hypot(vals)) if same else None)
    if t != N:
        return None, None
    if name == "pow":
        if len(args) != 2:
            return None, None
        return N, G.amb(lambda: M.pow_(vals[0], vals[1]))
    if name == "log":
        if len(args) > 2:
            return None, None
        return N, G.amb(lambda: M.log(vals[0], vals[1] if len(args) == 2 else None, len(args) == 2))
    if len(args) != 1:
        return None, None
    if name == "sqrt":
        return N, G.amb(lambda: M.sqrt(vals[0]))
    return N, G.amb(lambda: M.exp(vals[0]))


G.leaf = leaf93
G.fn_node = fn_node93
G.eval_fn = eval_fn93


def drop(suite):
    DROPPED[suite] = DROPPED.get(suite, 0) + 1


def expect(tt, v):
    return G.expect_eval(tt, v)


EV_HELPER = ["static char g_o[64], g_r[96];", "",
             "static const char *ev(const char *v) {",
             "    int t = -1, r = wf_cssprop_math_eval(v, &t, g_o, (int)sizeof(g_o));",
             "    if (r < 0) return t == 0 && !g_o[0] ? \"BAD\" : \"BAD BUT SET\";",
             "    if (r == 0) snprintf(g_r, sizeof(g_r), \"T%d %s\", t, g_o[0] ? \"WRITTEN\" : \"KEEP\");",
             "    else snprintf(g_r, sizeof(g_r), \"T%d %s\", t, g_o);",
             "    return g_r;",
             "}", ""]


def write_ev_suite(fname, title, prefix, cases):
    o = [HEADER % title, '#include "../../framework/unity.h"', "#include <string.h>", "#include <stdio.h>",
         '#include "wf_cssprop.h"', ""] + EV_HELPER
    names, per = [], 8
    for b in range(0, len(cases), per):
        name = "%s_%d" % (prefix, b // per)
        names.append(name)
        o.append("static void %s(void) {" % name)
        for text, e in cases[b:b + per]:
            o.append("    TEST_ASSERT_EQUAL_STRING(%s, ev(%s));" % (cstr(e), cstr(text)))
        o.append("}")
        o.append("")
    G.finish(o, names, fname)


def tree_case(rng, n, suite, cases, limit=200):
    G.AMBIG[0] = False
    tt, v = G.evaluate(n)
    text = G.write(rng, n)
    if G.AMBIG[0]:
        drop(suite)
        return
    if len(text) > limit:
        return
    cases.append((text, expect(tt, v)))


# ------------------------------------------------------------ trig
def angle_leaf(rng):
    """an angle leaf: often a multiple of 15 or 30 degrees (exact values)"""
    r = rng.random()
    if r < 0.3:
        deg = rng.choice([15, 30, 45, 60, 90]) * rng.randint(-24, 24)
        u = rng.choice(["deg", "deg", "grad", "turn"])
        fac = {"deg": G.F(1), "grad": G.F(9, 10), "turn": G.F(360)}[u]
        x = G.F(deg) / fac
        if x.denominator not in (1, 2, 4, 5, 8, 10, 20, 25, 40, 50, 100, 1000, 10000):
            u, x = "deg", G.F(deg)
        num = G.F(x)
        text = str(num.numerator) if num.denominator == 1 else ("%.4f" % float(num)).rstrip("0")
        if text.startswith("-0."):
            text = "-" + text[2:] if rng.random() < 0.2 else text
        return {"kind": "leaf", "text": text + rcase(rng, u), "t": A, "v": G.rha(G.F(deg) * S)}
    if r < 0.4:
        # near a pole of tan
        deg = rng.choice([90, -90, 270, 450]) + G.F(rng.randint(-200, 200), 10000)
        text = ("%.4f" % float(deg)).rstrip("0").rstrip(".")
        return {"kind": "leaf", "text": text + "deg", "t": A, "v": G.rha(deg * S)}
    return LOT92_LEAF(rng, A)


def num_leaf(rng):
    r = rng.random()
    if r < 0.5:
        return small_num(rng, -7, 7, rng.choice([0, 1, 2, 4]))
    if r < 0.6:
        return small_num(rng, 95, 105, rng.choice([0, 2, 4]))
    if r < 0.7:
        return leaf93(rng, N)
    return LOT92_LEAF(rng, N)


def write_trig():
    rng = random.Random(SEED_TRIG)
    cases = []
    while len(cases) < 1000:
        k = rng.random()
        if k < 0.55:
            name = rng.choice(["sin", "cos", "tan"])
            if rng.random() < 0.6:
                arg = angle_leaf(rng)
            else:
                arg = num_leaf(rng)
            if rng.random() < 0.15:
                t = arg["t"]
                other = angle_leaf(rng) if t == A else num_leaf(rng)
                arg = {"kind": "sum", "items": [arg, other], "ops": [rng.choice("+-")]}
            n = {"kind": "fn", "name": name, "args": [arg], "strategy": None}
        elif k < 0.8:
            name = rng.choice(["asin", "acos", "atan"])
            if name == "atan" and rng.random() < 0.5:
                arg = num_leaf(rng)
            else:
                arg = small_num(rng, -1.01, 1.01, rng.choice([1, 2, 3, 4]))
                if rng.random() < 0.1:
                    arg = small_num(rng, -1, 1, 0)
            n = {"kind": "fn", "name": name, "args": [arg], "strategy": None}
        else:
            tt = rng.choice([N, L, L, P, A, T])
            if rng.random() < 0.15:
                a, b = LOT92_LEAF(rng, tt), LOT92_LEAF(rng, tt)
                if rng.random() < 0.5:
                    b["text"], b["v"] = "0" + {N: "", L: "px", P: "%", A: "deg", T: "s"}[tt], 0
                else:
                    a["text"], a["v"] = "0" + {N: "", L: "px", P: "%", A: "deg", T: "s"}[tt], 0
            else:
                a, b = LOT92_LEAF(rng, tt), LOT92_LEAF(rng, tt)
            n = {"kind": "fn", "name": "atan2", "args": [a, b], "strategy": None}
        tree_case(rng, n, "trig", cases)
    write_ev_suite("test_lot93_trig.c", "Lot 93: sin, cos, tan, asin, acos, atan and atan2 simplified",
                   "test_l93_trig", cases)
    return len(cases)


