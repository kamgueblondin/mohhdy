# ------------------------------------------------------------ box shorthands
BOX_FROM = [[0, 0, 0, 0], [0, 1, 0, 1], [0, 1, 2, 1], [0, 1, 2, 3]]


def box_case(rng):
    """padding and margin shorthands (1 to 4 unit tokens, a refused token
    is 0), inset on a relative box and border-spacing on a table"""
    spec = []
    for _ in range(3):
        fs = [rng.choice(FS_GOOD[:30])] if rng.random() < 0.7 else []
        lh = [rng.choice(LH_GOOD)] if rng.random() < 0.5 else []
        spec.append((fs, lh))
    elems = M.chain([M.Elem(*spec[0]), M.Elem(), M.Elem(*spec[1]), M.Elem(*spec[2])])
    ctx = elems[3].ctx

    def toks(n, neg):
        out = []
        for _ in range(n):
            if neg and rng.random() < 0.25:
                out.append("-" + unit_text(rng, 0, 2))
            else:
                out.append(unit_text(rng, 0, 3))
        return out
    pad = toks(rng.randrange(1, 5), True)
    mar = toks(rng.randrange(1, 5), True)
    ins = toks(1, True)
    bsp = toks(rng.randrange(1, 3), False)
    pv = []
    for t in pad:
        px = M.unit_px(t, ctx)
        pv.append(0 if px is None or px < 0 else px)
    mv = []
    for t in mar:
        px = M.unit_px(t, ctx)
        mv.append(0 if px is None else px)
    ipx = M.unit_px(ins[0], ctx)
    bpx = [M.unit_px(t, ctx) for t in bsp]
    if ipx is None or abs(ipx) > 300 or max(abs(v) for v in mv) > 300 or max(pv) > 300:
        return None
    bok = all(v is not None and 0 <= v <= 64 for v in bpx)
    bx, by = (bpx[0], bpx[-1]) if bok else (0, 0)

    def sty(fs, lh):
        return ";".join(["font-size:%s" % v for v in fs] + ["line-height:%s" % v for v in lh])
    own = sty(*spec[2])
    sep = ";" if own else ""
    html = ("<html style='%s'><body style='margin:0'><div id=p style='%s'>"
            "<div id=e style='%s%spadding:%s;margin:%s'>xx</div>"
            "<div id=r style='%s%sposition:relative;inset:%s'>yy</div>"
            "<table id=t style='%s%sborder-spacing:%s'><tr><td>z</td></tr></table></div></body></html>"
            % (sty(*spec[0]), sty(*spec[1]), own, sep, " ".join(pad), " ".join(mar), own, sep, ins[0],
               own, sep, " ".join(bsp)))
    lines = ["lay(%s);" % cstr(html)]
    for k in range(4):
        lines.append("TEST_ASSERT_EQUAL(%d, el(\"e\")->padding[%d]);" % (pv[BOX_FROM[len(pad) - 1][k]], k))
    for k in range(4):
        lines.append("TEST_ASSERT_EQUAL(%d, el(\"e\")->margin[%d]);" % (mv[BOX_FROM[len(mar) - 1][k]], k))
    lines.append("TEST_ASSERT_EQUAL(%d, el(\"r\")->offset_x);" % ipx)
    lines.append("TEST_ASSERT_EQUAL(%d, el(\"r\")->offset_y);" % ipx)
    lines.append("TEST_ASSERT_EQUAL(%d, el(\"t\")->border_spacing);" % bx)
    lines.append("TEST_ASSERT_EQUAL(%d, el(\"t\")->border_spacing_y);" % by)
    lines.append("TEST_ASSERT_%s(diag_has(\"border spacing refused\"));" % ("FALSE" if bok else "TRUE"))
    return html, lines


