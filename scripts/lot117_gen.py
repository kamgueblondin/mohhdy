def um_leaf(rng):
    k = rng.random()
    if k < 0.45:
        return unit_text(rng, 0, 6)
    if k < 0.65:
        return "%dpx" % rng.randrange(0, 200)
    if k < 0.8:
        return "%d%%" % rng.randrange(0, 101)
    if k < 0.85:
        return rng.choice(["1.5px", "2.5%", "1.5", "3rex", "2zz", "2000em", "130em", "124em", ".5em", "1.e"])
    return "%dpx" % rng.randrange(0, 40)


def um_val(rng, depth):
    k = rng.random()
    if depth >= 3 or k < 0.3:
        return um_leaf(rng)
    if k < 0.5:
        f = rng.choice(["min", "max"])
        return "%s(%s)" % (f, ", ".join(um_val(rng, depth + 1) for _ in range(rng.randrange(1, 5))))
    if k < 0.6:
        return "clamp(%s)" % ", ".join(um_val(rng, depth + 1) for _ in range(3))
    if k < 0.7:
        return "calc(%s)" % um_val(rng, depth + 1)
    if k < 0.9:
        n = rng.randrange(2, 5)
        return " ".join(sum(([um_val(rng, depth + 1), rng.choice("+-")] for _ in range(n)), [])[:-1])
    return "%s * %d" % (um_val(rng, depth + 1), rng.choice([2, 3])) if rng.random() < 0.6 else \
        "%s / %d" % (um_val(rng, depth + 1), rng.choice([2, 3, 0]))


def um_value(rng):
    while True:
        v = um_val(rng, 0)
        if v.startswith(("calc(", "min(", "max(", "clamp(")):
            return v


def write_umath():
    rng = random.Random(11703)
    cases, seen, took = [], set(), 0
    while len(cases) < 360:
        v = um_value(rng)
        f = rng.choice(["16px", "20px", "13.5px", "22.5px", "10px", "1.5em", "30px"])
        r = rng.choice(["16px", "20px", "12.5px"])
        lh = rng.choice(["normal", "1.5", "20px", "1.25"])
        if (v, f, r, lh) in seen or len(v) > 400:
            continue
        seen.add((v, f, r, lh))
        elems = M.chain([M.Elem([r]), M.Elem(), M.Elem(), M.Elem([f], [lh])])
        e = elems[3]
        # Lot 118: the math of scripts/lot118_model.py (values in thousandths)
        try:
            root = M118.parse(v, M.ctx118(e.ctx))
            count = _count_nodes(v, e.ctx)
            try:
                w = min(max(M118.px_of(M118.evaluate(root, 600)[0]), 0), L116.LAYOUT_MAX)
            except M118.Refused:
                w = 600
        except M118.Refused:
            w, count = None, 0
        if w is None and rng.random() < 0.5:
            continue
        html = ("<html style='font-size:%s'><body style='margin:0'><div id=g style='width:600px'>"
                "<div id=a style='font-size:%s;line-height:%s;height:10px;width:50px;width:%s'>A</div></div></body></html>"
                % (r, f, lh, v))
        lines = ["lay(%s);" % cstr(html)]
        if w is None:
            lines += ["TEST_ASSERT_EQUAL(50, el(\"a\")->w);", "TEST_ASSERT_EQUAL(0, el(\"a\")->length[WE_LEN_WIDTH].count);",
                      "TEST_ASSERT_TRUE(diag_has(\"math length refused\"));"]
        else:
            took += 1
            lines += ["TEST_ASSERT_EQUAL(%d, el(\"a\")->w);" % w,
                      "TEST_ASSERT_EQUAL(%d, el(\"a\")->length[WE_LEN_WIDTH].count);" % count,
                      "TEST_ASSERT_FALSE(diag_has(\"math length refused\"));"]
        cases.append(lines)
    o = [HEADER % "Lot 117: width math with font-relative leaves"] + PRELUDE
    names = chunks(o, "test_l117_umath", cases, 16)
    finish(o, names, "test_lot117_umath.c")
    return "%d (%d taken)" % (len(cases), took)


def _count_nodes(v, ctx):
    p = M118.Parser(v, M.ctx118(ctx))
    p.sum()
    return p.count


