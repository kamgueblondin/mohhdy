def _lead_digit(v):
    return v[:1].isdigit()


# property: (field expression, initial, check(px, v) -> stored value or None refused)
PROP2 = {
    "letter-spacing": ("el(\"e\")->letter_spacing", 0, lambda px, v: px if -4 <= px <= 16 else None),
    "word-spacing": ("el(\"e\")->word_spacing", 0, lambda px, v: px if -8 <= px <= 32 else None),
    "tab-size": ("el(\"e\")->tab_px", 64, lambda px, v: px if _lead_digit(v) and 0 <= px <= 255 else None),
    "outline-width": ("el(\"e\")->outline_w", 3, lambda px, v: min(px, 64) if _lead_digit(v) and px >= 0 else None),
    "text-underline-offset": ("el(\"e\")->underline_off", 0, lambda px, v: px if 0 <= px <= 16 else None),
    "column-width": ("el(\"e\")->col_width", -1, lambda px, v: px if _lead_digit(v) and px >= 1 else None),
    "border-width": ("el(\"e\")->border", 0, lambda px, v: px if 0 <= px <= 64 else None),
    "flex-basis": ("el(\"e\")->flex_basis", -1, lambda px, v: px if px >= 0 else None),
    "margin-inline": ("el(\"e\")->margin[3]", 0, lambda px, v: px),
    "padding-block": ("el(\"e\")->padding[0]", 0, lambda px, v: px if px >= 0 else None),
    "max-width": ("el(\"e\")->w", 640, lambda px, v: min(px, 640) if px >= 0 else None),
    "left": ("el(\"e\")->offset_x", 0, lambda px, v: px),
}


def props_case(rng):
    spec = []
    for _ in range(3):
        fs = [rng.choice(FS_GOOD[:30])] if rng.random() < 0.7 else []
        lh = [rng.choice(LH_GOOD)] if rng.random() < 0.5 else []
        spec.append((fs, lh))
    elems = M.chain([M.Elem(*spec[0]), M.Elem(), M.Elem(*spec[1]), M.Elem(*spec[2])])
    e = elems[3]
    prop = rng.choice(sorted(PROP2))
    field, cur, check = PROP2[prop]
    vals = []
    for _ in range(rng.choice([1, 1, 2])):
        if prop in ("margin-inline", "left", "letter-spacing", "word-spacing") and rng.random() < 0.25:
            vals.append("-" + unit_text(rng, 0, 2))
        elif rng.random() < 0.1:
            vals.append(rng.choice([".5em", ".25rem"]))
        else:
            vals.append(unit_text(rng, 0, 4))
    for v in vals:
        px = M.unit_px(v, e.ctx)
        r = None if px is None else check(px, v)
        if r is not None:
            cur = r
    if prop == "left" and abs(cur) > 600:
        return None
    pre = "position:relative;" if prop == "left" else ""
    decls = ["font-size:%s" % v for v in spec[2][0]] + ["line-height:%s" % v for v in spec[2][1]]
    pos = rng.randrange(len(decls) + 1)
    decls[pos:pos] = ["%s:%s" % (prop, v) for v in vals]

    def sty(fs, lh):
        return ";".join(["font-size:%s" % v for v in fs] + ["line-height:%s" % v for v in lh])
    html = ("<html style='%s'><body style='margin:0'><div id=p style='%s'><div id=e style='%s%s'>xx yy</div></div>"
            "</body></html>" % (sty(*spec[0]), sty(*spec[1]), pre, ";".join(decls)))
    return html, ["lay(%s);" % cstr(html), "TEST_ASSERT_EQUAL(%d, %s);" % (cur, field)]


