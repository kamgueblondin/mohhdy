def lh_value(rng):
    k = rng.random()
    if k < 0.55:
        return rng.choice(LH_GOOD)
    if k < 0.65:
        return rng.choice(LH_BAD)
    if k < 0.85:
        return unit_text(rng, 0, 3, places=3)
    return dec(rng, 0, 3, 3)


# ------------------------------------------------------------ units
PROPS = ["margin-left", "padding-left", "text-indent", "width", "height"]


def prop_value(rng, prop):
    k = rng.random()
    if prop == "margin-left" and k < 0.2:
        return "-" + unit_text(rng, 0, 8)
    if k < 0.08:
        # refused: no number (a number with another unit is the legacy px)
        return rng.choice(["em", "rem", "lh", "xem", "-em"])
    return unit_text(rng, 0, 12)


def apply_prop(prop, vals, ctx):
    """the property's value after its declarations: (field value, refused any)"""
    cur, refused = {"margin-left": 0, "padding-left": 0, "text-indent": 0, "width": None, "height": None}[prop], False
    for v in vals:
        px = M.unit_px(v, ctx)
        if px is None:
            refused = True
            continue
        if prop == "padding-left" and px < 0:
            refused = True
            continue
        if prop == "text-indent" and not 0 <= px <= 400:
            refused = True
            continue
        if prop in ("width", "height") and px < 0:
            refused = True
            continue
        cur = px
    return cur, refused


def units_case(rng):
    spec = []
    for _ in range(3):        # html, p, e
        fs = [fs_value(rng)] if rng.random() < 0.6 else []
        if rng.random() < 0.15:
            fs.append(fs_value(rng))
        lh = [lh_value(rng)] if rng.random() < 0.5 else []
        spec.append((fs, lh))
    elems = M.chain([M.Elem(*spec[0]), M.Elem(), M.Elem(*spec[1]), M.Elem(*spec[2])])
    e = elems[3]
    prop = rng.choice(PROPS)
    vals = [prop_value(rng, prop) for _ in range(rng.choice([1, 1, 2]))]
    val, refused = apply_prop(prop, vals, e.ctx)
    if prop == "width" and val is not None and val > 600:
        return None
    if prop == "height" and val is not None and val > 1500:
        return None
    if any("'" in x or ";" in x for x in vals):
        return None
    decls = ["font-size:%s" % v for v in spec[2][0]] + ["line-height:%s" % v for v in spec[2][1]] + \
            ["%s:%s" % (prop, v) for v in vals]
    rng.shuffle(decls)
    # keep the order of the font-size, line-height and property declarations among themselves
    fsq = ["font-size:%s" % v for v in spec[2][0]]
    lhq = ["line-height:%s" % v for v in spec[2][1]]
    pq = ["%s:%s" % (prop, v) for v in vals]
    out = []
    for d in decls:
        q = fsq if d.startswith("font-size:") else lhq if d.startswith("line-height:") else pq
        out.append(q.pop(0))

    def sty(fs, lh):
        return ";".join(["font-size:%s" % v for v in fs] + ["line-height:%s" % v for v in lh])
    html = ("<html style='%s'><body style='margin:0'><div id=p style='%s'><div id=e style='%s'>x</div></div></body></html>"
            % (sty(*spec[0]), sty(*spec[1]), ";".join(out)))
    if any(c in html for c in "\"\\"):
        return None
    lines = ["lay(%s);" % cstr(html)]
    for ident, el in (("p", elems[2]), ("e", e)):
        lines.append("font_lh(%s, %d, %d, %d, %d, %d);" % ((cstr(ident), M.font_px(el.font100), el.font100) +
                                                           L116.lh_fields(el.lhc)))
    if prop == "margin-left":
        lines.append("TEST_ASSERT_EQUAL(%d, el(\"e\")->margin[3]);" % val)
    elif prop == "padding-left":
        lines.append("TEST_ASSERT_EQUAL(%d, el(\"e\")->padding[3]);" % val)
    elif prop == "text-indent":
        lines.append("TEST_ASSERT_EQUAL(%d, el(\"e\")->text_indent);" % val)
    elif prop == "width":
        lines.append("TEST_ASSERT_EQUAL(%d, el(\"e\")->w);" % (640 if val is None else val))
    else:
        if val is None:
            lines.append("TEST_ASSERT_EQUAL(%d, el(\"e\")->h);" % L116.lines_h(e.lh100, 1))
        else:
            lines.append("TEST_ASSERT_EQUAL(%d, el(\"e\")->h);" % val)
    return html, lines


def write_units():
    rng = random.Random(11701)
    cases, seen = [], set()
    while len(cases) < 420:
        r = units_case(rng)
        if r is None or r[0] in seen:
            continue
        seen.add(r[0])
        cases.append(r[1])
    o = [HEADER % "Lot 117: font-relative units in the engine's lengths"] + PRELUDE
    names = chunks(o, "test_l117_units", cases, 12)
    finish(o, names, "test_lot117_units.c")
    return len(cases)


