def write_clamp():
    rng = random.Random(11705)
    cases, seen = [], set()
    while len(cases) < 200:
        n = rng.randrange(1, 6)
        total = rng.randrange(n + 1, 9)
        k = rng.random()
        if k < 0.4:
            lh = dec(rng, 10, 40, 2) + "px"
            fs = "16px"
        elif k < 0.8:
            lh = rng.choice(["1.3", "1.25", "1.5", "1.15", "1.7"])
            fs = rng.choice(["13.5px", "15.25px", "17.77px", "16px", "22.5px", "11.1px"])
        else:
            lh = rng.choice(["1.3em", "125%", "1.15lh", "calc(1em + 0.3ex)", "1.5rem"])
            fs = rng.choice(["13.5px", "15.25px", "17px"])
        elems = M.chain([M.Elem(), M.Elem(), M.Elem([fs], [lh])])
        used = elems[2].lh100
        html = ("<body style='margin:0'><div id=a style='width:300px;font-size:%s;line-height:%s;line-clamp:%d'>%s</div>"
                "<div id=n>after</div></body>" % (fs, lh, n, "<br>".join("L%d" % i for i in range(total))))
        if html in seen:
            continue
        seen.add(html)
        h = L116.lines_h(used, n)
        lines = ["lay(%s);" % cstr(html),
                 "TEST_ASSERT_EQUAL(%d, el(\"a\")->h);" % h,
                 "TEST_ASSERT_EQUAL(%d, text_y(\"after\"));" % (h + 1),
                 "TEST_ASSERT_EQUAL(-1000, text_y(\"L%d\"));" % n,
                 "TEST_ASSERT_TRUE(diag_has(\"line clamp\"));"]
        if n > 2:
            # the last kept line ends with the dots: the one before it
            lines.append("TEST_ASSERT_EQUAL(%d, text_y(\"L%d\") - 1);" % (L116.lines_h(used, n - 2), n - 2))
        cases.append(lines)
    o = [HEADER % "Lot 117: line-clamp with fractional line heights"] + PRELUDE
    names = chunks(o, "test_l117_clamp", cases, 10)
    finish(o, names, "test_lot117_clamp.c")
    return len(cases)


