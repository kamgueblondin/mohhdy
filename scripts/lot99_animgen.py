TF_POOL = ["translate", "translatex", "translatey", "translatez", "translate3d", "scale", "scalex", "scaley",
           "scalez", "scale3d", "rotate", "rotatex", "rotatey", "rotatez", "rotate3d", "skew", "skewx", "skewy",
           "matrix", "perspective"]
COMMON = ["translate", "rotate", "scale", "skew", "translatex", "rotate3d"]


def targ(rng, kind):
    if kind == "P":
        return rng.choice([dec(rng, -200, 200, 2) + "px", dec(rng, -100, 100, 2) + "%", "0px", "10px", "50%",
                           "1in"])
    if kind == "L":
        return rng.choice([dec(rng, -200, 200, 2) + "px", "0px", "1cm", "12pt"])
    if kind == "A":
        return rng.choice([dec(rng, -360, 360, 2) + "deg", dec(rng, -1, 1, 2) + "turn", dec(rng, -400, 400, 1) + "grad",
                           dec(rng, -3, 3, 3) + "rad", "0deg", "45deg", "0"])
    if kind == "S":
        return rng.choice([dec(rng, -3, 5, 2), dec(rng, -100, 300, 1) + "%", "1", "2", "0.5", "100%"])
    return rng.choice(["0", "1", "0.5", dec(rng, -2, 2, 2)])


def tf_text(rng, name=None):
    name = name or (rng.choice(COMMON) if rng.random() < 0.6 else rng.choice(TF_POOL))
    lo, hi, kinds = P.TFNS[name]
    n = rng.randrange(lo, hi + 1)
    if name == "rotate3d" and rng.random() < 0.6:
        axis = rng.choice(["0, 0, 1", "1, 0, 0", "0, 1, 0"])
        return "rotate3d(%s, %s)" % (axis, targ(rng, "A"))
    return "%s(%s)" % (name, ", ".join(targ(rng, kinds[k]) for k in range(n)))


def tl_text(rng, like=None):
    if like is not None and rng.random() < 0.7:
        names = [f.split("(")[0] for f in M.tl_funcs(like)] if like.endswith(")") else [rng.choice(COMMON)]
        if rng.random() < 0.3:
            names = names[:rng.randrange(1, len(names) + 1)] if rng.random() < 0.5 else \
                names + [rng.choice(COMMON)]
        return " ".join(tf_text(rng, nm) for nm in names)
    return " ".join(tf_text(rng) for _ in range(rng.randrange(1, 4)))


SYNS = ["'<transform-list>'", "'<transform-list>'", "'<transform-function>'", "'<transform-function>+'",
        "'<transform-function>#'", "'<length> | <transform-list>'", "'<transform-function> | <transform-list>'",
        "'<length>'", "'<angle>+'", "'<color>'", "'<percentage>#'", "'<number>'", "'*'"]


def acc_values(rng, syn):
    if "transform" not in syn:
        t = syn.strip("'")
        if t == "*":
            return "translate(1px)", "translate(2px)"
        m = t[-1] if t[-1] in "+#" else ""
        base = t.rstrip("+#")
        one = lambda: G.value_of(rng, base)  # noqa: E731
        n = rng.randrange(1, 3) if m else 1
        sep = ", " if m == "#" else " "
        return sep.join(one() for _ in range(n)), sep.join(one() for _ in range(n))
    if syn == "'<transform-function>#'":
        n = rng.randrange(1, 3)
        a = [tf_text(rng) for _ in range(n)]
        b = [tf_text(rng, f.split("(")[0]) if rng.random() < 0.7 else tf_text(rng) for f in a]
        if rng.random() < 0.15:
            b = b[:1] + [tf_text(rng)]
        return ", ".join(a), ", ".join(b)
    if syn == "'<transform-function>'":
        a = tf_text(rng)
        return a, tf_text(rng, a.split("(")[0]) if rng.random() < 0.7 else tf_text(rng)
    if syn == "'<transform-function> | <transform-list>'" and rng.random() < 0.5:
        a = tf_text(rng)
        return a, tl_text(rng, a)
    if syn == "'<length> | <transform-list>'" and rng.random() < 0.3:
        return rng.choice([("10px", "translate(1px)"), ("5px", "2px"), ("translate(1px)", "3px")])
    a = tl_text(rng)
    return a, tl_text(rng, a)


def write_accum():
    rng = random.Random(9902)
    cases = []
    while len(cases) < 520:
        syn = rng.choice(SYNS)
        code, parsed = P.parse_syntax(syn)
        alts = None if syn == "'*'" else parsed
        if alts is None and syn != "'*'":
            continue
        a, b = acc_values(rng, syn)
        if alts is not None:
            if A.first_alt(alts, a) is None or A.first_alt(alts, b) is None:
                continue
            a, b = G98.computed(alts, a), G98.computed(alts, b)
        ra, ca = M.combine(alts, "add", a, b, 160)
        rc, cc = M.combine(alts, "accumulate", a, b, 160)
        if len(a) >= 120 or len(b) >= 120:
            continue
        cases.append(["TEST_ASSERT_EQUAL_STRING(%s, ad(%s, %s, %s, %d));" % (cstr(ra), cstr(syn), cstr(a), cstr(b), ca),
                      "TEST_ASSERT_EQUAL_STRING(%s, ac(%s, %s, %s, %d));" % (cstr(rc), cstr(syn), cstr(a), cstr(b), cc)])
    o = [HEADER % "Lot 99: add and accumulate side by side (wf_cssprop_add, wf_cssprop_accumulate)"] + G98.IP_C + [
        "/* the sum text; the return code is checked against code */",
        "static const char *ad(const char *s, const char *under, const char *v, int code) {",
        "    if (!syn(s)) return \"BAD SYNTAX\";",
        "    if (wf_cssprop_add(&g_p, under, v, g_o, (int)sizeof(g_o)) != code) return \"BAD CODE\";",
        "    return g_o;",
        "}", "",
        "static const char *ac(const char *s, const char *under, const char *v, int code) {",
        "    if (!syn(s)) return \"BAD SYNTAX\";",
        "    if (wf_cssprop_accumulate(&g_p, under, v, g_o, (int)sizeof(g_o)) != code) return \"BAD CODE\";",
        "    return g_o;",
        "}", ""]
    names = chunks(o, "test_l99_accum", cases, 10)
    finish(o, names, "test_lot99_accum.c")
    return len(cases)


