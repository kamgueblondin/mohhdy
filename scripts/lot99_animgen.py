def hue_text(rng, upper=False):
    k = rng.randrange(7)
    if k == 0:
        h = dec(rng, -400, 800) + "deg"
    elif k == 1:
        h = dec(rng, -400, 800) + "grad"
    elif k == 2:
        h = dec(rng, -2, 3) + "turn"
    elif k == 3:
        h = dec(rng, -7, 13) + "rad"
    elif k == 4:
        h = rng.choice(["0.5turn", "1turn", "0.25turn", "200grad", "100grad", "3.1416rad", "1.5708rad", "6.2832rad",
                        "0rad", "-0.5turn", "400grad", "0.1turn", "2rad"])
    elif k == 5:
        h = dec(rng, -720, 720)
    else:
        h = str(rng.randrange(0, 361))
    if upper and rng.random() < 0.5:
        h = h.upper() if rng.random() < 0.5 else h[:-1] + h[-1].upper()
    return h


def sl(rng, pct=True):
    return G98.sl_text(rng, pct)


def hsl_unit(rng, alpha=None):
    """an hsl() text with a hue in any unit; alpha: None (random), or a
    text"""
    h = hue_text(rng)
    form = rng.randrange(3)
    if alpha is None:
        alpha = rng.choice(["", "", "", "1", "100%", "0.5", "50%", "2", "150%", "0", "0.9999", "99.99%"])
    if form == 0:
        f = "hsla" if alpha and rng.random() < 0.6 else "hsl"
        return "%s(%s, %s, %s%s)" % (f, h, sl(rng), sl(rng), ", " + alpha if alpha else "")
    if form == 1:
        return "hsl(%s %s %s%s)" % (h, sl(rng, rng.random() < 0.7), sl(rng, rng.random() < 0.7),
                                    " / " + alpha if alpha else "")
    return "hsla(%s %s %s%s)" % (h, sl(rng), sl(rng), " / " + alpha if alpha else "")


def rgb24_text(rng):
    k = rng.randrange(12)
    if k < 5:
        t = hsl_unit(rng)
    elif k == 5:
        t = hsl_unit(rng, "1").upper()
    elif k == 6:
        t = rng.choice(["rgb(1, 2, 3)", "red", "#123456", "rgba(1, 2, 3, 1)", "hsx(1, 2%, 3%)", "hs(1, 2%, 3%)",
                        "hsl(1, 2%, 3%", "hsl(tan, 2%, 3%)", "hsl()", "hsl(1turns, 2%, 3%)", "hsl(1 2% 3% 4%)",
                        "hsl(1, 2%, 3%) 4", "hsl(1deg 2% 3%)x", "hsl(1, 2, 3%)", "hsl(1, 2%, 3% / 1)",
                        "hsl(1rad, 50%, 50%, 1, 1)", "hsl((1), 2%, 3%)", "hsl(calc(1deg), 2%, 3%)", "hsl(1gr, 2%, 3%)"])
    elif k == 7:
        t = hsl_unit(rng, "1") + rng.choice([";", " ;", "; color: red", " !important", "!important", " x", "x",
                                              "  ", " )", ", red"])
    elif k == 8:
        t = rng.choice([" ", "  ", "\t"]) + hsl_unit(rng, "")
    elif k == 9:
        t = hsl_unit(rng, rng.choice(["0.5", "0", "99%", "0.99995", "1.5", "100%", "1"]))
    elif k == 10:
        t = "hsl(%s, %s, 50%%)" % (hue_text(rng, True), rng.choice(["100%", "50%", "0%"]))
    else:
        t = "hsl(%s %s %s)" % (rng.choice(["0", "120", "240", "60", "180", "300", "0.5turn", "1rad", "100grad"]),
                               rng.choice(["100%", "50%", "0%", "75%"]), rng.choice(["50%", "25%", "75%", "100%", "0%"]))
    return t


def rgb_str(c):
    return "-" if c is None else "#%02x%02x%02x" % c


def write_color():
    rng = random.Random(9901)
    cases = []
    seen = set()
    while len(cases) < 300:
        t = rgb24_text(rng)
        if t in seen or len(t) >= 120:
            continue
        seen.add(t)
        cases.append(["TEST_ASSERT_EQUAL_STRING(%s, rg(%s));" % (cstr(rgb_str(M.rgb24(t))), cstr(t))])
    while len(cases) < 520:
        a = hsl_unit(rng)
        b = rng.choice([hsl_unit(rng), hsl_unit(rng), G.colour_text(rng), a])
        if rng.random() < 0.5:
            a, b = b, a
        if not (A.colour_match(a) and A.colour_match(b)):
            continue
        tt = rng.choice([5000, rng.randrange(1, S), rng.randrange(1, S), 1, 9999, 2500])
        r, c = A.interp([("<color>", "", None)], a, b, tt)
        if r is None:
            continue
        cases.append(["TEST_ASSERT_EQUAL_STRING(%s, ip(%s, %s, %d, %d));" % (cstr(r), cstr(a), cstr(b), tt, c)])
    o = [HEADER % "Lot 99: hsl() hue units, the reader colour (wf_cssprop_rgb24) and hsl() interpolation"] + \
        G98.IP_C + [
        "/* the reader colour of v as #rrggbb, \"-\" when it is not one */",
        "static const char *rg(const char *v) {",
        "    unsigned int c = 0xdeadbeefu;",
        "    int r = wf_cssprop_rgb24(v, (int)strlen(v), &c);",
        "    if (!r) return c == 0xdeadbeefu ? \"-\" : \"WRITTEN\";",
        "    if (r != 1 || c > 0xffffffu) return \"BAD CODE\";",
        "    snprintf(g_o, sizeof(g_o), \"#%06x\", c);",
        "    return g_o;",
        "}", "",
        "/* the interpolated text of two colours; the return code is checked */",
        "static const char *ip(const char *a, const char *b, int t, int code) {",
        "    if (!syn(\"'<color>'\")) return \"BAD SYNTAX\";",
        "    if (wf_cssprop_interp(&g_p, a, b, t, g_o, (int)sizeof(g_o)) != code) return \"BAD CODE\";",
        "    return g_o;",
        "}", ""]
    o.insert(3, "#include <stdio.h>")
    names = chunks(o, "test_l99_color", cases, 10)
    finish(o, names, "test_lot99_color.c")
    return len(cases)


