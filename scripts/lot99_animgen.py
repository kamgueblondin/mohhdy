def sheet_value(rng, t, like=None):
    if t == "<transform-list>":
        return tl_text(rng, like)
    if t == "<transform-function>+":
        return tl_text(rng, like)
    if t == "<transform-function>":
        if like and rng.random() < 0.7:
            return tf_text(rng, like.split("(")[0])
        return tf_text(rng)
    if t == "<color>" and rng.random() < 0.3:
        return hsl_unit(rng, rng.choice(["", "1", "0.5"]))
    return G98.sheet_value(rng, t)


def keyframes(rng, t, alts, name, like):
    """the rule text and its model frames: often without 0% or 100%"""
    offs = sorted(rng.sample([0, 2500, 5000, 7500, 10000, 3333, 6000, 5000], rng.randrange(1, 3)))
    offs = sorted(set(offs))
    if rng.random() < 0.6:
        offs = [o for o in offs if o not in (0, S)] or [5000]
    blocks, frames = [], []
    for o in offs:
        v = sheet_value(rng, t, like)
        body = "--p: %s" % v
        fe = fc = None
        if rng.random() < 0.15:
            ft = rng.choice(["linear", "ease-in", "steps(2)"])
            fe = A.ease_parse(ft)
            body += "; animation-timing-function: %s" % ft
        if rng.random() < 0.2:
            fc = rng.choice(M98.COMPS)
            body += "; animation-composition: %s" % fc
        blocks.append("%s { %s }" % (G98.offset_sel(rng, o), body))
        frames.append((o, G98.computed(alts, v), fe, fc))
    return "@keyframes %s { %s }" % (name, " ".join(blocks)), frames


