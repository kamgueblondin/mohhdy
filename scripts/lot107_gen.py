def height_case(rng):
    rules = [("#o", h_decls(rng)), ("#b", h_decls(rng))]
    if rng.random() < 0.3:
        rules.append(("div", h_decls(rng)))
    rng.shuffle(rules)
    ranked = ranked_of(rules)
    fsz = font_sizes(rng)
    try:
        nodes = nodes_of(ranked, fsz)
    except M.Unsure:
        return None
    css = "@keyframes k { from { color: #000000 } to { color: #ffffff } } " + G5.rules_css(rules) + " " + \
        fs_css(fsz) + " #i { animation: k 1s linear; animation-timeline: scroll(nearest) }" + \
        " #r { animation: k 1s linear; animation-timeline: view() }"
    scr = set()
    for k in (4, 5):
        s = M5.scroller_of(nodes, k)
        if s >= 0:
            scr.add(s)
    lines = ["prep(%s);" % cstr(css)]
    try:
        for k in (2, 3):
            lines.append("TEST_ASSERT_EQUAL(%d, wf_site_box_scroller(&g_d, %d));" % (M5.box_scroller(nodes, k), ci(k)))
            sc = nodes[k]["sc"]
            lines.append("TEST_ASSERT_EQUAL_STRING(%s, sc_of(%d));" % (cstr("%d %d %d %d %d %d" % (
                sc[0], sc[1], sc[2], sc[4], int(k in scr), nodes[k]["fs"] * 1000)), ci(k)))
            t = [x for x in (own_fs(fsz, k), M.passed(nodes, k, scr)) if x]
            lines.append("TEST_ASSERT_EQUAL_STRING(%s, style_of(%s));" % (
                cstr(' style="%s"' % ";".join(t) if t else ""), cstr(IDS[k])))
    except M.Unsure:
        return None
    return css, lines


