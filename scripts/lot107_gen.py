def h_value(rng):
    k = rng.random()
    if k < 0.1:
        return rng.choice(BAD)
    if k < 0.2:
        return rng.choice(KEEP)
    if k < 0.45:
        return rng.choice(REL) if rng.random() < 0.8 else "%s%s" % (
            rng.choice(["%d" % rng.randrange(0, 60), "%d.%d" % (rng.randrange(0, 30), rng.randrange(1, 100))]),
            rng.choice(["em", "rem", "vw", "vh", "vmin", "vmax"]))
    if k < 0.6:
        return rng.choice(PCT) if rng.random() < 0.7 else "%d%%" % rng.randrange(0, 300)
    if k < 0.78:
        return rng.choice(MATH)
    return rng.choice(ABSV) if rng.random() < 0.5 else "%dpx" % rng.randrange(0, 600)


def ov_value(rng):
    return rng.choice(["auto", "scroll", "auto", "scroll", "hidden", "visible", "clip", "hidden auto",
                       "visible scroll", "auto hidden"])


def h_decls(rng):
    d = []
    if rng.random() < 0.85:
        p = rng.choice(["overflow", "overflow", "overflow-y"])
        d.append((p, ov_value(rng) if p == "overflow" else rng.choice(["auto", "scroll", "hidden", "visible"])))
    for prop, q in (("height", 0.7), ("max-height", 0.55)):
        if rng.random() < q:
            d.append((prop, h_value(rng)))
    if rng.random() < 0.25:
        d.append((rng.choice(["height", "max-height"]), h_value(rng)))
    rng.shuffle(d)
    return [(p, v + (" !important" if rng.random() < 0.1 else "")) for p, v in d]


def font_sizes(rng):
    """font-size px on html, #o, #b (None: not set)"""
    return {k: (rng.choice([8, 10, 12, 20, 24, 32, rng.randrange(4, 50)]) if rng.random() < q else None)
            for k, q in ((0, 0.4), (2, 0.25), (3, 0.4))}


def fs_of(fsz):
    """the font size of each node and the root's"""
    root = fsz[0] or 16
    fs = []
    for k in range(len(ELS)):
        p = PARENTS[k]
        f = fsz.get(k) or (fs[p] if p >= 0 else 16)
        fs.append(f)
    return fs, root


def ranked_of(rules):
    ranked = {k: [] for k in range(len(ELS))}
    order = 0
    for sel, decls in rules:
        for p, v in decls:
            order += 1
            im = v.endswith(" !important")
            vv = v[:-len(" !important")] if im else v
            for k in range(len(ELS)):
                if sel == ELS[k] or (sel == "div" and TAGS[k] == "div"):
                    spec = (1, 0, 0) if sel.startswith("#") else (0, 0, 1)
                    ranked[k].append(((int(im), spec, order), p, vv))
    return ranked


def nodes_of(ranked, fsz, tl=None, sp=None):
    fs, root = fs_of(fsz)
    nodes = []
    for k in range(len(ELS)):
        nodes.append({"parent": PARENTS[k], "tag": TAGS[k], "sc": M.sc_cascade(ranked[k]), "fs": fs[k], "rem": root,
                      "tl": tl[k] if tl else [None] * 6,
                      "sp": M.sp_cascade(sp[k]) if sp else [("auto",)] * 4})
    return nodes


def own_fs(fsz, k):
    """the font-size the reader writes for node k (its own one)"""
    return "font-size:%dpx" % fsz[k] if fsz.get(k) else ""


def fs_css(fsz):
    return " ".join("%s { font-size: %dpx }" % (ELS[k], v) for k, v in sorted(fsz.items()) if v)


