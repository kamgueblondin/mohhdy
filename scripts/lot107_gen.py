#!/usr/bin/env python3
"""Lot 107 test generator: relative heights and max-height on box
scrollers, scroll-padding as the auto insets of view timelines, legacy
colour interpolation past the ends (CSS Color 4 12.3).

Expectations come from scripts/lot107_model.py (written from CSS Values 4
for the font and viewport units and the math functions, CSS Overflow 3,
CSS Scroll Snap 1 for scroll-padding, CSS Scroll-driven Animations 1 for
the auto insets and CSS Color 4 12.3) with the lot 97 to 106 models, not
from the C sources. A value the exact model cannot place against the C's
rounding (lot107_model.Unsure, lot101_colormodel.Unsure) is left out.

* test_lot107_height.c: overflow, height, max-height and font-size on the
  elements of a page (the box scrollers, hpx and mpx kept, the style the
  reader passes on for a box scroller a timeline reads);
* test_lot107_pad.c: wf_site_prepare_ext after wf_site_set_geom: colour
  keyframes on view timelines whose auto insets come from the
  scroll-padding of the scroller (a box scroller or the root element);
* test_lot107_interp.c: legacy sRGB interpolation of <color> values past
  0 and 1 (premultiplied by the unclamped alpha, the alpha clamped after);
* test_lot107_flow.c: the reader's style on a box scroller with font,
  viewport or math heights and max-height, laid out by the engine (the
  scrollport is the height, the smaller of height and max-height, or the
  smaller of max-height and the content height measured in the test).

Run: python3 scripts/lot107_gen.py
"""
