# ------------------------------------------------------------- reader to engine
FLOW_H = ["10em", "2.5em", "3rem", "20vh", "10vw", "12.5vh", "5vmin", "5vmax", "calc(2em + 10px)", "max(50px, 4em)",
          "min(300px, 20vh)", "clamp(40px, 10vh, 90px)", "calc(1rem * 5)", "7.5rem", "100px", "64px", "1in", "6pc"]


def flow_case(rng):
    """a box scroller #o read by scroll(nearest) on #i, its height and/or
    max-height given in font, viewport or math lengths, n lines inside:
    (css, n, the style the reader writes on #o, the expected scrollport:
    ("h", px) for a height (min with max-height), ("m", px) for a
    max-height alone (min with the content height), the css measuring the
    content height)"""
    fsz = {0: rng.choice([None, None, 10, 12, 20, 24]), 2: rng.choice([None, None, 8, 10, 14, 20])}
    root = fsz[0] or 16
    em = fsz[2] or root
    k = rng.randrange(3)
    h = rng.choice(FLOW_H) if k != 1 else None
    m = rng.choice(FLOW_H) if k != 0 else None
    decls = [("overflow", rng.choice(["auto", "scroll", "hidden auto", "visible scroll"]))]
    if h:
        decls.append(("height", h))
    if m:
        decls.append(("max-height", m))
    if fsz[2]:
        decls.append(("font-size", "%dpx" % fsz[2]))
    rng.shuffle(decls)
    try:
        hv = M.box_len(M.height_val(h), em, root) if h else None
        mv = M.box_len(M.height_val(m, True), em, root) if m else None
    except M.Unsure:
        return None
    if (h and hv is None) or (m and mv is None) or any(v and (v[0] < 10 or v[0] > 1500) for v in (hv, mv)):
        return None
    ov = {"auto": "auto", "scroll": "scroll", "hidden auto": "auto", "visible scroll": "scroll"}[decls[[d[0] for d in
                                                                                                    decls].index("overflow")][1]]
    sty = []
    if fsz[2]:
        sty.append("font-size:%dpx" % fsz[2])
    t = "overflow-y:%s" % ov
    if hv:
        t += ";height:%dpx" % hv[0]
    if mv:
        t += ";max-height:%dpx" % mv[0]
    sty.append(t)
    css = ("html { font-size: %dpx } " % fsz[0] if fsz[0] else "") + "#o { %s } " % "; ".join(
        "%s: %s" % d for d in decls) + "#i { animation: k 1s linear; animation-timeline: scroll(nearest) }"
    n = rng.randrange(1, 25)
    exp = ("h", min(hv[0], mv[0]) if mv else hv[0]) if hv else ("m", mv[0])
    ref = ("html { font-size: %dpx } " % fsz[0] if fsz[0] else "") + "#o { overflow: auto; max-height: 1999px%s } " % (
        "; font-size: %dpx" % fsz[2] if fsz[2] else "") + "#i { animation: k 1s linear; animation-timeline: scroll(nearest) }"
    return css, n, ";".join(sty), exp, ref


FLOW_C = r'''#include "../../framework/unity.h"
#include <string.h>
#include <stdio.h>
#include "webeng.h"
#include "wf_html.h"

static we_doc_t g_doc;
static wf_geom_t g_g;
static char g_html[8192], g_out[65536], g_o[512];
static int g_at, g_c;

static int min_i(int a, int b) { return a < b ? a : b; }

/* the page with n lines in #o (#i first), reduced by the reader with
 * marks, laid out at 640 x 480 */
static void pass(const char *css, int n) {
    wf_html_stats_t st;
    int k, l;
    l = snprintf(g_html, sizeof(g_html), "<html><head><style>@keyframes k { from { color: #000000 } to { color: "
                 "#ffffff } } %s</style></head><body><main><div id=o><p id=i>i</p>", css);
    for (k = 1; k < n; k++) l += snprintf(g_html + l, sizeof(g_html) - (size_t)l, "<p>line %d</p>", k);
    snprintf(g_html + l, sizeof(g_html) - (size_t)l, "</div><p>after</p></main></body></html>");
    wf_html_set_sitecss(1);
    wf_html_set_geommarks(1);
    k = wf_html_reduce(g_html, (int)strlen(g_html), 0, g_out, (int)sizeof(g_out), &st);
    wf_html_set_geommarks(0);
    wf_html_set_sitecss(0);
    TEST_ASSERT_TRUE(k > 0);
    TEST_ASSERT_EQUAL(0, we_parse(&g_doc, g_out, k));
    TEST_ASSERT_EQUAL(0, we_style(&g_doc));
    TEST_ASSERT_EQUAL(0, we_layout_viewport(&g_doc, 640, 480));
    memset(&g_g, 0, sizeof(g_g));
    (void)we_geom_feed(&g_doc, "wg", &g_g);
}

/* the style the reader writes on the marked box #o; g_at its mark */
static const char *flow(const char *css, int n) {
    const char *p, *q;
    pass(css, n);
    p = strstr(g_out, "<div id=\"wg");
    if (!p) return "NO MARK";
    for (g_at = 0, q = p + 11; *q >= '0' && *q <= '9'; q++) g_at = g_at * 10 + (*q - '0');
    p = strstr(p, "style=\"");
    if (!p) return "NO STYLE";
    p += 7;
    q = strchr(p, '"');
    snprintf(g_o, sizeof(g_o), "%.*s", (int)(q - p), p);
    return g_o;
}

/* the content height of n lines: the same box and font sizes with a
 * large max-height */
static int content_h(const char *css, int n) {
    (void)flow(css, n);
    return g_g.box[g_at].b_size;
}
'''


def write_flow():
    rng = random.Random(10704)
    cases = []
    while len(cases) < 150:
        got = flow_case(rng)
        if got is None:
            continue
        css, n, sty, (kind, v), ref = got
        lines = [] if kind == "h" else ["g_c = content_h(%s, %d);" % (cstr(ref), n)]
        lines.append("TEST_ASSERT_EQUAL_STRING(%s, flow(%s, %d));" % (cstr(sty), cstr(css), n))
        if kind == "h":
            lines.append("TEST_ASSERT_EQUAL(%d, g_g.box[g_at].s_vp);" % v)
        else:
            lines.append("TEST_ASSERT_EQUAL(min_i(%d, g_c), g_g.box[g_at].s_vp);" % v)
        lines.append("TEST_ASSERT_EQUAL(g_g.box[g_at].s_vp, g_g.box[g_at].b_size);")
        lines.append("TEST_ASSERT_EQUAL(1, g_g.box[g_at].sv);")
        cases.append(lines)
    o = [HEADER % "Lot 107: relative heights and max-height from the reader laid out by the engine"] + FLOW_C.split("\n")
    names = chunks(o, "test_l107_flow", cases, 6)
    finish(o, names, "test_lot107_flow.c")
    return len(cases)


