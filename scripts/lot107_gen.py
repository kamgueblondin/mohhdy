def pad_case(rng):
    rules, ranked = G5.rules_of(rng, 0.6)
    tld = pad_tl_rules(rng)
    spd = {k: [] for k in range(len(ELS))}
    sp_rules = []
    order = 0
    for k in (0, 2, 3, 1):
        if rng.random() < (0.85 if k != 1 else 0.2):
            ds = sp_decls(rng)
            sp_rules.append((ELS[k], ds))
            for p, v in ds:
                order += 1
                spd[k].append(((0, (1, 0, 0), order), p, v))
    fsz = font_sizes(rng)
    target = 4 if rng.random() < 0.8 else 3
    try:
        tl = [M4.tl_cascade(tld[el]) for el in ELS]
        fs, root = fs_of(fsz)
        nodes = G5.sc_nodes(ranked, tl)
        for k, nd in enumerate(nodes):
            nd["fs"], nd["rem"], nd["sp"] = fs[k], root, M.sp_cascade(spd[k])
    except (M.Unsure, M5.Unsure):
        return None
    text = "@keyframes k { from { color: #000000 } to { color: #ffffff } }"
    adecls = [("animation", "k 1s linear" + rng.choice(["", "", " both"])),
              ("animation-timeline", rng.choice(VIEW_TL))]
    if rng.random() < 0.3:
        adecls.append(("animation-range", rng.choice(["contain", "entry", "exit", "cover 10% 90%",
                                                      "entry-crossing", "contain 0% 50%"])))
    anims = L102.coord(L102.anim_cascade([(100, adecls)]))
    rgy = rng.choice([400, 1000, rng.randrange(0, 3000)])
    geom = {"rg_y": rgy, "sc_y": rng.choice([0, rgy, rgy // 2, rng.randrange(0, rgy + 1)]), "box": {}}
    if rng.random() < 0.3:
        geom["body"] = G6.body_box(rng, rgy)
    for k in (0, 1, 2, 3, 4):
        if k == target or rng.random() < 0.5:
            geom["box"][k] = G5.rand_box(rng, k, nodes, rgy)
    c = M5.Ctx(geom, 0, rng.random() < 0.3)
    try:
        L.CUR = L.BLACK
        kfr = {"k": [(0, "#000000", None, None), (S, "#ffffff", None, None)]}
        cur, animated, _ = M.stack(L.ALTS, anims, kfr, "#000000", 0, nodes, target, c)
        t = L.paint_text(cur) if animated else None
        n_sc, n_vw, n_bx, n_idle = M.counts(anims, {"k"}, nodes, target, 0, c)
    except (T.Unsure, M.Unsure):
        return None
    finally:
        L.CUR = None
    el = ELS[target]
    tld[el] = tld[el] + adecls
    css = G102.PROP + text + " " + G5.rules_css(rules) + " " + G5.rules_css(sp_rules) + " " + fs_css(fsz) + " " + " ".join(
        "%s { %s }" % (e, "; ".join("%s: %s" % x for x in tld[e])) for e in ELS if tld[e])
    sty = ["color:%s" % t] if t else []
    if own_fs(fsz, target):
        sty.append(own_fs(fsz, target))
    if 4 in c.scr and target == 4 and M.passed(nodes, 4, c.scr):
        sty.append(M.passed(nodes, 4, c.scr))
    if target == 3 and 3 in c.scr and M.passed(nodes, 3, c.scr):
        sty.append(M.passed(nodes, 3, c.scr))
    return {"css": css, "geom": geom, "gui": int(c.gui), "target": IDS[target],
            "style": ' style="%s"' % ";".join(sty) if sty else "",
            "counts": (int(bool(t)), n_sc, n_vw, n_bx, n_idle, int(c.live))}


