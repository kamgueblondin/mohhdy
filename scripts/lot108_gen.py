# ------------------------------------------------------------- widths
def ov_x(rng):
    return rng.choice(["auto", "scroll", "hidden", "visible", "clip", "auto", "scroll"])


def w_decls(rng):
    d = []
    if rng.random() < 0.9:
        p = rng.choice(["overflow", "overflow", "overflow-x", "overflow-x", "overflow-y"])
        d.append((p, G7.ov_value(rng) if p == "overflow" else ov_x(rng)))
    if rng.random() < 0.3:
        d.append((rng.choice(["overflow-x", "overflow-y"]), ov_x(rng)))
    for prop, q in (("width", 0.65), ("max-width", 0.45), ("min-height", 0.35), ("height", 0.35),
                    ("max-height", 0.2)):
        if rng.random() < q:
            d.append((prop, G7.h_value(rng)))
    if rng.random() < 0.2:
        d.append((rng.choice(["width", "max-width", "min-height"]), G7.h_value(rng)))
    rng.shuffle(d)
    return [(p, v + (" !important" if rng.random() < 0.1 else "")) for p, v in d]


def width_case(rng):
    rules = [("#o", w_decls(rng)), ("#b", w_decls(rng))]
    if rng.random() < 0.3:
        rules.append(("div", w_decls(rng)))
    rng.shuffle(rules)
    ranked = G7.ranked_of(rules)
    fsz = G7.font_sizes(rng)
    fs, root = G7.fs_of(fsz)
    try:
        nodes = [{"parent": PARENTS[k], "tag": TAGS[k], "sc": M.sc_cascade(ranked[k]), "fs": fs[k], "rem": root}
                 for k in range(len(ELS))]
    except (M7.Unsure, M5.Unsure):
        return None
    css = "@keyframes k { from { color: #000000 } to { color: #ffffff } } " + G5.rules_css(rules) + " " + \
        G7.fs_css(fsz) + " #i { animation: k 1s linear; animation-timeline: scroll(nearest " + \
        rng.choice(["inline", "x", "block", "y", "inline"]) + ") }"
    scr = set()
    s = M5.scroller_of(nodes, 4)
    if s >= 0:
        scr.add(s)
    lines = ["prep(%s);" % cstr(css)]
    try:
        for k in (2, 3):
            lines.append("TEST_ASSERT_EQUAL(%d, wf_site_box_scroller(&g_d, %d));" % (M5.box_scroller(nodes, k), ci(k)))
            sc = nodes[k]["sc"]
            xp = [sc[j][1] if sc[j][0] == "px" else 0 for j in (6, 7, 8)]
            lines.append("TEST_ASSERT_EQUAL_STRING(%s, sc_of(%d));" % (cstr("%d %d %d %d %d %d %d %d %d" % (
                sc[0], sc[1], sc[2], sc[4], xp[0], xp[1], xp[2], int(k in scr), nodes[k]["fs"] * 1000)), ci(k)))
            t = [x for x in (G7.own_fs(fsz, k), M.passed(nodes, k, scr)) if x]
            lines.append("TEST_ASSERT_EQUAL_STRING(%s, style_of(%s));" % (
                cstr(' style="%s"' % ";".join(t) if t else ""), cstr(IDS[k])))
    except (M7.Unsure, M5.Unsure):
        return None
    return css, lines


