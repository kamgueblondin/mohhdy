AXES = ["inline", "x", "inline", "x", "block", "y", ""]
SCROLL_TL = ["scroll(nearest inline)", "scroll(nearest inline)", "scroll(x)", "scroll(inline)", "scroll(inline)", "scroll(x)", "scroll(x nearest)", "scroll(self inline)",
             "scroll(self x)", "scroll(root inline)", "scroll(root x)", "scroll(inline root)", "scroll(nearest)",
             "scroll(block)", "--s", "--s", "--s", "--v", "view(inline)", "view(x)", "view(inline 10px)",
             "view(x auto 20%)", "view()", "view(inline auto)"]


def x_tl_rules(rng):
    d = {el: [] for el in ELS}
    for el in ("#o", "#b", "#i"):
        if rng.random() < (0.5 if el != "#i" else 0.15):
            ax = rng.choice(AXES)
            if rng.random() < 0.6:
                d[el].append(("scroll-timeline", "--s" + (" " + ax if ax else "")))
            else:
                d[el].append(("scroll-timeline-name", "--s"))
                if ax:
                    d[el].append(("scroll-timeline-axis", ax))
        if rng.random() < 0.2:
            ax = rng.choice(AXES)
            d[el].append(("view-timeline", "--v" + (" " + ax if ax else "")))
    if rng.random() < 0.1:
        d["body"].append(("timeline-scope", rng.choice(["--s", "all", "--v"])))
    return d


def x_rules(rng):
    rules, ranked = G5.rules_of(rng, 0.95)
    extra = []
    for el in ("#o", "#b"):
        if rng.random() < 0.5:
            ds = [("overflow-x", rng.choice(["auto", "scroll", "hidden", "visible"]))] if rng.random() < 0.5 else []
            for prop, q in (("width", 0.6), ("max-width", 0.3), ("min-height", 0.2)):
                if rng.random() < q:
                    ds.append((prop, G7.h_value(rng)))
            if ds:
                extra.append((el, ds))
    order = 1000
    for sel, ds in extra:
        k = ELS.index(sel)
        for p, v in ds:
            order += 1
            ranked[k].append(((0, (1, 0, 0), order), p, v))
    return rules + extra, ranked


def x_box(rng, b):
    """the box record b with a range and offset along x (svx) and along
    the inline axis of its scroller"""
    if rng.random() < 0.8:
        b["svx"] = 1
        b["x_vp"] = rng.choice([100, 200, 300])
        b["x_rg"] = rng.choice([0, 100, 400, rng.randrange(0, 1000)])
        b["x_sc"] = rng.choice([0, b["x_rg"], b["x_rg"] // 2, rng.randrange(0, b["x_rg"] + 1)])
    else:
        b["svx"] = b["x_vp"] = b["x_rg"] = b["x_sc"] = 0
    if b["bvert"] and not b["root"] and rng.random() < 0.7:
        b["vp_i"] = rng.choice([100, 200, 300])
        b["rg_i"] = rng.choice([0, 300, rng.randrange(0, 800)])
        b["sc_i"] = rng.choice([0, b["rg_i"], rng.randrange(0, b["rg_i"] + 1)])
        b["i_off"] = rng.randrange(-50, b["rg_i"] + b["vp_i"] + 50)
        b["i_size"] = rng.choice([0, 50, rng.randrange(0, 400)])
    return b


def xclock_case(rng):
    rules, ranked = x_rules(rng)
    tld = x_tl_rules(rng)
    target = 4 if rng.random() < 0.85 else 3
    try:
        tl = [M4.tl_cascade(tld[el]) for el in ELS]
        nodes = G5.sc_nodes(ranked, tl)
        for nd in nodes:
            nd["fs"], nd["rem"] = 16, 16
    except (M7.Unsure, M5.Unsure):
        return None
    adecls = [("animation", "k 1s linear" + rng.choice(["", "", " both"])),
              ("animation-timeline", rng.choice(SCROLL_TL))]
    if rng.random() < 0.2:
        adecls.append(("animation-range", rng.choice(["contain", "entry", "exit", "cover 10% 90%", "0% 50%",
                                                      "100px 300px"])))
    anims = L102.coord(L102.anim_cascade([(100, adecls)]))
    rgy = rng.choice([400, 1000, rng.randrange(0, 3000)])
    geom = {"rg_y": rgy, "sc_y": rng.choice([0, rgy, rgy // 2, rng.randrange(0, rgy + 1)]), "box": {}}
    for k in (0, 1, 2, 3, 4):
        if k == target or rng.random() < 0.6:
            geom["box"][k] = x_box(rng, G5.rand_box(rng, k, nodes, rgy))
    c = M5.Ctx(geom, 0, rng.random() < 0.3)
    try:
        L.CUR = L.BLACK
        kfr = {"k": [(0, "#000000", None, None), (M7.S, "#ffffff", None, None)]}
        cur, animated, _ = M7.stack(L.ALTS, anims, kfr, "#000000", 0, nodes, target, c)
        t = L.paint_text(cur) if animated else None
        n_sc, n_vw, n_bx, n_idle = M7.counts(anims, {"k"}, nodes, target, 0, c)
    except (T.Unsure, M7.Unsure, M5.Unsure):
        return None
    finally:
        L.CUR = None
    el = ELS[target]
    tld[el] = tld[el] + adecls
    css = G102.PROP + "@keyframes k { from { color: #000000 } to { color: #ffffff } } " + G5.rules_css(rules) + \
        " " + " ".join("%s { %s }" % (e, "; ".join("%s: %s" % x for x in tld[e])) for e in ELS if tld[e])
    sty = ["color:%s" % t] if t else []
    pas = M.passed(nodes, target, c.scr)
    if pas:
        sty.append(pas)
    others = []
    for k in (2, 3):
        if k != target:
            po = M.passed(nodes, k, c.scr)
            others.append((IDS[k], ' style="%s"' % po if po else ""))
    return {"css": css, "geom": geom, "gui": int(c.gui), "target": IDS[target], "others": others,
            "style": ' style="%s"' % ";".join(sty) if sty else "",
            "counts": (int(bool(t)), n_sc, n_vw, n_bx, n_idle, int(c.live)),
            "flags": "".join(str(int(any(ci(k) == q and k in c.scr for k in range(len(ELS))))) for q in range(5))}


