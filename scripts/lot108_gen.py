"""Lot 108 test generator: box scrollers along x (overflow-x with width and
max-width, min-height), scroll and view timelines on the inline axis of a
box scroller, horizontal box scrolling in the engine, relative colour
syntax.

Expectations come from scripts/lot108_model.py (written from CSS Overflow
3, CSS Box Sizing 3, CSS Scroll-driven Animations 1 and CSS Color 4 and 5)
with the lot 97 to 107 models, not from the C sources. A value the exact
model cannot place against the C's rounding (an Unsure) is left out.

* test_lot108_width.c: overflow, overflow-x, width, max-width, min-height
  and font-size on the elements of a page (the slots kept, the style the
  reader passes on for a box scroller a timeline reads);
* test_lot108_xclock.c: wf_site_prepare_ext after wf_site_set_geom: colour
  keyframes on scroll and view timelines along the inline or x axis of a
  box scroller (its range and offset along x from the geometry);
* test_lot108_xflow.c: the engine's horizontal box scrolling: the
  scrollport, the content width, the bar, clicks on its track, the offset
  kept across layouts and the geometry along x;
* test_lot108_rel.c: relative colours (rgb(), hsl(), oklab(), oklch()
  from an origin colour) in the reader's colours.

Run: python3 scripts/lot108_gen.py
"""
