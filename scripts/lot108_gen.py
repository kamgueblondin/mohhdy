def xflow_case(rng):
    pct = rng.random() < 0.12
    if pct:
        # whole percentages (the reader passes the integer part on)
        q = rng.choice([25, 50, 75, 10, 33, rng.randrange(5, 90)])
        W = 624 * q // 100
        wcss = "%d%%" % q
    else:
        W = rng.choice([40, 100, 150, 200, 300, rng.randrange(20, 500)])
        wcss = "%dpx" % W
    c = {"W": W, "wcss": wcss, "L": rng.choice([0, 0, 3, 10]), "R": rng.choice([0, 0, 4, 10]),
         "B": rng.choice([0, 0, 1, 2, 5]), "ovx": rng.choice(["auto", "scroll"]),
         "ovy": rng.choice([None, None, "auto", "scroll", "hidden"]),
         "H": rng.choice([None, None, 20, 30, 40, rng.randrange(10, 90)])}
    if c["W"] + c["L"] + c["R"] + 2 * c["B"] > 600:
        return None
    kids = []
    for _ in range(rng.randrange(1, 7)):
        k = rng.random()
        C = rng.choice([W // 2, W, W + 1, 2 * W, rng.randrange(10, 900)])
        if k < 0.55:
            kids.append(("w", C))
        elif k < 0.75:
            kids.append(("nest", C, rng.choice([C // 2, 2 * C, rng.randrange(10, 900)])))
        elif k < 0.9:
            kids.append(("clip", C, rng.choice([2 * C, rng.randrange(10, 900)])))
        else:
            kids.append(("none", rng.randrange(10, 1500)))
    c["kids"] = kids
    pre = M.xflow(dict(c, clicks=[]))
    clicks = []
    for _ in range(rng.randrange(1, 5)):
        k = rng.random()
        if k < 0.75:
            clicks.append((pre["tx"] + rng.choice([0, pre["tw"] - 1, pre["tw"] // 2, rng.randrange(0, max(1, pre["tw"]))]),
                           pre["ty"] + rng.randrange(0, 6)))
        elif k < 0.9:
            clicks.append((pre["tx"] + rng.randrange(0, max(1, pre["tw"])), rng.choice([pre["ty"] - 1, pre["ty"] + 6])))
        else:
            clicks.append((pre["tx"] - 1, pre["ty"] + 2))
    c["clicks"] = clicks
    return c, M.xflow(c)


