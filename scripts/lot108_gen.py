def rel_value(rng, depth=0, good=False):
    name, fn = rng.choice(REL_NAMES)
    if rng.random() < 0.05:
        name = name.upper()
    args = [arg(rng, fn, p) for p in range(3)]
    k = rng.random()
    alpha = ""
    if k < 0.2:
        alpha = " / alpha"
    elif k < 0.35:
        alpha = " / " + rng.choice(["0.5", "50%", "none", "1", "0", "calc(alpha / 2)", "calc(alpha * 0.5)",
                                    "calc(alpha - 0.25)"])
    elif k < 0.4:
        alpha = "/" + rng.choice(["0.5", "alpha"])
    v = "%s(from %s %s%s)" % (name, origin(rng, depth), " ".join(args), alpha)
    if not good and rng.random() < 0.1:
        bad = rng.randrange(7)
        if bad == 0:
            v = v.replace(" %s" % args[0], ", %s" % args[0], 1)
        elif bad == 1:
            v = v.replace(" " + args[2] + alpha + ")", alpha + ")", 1) if alpha else v[:-1] + " / 1 / 1)"
        elif bad == 2:
            v = v[:-1] + " %s)" % args[0]
        elif bad == 3:
            v = v.replace("(from ", "(from", 1)
        elif bad == 4:
            v = v.replace("(from ", "(", 1)
        elif bad == 5:
            v = v[:-1] + " x)" if not alpha else v.replace(args[1], "q", 1)
        else:
            v = v.replace("(from ", "( from  ", 1)
    return v


