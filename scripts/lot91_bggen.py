#!/usr/bin/env python3
"""Lot 91 test generator: reader backgrounds (explicit radial radii,
gradians, background-clip and background-origin).

Expectations come from this file, not from the C sources. Each value is
built from a structure (a shape word, a size, a position, a list of box
keywords) and the generator writes the CSS text with random case and
spacing, plus the answer the structure stands for. A value is invalid
because of a known fault in its structure (a circle with two radii, a
percentage circle, an extent with a radius, layers that end in different
boxes ...), never because of a parse of the text.

Rules modelled (CSS Images 3/4 radial-gradient grammar, restricted to what
the engine draws):
* <radial-shape> || <radial-size>: circle takes one length (px or 0, not a
  percentage), ellipse two lengths or percentages; with no shape word one
  length is a circle (so a single percentage is invalid) and two are an
  ellipse. An extent keyword never mixes with radii; the two radii are
  adjacent; a radius is never negative. Lengths: px or %, at most two
  decimals, at most 9999; unitless only when zero.
* the normal form of a gradient keeps each argument lower case with one
  space between words, joined with ", "; longer than 127 bytes: refused.
* angles: deg (integer multiple of 90, at most 3600), turn (a multiple of
  0.25, at most 10), grad (integer multiple of 100, at most 4000); rad is
  refused (no exact quarter turn).
* background-clip / background-origin: one of border-box, padding-box,
  content-box, or a list of up to four that all name the same box (the
  engine paints every layer in one box); text is refused.
* background shorthand: per layer, no box keyword means origin
  padding-box and clip border-box; one keyword sets both; two set the
  origin then the clip. Every layer must end with the same pair, else the
  shorthand is refused. The pair is "given" when any layer named a box.
* reader sheet: the winner of each longhand is the declaration with the
  highest (important, specificity, order); background-clip and
  background-origin do not inherit; inherit copies the parent's winner,
  initial and unset (not inherited) give the initial value, which is not
  written into the style attribute.

Run: python3 scripts/lot91_bggen.py
"""
import os
import random

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "tests", "unit", "userspace")
HEADER = "/* %s (generated by scripts/lot91_bggen.py; expectations from that model). */\n"
SEED_RADIAL = 9101
SEED_BOX = 9102


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def rcase(rng, s):
    m = rng.randrange(4)
    if m == 0:
        return s
    if m == 1:
        return s.upper()
    return "".join(c.upper() if rng.random() < 0.3 else c for c in s)


def sp(rng):
    return rng.choice([" ", " ", " ", "  ", "\t", " \t "])


def norm_words(text):
    return " ".join(text.split()).lower()


# ------------------------------------------------------------- colours
NAMED = ["black", "white", "red", "green", "blue", "yellow", "gray", "grey", "navy", "teal", "orange",
         "purple", "silver", "maroon", "lime", "transparent"]


def colour(rng):
    k = rng.randrange(4)
    if k == 0:
        return rcase(rng, rng.choice(NAMED))
    if k == 1:
        return "#" + "".join(rng.choice("0123456789abcdefABCDEF") for _ in range(rng.choice([3, 6])))
    if k == 2:
        return "rgb(%d, %d, %d)" % (rng.randrange(256), rng.randrange(256), rng.randrange(256))
    return "#" + "".join(rng.choice("0123456789abcdef") for _ in range(8))


def stop(rng):
    c = colour(rng)
    if rng.random() < 0.4:
        v = rng.randrange(0, 101)
        p = str(v)
        if v < 100 and rng.random() < 0.3:
            p += "." + str(rng.randrange(10))
        return c + sp(rng) + p + "%"
    return c


def stops(rng, n=None):
    n = n or rng.randrange(2, 5)
    return [stop(rng) for _ in range(n)]


# ------------------------------------------------------------- lengths
def radius(rng, pct_ok=True, zero_ok=True):
    """(text, is_pct) of a valid radius"""
    if zero_ok and rng.random() < 0.08:
        return "0", False
    v = rng.randrange(0, 3000)
    s = str(v)
    r = rng.random()
    if r < 0.2:
        s += "." + str(rng.randrange(1, 10))
    elif r < 0.3:
        s += "." + "%02d" % rng.randrange(1, 100)
    pct = pct_ok and rng.random() < 0.4
    return s + ("%" if pct else rcase(rng, "px")), pct


BAD_RADIUS = ["-5px", "10em", "1.234px", "10000px", "12", "px", "5vw", "1e2px"]

POSITIONS = ["center", "left", "right top", "top", "bottom right", "10px 20px", "25% 75%", "left 10px",
             "center bottom", "0 0", "100% 0"]
BAD_POSITIONS = ["left right", "top bottom", "middle", "10em"]
EXT = ["closest-side", "closest-corner", "farthest-side", "farthest-corner"]


def shape_arg(rng):
    """(text or None when there is no shape argument, valid flag)"""
    form = rng.choice([None, None, "circle", "ellipse"])
    kind = rng.choice(["none", "extent", "one", "one", "two", "two"])
    words = []
    valid = True
    size_words = []
    if kind == "extent":
        size_words = [rcase(rng, rng.choice(EXT))]
    elif kind == "one":
        pct_ok = form != "circle" or rng.random() < 0.15        # a percentage circle: a fault
        t, pct = radius(rng, pct_ok=pct_ok)
        size_words = [t]
        if form == "ellipse":
            valid = False                                        # an ellipse needs two radii
        if pct:
            valid = False                                        # circle (said or implied) with a percentage
    elif kind == "two":
        size_words = [radius(rng)[0], radius(rng)[0]]
        if form == "circle":
            valid = False                                        # a circle takes one radius
    faults = []
    if rng.random() < 0.12 and size_words and kind in ("one", "two"):
        size_words[rng.randrange(len(size_words))] = rng.choice(BAD_RADIUS)
        faults.append("radius")
        valid = False
    if rng.random() < 0.06 and kind in ("one", "two"):
        size_words.insert(0, rcase(rng, rng.choice(EXT)))         # an extent with radii
        valid = False
    fw = [rcase(rng, form)] if form else []
    if rng.random() < 0.5:
        words = fw + size_words
    else:
        words = size_words + fw
    if kind == "two" and form and rng.random() < 0.08:
        words = [size_words[0], rcase(rng, form), size_words[1]]  # radii split by the shape word
        valid = False
    if rng.random() < 0.05 and form:
        words = words + [rcase(rng, rng.choice(["circle", "ellipse"]))]   # two shape words
        valid = False
    at = None
    if rng.random() < 0.5 or not words:
        if rng.random() < 0.9:
            at = rng.choice(POSITIONS)
        else:
            at = rng.choice(BAD_POSITIONS)
            valid = False
        at = " ".join(rcase(rng, w) for w in at.split())
        words = words + [rcase(rng, "at")] + at.split()
    if not words:
        return None, True
    if words and words[0] in BAD_RADIUS and len(words) == 1:
        valid = False
    return sp(rng).join(words), valid


def radial_case(rng):
    arg, valid = shape_arg(rng)
    st = stops(rng)
    args = ([arg] if arg is not None else []) + st
    text = rcase(rng, "radial-gradient(") + ("," + sp(rng)).join(args) + ")"
    normal = "radial-gradient(" + ", ".join(norm_words(a) for a in args) + ")"
    if not valid or len(normal) > 127:
        return text, None
    return text, normal


def angle_case(rng):
    k = rng.randrange(8)
    if k == 0:
        q = rng.randrange(0, 41)
        v = 90 * q
        ok = v <= 3600
        if rng.random() < 0.3:
            v = rng.choice([45, 30, 135, 1, 91, 89, 3690, 450 + 1])
            ok = False
        t = ("-" if rng.random() < 0.2 else "") + str(v) + rcase(rng, "deg")
    elif k in (1, 2):
        g = 100 * rng.randrange(0, 41)
        ok = True
        if rng.random() < 0.3:
            g = rng.choice([50, 150, 99, 101, 4100, 333])
            ok = False
        t = ("-" if rng.random() < 0.2 else "") + str(g) + rcase(rng, "grad")
        if rng.random() < 0.1:
            t = t[:-4] + ".5" + t[-4:]
            ok = False
    elif k == 3:
        q = rng.randrange(0, 41)
        whole, part = divmod(q * 25, 100)
        t = str(whole) + ("" if part == 0 else "." + ("%02d" % part).rstrip("0")) + rcase(rng, "turn")
        ok = True
    elif k == 4:
        t = rng.choice(["1.5708rad", "3.1416rad", "0rad", "6.2832rad", "1rad"])
        ok = False
    elif k == 5:
        t = rng.choice(["0.3turn", "0.1turn", "11turn", "0.125turn"])
        ok = False
    elif k == 6:
        t = rcase(rng, "to ") + rcase(rng, rng.choice(["top", "right", "bottom", "left"]))
        ok = True
    else:
        t = rcase(rng, "to ") + rcase(rng, rng.choice(["top left", "bottom right"]))
        ok = False
    args = [t] + stops(rng)
    text = rcase(rng, "linear-gradient(") + ("," + sp(rng)).join(args) + ")"
    normal = "linear-gradient(" + ", ".join(norm_words(a) for a in args) + ")"
    if not ok or len(normal) > 127:
        return text, None
    return text, normal


def write_radial():
    rng = random.Random(SEED_RADIAL)
    cases = []
    for _ in range(520):
        cases.append(("grad",) + radial_case(rng))
    for _ in range(200):
        cases.append(("grad",) + angle_case(rng))
    # through the image list: url layers then the gradient last
    for _ in range(120):
        g, n = radial_case(rng) if rng.random() < 0.6 else angle_case(rng)
        urls = ["url(i%d.png)" % rng.randrange(100) for _ in range(rng.randrange(0, 3))]
        text = ("," + sp(rng)).join(urls + [g])
        normal = None if n is None else ", ".join(urls + [n])
        if normal is not None and len(normal) > 127:
            normal = None
        cases.append(("img", text, normal))
    o = [HEADER % "Lot 91: radial-gradient radii and gradian angles in the reader's normal form",
         '#include "../../framework/unity.h"', "#include <string.h>", '#include "wf_cssbg.h"', "",
         "static char g_o[WF_CSSBG_VAL];", "",
         "static const char *run(const char *f, const char *v) {",
         "    int r;",
         "    if (!strcmp(f, \"img\")) r = wf_cssbg_image(v, g_o, (int)sizeof(g_o));",
         "    else r = wf_cssbg_gradient(v, (int)strlen(v), g_o, (int)sizeof(g_o));",
         "    if (r <= 0) return g_o[0] ? \"REFUSED BUT WRITTEN\" : \"REFUSED\";",
         "    if (r != (int)strlen(g_o)) return \"BAD LENGTH\";",
         "    return g_o;",
         "}", ""]
    names = []
    per = 6
    for b in range(0, len(cases), per):
        name = "test_l91_radial_%d" % (b // per)
        names.append(name)
        o.append("static void %s(void) {" % name)
        for f, v, e in cases[b:b + per]:
            o.append("    TEST_ASSERT_EQUAL_STRING(%s, run(%s, %s));" % (cstr(e if e is not None else "REFUSED"), cstr(f), cstr(v)))
        o.append("}")
        o.append("")
    o += ["int main(void) {", "    unity_init();"]
    o += ["    RUN_TEST(%s);" % n for n in names]
    o += ["    unity_print_results();", "    unity_cleanup();", "    return unity_stats.tests_failed == 0 ? 0 : 1;", "}", ""]
    open(os.path.join(OUT, "test_lot91_bgradial.c"), "w").write("\n".join(o))
    return len(cases)


# ------------------------------------------------------------- boxes
BOXES = ["border-box", "padding-box", "content-box"]
INIT_ORIGIN, INIT_CLIP = "padding-box", "border-box"


def box_list(rng):
    """(text, normal or None)"""
    k = rng.randrange(10)
    if k == 0:
        return rng.choice(["text", "border", "", "padding", "margin-box", "fill-box", "content-box content-box",
                           "border-box,", ", border-box"]), None
    n = rng.choice([1, 1, 1, 2, 3, 4, 5])
    b = rng.choice(BOXES)
    items = [b] * n
    ok = n <= 4
    if rng.random() < 0.25 and n > 1:
        items[rng.randrange(n)] = rng.choice([x for x in BOXES if x != b])
        ok = False
    text = ("," + sp(rng)).join(rcase(rng, x) for x in items)
    return text, (b if ok else None)


URLS = ["url(a.png)", "url(b.gif)", "url(c/d.png)", "url('e.png')"]
RCOLOURS = {"black": "#000000", "white": "#ffffff", "red": "#ff0000", "green": "#008000", "blue": "#0000ff",
            "gray": "#808080", "navy": "#000080"}


def layer(rng, last, colour_ok=True):
    """(text, boxes list, has colour, colour normal)"""
    comps = []
    if rng.random() < 0.8:
        comps.append(rng.choice(URLS))
    if rng.random() < 0.3:
        comps.append(rcase(rng, rng.choice(["no-repeat", "repeat-x", "space"])))
    if rng.random() < 0.3:
        comps.append(rcase(rng, rng.choice(["center", "left top", "10px 20px"])))
    nb = rng.choice([0, 0, 1, 1, 2])
    boxes = [rng.choice(BOXES) for _ in range(nb)]
    col = None
    if last and colour_ok and rng.random() < 0.4:
        col = rng.choice(sorted(RCOLOURS))
    words = comps + [rcase(rng, b) for b in boxes] + ([rcase(rng, col)] if col else [])
    if not words:
        words = [rng.choice(URLS)]
    # box keywords stay in order among themselves; other words move
    others = [w for w in words if w.lower() not in BOXES]
    bx = [w for w in words if w.lower() in BOXES]
    out = []
    while others or bx:
        if bx and (not others or rng.random() < 0.4):
            out.append(bx.pop(0))
        else:
            out.append(others.pop(rng.randrange(len(others))))
    return sp(rng).join(out), boxes, col


def layer_pair(boxes):
    if not boxes:
        return (INIT_ORIGIN, INIT_CLIP)
    return (boxes[0], boxes[-1])


def shorthand_expect(layers):
    """None (refused) or (origin, clip, given)"""
    pairs = set(layer_pair(b) for _, b, _ in layers)
    if len(pairs) > 1:
        return None
    o, c = pairs.pop()
    return o, c, any(b for _, b, _ in layers)


SELS = [("p", 1), (".k", 10), ("#t", 100), ("p.k", 11), ("div p", 2)]
PSELS = [("div", 1), (".q", 10), ("#p", 100)]


def write_box():
    rng = random.Random(SEED_BOX)
    o = [HEADER % "Lot 91: background-clip and background-origin in the reader (longhands, shorthand, cascade)",
         '#include "../../framework/unity.h"', "#include <string.h>", '#include "wf_sitecss.h"', '#include "wf_cssbg.h"', "",
         "static wf_site_t g_d;", "static char g_o[1400];", "static char g_v[WF_CSSBG_VAL];", "static wf_cssbg_t g_bg;", "",
         "static const char *box_of(const char *v) {",
         "    int r = wf_cssbg_box(v, g_v, (int)sizeof(g_v));",
         "    if (r <= 0) return g_v[0] ? \"REFUSED BUT WRITTEN\" : \"REFUSED\";",
         "    if (r != (int)strlen(g_v)) return \"BAD LENGTH\";",
         "    return g_v;",
         "}", "",
         "static const char *style_of(const char *html, const char *id) {",
         "    int i;",
         "    if (wf_site_prepare(&g_d, html, (int)strlen(html)) != 0) return \"PREPARE FAILED\";",
         "    g_o[0] = 0;",
         "    for (i = 0; i < g_d.nnodes; i++)",
         "        if (!strcmp(g_d.node[i].id, id)) { wf_site_style_attr(&g_d, g_d.node[i].start, g_o, (int)sizeof(g_o)); return g_o; }",
         "    return \"NO SUCH ID\";",
         "}", ""]
    names = []
    count = 0
    # 1. longhand values
    for t in range(40):
        name = "test_l91_boxval_%d" % t
        names.append(name)
        o.append("static void %s(void) {" % name)
        for _ in range(6):
            text, n = box_list(rng)
            o.append("    TEST_ASSERT_EQUAL_STRING(%s, box_of(%s));" % (cstr(n if n else "REFUSED"), cstr(text)))
            count += 1
        o += ["}", ""]
    # 2. the shorthand
    for t in range(160):
        nl = rng.choice([1, 1, 2, 2, 3])
        layers = [layer(rng, i == nl - 1) for i in range(nl)]
        text = ("," + sp(rng)).join(l[0] for l in layers)
        exp = shorthand_expect(layers)
        name = "test_l91_boxshort_%d" % t
        names.append(name)
        o.append("static void %s(void) {" % name)
        if exp is None:
            o += ["    TEST_ASSERT_EQUAL(0, wf_cssbg_shorthand(%s, &g_bg));" % cstr(text),
                  "    TEST_ASSERT_EQUAL(0, g_bg.layers);", "    TEST_ASSERT_EQUAL_STRING(\"\", g_bg.clip);"]
        else:
            org, clp, given = exp
            o += ["    TEST_ASSERT_EQUAL(1, wf_cssbg_shorthand(%s, &g_bg));" % cstr(text),
                  "    TEST_ASSERT_EQUAL(%d, g_bg.layers);" % nl,
                  "    TEST_ASSERT_EQUAL_STRING(%s, g_bg.origin);" % cstr(org),
                  "    TEST_ASSERT_EQUAL_STRING(%s, g_bg.clip);" % cstr(clp),
                  "    TEST_ASSERT_EQUAL(%d, g_bg.has_origin);" % (1 if given else 0),
                  "    TEST_ASSERT_EQUAL(%d, g_bg.has_clip);" % (1 if given else 0)]
        o += ["}", ""]
        count += 1
    # 3. the cascade on <p id=t> inside <div id=p>
    for t in range(300):
        rules = []
        nr = rng.randrange(1, 5)
        for r in range(nr):
            on_parent = rng.random() < 0.25
            sel, spec = rng.choice(PSELS if on_parent else SELS)
            imp = rng.random() < 0.15
            kinds = {}
            k = rng.randrange(6)
            if k <= 1:
                prop = "background-clip" if k == 0 else "background-origin"
                key = "clip" if k == 0 else "origin"
                if rng.random() < 0.2:
                    kw = rng.choice(["inherit", "initial", "unset"])
                    decl = prop + ": " + rcase(rng, kw)
                    kinds[key] = ("kw", kw)
                else:
                    text, n = box_list(rng)
                    decl = prop + ": " + text
                    if n:
                        kinds[key] = ("given", n)
            elif k <= 3:
                lay = layer(rng, True)
                decl = "background: " + lay[0]
                exp = shorthand_expect([lay])
                if exp is not None:
                    org, clp, given = exp
                    img = [w for w in lay[0].split() if w.lower().startswith("url(")]
                    kinds["image"] = ("given", img[0].replace("'", "")) if img else ("initial", None)
                    kinds["colour"] = ("given", RCOLOURS[lay[2]]) if lay[2] else ("initial", None)
                    kinds["clip"] = ("given", clp) if given else ("initial", None)
                    kinds["origin"] = ("given", org) if given else ("initial", None)
                    # position and repeat words of the layer: compare only clip/origin/image/colour,
                    # so the layer in the cascade has none of them
                    if any(w.lower() in ("no-repeat", "repeat-x", "space", "center", "left", "top", "10px", "20px")
                           for w in lay[0].split()):
                        decl = "background: " + " ".join(w for w in lay[0].split()
                                                         if w.lower() not in ("no-repeat", "repeat-x", "space", "center",
                                                                              "left", "top", "10px", "20px"))
            elif k == 4:
                kw = rng.choice(["inherit", "initial", "unset"])
                decl = "background-clip: " + kw + "; background-origin: " + rng.choice(BOXES)
                kinds = None    # two declarations: handled below
            else:
                b = rng.choice(BOXES)
                decl = "background-origin: " + rcase(rng, b)
                kinds["origin"] = ("given", b)
            if kinds is None:
                kw = decl.split(": ")[1].split(";")[0]
                b = decl.split(": ")[-1]
                kinds = {"clip": ("kw", kw), "origin": ("given", b)}
                if imp:
                    decl = "background-clip: " + kw + " !important; background-origin: " + b + " !important"
                rules.append((sel, spec, imp, r, decl, kinds, on_parent))
                continue
            rules.append((sel, spec, imp, r, decl + (" !important" if imp else ""), kinds, on_parent))

        def winners(parent):
            win = {}
            for sel, spec, imp, r, decl, kinds, onp in rules:
                if onp != parent:
                    continue
                key = (1 if imp else 0, spec, r)
                for kk, v in kinds.items():
                    if kk not in win or key >= win[kk][0]:
                        win[kk] = (key, v)
            return {kk: v[1] for kk, v in win.items()}

        pw = winners(True)

        def resolve(w, kk, par):
            v = w.get(kk)
            if v is None:
                return None
            if v[0] == "kw":
                if v[1] == "inherit":
                    return par.get(kk) if par is not None else None
                return None
            if v[0] == "initial":
                return None
            return v[1]

        pres = {kk: resolve(pw, kk, None) for kk in ("clip", "origin", "image", "colour")}
        pres = {kk: v for kk, v in pres.items() if v is not None}
        cw = winners(False)
        cres = {kk: resolve(cw, kk, pres) for kk in ("clip", "origin", "image", "colour")}
        parts = []
        if cres.get("colour"):
            parts.append("background-color:" + cres["colour"])
        if cres.get("image"):
            parts.append("background-image:" + cres["image"])
        if cres.get("clip"):
            parts.append("background-clip:" + cres["clip"])
        if cres.get("origin"):
            parts.append("background-origin:" + cres["origin"])
        css = " ".join("%s { %s }" % (s, d) for s, _, _, _, d, _, _ in rules)
        html = "<html><head><style>%s</style></head><body><div id=p class=q><p id=t class=k>x</p></div></body></html>" % css
        name = "test_l91_boxsheet_%d" % t
        names.append(name)
        o.append("static void %s(void) {" % name)
        o.append("    const char *s = style_of(%s, \"t\");" % cstr(html))
        if parts:
            o.append("    TEST_ASSERT_EQUAL_STRING(%s, s);" % cstr(' style="' + ";".join(parts) + '"'))
        else:
            o.append("    TEST_ASSERT_EQUAL_STRING(\"\", s);")
        o += ["}", ""]
        count += 1
    o += ["int main(void) {", "    unity_init();"]
    o += ["    RUN_TEST(%s);" % n for n in names]
    o += ["    unity_print_results();", "    unity_cleanup();", "    return unity_stats.tests_failed == 0 ? 0 : 1;", "}", ""]
    open(os.path.join(OUT, "test_lot91_bgbox.c"), "w").write("\n".join(o))
    return count


if __name__ == "__main__":
    a = write_radial()
    b = write_box()
    print("radial %d, box %d" % (a, b))
