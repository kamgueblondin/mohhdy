VW, VH = 320, 480


def geom_case(rng):
    """a body with margins, padding, a border (and maybe a height) over
    stacked blocks: the page html, the root scroll and the expected body
    record and root state"""
    bs = G4.box_style(rng)
    bs["h"] = None
    if rng.random() < 0.2:
        bs["h"] = rng.choice([100, 300, 600, 1200])
    kids, inner, cy = rng.randrange(0, 5), "", 0
    for _ in range(kids):
        s = G4.box_style(rng)
        inner += "<div style='%s'></div>" % G4.css_of(s)
        cy += G4.outer_h(s)
    if bs["h"] is not None and bs["h"] < cy:
        bs["h"] = cy + rng.choice([0, 20, 100])
    h = bs["h"] if bs["h"] is not None else cy
    bb = 2 * (bs["p"] + bs["b"])
    page_h = bs["mt"] + h + bb + bs["mb"]
    rg = max(0, page_h - VH)
    scroll = rng.choice([0, 0, 50, rg, rg // 2, rng.randrange(0, rg + 100)])
    sy = min(max(scroll, 0), rg)
    st = "margin:%dpx %dpx %dpx %dpx" % (bs["mt"], bs["mr"], bs["mb"], bs["ml"])
    if bs["h"] is not None:
        st += ";height:%dpx" % bs["h"]
    if bs["p"]:
        st += ";padding:%dpx" % bs["p"]
    if bs["b"]:
        st += ";border:%dpx solid #123456" % bs["b"]
    hidden = rng.random() < 0.05
    if hidden:
        st += ";display:none"
    body = "<body style='%s'>%s</body>" % (st, inner)
    exp = "none" if hidden else "1 1 %d+%d %d+%d vp %d/%d sc %d/0 rg %d/0 sv 0 sm 0" % (
        bs["mt"], h + bb, bs["ml"], VW - bs["ml"] - bs["mr"], VH, VW, sy, rg)
    return body, exp, (0 if hidden else page_h), rg if not hidden else 0, scroll, sy if not hidden else 0


def write_geom():
    rng = random.Random(10603)
    cases = []
    while len(cases) < 160:
        body, exp, page_h, rg, scroll, sy = geom_case(rng)
        if len(body) > 3000:
            continue
        lines = ["TEST_ASSERT_EQUAL(0, page(%s));" % cstr(body),
                 "TEST_ASSERT_EQUAL(%d, (int)g_doc.perf.page_h);" % page_h,
                 "TEST_ASSERT_EQUAL(0, feed(%d));" % scroll,
                 "TEST_ASSERT_EQUAL_STRING(%s, root());" % cstr("%d %d 0 %d %d" % (VW, VH, rg, sy)),
                 "TEST_ASSERT_EQUAL_STRING(%s, box());" % cstr(exp)]
        cases.append(lines)
    o = [HEADER % "Lot 106: the body box the engine hands back to the reader"] + [
        '#include "../../framework/unity.h"', "#include <string.h>", "#include <stdio.h>", '#include "webeng.h"', "",
        "static we_doc_t g_doc;", "static wf_geom_t g_g;",
        "static char g_html[4096], g_o[200];", "",
        "/* the page laid out at 320 x 480 */",
        "static int page(const char *body) {",
        "    snprintf(g_html, sizeof(g_html), \"<html>%s</html>\", body);",
        "    if (we_parse(&g_doc, g_html, (int)strlen(g_html)) || we_style(&g_doc) || we_layout_viewport(&g_doc, 320, 480))",
        "        return -9;",
        "    return 0;",
        "}", "",
        "/* the root scrolled, fed (no marks: no box by index) */",
        "static int feed(int y) {",
        "    (void)we_scroll(&g_doc, y);",
        "    memset(&g_g, 0x5a, sizeof(g_g));",
        "    return we_geom_feed(&g_doc, \"wg\", &g_g);",
        "}", "",
        "static const char *root(void) {",
        "    snprintf(g_o, sizeof(g_o), \"%d %d %d %d %d\", g_g.vw, g_g.vh, g_g.rg_x, g_g.rg_y, g_g.sc_y);",
        "    return g_o;",
        "}", "",
        "static const char *box(void) {",
        "    const wf_geom_box_t *b = &g_g.body;",
        "    if (!b->ok) return \"none\";",
        "    snprintf(g_o, sizeof(g_o), \"%d %d %d+%d %d+%d vp %d/%d sc %d/%d rg %d/%d sv %d sm %d\", b->root,",
        "             b->bvert, b->b_off, b->b_size, b->i_off, b->i_size, b->vp_b, b->vp_i, b->sc_b, b->sc_i, b->rg_b,",
        "             b->rg_i, b->sv, b->sm);",
        "    return g_o;",
        "}", ""]
    names = chunks(o, "test_l106_geom", cases, 8)
    finish(o, names, "test_lot106_geom.c")
    return len(cases)


