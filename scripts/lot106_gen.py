def model(fn, *args):
    """("ok", fn(*args)), None for an unsure colour (the case is left out)"""
    try:
        return ("ok", fn(*args))
    except T.Unsure:
        return None


# ------------------------------------------------------------- interp
LEGACY = ["red", "blue", "lime", "white", "black", "transparent", "#123", "#80ff00", "#00000080", "rgb(10 20 30)",
          "rgba(200, 100, 0, 0.5)", "hsl(120 50% 50%)", "hsla(300, 100%, 25%, 0.8)", "hwb(30 10% 20%)",
          "rgb(none 128 255)", "hsl(none 100% 50%)", "rebeccapurple", "currentcolor"]
NONLEG = ["lab(50 20 -30)", "lch(60 40 120)", "oklab(0.6 0.1 -0.1)", "oklch(0.7 0.15 30)", "oklch(0.5 0.2 none)",
          "oklab(none 0.1 0.1)", "lab(none 0 0)", "color(display-p3 0 1 0)", "color(srgb 1 0 0)",
          "color(srgb-linear 0.2 0.5 none)", "color(xyz 0.3 0.3 0.3)", "color(rec2020 1 0 0 / 0.5)",
          "color-mix(in srgb, red, blue)", "color-mix(in oklch, red, blue)", "color-mix(in lab, white 30%, navy)",
          "oklch(0.9 0.05 200 / 0.25)", "lab(30 -40 50 / none)", "oklch(0 0.2 100)", "oklab(1 0 0)"]
TS = [5000, 2500, 7500, 1, 9999, 3333, -2500, 12500, -10000, 20000, 100, 9900]


def colour(rng):
    k = rng.randrange(10)
    if k < 2:
        return rng.choice(LEGACY)
    if k < 4:
        return rng.choice(NONLEG)
    if k < 6:
        return G101.reg_new(rng).lower()
    if k < 8:
        return G100.reg_colour(rng).lower()
    return (G103.miss_mix(rng) if rng.random() < 0.5 else G102.reg_none(rng)).lower()


def interp_case(rng, alts):
    a, b = colour(rng), colour(rng)
    if rng.random() < 0.25:
        # a legacy one against a non-legacy one: the pair goes to Oklab
        a, b = rng.choice(LEGACY), rng.choice(NONLEG)
        if rng.random() < 0.5:
            a, b = b, a
    if len(a) >= 128 or len(b) >= 128:
        return None
    for v in (a, b):
        m = model(A.colour_match, v)
        if m is None or not m[1]:
            return None
    t = rng.choice(TS + [rng.randrange(1, S), rng.randrange(-S, 2 * S)])
    if t in (0, S):
        return None
    m = model(A.interp, alts, a, b, t)
    if m is None or m[1][0] is None or len(m[1][0]) >= 160:
        return None
    return a, b, t, m[1]


def write_interp():
    rng = random.Random(10601)
    alts = L.ALTS
    cases, seen = [], set()
    L.CUR = G100.cur_of("#008080")      # wf_cssprop_set_current(1, 0x008080, 255)
    try:
        while len(cases) < 640:
            got = interp_case(rng, alts)
            if got is None or got[:3] in seen:
                continue
            seen.add(got[:3])
            a, b, t, (r, c) = got
            leg = int(M.legacy(a) and M.legacy(b))
            cases.append(["TEST_ASSERT_EQUAL_STRING(%s, ip(%s, %s, %d, %d));   /* %s */" % (
                cstr(r), cstr(a), cstr(b), t, c, "srgb" if leg else "oklab")])
        # <color>+ lists: item by item
        while len(cases) < 720:
            n = rng.choice([2, 3])
            xs = [colour(rng) for _ in range(n)]
            ys = [colour(rng) for _ in range(n)]
            if any(len(v) >= 40 or "," in v for v in xs + ys):
                continue
            t = rng.choice(TS)
            m = model(A.interp, [("<color>", "+", None)], " ".join(xs), " ".join(ys), t)
            if m is None or m[1][0] is None or len(m[1][0]) >= 300:
                continue
            r, c = m[1]
            cases.append(["TEST_ASSERT_EQUAL_STRING(%s, ipl(%s, %s, %d, %d));" % (
                cstr(r), cstr(" ".join(xs)), cstr(" ".join(ys)), t, c)])
        # add and accumulate: sRGB, a missing component 0 (CSS Color 4 4.4)
        while len(cases) < 840:
            a, b = colour(rng), colour(rng)
            if len(a) >= 128 or len(b) >= 128:
                continue
            ok = True
            for v in (a, b):
                m = model(A.colour_match, v)
                ok = ok and m is not None and m[1]
            if not ok:
                continue
            m = model(M98.add, alts, a, b)
            if m is None or m[1][0] is None or len(m[1][0]) >= 160:
                continue
            r, c = m[1]
            fn = rng.choice(["ad", "ac"])
            cases.append(["TEST_ASSERT_EQUAL_STRING(%s, %s(%s, %s, %d));" % (cstr(r), fn, cstr(a), cstr(b), c)])
    finally:
        L.CUR = None
    o = [HEADER % "Lot 106: Oklab interpolation of registered <color> values unless both are legacy sRGB"] + [
        '#include "../../framework/unity.h"', "#include <string.h>", "#include <stdio.h>", '#include "wf_cssprop.h"', "",
        "static wf_cssprop_t g_p;", "static char g_o[320];", "",
        "/* currentcolor is teal (wf_cssprop_set_current) */",
        "static int syn(const char *s) {",
        "    wf_cssprop_set_current(1, 0x008080u, 255);",
        "    memset(&g_p, 0, sizeof(g_p));",
        "    g_p.syntax = (unsigned char)wf_cssprop_syntax_parse(s, (int)strlen(s), &g_p);",
        "    return g_p.syntax != 0;",
        "}", "",
        "/* the interpolated text of two colours; the return code is checked */",
        "static const char *ip(const char *a, const char *b, int t, int code) {",
        "    if (!syn(\"'<color>'\")) return \"BAD SYNTAX\";",
        "    if (wf_cssprop_interp(&g_p, a, b, t, g_o, (int)sizeof(g_o)) != code) return \"BAD CODE\";",
        "    return g_o;",
        "}", "",
        "static const char *ipl(const char *a, const char *b, int t, int code) {",
        "    if (!syn(\"'<color>+'\")) return \"BAD SYNTAX\";",
        "    if (wf_cssprop_interp(&g_p, a, b, t, g_o, (int)sizeof(g_o)) != code) return \"BAD CODE\";",
        "    return g_o;",
        "}", "",
        "static const char *ad(const char *a, const char *b, int code) {",
        "    if (!syn(\"'<color>'\")) return \"BAD SYNTAX\";",
        "    if (wf_cssprop_add(&g_p, a, b, g_o, (int)sizeof(g_o)) != code) return \"BAD CODE\";",
        "    return g_o;",
        "}", "",
        "/* accumulate is add for colours (Lot 99) */",
        "static const char *ac(const char *a, const char *b, int code) {",
        "    if (!syn(\"'<color>'\")) return \"BAD SYNTAX\";",
        "    if (wf_cssprop_accumulate(&g_p, a, b, g_o, (int)sizeof(g_o)) != code) return \"BAD CODE\";",
        "    return g_o;",
        "}", ""]
    names = chunks(o, "test_l106_interp", cases, 12)
    finish(o, names, "test_lot106_interp.c")
    return len(cases)


