#!/usr/bin/env python3
"""Lot 72: writes tests/unit/userspace/imgdec_gif_samples.h (GIF fixtures).

Host tool (Pillow). The fixtures are committed; rerun only to change them.
Pixel rule of every fixture: palette index (x + 2*y) % 16, palette entry
k = (k*16, 255 - k*16, (k*37) & 255). Variants: plain 87a-like, interlaced,
transparent index 3, two frames (animated), local color table, big 200x150
(LZW codes up to 12 bits and table resets). Favicons: a 32x32 RGBA
icon (16, 32, 48 entries) as PNG and as DIB entries; pixel (x, y) =
(8x, 8y, 4(x+y)), columns x < 4 transparent."""
import io
import sys
from PIL import Image

W, H = 23, 17
PAL = []
for k in range(16):
    PAL += [k * 16, 255 - k * 16, (k * 37) & 255]


def frame(w, h, shift=0):
    im = Image.new("P", (w, h))
    im.putpalette(PAL + [0] * (768 - len(PAL)))
    im.putdata([((x + 2 * y + shift) % 16) for y in range(h) for x in range(w)])
    return im


def enc(im, **kw):
    b = io.BytesIO()
    im.save(b, "GIF", **kw)
    return b.getvalue()


def enc_ico(im, fmt):
    b = io.BytesIO()
    im.save(b, "ICO", sizes=[(16, 16), (32, 32), (48, 48)], bitmap_format=fmt)
    return b.getvalue()


def local_table(data):
    """Moves the global color table into the image descriptor."""
    flags = data[10]
    if not flags & 0x80:
        return data
    n = 2 << (flags & 7)
    gct = data[13:13 + 3 * n]
    rest = bytearray(data[:10] + bytes([flags & 0x70, data[11], data[12]]) + data[13 + 3 * n:])
    i = rest.index(0x2C, 13)
    rest[i + 9] = (rest[i + 9] & 0x40) | 0x80 | (flags & 7)
    return bytes(rest[:i + 10]) + gct + bytes(rest[i + 10:])


def main(out):
    plain = enc(frame(W, H), optimize=False, interlace=False)
    inter = enc(frame(W, H), optimize=False, interlace=True)
    transp = enc(frame(W, H), optimize=False, transparency=3, interlace=False)
    anim = enc(frame(W, H), save_all=True, append_images=[frame(W, H, 5)], optimize=False, duration=100, loop=0)
    big = enc(frame(200, 150), optimize=False, interlace=False)
    loc = local_table(plain)
    rgba = Image.new("RGBA", (32, 32))
    rgba.putdata([((x * 8) & 255, (y * 8) & 255, ((x + y) * 4) & 255, 0 if x < 4 else 255)
                  for y in range(32) for x in range(32)])
    ico_png = enc_ico(rgba, "png")
    ico_bmp = enc_ico(rgba, "bmp")
    with open(out, "w") as f:
        f.write("/* Generated by scripts/gen_gif_fixtures.py (Lot 72). Do not edit. */\n")
        f.write("#define GIFS_W %d\n#define GIFS_H %d\n" % (W, H))
        for name, d in (("plain", plain), ("inter", inter), ("transp", transp), ("anim", anim),
                        ("big", big), ("local", loc), ("ico_png", ico_png), ("ico_bmp", ico_bmp)):
            f.write("static const unsigned char gif_%s[%d] = {\n" % (name, len(d)))
            for i in range(0, len(d), 16):
                f.write("    " + ", ".join("0x%02x" % c for c in d[i:i + 16]) + ",\n")
            f.write("};\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "tests/unit/userspace/imgdec_gif_samples.h")
