#!/usr/bin/env python3
"""Lot 72: high halves (0x80..0xFF) of the single-byte Cyrillic and Greek
page charsets the Ring 3 web stack decodes (userspace/wf_entity.c), from
the Python codecs. Writes userspace/wf_charset_table.inc; --check compares
the file with the codecs instead (make font-check).
Row k is charset WF_CS_CP1251 + k of userspace/wf_entity.h."""
import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "userspace", "wf_charset_table.inc")
CODECS = ("cp1251", "koi8_r", "koi8_u", "iso8859_5", "iso8859_7", "cp1253")


def high(codec):
    row = []
    for b in range(0x80, 0x100):
        try:
            row.append(ord(bytes([b]).decode(codec)))
        except UnicodeDecodeError:
            row.append(0)
    return row


def render():
    lines = ["/* Generated by scripts/gen_charset_tables.py from the Python codecs.",
             " * Lot 72: code points of bytes 0x80..0xFF of the single-byte page",
             " * charsets (0 = undefined byte), rows in WF_CS_CP1251.. order:",
             " * " + ", ".join(CODECS) + ". */",
             "#define WF_CS_TABLES %d" % len(CODECS),
             "static const uint16_t wf_cs_high[WF_CS_TABLES][128] = {"]
    for codec in CODECS:
        row = high(codec)
        lines.append("    { /* %s */" % codec)
        for i in range(0, 128, 8):
            lines.append("        " + " ".join("0x%04X," % v for v in row[i:i + 8]))
        lines.append("    },")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        if open(OUT).read() != text:
            print("wf_charset_table.inc differs from scripts/gen_charset_tables.py")
            return 1
        print("charset tables ok (%d charsets)" % len(CODECS))
        return 0
    with open(OUT, "w") as handle:
        handle.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
