#!/usr/bin/env python3
"""Lot 100 test generator: the reader colour (named colours, hwb(),
color-mix(), alpha), those colours in registered <color> values, the
reader paint of color, background-color and the background shorthand,
and colour animations and transitions.

Expectations come from scripts/lot100_colormodel.py (written from the
rules in docs/lot100_plan.md), scripts/lot99_animmodel.py,
scripts/lot98_animmodel.py and scripts/lot97_animmodel.py, not from the
C sources:

* test_lot100_color.c: wf_cssprop_color, every named colour, hex, rgb(),
  hsl(), hwb() and color-mix() with their alpha, and the bounds of the
  text (n, terminators, 128 bytes);
* test_lot100_mix.c: wf_cssprop_interp and wf_cssprop_add on registered
  <color> values written with names, hwb() and color-mix();
* test_lot100_paint.c: wf_site_prepare: the style the reader writes for
  color, background-color, the background shorthand, var() and
  !important with those colours;
* test_lot100_anim.c: wf_site_prepare_ext after wf_site_set_time:
  keyframes and @starting-style transitions on color and
  background-color (the written style, the counts).

Run: python3 scripts/lot100_colorgen.py
"""
