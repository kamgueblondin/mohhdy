NAMES = sorted(L.NAMED)


# ------------------------------------------------------------- colour texts
def rcase(rng, t):
    k = rng.randrange(6)
    if k == 0:
        return t.upper()
    if k == 1:
        return t[0].upper() + t[1:]
    return t


def name_text(rng):
    return rcase(rng, rng.choice(NAMES))


def hex_text(rng):
    return "#" + "".join(rng.choice("0123456789abcdefABCDEF") for _ in range(rng.choice([3, 4, 6, 8])))


def alpha_text(rng):
    return rng.choice([dec(rng, 0, 1, 2), str(rng.randrange(0, 101)) + "%", dec(rng, 0, 1, 4), "0", "1", "1.5",
                       "-0.5", "50%", "0.5", "120%", dec(rng, 0, 100, 2) + "%"])


def rgb_text(rng):
    k = rng.randrange(6)
    if k == 0:
        return G.colour_text(rng)
    ch = lambda: rng.choice([str(rng.randrange(256)), str(rng.randrange(-40, 320)), dec(rng, 0, 255, 2),  # noqa: E731
                             str(rng.randrange(101)) + "%", dec(rng, 0, 100, 1) + "%"])
    if k == 1:
        return "rgb(%s, %s, %s)" % (ch(), ch(), ch())
    if k == 2:
        return "rgba(%s, %s, %s, %s)" % (ch(), ch(), ch(), alpha_text(rng))
    if k == 3:
        return "rgb(%s %s %s / %s)" % (ch(), ch(), ch(), alpha_text(rng))
    if k == 4:
        return "rgb(%s %s %s)" % (ch(), ch(), ch())
    return rng.choice(["rgb(1, 2)", "rgb(1 2 3 4)", "rgb(1, 2 3)", "rgb(1, 2, 3, 4, 5)", "rgb(a, 2, 3)",
                       "rgb(1 2 3 / 4 / 5)", "rgb(1,2,3", "rgb()", "rgba(1 2 3)", "rgb(1px, 2, 3)"])


def hsl_text(rng):
    return G99.hsl_unit(rng) if rng.random() < 0.6 else G98.hsl_text(rng, rng.random() < 0.8)


def wb_text(rng):
    return rng.choice([str(rng.randrange(0, 101)) + "%", dec(rng, 0, 100, 2) + "%", str(rng.randrange(0, 101)),
                       dec(rng, -20, 130, 1) + "%", "0%", "100%", "50%", dec(rng, 0, 100, 4) + "%"])


def hwb_text(rng, good=True):
    h = G99.hue_text(rng) if rng.random() < 0.7 else G98.hue_text(rng)
    t = "hwb(%s %s %s" % (h, wb_text(rng), wb_text(rng))
    if rng.random() < 0.4:
        t += rng.choice([" / ", "/", " /"]) + alpha_text(rng)
    t += ")"
    if rng.random() < 0.15:
        t = rcase(rng, t)
    if not good:
        j = rng.randrange(9)
        if j == 0:
            t = "hwb(%s, %s, %s)" % (h, wb_text(rng), wb_text(rng))
        elif j == 1:
            t = "hwb(%s %s)" % (h, wb_text(rng))
        elif j == 2:
            t = "hwb(%s %s %s %s)" % (h, wb_text(rng), wb_text(rng), wb_text(rng))
        elif j == 3:
            t = "hwba(%s %s %s)" % (h, wb_text(rng), wb_text(rng))
        elif j == 4:
            t = "hwb(%s %s %s / 0.5 / 1)" % (h, wb_text(rng), wb_text(rng))
        elif j == 5:
            t = "hwb(%spx %s %s)" % (dec(rng, 0, 100), wb_text(rng), wb_text(rng))
        elif j == 6:
            t = "hwb(%s %s, %s)" % (h, wb_text(rng), wb_text(rng))
        elif j == 7:
            t = "hwb(%s %s %s" % (h, wb_text(rng), wb_text(rng))
        else:
            t = "hwb(%s %s 1e2%%)" % (h, wb_text(rng))
    return t


def simple_colour(rng):
    k = rng.randrange(6)
    if k == 0:
        return name_text(rng).lower()
    if k == 1:
        return hex_text(rng).lower()
    if k == 2:
        return rgb_text(rng) if rng.random() < 0.5 else "rgb(%d %d %d / %s)" % (
            rng.randrange(256), rng.randrange(256), rng.randrange(256), alpha_text(rng))
    if k == 3:
        return hwb_text(rng).lower()
    if k == 4:
        return rng.choice(["transparent", "red", "blue", "white", "black", "lime", "rebeccapurple"])
    return G99.hsl_unit(rng).lower()


def pct_text(rng):
    return rng.choice([str(rng.randrange(0, 101)) + "%", dec(rng, 0, 100, 2) + "%", "0%", "100%", "50%", "25%",
                       dec(rng, 0, 100, 4) + "%"])


def mix_text(rng, depth=0, good=True):
    def item():
        c = mix_text(rng, depth + 1) if depth < 2 and rng.random() < 0.15 else simple_colour(rng)
        k = rng.randrange(5)
        if k == 0:
            return "%s %s" % (c, pct_text(rng))
        if k == 1:
            return "%s %s" % (pct_text(rng), c)
        return c
    method = rng.choice(["in srgb", "in srgb", "in srgb", "in  srgb", "IN SRGB", "in\tsrgb"])
    sep = rng.choice([", ", ",", " , "])
    t = "color-mix(%s%s%s%s%s)" % (method, sep, item(), sep, item())
    if not good:
        j = rng.randrange(14)
        a, b = simple_colour(rng), simple_colour(rng)
        t = ["color-mix(in hsl, %s, %s)" % (a, b), "color-mix(srgb, %s, %s)" % (a, b),
             "color-mix(in srgb, %s)" % a, "color-mix(in srgb, %s, %s, %s)" % (a, b, a),
             "color-mix(in srgb, %s 0%%, %s 0%%)" % (a, b), "color-mix(in srgb, %s 120%%, %s)" % (a, b),
             "color-mix(in srgb, %s -10%%, %s)" % (a, b), "color-mix(in srgb, %s 50, %s)" % (a, b),
             "color-mix(in srgb, %s 10%% 20%%, %s)" % (a, b), "color-mix(in srgb %s, %s)" % (a, b),
             "color-mix(in srgb, %s, %s" % (a, b), "color-mix(in srgb, , %s)" % b,
             "color-mix(in srgb, currentcolor, %s)" % b, "color-mix(insrgb, %s, %s)" % (a, b)][j]
    return t


def deep_mix(n):
    t = "red"
    for k in range(n):
        t = "color-mix(in srgb, %s, %s)" % (t, ["blue", "lime", "#0000", "white", "black"][k % 5])
    return t


def any_colour(rng, good=None):
    if good is None:
        good = rng.random() < 0.8
    k = rng.randrange(7)
    if k == 0:
        return name_text(rng)
    if k == 1:
        return hex_text(rng)
    if k == 2:
        return rgb_text(rng)
    if k == 3:
        return hsl_text(rng)
    if k == 4 or k == 5:
        return hwb_text(rng, good)
    return mix_text(rng, 0, good)


# ------------------------------------------------------------- color
def rc_str(r):
    return "-" if r is None else "#%06x %d" % r


def write_color():
    rng = random.Random(10001)
    cases = []
    for nm in NAMES:      # every name, once
        t = rcase(rng, nm)
        cases.append(["TEST_ASSERT_EQUAL_STRING(%s, rc(%s));" % (cstr(rc_str(L.reader(t))), cstr(t))])
    for n in range(1, 7):
        t = deep_mix(n)
        cases.append(["TEST_ASSERT_EQUAL_STRING(%s, rc(%s));" % (cstr(rc_str(L.reader(t))), cstr(t))])
    seen = set()
    while len(cases) < 700:
        k = rng.randrange(10)
        if k < 7:
            t = any_colour(rng)
        elif k == 7:
            t = rng.choice([" ", "  ", "\t", ""]) + any_colour(rng, True) + rng.choice(
                ["", " ", ";", " ;", "!important", " !important", " x", "x", ")", "; color: red", "  "])
        elif k == 8:
            t = rng.choice(["transparent", "TRANSPARENT", "currentcolor", "redd", "re d", "#12345", "#1234567",
                            "#ggg", "#", "", "   ", "red blue", "hwb", "hwb()", "color-mix()", "red)", "(red)",
                            "rgb(1 2 3)) ", "hsl(1 2% 3%)(", "darkgrey", "darkgray", "lightgoldenrodyellow"])
        else:
            t = "color-mix(in srgb, %s, %s)" % (any_colour(rng, True), any_colour(rng, True))
        if t in seen:
            continue
        seen.add(t)
        if k == 9 and rng.random() < 0.3:
            t = t + " " * (128 - len(t))  # spaces after the colour do not count
        cases.append(["TEST_ASSERT_EQUAL_STRING(%s, rc(%s));" % (cstr(rc_str(L.reader(t))), cstr(t))])
    # n bounds: a prefix of the text
    while len(cases) < 760:
        t = any_colour(rng, True) + rng.choice([";x", " ff", "0", ")", "!"])
        n = rng.choice([len(t) - 2, len(t) - 1, rng.randrange(1, len(t) + 1)])
        cases.append(["TEST_ASSERT_EQUAL_STRING(%s, rcn(%s, %d));" % (cstr(rc_str(L.reader(t[:n]))), cstr(t), n)])
    # 127 and 128 bytes
    for n in (126, 127, 128, 129):
        base = "color-mix(in srgb, red 25%, blue)"
        t = base.replace("in srgb", "in" + " " * (n - len(base) + 1) + "srgb")
        assert len(t) == n
        cases.append(["TEST_ASSERT_EQUAL_STRING(%s, rc(%s));" % (cstr(rc_str(L.reader(t))), cstr(t))])
    o = [HEADER % "Lot 100: the reader colour (wf_cssprop_color): names, hex, rgb(), hsl(), hwb(), color-mix()"] + \
        G98.IP_C + [
        "/* the reader colour of v[0..n) as \"#rrggbb alpha\", \"-\" when it is not one */",
        "static const char *rcn(const char *v, int n) {",
        "    unsigned int c = 0xdeadbeefu;",
        "    int a = -7, r = wf_cssprop_color(v, n, &c, &a);",
        "    if (!r) return c == 0xdeadbeefu && a == -7 ? \"-\" : \"WRITTEN\";",
        "    if (r != 1 || c > 0xffffffu || a < 0 || a > 255) return \"BAD CODE\";",
        "    snprintf(g_o, sizeof(g_o), \"#%06x %d\", c, a);",
        "    return g_o;",
        "}", "",
        "static const char *rc(const char *v) { return rcn(v, (int)strlen(v)); }", ""]
    o.insert(3, "#include <stdio.h>")
    names = chunks(o, "test_l100_color", cases, 12)
    finish(o, names, "test_lot100_color.c")
    return len(cases)


# ------------------------------------------------------------- mix
def reg_colour(rng):
    k = rng.randrange(8)
    if k < 3:
        return mix_text(rng).lower()
    if k < 5:
        return hwb_text(rng).lower()
    if k == 5:
        return rng.choice(NAMES)
    return simple_colour(rng)


def write_mix():
    rng = random.Random(10002)
    cases = []
    alts = L.ALTS
    while len(cases) < 400:
        a, b = reg_colour(rng), reg_colour(rng)
        if len(a) >= 128 or len(b) >= 128 or not (A.colour_match(a) and A.colour_match(b)):
            continue
        tt = rng.choice([5000, rng.randrange(1, S), rng.randrange(1, S), 1, 9999, 2500])
        r, c = A.interp(alts, a, b, tt)
        if r is None or len(r) >= 160:
            continue
        cases.append(["TEST_ASSERT_EQUAL_STRING(%s, ip(%s, %s, %d, %d));" % (cstr(r), cstr(a), cstr(b), tt, c)])
    while len(cases) < 560:
        a, b = reg_colour(rng), reg_colour(rng)
        if len(a) >= 128 or len(b) >= 128 or not (A.colour_match(a) and A.colour_match(b)):
            continue
        r, c = M98.add(alts, a, b)
        if r is None or len(r) >= 160:
            continue
        cases.append(["TEST_ASSERT_EQUAL_STRING(%s, ad(%s, %s, %d));" % (cstr(r), cstr(a), cstr(b), c)])
    seen = set()
    while len(cases) < 720:
        v = any_colour(rng).lower() if rng.random() < 0.8 else rng.choice(
            ["currentcolor", "transparent", "hwb(1 2% 3%) x", "color-mix(in srgb, red, blue) ", "nosuchcolour"])
        if v in seen or len(v) >= 128 or not v:
            continue
        seen.add(v)
        cases.append(["TEST_ASSERT_EQUAL(%d, mt(%s));" % (int(A.colour_match(v)), cstr(v))])
    o = [HEADER % "Lot 100: names, hwb() and color-mix() in registered <color> values (interp, add, match)"] + \
        G98.IP_C + [
        "/* the interpolated text of two colours; the return code is checked */",
        "static const char *ip(const char *a, const char *b, int t, int code) {",
        "    if (!syn(\"'<color>'\")) return \"BAD SYNTAX\";",
        "    if (wf_cssprop_interp(&g_p, a, b, t, g_o, (int)sizeof(g_o)) != code) return \"BAD CODE\";",
        "    return g_o;",
        "}", "",
        "/* the sum text; the return code is checked */",
        "static const char *ad(const char *under, const char *v, int code) {",
        "    if (!syn(\"'<color>'\")) return \"BAD SYNTAX\";",
        "    if (wf_cssprop_add(&g_p, under, v, g_o, (int)sizeof(g_o)) != code) return \"BAD CODE\";",
        "    return g_o;",
        "}", "",
        "/* whether a '<color>' registration matches v */",
        "static int mt(const char *v) {",
        "    if (!syn(\"'<color>'\")) return -1;",
        "    return wf_cssprop_match_prop(&g_p, v) != 0;",
        "}", ""]
    names = chunks(o, "test_l100_mix", cases, 10)
    finish(o, names, "test_lot100_mix.c")
    return len(cases)


# ------------------------------------------------------------- paint
def css_ok(v):
    return not any(c in v for c in ";{}!\\\"'") and len(v) < 120


def paint_case(rng):
    """(css, [assertion lines]) for #o"""
    v = any_colour(rng)
    while not css_ok(v):
        v = any_colour(rng)
    k = rng.randrange(7)
    t = L.paint_text(v.lower().strip(L.SP))
    if k == 0:
        css = "#o { color: blue } #o { color: %s }" % v
        return css, ["TEST_ASSERT_EQUAL_STRING(%s, style_of(\"o\"));" % cstr(' style="color:%s"' % (t or "#0000ff"))]
    if k == 1:
        css = "#o { background-color: blue } #o { background-color: %s }" % v
        return css, ["TEST_ASSERT_EQUAL_STRING(%s, style_of(\"o\"));" %
                     cstr(' style="background-color:%s"' % (t or "#0000ff"))]
    if k == 2:
        lay = rng.choice(["", "url(x.png) ", "no-repeat ", "url(x.png) left top "])
        css = "#o { background-color: blue } #o { background: %s%s }" % (lay, v)
        w = L.bg_word(v.lower().strip(L.SP))
        if w == "":
            return css, ["TEST_ASSERT_NULL(strstr(style_of(\"o\"), \"background-color\"));"]
        return css, ["TEST_ASSERT_NOT_NULL(strstr(style_of(\"o\"), %s));" % cstr("background-color:%s" %
                                                                                 (w or "#0000ff"))]
    if k == 3:
        css = "#o { color: %s !important } #o { color: blue }" % v
        return css, ["TEST_ASSERT_EQUAL_STRING(%s, style_of(\"o\"));" % cstr(' style="color:%s"' % (t or "#0000ff"))]
    if k == 4:
        css = "#o { --c: %s; background-color: blue } #o { background-color: var(--c) }" % v
        lines = ["TEST_ASSERT_EQUAL_STRING(%s, style_of(\"o\"));" %
                 cstr(' style="background-color:%s"' % t)] if t else []
        return css, lines or None
    if k == 5:
        # two colours, the later one wins when it is a colour
        w = any_colour(rng, True)
        while not css_ok(w):
            w = any_colour(rng, True)
        tw = L.paint_text(w.lower())
        css = "#o { color: %s; background-color: %s }" % (v, w)
        parts = (["color:" + t] if t else []) + (["background-color:" + tw] if tw else [])
        return css, ["TEST_ASSERT_EQUAL_STRING(%s, style_of(\"o\"));" %
                     cstr(' style="%s"' % ";".join(parts) if parts else "")]
    # inherited: the child p gets no style of its own
    css = "#o { color: %s }" % v
    return css, ["TEST_ASSERT_EQUAL_STRING(%s, style_of(\"o\"));" % cstr(' style="color:%s"' % t if t else ""),
                 "TEST_ASSERT_EQUAL_STRING(\"\", style_of(\"i\"));"]


SHEET_HEAD = [
    '#include "../../framework/unity.h"', "#include <string.h>", "#include <stdio.h>", '#include "wf_sitecss.h"', "",
    "static wf_site_t g_d;", "static char g_html[4096];", "static char g_o[1024];", "",
    "static void prep(const char *css, int ms) {",
    "    wf_site_set_time(ms);",
    "    snprintf(g_html, sizeof(g_html), \"<html><head><style>%s</style></head><body>\"",
    "             \"<div id=o><p id=i>i</p></div><p id=q>q</p></body></html>\", css);",
    "    TEST_ASSERT_EQUAL(0, wf_site_prepare_ext(&g_d, g_html, (int)strlen(g_html), 640, 480, 0, 0));",
    "    wf_site_set_time(0);",
    "}", "",
    "static const char *style_of(const char *id) {",
    "    int i;",
    "    g_o[0] = 0;",
    "    for (i = 0; i < g_d.nnodes; i++)",
    "        if (!strcmp(g_d.node[i].id, id)) wf_site_style_attr(&g_d, g_d.node[i].start, g_o, (int)sizeof(g_o));",
    "    return g_o;",
    "}", ""]


def write_paint():
    rng = random.Random(10003)
    cases = []
    while len(cases) < 420:
        css, lines = paint_case(rng)
        if not lines:
            continue
        cases.append(["prep(%s, 0);" % cstr(css)] + lines)
    o = [HEADER % "Lot 100: the reader paint of names, hwb(), color-mix() and translucent colours"] + SHEET_HEAD
    names = chunks(o, "test_l100_paint", cases, 6)
    finish(o, names, "test_lot100_paint.c")
    return len(cases)


# ------------------------------------------------------------- anim
PROPS = ["color", "background-color"]


def kf_value(rng):
    if rng.random() < 0.1:
        return rng.choice(["currentcolor", "nosuch", "1px", "red !important", "var(--c)", "hwb(1, 2%, 3%)"])
    return reg_colour(rng) if rng.random() < 0.5 else simple_colour(rng)


def keyframes(rng, name):
    """the rule text and the model frames of each property"""
    offs = sorted(set(rng.sample([0, 2500, 5000, 7500, 10000, 3333, 6000], rng.randrange(1, 4))))
    if rng.random() < 0.5:
        offs = [o for o in offs if o not in (0, S)] or [5000]
    blocks, frames = [], {p: [] for p in PROPS}
    for o in offs:
        decls, vals = [], {}
        for p in PROPS:
            if rng.random() < 0.65:
                v = kf_value(rng)
                decls.append("%s: %s" % (p, v))
                vals[p] = v
        if not decls:
            v = kf_value(rng)
            decls.append("color: %s" % v)
            vals["color"] = v
        fe = fc = None
        if rng.random() < 0.15:
            ft = rng.choice(["linear", "ease-in", "steps(2)"])
            fe = A.ease_parse(ft)
            decls.append("animation-timing-function: %s" % ft)
        if rng.random() < 0.2:
            fc = rng.choice(M98.COMPS)
            decls.append("animation-composition: %s" % fc)
        rng.shuffle(decls)
        blocks.append("%s { %s }" % (G98.offset_sel(rng, o), "; ".join(decls)))
        for p, v in vals.items():
            raw = v.strip().lower()
            if "!" in raw or "var(" in raw or len(raw) >= 128 or not A.colour_match(raw):
                continue
            frames[p].append((o, raw, fe, fc))
    return "@keyframes %s { %s }" % (name, " ".join(blocks)), frames


def trans_decls(rng):
    decls = []
    if rng.random() < 0.5:
        decls.append(("transition", rng.choice(["color 1000ms linear", "all 400ms", "none", "--x 1s, color 2s ease-in",
                                                "background-color 1s allow-discrete", "background-color 2s linear",
                                                "color 1s, background-color 500ms linear", "all 2s 500ms linear"])))
    else:
        decls.append(("transition-property", rng.choice(["color", "all", "background-color", "--x, color",
                                                         "color, background-color", "none", "--x"])))
        decls.append(("transition-duration", rng.choice(["1000ms", "2s", "400ms, 1s", "0s", "1s, 0s"])))
        if rng.random() < 0.6:
            decls.append(("transition-timing-function", rng.choice(["linear", "ease-in", "steps(3)", "linear, ease"])))
        if rng.random() < 0.3:
            decls.append(("transition-delay", rng.choice(["200ms", "-500ms", "0s, 1s"])))
    return decls


def anim_case(rng):
    own = {}
    imp = {}
    rules = []
    body = []
    for p in PROPS:
        if rng.random() < 0.5:
            v = simple_colour(rng) if rng.random() < 0.7 else reg_colour(rng)
            if not css_ok(v) or v == "transparent":
                continue
            own[p] = v
            imp[p] = rng.random() < 0.12
            body.append("%s: %s%s" % (p, v, " !important" if imp[p] else ""))
    kfs = {p: {} for p in PROPS}
    use_anim = rng.random() < 0.75
    adecls, tdecls = [], []
    if use_anim:
        for name in ("k", "j") if rng.random() < 0.35 else ("k",):
            text, fr = keyframes(rng, name)
            for p in PROPS:
                kfs[p][name] = fr[p]
            rules.append(text)
        adecls = G99.anim_decls(rng)
    start = {}
    if not use_anim or rng.random() < 0.3:
        tdecls = trans_decls(rng)
        sd = []
        for p in PROPS:
            if rng.random() < 0.6 or (p == "color" and not sd):
                v = simple_colour(rng) if rng.random() < 0.8 else reg_colour(rng)
                if not css_ok(v):
                    v = "red"
                start[p] = v
                sd.append("%s: %s" % (p, v))
        rules.append("@starting-style { #o { %s } }" % "; ".join(sd))
    anims = M99.coord(G99.cascade([(100, adecls)])) if adecls else []
    tl = M98.coord(False, G98.cascade(False, [(100, tdecls)])) if tdecls else []
    ms = rng.choice([0, rng.randrange(0, 2500), rng.randrange(0, 1200), 250, 500, 750, 1500])
    body += ["%s: %s" % d for d in adecls + tdecls]
    css = "%s #o { %s }" % (" ".join(rules), "; ".join(body))
    out, n_anim, n_trans, n_comp = [], 0, 0, 0
    for p in PROPS:
        town = L.paint_text(own[p].lower()) if p in own else None
        if town is not None:
            base = town
        else:
            base = "#000000" if p == "color" else "transparent"
        final = town
        cur, animated, composed = L.col_value(anims, kfs[p], base, ms, imp.get(p, False) and town is not None)
        n_comp += int(composed)
        if animated:
            n_anim += 1
            t = L.paint_text(cur)
            if t:
                final = t
        elif p in start:
            st = L.paint_text(start[p].lower())
            if st is None and p == "background-color" and start[p].lower() == "transparent":
                st = "#00000000"
            if st is not None:
                v = L.col_trans(tl, p, st, cur, ms)
                if v is not None:
                    n_trans += 1
                    t = L.paint_text(v)
                    if t:
                        final = t
        if final:
            out.append("%s:%s" % (p, final))
    style = ' style="%s"' % ";".join(out) if out else ""
    return css, ms, style, n_anim, n_trans, n_comp


