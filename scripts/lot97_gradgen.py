#!/usr/bin/env python3
"""Lot 97 test generator for the engine's gradients (test_lot97_cells.c).

Expectations come from scripts/lot97_gradmodel.py with lot96_gradmodel.py
and lot94_gradmodel.py (written from the rules in docs/lot97_plan.md,
docs/lot96_plan.md and docs/lot94_plan.md), not from the C sources:

* a repeating linear, radial or conic gradient with a period of 0 paints
  its average colour (one rectangle, translucent stops included);
* a repeating linear gradient along an axis with hard stops is painted
  per pixel (merged runs) when the runs fit 32 cells;
* in a vertical-rl box: a repeating radial gradient (its centre mirrored
  in the logical frame) and linear gradients at an angle (repeating or
  not) and along an axis, with the rows of the cells cut from the logical
  bottom; the rectangles are checked relative to the box.

Run: python3 scripts/lot97_gradgen.py
"""
import os
import random
import sys
from fractions import Fraction as F

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lot94_gradmodel as M  # noqa: E402
import lot96_gradmodel as M96  # noqa: E402
import lot97_gradmodel as M97  # noqa: E402
import lot94_gradgen as G  # noqa: E402
import lot96_gradgen as G96  # noqa: E402

HEADER = "/* %s (generated by scripts/lot97_gradgen.py; expectations from scripts/lot97_gradmodel.py, lot96_gradmodel.py and lot94_gradmodel.py). */"
cstr, rcase = G.cstr, G.rcase
SIDE_ANGLE = {"top": 0, "right": 90, "bottom": 180, "left": 270}


def alpha_hex(rng):
    """(text, 0xAARRGGBB with the alpha byte inverted)"""
    k = rng.randrange(5)
    if k == 0:
        return "transparent", 255 << 24
    if k == 1:
        r, g, b, a = (rng.randrange(16) for _ in range(4))
        return "#%x%x%x%x" % (r, g, b, a), ((255 - a * 17) << 24) | (r * 17 << 16) | (g * 17 << 8) | b * 17
    if k == 2:
        r, g, b, a = (rng.randrange(256) for _ in range(4))
        return "#%02x%02x%02x%02x" % (r, g, b, a), ((255 - a) << 24) | (r << 16) | (g << 8) | b
    t, v = G.hex_colour(rng)
    return t, v


def average_case(rng):
    style, o, c = G.box_style(rng)
    kind = rng.choice(["linear", "radial", "conic"])
    n = rng.choice([2, 2, 3, 4])
    at = rng.randrange(0, 101)
    texts, cols = [], []
    for k in range(n):
        t, v = alpha_hex(rng)
        if k == 0:
            t += " %d%%" % at
        elif rng.random() < 0.7 or k == n - 1:
            t += " %d%%" % rng.randrange(0, at + 1)
        texts.append(t)
        cols.append(v)
    first = ""
    if kind == "linear" and rng.random() < 0.4:
        first = rng.choice(["to left, ", "45deg, ", "to top right, "])
    elif kind == "radial" and rng.random() < 0.4:
        first = rng.choice(["circle 5px, ", "closest-side at 2px 3px, "])
    g = rcase(rng, "repeating-%s-gradient(" % kind) + first + ", ".join(texts) + ")"
    avg = M97.average(cols)
    if avg >> 24:
        # translucent: the page composites the rectangle, so the parsed
        # gradient is checked (two stops of the average, 180deg, no repeat)
        return "avg", g, "%08X %08X WE_GRAD_ANGLE 18000 0 2" % (avg, avg)
    return "cells", style + ";background-image:" + g, M.items_text(M97.solid_items(o, c, avg))


def pct(a):
    return "%d%%" % (a // 10) if a % 10 == 0 else "%d.%d%%" % (a // 10, a % 10)


def hard_stops_pct(rng):
    n = rng.choice([1, 2, 2])          # at most WE_GRAD_STOPS (4) stops
    width = rng.choice([100, 125, 200, 250, 333, 500])
    texts, model, at = [], [], 0
    for _ in range(n):
        t, v = G.hex_colour(rng)
        texts += ["%s %s" % (t, pct(at)), "%s %s" % (t, pct(at + width))]
        model += [(v, at * 10), (v, (at + width) * 10)]
        at += width
    return texts, model


def axis_case(rng):
    style, o, c = G.box_style(rng)
    texts, stops = hard_stops_pct(rng) if rng.random() < 0.7 else G96.rep_stops(rng)
    if rng.random() < 0.5:
        side = rng.choice(list(SIDE_ANGLE))
        first, ang = "to " + side, SIDE_ANGLE[side]
    else:
        ang = rng.choice([0, 90, 180, 270])
        first = rng.choice(["%ddeg" % ang, "%dturn" % (ang // 90 // 4) if ang == 0 else "%ddeg" % (ang - 360)])
    g = rcase(rng, "repeating-linear-gradient(") + ", ".join([first] + texts) + ")"
    return "cells", style + ";background-image:" + g, M.items_text(M97.axis_items(o, c, stops, ang))


def rl_radial_case(rng):
    w, h = rng.randrange(4, 90), rng.randrange(4, 70)
    first, shape, at = G96.radial_shape(rng)
    texts, stops = G96.rep_stops(rng)
    g = rcase(rng, "repeating-radial-gradient(") + ", ".join(([first] if first else []) + texts) + ")"
    form, extent, sizes = shape
    shape_l = (form, extent, list(reversed(sizes)) if len(sizes) == 2 else sizes)
    o_l = (0, 0, h, w)
    cx, cy, rx, ry = M96.radial_radii(o_l, shape_l, (at[1], at[0]))
    cy = w - cy
    pos = M.stop_positions(stops)
    items = [cell + (M.colour_at(stops, M96.repeat_p(pos, M96.radial_p(cx, cy, rx, ry, cell))),)
             for cell in M97.grid(o_l, o_l, rl=True)]
    return "rl", "width:%dpx;height:%dpx;background:%s" % (w, h, g), M.items_text(M97.rl_physical(items, w))


def rl_linear_case(rng):
    w, h = rng.randrange(4, 90), rng.randrange(4, 70)
    o_l = (0, 0, h, w)
    rep = rng.random() < 0.6
    if rep and rng.random() < 0.4:
        side = rng.choice(list(SIDE_ANGLE))
        texts, stops = hard_stops_pct(rng) if rng.random() < 0.5 else G96.rep_stops(rng)
        la = M97.rl_logical_angle(SIDE_ANGLE[side] * 100) // 100
        items = M97.axis_items_rl(o_l, o_l, stops, la, True)
        g = "repeating-linear-gradient(to %s, %s)" % (side, ", ".join(texts))
    else:
        while True:
            a, d = G96.frac_angle(rng, rad_ok=False)
            if d % 9000:
                break
        texts, stops = G96.rep_stops(rng) if rep else G.engine_stops(rng)
        la = F(M97.rl_logical_angle(d % 36000), 100)
        pos = M.stop_positions(stops)
        try:
            items = []
            for cell in M97.grid(o_l, o_l, rl=True):
                p = M.linear_p(o_l, cell, angle=la)
                items.append(cell + (M.colour_at(stops, M96.repeat_p(pos, p) if rep else p),))
        except M.Ambiguous:
            return None
        g = "%slinear-gradient(%s, %s)" % ("repeating-" if rep else "", a, ", ".join(texts))
    return "rl", "width:%dpx;height:%dpx;background:%s" % (w, h, g), M.items_text(M97.rl_physical(items, w))


CELLS_C = ['#include "../../framework/unity.h"', "#include <string.h>", "#include <stdio.h>", '#include "webeng.h"', "",
           "static we_doc_t g_doc;", "static char g_html[1024], g_out[2400];", "",
           "/* every painted rectangle, \"x y w h AARRGGBB\" joined by ';', relative to",
           " * (bx, by) */",
           "static const char *list(int bx, int by) {",
           "    int i, n = 0;",
           "    for (i = 0; i < (int)g_doc.ndiag; i++) if (strstr(g_doc.diag[i], \"refused\")) return \"REFUSED\";",
           "    g_out[0] = 0;",
           "    for (i = 0; i < (int)g_doc.nitems; i++) {",
           "        const os_fb_web_item_t *it = &g_doc.items[i];",
           "        if (it->kind != OS_FB_WEB_RECT) continue;",
           "        n += snprintf(g_out + n, sizeof(g_out) - (size_t)n, \"%s%d %d %d %d %08X\", n ? \";\" : \"\", it->x - bx,",
           "                      it->y - by, (int)it->w, (int)it->h, (unsigned)it->color);",
           "    }",
           "    return g_out;",
           "}", "",
           "/* a div with this style at the page origin */",
           "static const char *cells(const char *style) {",
           "    snprintf(g_html, sizeof(g_html), \"<html><body style='margin:0'><div style='%s'></div></body></html>\", style);",
           "    if (we_render(&g_doc, g_html, (int)strlen(g_html), 320) != 0) return \"RENDER FAILED\";",
           "    return list(0, 0);",
           "}", "",
           "/* the parsed gradient of a div with background-image g: both stop colours,",
           " * the direction, the angle (1/100 degree), the repeat and the stop count */",
           "static const char *avg(const char *g) {",
           "    int idx;",
           "    const we_node_t *n;",
           "    snprintf(g_html, sizeof(g_html), \"<html><body><div id=t style='height:4px;background-image:%s'></div></body></html>\", g);",
           "    memset(&g_doc, 0, sizeof(g_doc));",
           "    if (we_parse(&g_doc, g_html, (int)strlen(g_html)) != 0 || we_style(&g_doc) != 0) return \"STYLE FAILED\";",
           "    idx = we_find_id(&g_doc, \"t\");",
           "    if (idx < 0) return \"NO NODE\";",
           "    n = &g_doc.nodes[idx];",
           "    snprintf(g_out, sizeof(g_out), \"%08X %08X %s %d %d %d\", (unsigned)n->grad_color[0], (unsigned)n->grad_color[1],",
           "             n->grad_dir == WE_GRAD_ANGLE ? \"WE_GRAD_ANGLE\" : \"OTHER\", n->grad_angle * 100 + n->grad_frac, n->grad_repeat,",
           "             n->grad_count);",
           "    return g_out;",
           "}", "",
           "/* a div with this style in a vertical-rl box; rectangles relative to it */",
           "static const char *rl(const char *style) {",
           "    int idx;",
           "    snprintf(g_html, sizeof(g_html), \"<html><body style='margin:0'><div style='writing-mode:vertical-rl'>\"",
           "             \"<div id=c style='%s'></div></div></body></html>\", style);",
           "    if (we_render(&g_doc, g_html, (int)strlen(g_html), 320) != 0) return \"RENDER FAILED\";",
           "    idx = we_find_id(&g_doc, \"c\");",
           "    if (idx < 0) return \"NO NODE\";",
           "    if (g_doc.nodes[idx].grad_repeat > 1) return \"RL MARK LEFT\";",
           "    return list(g_doc.nodes[idx].x, g_doc.nodes[idx].y);",
           "}", ""]


def write_cells():
    rng = random.Random(9705)
    cases = []
    for _ in range(160):
        cases.append(average_case(rng))
    for _ in range(240):
        cases.append(axis_case(rng))
    for _ in range(160):
        cases.append(rl_radial_case(rng))
    got = 0
    while got < 200:
        c = rl_linear_case(rng)
        if c:
            cases.append(c)
            got += 1
    o = [HEADER % "Lot 97: average colours, per-pixel axis runs and vertical-rl cells painted by the engine"] + CELLS_C
    names, per = [], 4
    runs = 0
    for b in range(0, len(cases), per):
        name = "test_l97_cells_%d" % (b // per)
        names.append(name)
        o.append("static void %s(void) {" % name)
        for fn, style, want in cases[b:b + per]:
            o.append("    TEST_ASSERT_EQUAL_STRING(%s,\n        %s(%s));" % (cstr(want), fn, cstr(style)))
        o.append("}")
        o.append("")
    G96.finish(o, names, "test_lot97_cells.c")
    return len(cases)


if __name__ == "__main__":
    print("cells %d" % write_cells())
