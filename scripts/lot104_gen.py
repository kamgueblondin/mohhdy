#!/usr/bin/env python3
"""Lot 104 test generator: view progress timelines from the layout
geometry (the view math, the parsing of the insets, view() and length
edges, the reader sheet with a geometry, the engine geometry).

Expectations come from scripts/lot104_model.py (written from the rules in
docs/lot104_plan.md and CSS Scroll-driven Animations 1) with the lot 97 to
102 models, and for test_lot104_geom.c from the block layout rules of the
engine documented there (no margin collapsing: boxes stack by their
margin boxes), not from the C sources. A colour the float model cannot
place on one side of a rounding boundary (lot101_colormodel.Unsure) is
left out.

* test_lot104_view.c: wf_cssview_range, wf_cssview_edge,
  wf_cssanim_view_ms and wf_cssanim_scroll_px_ms;
* test_lot104_parse.c: wf_csstl_parse (WF_CSSTL_INSETS, WF_CSSTL_VSHORT),
  wf_csstl_text (the insets), wf_csstl_coord_ex, view() insets in
  animation-timeline and length edges in animation-range;
* test_lot104_sheet.c: wf_site_prepare_ext after wf_site_set_geom and
  wf_site_set_scroll: colour keyframes on #i driven by view(), named view
  timelines (view-timeline-inset, view-timeline) and scroll timelines with
  length edges (the written style, col_animated, anim_scroll, anim_view,
  anim_idle, geom_need, geom_used);
* test_lot104_geom.c: we_geom_feed after we_render of stacked boxes, a
  box scroller and marks that are not valid.

Run: python3 scripts/lot104_gen.py
"""
