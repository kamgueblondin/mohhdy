VW, VH = 320, 480


def box_style(rng):
    h = rng.choice([0, 10, 20, 50, 100, 150, rng.randrange(0, 400)])
    mt, mb = rng.choice([0, 0, 5, 10, rng.randrange(0, 40)]), rng.choice([0, 0, 5, 10, rng.randrange(0, 40)])
    ml, mr = rng.choice([0, 0, 8, rng.randrange(0, 30)]), rng.choice([0, 0, 8, rng.randrange(0, 30)])
    p = rng.choice([0, 0, 0, 4, rng.randrange(0, 20)])
    b = rng.choice([0, 0, 0, 1, 3])
    return {"h": h, "mt": mt, "mb": mb, "ml": ml, "mr": mr, "p": p, "b": b}


def css_of(s, extra=""):
    t = "height:%dpx;margin:%dpx %dpx %dpx %dpx" % (s["h"], s["mt"], s["mr"], s["mb"], s["ml"])
    if s["p"]:
        t += ";padding:%dpx" % s["p"]
    if s["b"]:
        t += ";border:%dpx solid #123456" % s["b"]
    return t + extra


def outer_h(s):
    return s["mt"] + s["h"] + 2 * (s["p"] + s["b"]) + s["mb"]


def geom_case(rng):
    """a page of stacked boxes (one may be a scroller with children, one
    may hold a child): the body html and the expected boxes {mark: text}"""
    n = rng.randrange(1, 6)
    used = set()

    def mark():
        k = rng.randrange(0, 192)
        while k in used:
            k = rng.randrange(0, 192)
        used.add(k)
        return k
    html, exp, y = [], {}, 0
    page_h = 0
    for _ in range(n):
        s = box_style(rng)
        k = rng.randrange(8)
        m = mark() if rng.random() < 0.8 else None
        hidden = rng.random() < 0.08
        bb = 2 * (s["p"] + s["b"])
        x0, w0 = s["ml"], VW - s["ml"] - s["mr"]
        top = y + s["mt"]
        inner = ""
        kids = []
        if k == 0 and not hidden:
            # a box scroller with children
            s["h"] = rng.choice([50, 100, 200])
            cy = 0
            for _ in range(rng.randrange(1, 4)):
                c = box_style(rng)
                c["p"] = c["b"] = 0
                cm = mark() if rng.random() < 0.85 else None
                ci = cy + c["mt"]
                cw = w0 - bb - c["ml"] - c["mr"]
                kids.append((cm, c, ci))
                cy += outer_h(c)
                inner += "<div%s style='%s'></div>" % (" id=wg%d" % cm if cm is not None else "", css_of(c))
            # the engine's scrollable content ends at the lowest border box
            # (scroll_content_bottom: the last margin is not in it)
            crange = max(0, max(ci + c["h"] for _, c, ci in kids) - s["h"])
            for cm, c, ci in kids:
                if cm is not None:
                    cw = w0 - bb - c["ml"] - c["mr"]
                    exp[cm] = "0 1 %d+%d %d+%d vp %d/%d rg %d/0" % (ci, c["h"], c["ml"], cw, s["h"], w0 - bb, crange)
            extra = ";overflow:auto"
        elif k == 1 and not hidden:
            # a child in normal flow
            c = box_style(rng)
            c["h"] = min(c["h"], s["h"])
            cm = mark() if rng.random() < 0.85 else None
            inner = "<div%s style='%s'></div>" % (" id=wg%d" % cm if cm is not None else "", css_of(c))
            if cm is not None:
                cy = top + s["b"] + s["p"] + c["mt"]
                cx = x0 + s["b"] + s["p"] + c["ml"]
                cw = w0 - bb - c["ml"] - c["mr"]
                exp[cm] = ("root", cy, c["h"] + 2 * (c["p"] + c["b"]), cx, cw)
            extra = ""
        else:
            extra = ""
        if hidden:
            extra += ";display:none"
        html.append("<div%s style='%s'>%s</div>" % (" id=wg%d" % m if m is not None else "", css_of(s, extra), inner))
        if m is not None and not hidden:
            exp[m] = ("root", top, s["h"] + bb, x0, w0)
        if not hidden:
            y += outer_h(s)
    page_h = y
    rg = max(0, page_h - VH)
    out = {}
    for m, e in exp.items():
        if isinstance(e, tuple):
            out[m] = "1 1 %d+%d %d+%d vp %d/%d rg %d/0" % (e[1], e[2], e[3], e[4], VH, VW, rg)
        else:
            out[m] = e
    # marks that are not valid (leading zero, too large, other prefix)
    if rng.random() < 0.4:
        bad = rng.choice(["wg07", "wg192", "wg1000", "xg5", "wg", "wg-1", "wgx", "WG5", "wg9999"])
        html.append("<div id=%s style='height:5px'></div>" % bad)
        page_h += 5
        rg = max(0, page_h - VH)
        out = {m: t.rsplit(" rg ", 1)[0] + " rg %d/0" % rg if t.startswith("1 1 ") else t for m, t in out.items()}
    return "".join(html), out, page_h, rg


