def sheet_case(rng):
    w, h = rng.randrange(4, 120), rng.randrange(4, 60)
    o = c = (0, 0, w, h)
    k = rng.randrange(6)
    axis_angle = None
    if k == 0:
        # radians: the reader writes 1/100 degrees, the engine paints them
        while True:
            body = "%d.%04d" % (rng.randrange(0, 13), rng.randrange(10000))
            if rng.random() < 0.3:
                body = "-" + body
            d = M96.rad_centi(body)
            if d is not None and d % 9000:
                break
        first, ang, kind, rep = body + "rad", F(d % 36000, 100), "linear", rng.random() < 0.5
        texts, stops = rep_stops(rng) if rep else G.named_stops(rng)
        pfun = lambda cell: M.linear_p(o, cell, angle=ang)  # noqa: E731
        cells = M.grid(o, c)
    elif k == 1:
        while True:
            a, d = frac_angle(rng, rad_ok=False)
            if a.lower().endswith("turn"):
                # the reader takes two decimals of a turn
                v = rng.randrange(-1000, 1001)
                a, d = dec_text(v, 2) + "turn", M96.engine_centi(dec_text(v, 2), "turn")
            if d % 9000:
                break
        first, ang, kind, rep = a.lower(), F(d % 36000, 100), "linear", rng.random() < 0.5
        texts, stops = rep_stops(rng) if rep else G.named_stops(rng)
        pfun = lambda cell: M.linear_p(o, cell, angle=ang)  # noqa: E731
        cells = M.grid(o, c)
    elif k == 2:
        side = rng.choice(list(SIDE_ANGLE))
        first, kind, rep = "to " + side, "linear", True
        texts, stops = rep_stops(rng)
        ang = F(SIDE_ANGLE[side])
        pfun = lambda cell: M.linear_p(o, cell, angle=ang)  # noqa: E731
        cells = M96.grid_axis(o, c, side in ("top", "bottom"))
        axis_angle = SIDE_ANGLE[side]
    elif k == 3:
        first, shape, at = radial_shape(rng)
        kind, rep = "radial", True
        texts, stops = rep_stops(rng)
        cx, cy, rx, ry = M96.radial_radii(o, shape, at)
        pfun = lambda cell: M96.radial_p(cx, cy, rx, ry, cell)  # noqa: E731
        cells = M.grid(o, c)
    else:
        body = "%d.%03d" % (rng.randrange(0, 7), rng.randrange(1000))
        d = M96.rad_centi(body)
        if d is None:
            return None
        x, y = rng.randrange(101), rng.randrange(101)
        first, kind, rep = "from %srad at %d%% %d%%" % (body, x, y), "conic", rng.random() < 0.7
        texts, stops = rep_stops(rng, conic=True)
        cx, cy = w * x // 100, h * y // 100
        frm = F(d % 36000, 100)
        pfun = lambda cell: M.conic_p(2 * cx, 2 * cy, cell, frm)  # noqa: E731
        cells = M.grid(o, c)
    try:
        items = paint(cells, stops, pfun, rep)
    except M.Ambiguous:
        STATS["ambiguous"] += 1
        return None
    if axis_angle is not None:
        items = M97.axis_items(o, c, stops, axis_angle)   # Lot 97 (converted): per-pixel runs
    g = "%s%s-gradient(%s)" % ("repeating-" if rep else "", kind, ", ".join(([first] if first else []) + texts))
    if len(g) > 120:
        return None
    prop = rng.choice(["background-image", "background"])
    return "#t { %s: %s }" % (prop, g), w, h, items


