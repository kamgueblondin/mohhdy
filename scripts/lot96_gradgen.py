#!/usr/bin/env python3
"""Lot 96 test generator: fractional degrees and repeating gradients.

Expectations come from scripts/lot96_gradmodel.py and
scripts/lot94_gradmodel.py (written from the rules in docs/lot96_plan.md
and docs/lot94_plan.md), not from the C sources:

* test_lot96_cells.c: the engine (webeng.c) paints a div with a linear or
  conic gradient at a fractional angle, or a repeating linear, conic or
  radial gradient; every painted rectangle (x, y, w, h, colour) is checked;
* test_lot96_bgval.c: the reader (wf_cssbg.c) checks and writes
  repeating gradients, fractional conic stops, radian angles to 1/100
  degree and radian conic "from"; and a registered <image> value
  (wf_cssprop.c) is matched as the reader takes the gradient;
* test_lot96_accept.c: every gradient the reader writes in
  test_lot96_bgval.c is read by the engine (direction, repeat, angle in
  1/100 degree, corner, stops);
* test_lot96_sheet.c: a style sheet through the reader, whose style goes
  on a sized div, and the engine's rectangles are checked.

Run: python3 scripts/lot96_gradgen.py
"""
