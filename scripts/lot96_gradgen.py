SEED_CELLS = 9601
SEED_VAL = 9602
SEED_SHEET = 9603
STATS = {"unknown": 0, "ambiguous": 0, "max_linear_err": 0.0, "max_radial_err": 0.0, "refused": 0}
cstr, rcase, sp, norm_words, dec_text = G.cstr, G.rcase, G.sp, G.norm_words, G.dec_text
SIDE_ANGLE = {"top": 0, "right": 90, "bottom": 180, "left": 270}


def finish(o, names, fname):
    o += ["int main(void) {", "    unity_init();"]
    o += ["    RUN_TEST(%s);" % n for n in names]
    o += ["    unity_print_results();", "    unity_cleanup();", "    return unity_stats.tests_failed == 0 ? 0 : 1;", "}", ""]
    open(os.path.join(G.OUT, fname), "w").write("\n".join(o))


def paint(cells, stops, pfun, repeat):
    pos = M.stop_positions(stops)
    items = []
    for cell in cells:
        p = pfun(cell)
        if repeat:
            p = M96.repeat_p(pos, p)
        items.append(cell + (M.colour_at(stops, p),))
    return items


# ------------------------------------------------------------ engine angles
def frac_angle(rng, rad_ok=True):
    """(text, 1/100 degrees as the engine reads it)"""
    k = rng.randrange(5 if rad_ok else 4)
    if k <= 1:
        v = rng.randrange(-72000, 72001)
        t = dec_text(v, 2) + rcase(rng, "deg")
        return t, M96.engine_centi(dec_text(v, 2), "deg")
    if k == 2:
        v = rng.randrange(-3000, 3001)
        t = dec_text(v, 3) + rcase(rng, "turn")
        return t, M96.engine_centi(dec_text(v, 3), "turn")
    if k == 3:
        v = rng.randrange(-80000, 80001)
        t = dec_text(v, 2) + rcase(rng, "grad")
        return t, M96.engine_centi(dec_text(v, 2), "grad")
    v = rng.randrange(-13000, 13001)
    t = dec_text(v, 3) + rcase(rng, "rad")
    return t, M96.engine_centi(dec_text(v, 3), "rad")


def rep_stops(rng, conic=False, n=None):
    """(texts, model stops) with a period above 0 (positions rise)"""
    n = n or rng.choice([2, 2, 3, 4])
    texts, model = [], []
    at = rng.choice([0, 0, rng.randrange(0, 400)])
    for k in range(n):
        t, v = G.hex_colour(rng)
        pos = None
        r = rng.random()
        if k == n - 1 or r < 0.6:
            at = min(1000, at + rng.randrange(20, 400))
            if conic and rng.random() < 0.4:
                c = min(36000, at * 36)
                c -= rng.randrange(0, 30) if c > 100 else 0
                t += " " + dec_text(c, 2) + "deg"
                pos = M96.conic_stop_pos_centi(c)
            else:
                t += " %d%%" % (at // 10) if at % 10 == 0 else " %d.%d%%" % (at // 10, at % 10)
                pos = at * 10
        texts.append(t)
        model.append((v, pos))
    pos = M.stop_positions(model)
    assert pos[-1] > pos[0]
    return texts, model


def flat_stops(rng):
    """stops with a period of 0 (Lot 97: the average colour when repeating)"""
    a = rng.randrange(0, 101)
    k = rng.randrange(3)
    if k == 0:
        return ["red %d%%" % a, "blue %d%%" % a]
    if k == 1:
        return ["red 100%", "blue"]
    return ["red %d%%" % a, "lime %d%%" % rng.randrange(0, a + 1), "blue %d%%" % rng.randrange(0, a + 1)]


def linear_frac_case(rng):
    while True:
        style, o, c = G.box_style(rng)
        a, d = frac_angle(rng)
        if d % 9000:
            break
    texts, stops = G.engine_stops(rng)
    g = rcase(rng, "linear-gradient(") + ", ".join([a] + texts) + ")"
    ang = F(d % 36000, 100)
    items = paint(M.grid(o, c), stops, lambda cell: M.linear_p(o, cell, angle=ang), False)
    for cell in M.grid(o, c):
        e = abs(M.linear_p(o, cell, angle=ang) - M.linear_p_true(o, cell, ang))
        STATS["max_linear_err"] = max(STATS["max_linear_err"], e)
        assert e < 2.5, (o, cell, d, e)
    return style + ";background-image:" + g, items


def conic_first(rng):
    k = rng.randrange(4)
    frm, at, parts = F(0), ((50, 1), (50, 1)), []
    if k in (1, 3):
        a, d = frac_angle(rng)
        frm = F(d % 36000, 100)
        parts += [rcase(rng, "from"), a]
    if k in (2, 3):
        pt, px, py = G.position(rng)
        parts += [rcase(rng, "at"), pt]
        at = (px, py)
    return (" ".join(parts) if parts else None), frm, at


def conic_cells(o, c, stops, frm, at, repeat):
    cx = o[0] + (o[2] * at[0][0] // 100 if at[0][1] else at[0][0])
    cy = o[1] + (o[3] * at[1][0] // 100 if at[1][1] else at[1][0])
    return paint(M.grid(o, c), stops, lambda cell: M.conic_p(2 * cx, 2 * cy, cell, frm), repeat)


def conic_frac_case(rng, repeat=False):
    while True:
        style, o, c = G.box_style(rng)
        first, frm, at = conic_first(rng)
        if repeat:
            texts, stops = rep_stops(rng, conic=True)
        else:
            texts, stops = rep_stops(rng, conic=True) if rng.random() < 0.6 else G.engine_stops(rng, conic=True)
        try:
            items = conic_cells(o, c, stops, frm, at, repeat)
        except M.Ambiguous:
            STATS["ambiguous"] += 1
            continue
        g = rcase(rng, ("repeating-" if repeat else "") + "conic-gradient(") + ", ".join(([first] if first else []) + texts) + ")"
        return style + ";background-image:" + g, items


def linear_first_rep(rng):
    """(text or None, ('angle', Fraction) or ('corner', (v, h)), axis)"""
    k = rng.randrange(6)
    if k == 0:
        return None, ("angle", F(180)), True
    if k == 1:
        side = rng.choice(list(SIDE_ANGLE))
        return rcase(rng, "to ") + rcase(rng, side), ("angle", F(SIDE_ANGLE[side])), True
    if k == 2:
        q = rng.randrange(-8, 9)
        t = rng.choice(["%ddeg" % (90 * q), dec_text(25 * q, 2) + "turn", "%dgrad" % (100 * q)])
        return t, ("angle", F((90 * q) % 360)), True
    if k == 3:
        v, h = rng.choice(G.CORNERS)
        words = [v, h] if rng.random() < 0.5 else [h, v]
        return rcase(rng, "to ") + " ".join(rcase(rng, w) for w in words), ("corner", (v, h)), False
    while True:
        a, d = frac_angle(rng)
        if d % 9000:
            return a, ("angle", F(d % 36000, 100)), False


def linear_rep_case(rng):
    style, o, c = G.box_style(rng)
    first, how, axis = linear_first_rep(rng)
    texts, stops = rep_stops(rng)
    g = rcase(rng, "repeating-linear-gradient(") + ", ".join(([first] if first else []) + texts) + ")"
    if how[0] == "corner":
        pfun = lambda cell: M.linear_p(o, cell, corner=how[1])  # noqa: E731
        cells = M.grid(o, c)
    else:
        pfun = lambda cell: M.linear_p(o, cell, angle=how[1])  # noqa: E731
        if axis:
            # Lot 97 (converted): per-pixel runs when they fit 32 cells
            return style + ";background-image:" + g, M97.axis_items(o, c, stops, how[1])
        cells = M.grid(o, c)
    return style + ";background-image:" + g, paint(cells, stops, pfun, True)


def radial_shape(rng, o_hint=None):
    """(text or None, (form, extent, sizes), at)"""
    k = rng.randrange(7)
    form, extent, sizes, words = None, None, [], []
    if k == 0:
        pass
    elif k == 1:
        r = rng.randrange(0, 80)
        words, form, sizes = [rcase(rng, "circle"), "%dpx" % r], "circle", [(r, 0)]
        if rng.random() < 0.3:
            words = words[::-1]
    elif k == 2:
        a, b = rng.randrange(0, 90), rng.randrange(0, 60)
        pa, pb = rng.random() < 0.3, rng.random() < 0.3
        words = ["%d%s" % (a, "%" if pa else "px"), "%d%s" % (b, "%" if pb else "px")]
        if rng.random() < 0.5:
            words.insert(0 if rng.random() < 0.5 else 2, rcase(rng, "ellipse"))
        form, sizes = "ellipse", [(a, pa), (b, pb)]
    elif k == 3:
        r = rng.randrange(1, 80)
        words, form, sizes = ["%dpx" % r], "circle", [(r, 0)]
    else:
        extent = rng.choice(sorted(M96.EXTENTS))
        form = rng.choice(["circle", "ellipse", None])
        words = [rcase(rng, extent)]
        if form:
            words.insert(rng.randrange(2), rcase(rng, form))
        form = form or "ellipse"
    at = ((50, 1), (50, 1))
    if rng.random() < 0.5:
        pt, px, py = G.position(rng)
        words += [rcase(rng, "at"), pt]
        at = (px, py)
    if not words:
        return None, ("ellipse", None, []), at
    if form is None:
        form = "ellipse"
    return " ".join(words), (form, extent, sizes), at


def radial_rep_case(rng):
    style, o, c = G.box_style(rng)
    first, shape, at = radial_shape(rng)
    texts, stops = rep_stops(rng)
    g = rcase(rng, "repeating-radial-gradient(") + ", ".join(([first] if first else []) + texts) + ")"
    cx, cy, rx, ry = M96.radial_radii(o, shape, at)
    cells = M.grid(o, c)
    for cell in cells:
        e = abs(M96.radial_p(cx, cy, rx, ry, cell) - M96.radial_p_true(cx, cy, rx, ry, cell))
        STATS["max_radial_err"] = max(STATS["max_radial_err"], e)
        assert e <= 1.0 + 10000 / (8 * 2 * rx * ry), (o, cell, e)
    return style + ";background-image:" + g, paint(cells, stops, lambda cell: M96.radial_p(cx, cy, rx, ry, cell), True)


FLAT_COLOURS = {"red": 0xFF0000, "lime": 0x00FF00, "blue": 0x0000FF}


def refused_case(rng):
    """Lot 97 (converted): a period of 0 paints its average colour as one
    rectangle (was REFUSED)"""
    style, o, c = G.box_style(rng)
    kind = rng.choice(["linear", "radial", "conic"])
    STATS["refused"] += 1
    st = flat_stops(rng)
    g = rcase(rng, "repeating-%s-gradient(" % kind) + ", ".join(st) + ")"
    avg = M97.average([FLAT_COLOURS[x.split()[0]] for x in st])
    return style + ";background-image:" + g, M97.solid_items(o, c, avg)


