# ------------------------------------------------------------ reader values
def first_arg(normal):
    """True when a written gradient has a first (non-stop) argument"""
    body = normal[normal.index("(") + 1:-1]
    a0 = M96.split_top(body)[0]
    return not M96.colour_ok(M96.words(a0)[0])


def period_ok(normal, conic):
    args = M96.split_top(normal[normal.index("(") + 1:-1])
    stops = args[1:] if first_arg(normal) else args
    pos = []
    for st in stops:
        w = M96.words(st)
        pos.append(M96.stop_pos(w[1], conic) if len(w) == 2 else None)
    p0 = pos[0] or 0
    top = max([p0] + [p for p in pos[1:] if p is not None] + ([10000] if pos[-1] is None else []))
    return top > p0


def radial_val_case(rng):
    """(source, written or None) of a radial gradient from radial_shape"""
    first, _, _ = radial_shape(rng)
    st = G.reader_stops(rng)
    args = ([first] if first else []) + st
    src = rcase(rng, "radial-gradient(") + sp(rng) + ("," + sp(rng)).join(args) + sp(rng) + ")"
    ok = M96.gradient_ok(src.lower())
    normal = "radial-gradient(" + ", ".join(norm_words(a) for a in args) + ")"
    return src, (normal if ok and len(normal) <= 127 else None)


def frac_stop(rng):
    """(text, valid)"""
    k = rng.randrange(6)
    if k <= 2:
        c = rng.randrange(0, 36001)
        return dec_text(c, 2) + "deg", True
    if k == 3:
        v = rng.randrange(0, 361000)
        return dec_text(v, 3) + "deg", v % 1000 == 0 and v <= 360000     # three decimals are refused
    if k == 4:
        c = rng.randrange(36001, 40000)
        return dec_text(c, 2) + "deg", False
    return rng.choice(["1.deg", ".5deg", "-0.5deg", "+1deg", "1.5e1deg", "0360deg", "45.5 deg", "1rad", "0.25turn"]), False


def frac_conic_case(rng):
    first, fw, ok = G.conic_reader_first(rng)
    n = rng.choice([2, 3, 4])
    st, valid = [], ok
    for _ in range(n):
        col = G.reader_colour(rng)
        if rng.random() < 0.6:
            t, v = frac_stop(rng)
            col += " " + t
            valid = valid and v
        st.append(col)
    args = ([first] if first else []) + st
    src = rcase(rng, "conic-gradient(") + sp(rng) + ("," + sp(rng)).join(args) + sp(rng) + ")"
    if not valid:
        return src, None
    normal = "conic-gradient(" + ", ".join(fw if (fw and k == 0) else norm_words(x) for k, x in enumerate(args)) + ")"
    return src, (normal if len(normal) <= 127 else None)


def repeating(rng, src, normal, conic):
    """src and its written form under the repeating- prefix"""
    s = rcase(rng, "repeating-") + src.lstrip()
    # Lot 97 (converted): a period of 0 is written too
    if normal is None or len(normal) + 10 > 127:
        return s, None
    return s, "repeating-" + normal


def rep_val_case(rng):
    k = rng.randrange(10)
    if k <= 2:
        src, n = G.gradient_val_case(rng)
        conic = False
    elif k <= 4:
        src, n = G.conic_val_case(rng)
        conic = True
    elif k <= 6:
        src, n = radial_val_case(rng)
        conic = False
    elif k == 7:
        src, n = frac_conic_case(rng)
        conic = True
    else:
        kind = rng.choice(["linear", "radial", "conic"])
        st = flat_stops(rng)
        src = kind + "-gradient(" + ", ".join(st) + ")"
        n = src
        conic = kind == "conic"
    return repeating(rng, src, n, conic)


