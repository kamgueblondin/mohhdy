#!/usr/bin/env python3
"""Lot 94 test generator: angled linear and conic gradients.

Expectations come from scripts/lot94_gradmodel.py (written from the rules
in docs/lot94_plan.md), not from the C sources.

* test_lot94_cells.c: the engine (webeng.c) paints a div with an angled
  linear gradient, a gradient to a corner or a conic gradient; every
  painted rectangle (x, y, w, h, colour) is checked;
* test_lot94_bgval.c: the reader (wf_cssbg.c) checks and writes gradient
  values: any linear angle (deg, turn, grad; radians as whole degrees),
  "to" a corner, conic-gradient() with from, at and angle stops;
* test_lot94_sheet.c: a sheet goes through the reader, the style it gives
  goes on a sized div, and the engine's rectangles are checked (radians
  and registered angles end up as whole degrees).

Run: python3 scripts/lot94_gradgen.py
"""
import math
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lot94_gradmodel as M  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "tests", "unit", "userspace")
HEADER = "/* %s (generated by scripts/lot94_gradgen.py; expectations from scripts/lot94_gradmodel.py). */\n"
SEED_CELLS = 9401
SEED_VAL = 9402
SEED_SHEET = 9403

NAMED = {"red": 0xFF0000, "blue": 0x0000FF, "lime": 0x00FF00, "black": 0x000000, "white": 0xFFFFFF,
         "navy": 0x000080, "teal": 0x008080, "gray": 0x808080, "orange": 0xFFA500}
STATS = {"ambiguous": 0, "max_linear_err": 0.0}


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\t", "\\t") + '"'


def rcase(rng, s):
    m = rng.randrange(4)
    if m == 0:
        return s.upper()
    if m == 1:
        return "".join(c.upper() if rng.random() < 0.5 else c for c in s)
    return s


def sp(rng):
    return rng.choice(["", " ", " ", "  ", "\t"])


def norm_words(text):
    return " ".join(text.split()).lower()


# ------------------------------------------------------------ engine stops
def hex_colour(rng):
    v = rng.randrange(1 << 24)
    return "#%06x" % v, v


def engine_stops(rng, conic=False, n=None):
    """(texts, model stops)"""
    n = n or rng.choice([2, 2, 3, 4])
    texts, model = [], []
    for _ in range(n):
        t, v = hex_colour(rng)
        pos = None
        r = rng.random()
        if r < 0.25:
            tenths = rng.randrange(1001)
            t += " %d%%" % (tenths // 10) if tenths % 10 == 0 else " %d.%d%%" % (tenths // 10, tenths % 10)
            pos = tenths * 10
        elif conic and r < 0.45:
            d = rng.randrange(361)
            t += " %ddeg" % d
            pos = M.conic_stop_pos(d)
        texts.append(t)
        model.append((v, pos))
    return texts, model


BOXES = ["padding-box", "content-box", "border-box"]


def box_rect(kind, w, h, p):
    """p: padding top, right, bottom, left"""
    if kind == "content-box":
        return (p[3], p[0], w, h)
    return (0, 0, w + p[1] + p[3], h + p[0] + p[2])


def box_style(rng):
    w = rng.choice([rng.randrange(1, 9), rng.randrange(1, 200), rng.randrange(20, 200)])
    h = rng.choice([rng.randrange(1, 9), rng.randrange(1, 110), rng.randrange(10, 110)])
    k = rng.randrange(4)
    if k == 0:
        p = (0, 0, 0, 0)
    elif k == 1:
        v = rng.randrange(1, 13)
        p = (v, v, v, v)
    else:
        p = tuple(rng.randrange(0, 13) for _ in range(4))
    origin, clip = rng.choice(BOXES), rng.choice(BOXES)
    style = "width:%dpx;height:%dpx" % (w, h)
    if k == 1:
        style += ";padding:%dpx" % p[0]
    elif k > 1:
        style += ";padding:%dpx %dpx %dpx %dpx" % p
    if origin != "padding-box" or rng.random() < 0.3:
        style += ";background-origin:" + origin
    if clip != "border-box" or rng.random() < 0.3:
        style += ";background-clip:" + clip
    return style, box_rect(origin, w, h, p), box_rect(clip, w, h, p)


def paint(o, c, stops, pfun):
    items = []
    for cell in M.grid(o, c):
        p = pfun(cell)
        items.append(cell + (M.colour_at(stops, p),))
    return items


# angles as the engine reads them (tf_angle): exact decimal values
def engine_angle(rng):
    """(text, whole degrees) that is not a multiple of 90"""
    while True:
        k = rng.randrange(5)
        if k <= 1:
            v = rng.randrange(-720, 721)
            t = "%d%s" % (v, rcase(rng, "deg"))
            d = v
        elif k == 2:
            v = rng.randrange(-7200, 7201)
            t = "%s%s" % (dec_text(v, 1), rcase(rng, "deg"))
            d = M.decimal_degrees(dec_text(v, 1), "deg")
        elif k == 3:
            v = rng.randrange(-200, 201)
            t = "%s%s" % (dec_text(v, 2), rcase(rng, "turn"))
            d = M.decimal_degrees(dec_text(v, 2), "turn")
        else:
            v = rng.randrange(-8000, 8001)
            t = "%s%s" % (dec_text(v, 1), rcase(rng, "grad"))
            d = M.decimal_degrees(dec_text(v, 1), "grad")
        if d % 90:
            return t, d


def dec_text(v, places):
    s = "-" if v < 0 else ""
    a = abs(v)
    whole, frac = divmod(a, 10 ** places)
    if frac == 0:
        return s + str(whole)
    return s + "%d.%s" % (whole, ("%0" + str(places) + "d") % frac)


CORNERS = [("top", "right"), ("top", "left"), ("bottom", "right"), ("bottom", "left")]


def linear_cell_case(rng):
    style, o, c = box_style(rng)
    a, d = engine_angle(rng)
    texts, stops = engine_stops(rng)
    g = rcase(rng, "linear-gradient(") + ", ".join([a] + texts) + ")"
    items = paint(o, c, stops, lambda cell: M.linear_p(o, cell, angle=d))
    for cell in M.grid(o, c):
        e = abs(M.linear_p(o, cell, angle=d) - M.linear_p_true(o, cell, d))
        STATS["max_linear_err"] = max(STATS["max_linear_err"], e)
        assert e < 1.5, (o, cell, d, e)
    return style + ";background-image:" + g, items


def corner_cell_case(rng):
    style, o, c = box_style(rng)
    v, h = rng.choice(CORNERS)
    words = [v, h] if rng.random() < 0.5 else [h, v]
    texts, stops = engine_stops(rng)
    g = rcase(rng, "linear-gradient(") + rcase(rng, "to ") + " ".join(rcase(rng, w) for w in words) + ", " + ", ".join(texts) + ")"
    items = paint(o, c, stops, lambda cell: M.linear_p(o, cell, corner=(v, h)))
    return style + ";background-image:" + g, items


def position(rng):
    """(text, (x, xpct), (y, ypct))"""
    k = rng.randrange(4)
    if k == 0:
        x, y = rng.randrange(101), rng.randrange(101)
        return "%d%% %d%%" % (x, y), (x, 1), (y, 1)
    if k == 1:
        x, y = rng.randrange(0, 200), rng.randrange(0, 120)
        return "%dpx %dpx" % (x, y), (x, 0), (y, 0)
    if k == 2:
        hx = rng.choice([("left", 0), ("center", 50), ("right", 100)])
        vy = rng.choice([("top", 0), ("center", 50), ("bottom", 100)])
        return "%s %s" % (hx[0], vy[0]), (hx[1], 1), (vy[1], 1)
    x, y = rng.randrange(101), rng.randrange(60)
    if rng.random() < 0.5:
        return "%d%% %dpx" % (x, y), (x, 1), (y, 0)
    return "%dpx %d%%" % (y, x), (y, 0), (x, 1)


def conic_first(rng):
    """(text or None, from degrees, (x, pct), (y, pct))"""
    k = rng.randrange(4)
    frm, at = 0, ((50, 1), (50, 1))
    parts = []
    if k in (1, 3):
        v = rng.randrange(-400, 401)
        if rng.random() < 0.3:
            t = dec_text(rng.randrange(-100, 101), 2) + rcase(rng, "turn")
            frm = M.decimal_degrees(t[:-4], "turn") % 360
        else:
            t = "%d%s" % (v, rcase(rng, "deg"))
            frm = v % 360
        parts += [rcase(rng, "from"), t]
    if k in (2, 3):
        pt, px, py = position(rng)
        parts += [rcase(rng, "at"), pt]
        at = (px, py)
    return (" ".join(parts) if parts else None), frm, at


def conic_paint(o, c, stops, frm, at):
    cx = o[0] + (o[2] * at[0][0] // 100 if at[0][1] else at[0][0])
    cy = o[1] + (o[3] * at[1][0] // 100 if at[1][1] else at[1][0])
    return paint(o, c, stops, lambda cell: M.conic_p(2 * cx, 2 * cy, cell, frm))


def conic_cell_case(rng):
    while True:
        style, o, c = box_style(rng)
        first, frm, at = conic_first(rng)
        texts, stops = engine_stops(rng, conic=True)
        try:
            items = conic_paint(o, c, stops, frm, at)
        except M.Ambiguous:
            STATS["ambiguous"] += 1
            continue
        args = ([first] if first else []) + texts
        g = rcase(rng, "conic-gradient(") + ", ".join(args) + ")"
        return style + ";background-image:" + g, items


def write_cells():
    rng = random.Random(SEED_CELLS)
    cases = []
    for _ in range(330):
        cases.append(linear_cell_case(rng))
    for _ in range(130):
        cases.append(corner_cell_case(rng))
    for _ in range(340):
        cases.append(conic_cell_case(rng))
    o = [HEADER % "Lot 94: angled linear, corner and conic gradients painted in cells by the engine",
         '#include "../../framework/unity.h"', "#include <string.h>", "#include <stdio.h>", '#include "webeng.h"', "",
         "static we_doc_t g_doc;", "static char g_html[1024], g_out[2048];", "",
         "/* every painted rectangle of a div, \"x y w h AARRGGBB\" joined by ';' */",
         "static const char *cells(const char *style) {",
         "    int i, n = 0;",
         "    snprintf(g_html, sizeof(g_html), \"<html><body style='margin:0'><div style='%s'></div></body></html>\", style);",
         "    if (we_render(&g_doc, g_html, (int)strlen(g_html), 320) != 0) return \"RENDER FAILED\";",
         "    for (i = 0; i < (int)g_doc.ndiag; i++) if (strstr(g_doc.diag[i], \"refused\")) return \"REFUSED\";",
         "    g_out[0] = 0;",
         "    for (i = 0; i < (int)g_doc.nitems; i++) {",
         "        const os_fb_web_item_t *it = &g_doc.items[i];",
         "        if (it->kind != OS_FB_WEB_RECT) continue;",
         "        n += snprintf(g_out + n, sizeof(g_out) - (size_t)n, \"%s%d %d %d %d %08X\", n ? \";\" : \"\", it->x, it->y,",
         "                      (int)it->w, (int)it->h, (unsigned)it->color);",
         "    }",
         "    return g_out;",
         "}", ""]
    names, per = [], 4
    for b in range(0, len(cases), per):
        name = "test_l94_cells_%d" % (b // per)
        names.append(name)
        o.append("static void %s(void) {" % name)
        for style, items in cases[b:b + per]:
            o.append("    TEST_ASSERT_EQUAL_STRING(%s,\n        cells(%s));" % (cstr(M.items_text(items)), cstr(style)))
        o.append("}")
        o.append("")
    finish(o, names, "test_lot94_cells.c")
    return len(cases)


# ------------------------------------------------------------ reader values
def reader_colour(rng):
    k = rng.randrange(3)
    if k == 0:
        return rcase(rng, rng.choice(list(NAMED)))
    if k == 1:
        return "#" + "".join(rng.choice("0123456789abcdef") for _ in range(rng.choice([3, 6])))
    return "rgb(%d, %d, %d)" % (rng.randrange(256), rng.randrange(256), rng.randrange(256))


def reader_stops(rng, conic=False, n=None):
    """(texts, valid)"""
    n = n or rng.choice([2, 2, 3, 4])
    out = []
    for _ in range(n):
        c = reader_colour(rng)
        r = rng.random()
        if r < 0.25:
            t = rng.randrange(1001)
            c += sp(rng) or " "
            c += ("%d%%" % (t // 10)) if t % 10 == 0 else ("%d.%d%%" % (t // 10, t % 10))
        elif conic and r < 0.45:
            c += " %d%s" % (rng.randrange(361), rcase(rng, "deg"))
        out.append(c)
    return out


def reader_angle(rng):
    """(text, written form or None)"""
    k = rng.randrange(9)
    neg = "-" if rng.random() < 0.25 else ""
    if k <= 1:
        v = rng.randrange(0, 3700)
        t = neg + str(v) + rcase(rng, "deg")
        return t, (t.lower() if v <= 3600 else None)
    if k == 2:
        places = rng.choice([1, 2, 3, 4, 5])
        v = rng.randrange(0, 3601 * 10 ** places)
        txt = dec_text(v, places)
        if "." not in txt:
            txt += "." + "0" * places
        t = neg + txt + rcase(rng, "deg")
        ok = places <= 4 and v <= 3600 * 10 ** places
        return t, (t.lower() if ok else None)
    if k == 3:
        places = rng.choice([0, 1, 2, 2, 3])
        v = rng.randrange(0, 11 * 10 ** places + 5)
        txt = dec_text(v, places) if places else str(v)
        t = neg + txt + rcase(rng, "turn")
        ok = places <= 2 and v <= 10 * 10 ** places
        return t, (t.lower() if ok else None)
    if k == 4:
        places = rng.choice([0, 1, 2, 3])
        v = rng.randrange(0, 4050 * 10 ** places)
        txt = dec_text(v, places) if places else str(v)
        t = neg + txt + rcase(rng, "grad")
        ok = places <= 2 and v <= 4000 * 10 ** places
        return t, (t.lower() if ok else None)
    if k in (5, 6):
        while True:
            ip = rng.choice([0, 1, 2, 2, 3])
            places = rng.choice([0, 1, 2, 3, 4, 4, 5])
            whole = rng.randrange(10 ** ip) if ip else 0
            frac = rng.randrange(10 ** places) if places else 0
            body = (str(whole) if ip else ("0" if not places or rng.random() < 0.7 else "")) + \
                ("." + ("%0" + str(places) + "d") % frac if places else "")
            if not body or body == ".":
                continue
            t = neg + body + rcase(rng, "rad")
            if (len(str(whole)) if ip else 0) > 2 or places > 4:
                return t, None
            d = M.rad_whole_degrees(neg + body)
            if d is None:
                STATS["ambiguous"] += 1
                continue
            return t, "%ddeg" % d
    if k == 7:
        v, h = rng.choice(CORNERS)
        words = [v, h] if rng.random() < 0.5 else [h, v]
        t = rcase(rng, "to") + (sp(rng) or " ") + (sp(rng) or " ").join(rcase(rng, w) for w in words)
        return t, norm_words(t)
    t = rng.choice(["45px", "+45deg", "45", "45.deg", "1.rad", "to top bottom", "to left right", "to top left bottom",
                    "to center", "to", "45deg 10deg", "0.12345turn", "100.555grad", "3600.5deg", "10.01turn",
                    "4000.1grad", "100rad", "1e2deg", "to top-left"])
    return t, None


def gradient_val_case(rng):
    a, aw = reader_angle(rng)
    st = reader_stops(rng)
    src = rcase(rng, "linear-gradient(") + sp(rng) + ("," + sp(rng)).join([a] + st) + sp(rng) + ")"
    if aw is None:
        return src, None
    normal = "linear-gradient(" + ", ".join([aw] + [norm_words(s) for s in st]) + ")"
    return src, (normal if len(normal) <= 127 else None)


def conic_reader_first(rng):
    """(text or None, written or None, valid)"""
    k = rng.randrange(8)
    if k == 0:
        return None, None, True
    if k in (1, 2):
        a, aw = reader_angle(rng)
        if aw is None or (a.lower().endswith("rad") and not a.lower().endswith("grad")) or a.lower().startswith("to"):
            return rcase(rng, "from") + " " + a, None, False
        return rcase(rng, "from") + " " + a, None, True
    if k in (3, 4):
        pt, _, _ = position(rng)
        return rcase(rng, "at") + " " + pt, None, True
    if k == 5:
        a = "%d%s" % (rng.randrange(-360, 361), rcase(rng, "deg"))
        pt, _, _ = position(rng)
        return rcase(rng, "from") + " " + a + " " + rcase(rng, "at") + " " + pt, None, True
    if k == 6:
        pt = rng.choice(["left", "top", "center", "30%", "12px", "right bottom", "left 10px", "0 0"])
        return rcase(rng, "at") + " " + pt, None, True
    t = rng.choice(["from", "at", "from 45px", "from 1rad", "at left from 45deg", "from 45deg left", "from 45deg at",
                    "at left right", "at top bottom", "at 10em 10px", "from at left", "45deg", "from 10deg 20deg",
                    "at left top center"])
    return t, None, False


def conic_val_case(rng):
    first, _, ok = conic_reader_first(rng)
    st = reader_stops(rng, conic=True)
    if rng.random() < 0.12:
        bad = rng.choice(["red 361deg", "red 45.5deg", "red -10deg", "red 1turn", "red 0360deg", "red 10deg 20%",
                          "red deg", "red 1rad", "red 100.5%"])
        st[rng.randrange(len(st))] = bad
        ok = False
    if rng.random() < 0.05:
        st = st[:1]
        ok = False
    args = ([first] if first else []) + st
    src = rcase(rng, "conic-gradient(") + sp(rng) + ("," + sp(rng)).join(args) + sp(rng) + ")"
    if not ok:
        return src, None
    normal = "conic-gradient(" + ", ".join(norm_words(x) for x in args) + ")"
    return src, (normal if len(normal) <= 127 else None)


def write_val():
    rng = random.Random(SEED_VAL)
    cases = []
    for _ in range(560):
        cases.append(("grad",) + gradient_val_case(rng))
    for _ in range(420):
        cases.append(("grad",) + conic_val_case(rng))
    for _ in range(140):
        g, n = gradient_val_case(rng) if rng.random() < 0.5 else conic_val_case(rng)
        urls = ["url(i%d.png)" % rng.randrange(100) for _ in range(rng.randrange(0, 3))]
        text = ("," + sp(rng)).join(urls + [g])
        normal = None if n is None else ", ".join(urls + [n])
        if normal is not None and len(normal) > 127:
            normal = None
        cases.append(("img", text, normal))
    # fixed edge cases: angle stops only in conic gradients, the bounds
    for v, e in [("linear-gradient(red 45deg, blue)", None), ("radial-gradient(red 45deg, blue)", None),
                 ("conic-gradient(red 360deg, blue 0deg)", "conic-gradient(red 360deg, blue 0deg)"),
                 ("conic-gradient(red 361deg, blue)", None), ("conic-gradient(red 1000deg, blue)", None),
                 ("conic-gradient(red 99deg, blue)", "conic-gradient(red 99deg, blue)"),
                 ("linear-gradient(3600deg, red, blue)", "linear-gradient(3600deg, red, blue)"),
                 ("linear-gradient(3600.0001deg, red, blue)", None),
                 ("linear-gradient(-3600deg, red, blue)", "linear-gradient(-3600deg, red, blue)"),
                 ("linear-gradient(10turn, red, blue)", "linear-gradient(10turn, red, blue)"),
                 ("linear-gradient(10.01turn, red, blue)", None),
                 ("linear-gradient(4000grad, red, blue)", "linear-gradient(4000grad, red, blue)"),
                 ("linear-gradient(4000.01grad, red, blue)", None),
                 ("linear-gradient(99.9999rad, red, blue)", "linear-gradient(%ddeg, red, blue)" % M.rad_whole_degrees("99.9999")),
                 ("linear-gradient(-99.9999rad, red, blue)", "linear-gradient(%ddeg, red, blue)" % M.rad_whole_degrees("-99.9999")),
                 ("linear-gradient(0.0087rad, red, blue)", "linear-gradient(0deg, red, blue)"),
                 ("linear-gradient(0.0088rad, red, blue)", "linear-gradient(1deg, red, blue)"),
                 ("linear-gradient(-0.0088rad, red, blue)", "linear-gradient(-1deg, red, blue)"),
                 ("linear-gradient(to left top, red, blue)", "linear-gradient(to left top, red, blue)"),
                 ("linear-gradient(to left left, red, blue)", None),
                 ("linear-gradient(to top left top, red, blue)", None),
                 ("linear-gradient(to top left top left, red, blue)", None),
                 ("conic-gradient(from 1rad, red, blue)", None),
                 ("conic-gradient(from -3600deg at 0 0, red, blue)", "conic-gradient(from -3600deg at 0 0, red, blue)"),
                 ("conic-gradient(at left, red, blue)", "conic-gradient(at left, red, blue)"),
                 ("conic-gradient(from 10deg, red, blue, lime, navy, black)", None)]:
        cases.append(("grad", v, e))
    # a conic gradient that is not the last layer
    for _ in range(20):
        g, _ = conic_val_case(rng)
        cases.append(("img", g + ", url(a.png)", None))
    o = [HEADER % "Lot 94: linear angles, corners and conic gradients in the reader",
         '#include "../../framework/unity.h"', "#include <string.h>", '#include "wf_cssbg.h"', "",
         "static char g_o[WF_CSSBG_VAL];", "",
         "static const char *run(const char *f, const char *v) {",
         "    int r;",
         "    if (!strcmp(f, \"img\")) r = wf_cssbg_image(v, g_o, (int)sizeof(g_o));",
         "    else r = wf_cssbg_gradient(v, (int)strlen(v), g_o, (int)sizeof(g_o));",
         "    if (r <= 0) return g_o[0] ? \"REFUSED BUT WRITTEN\" : \"REFUSED\";",
         "    if (r != (int)strlen(g_o)) return \"BAD LENGTH\";",
         "    return g_o;",
         "}", ""]
    names, per = [], 8
    for b in range(0, len(cases), per):
        name = "test_l94_val_%d" % (b // per)
        names.append(name)
        o.append("static void %s(void) {" % name)
        for f, v, e in cases[b:b + per]:
            o.append("    TEST_ASSERT_EQUAL_STRING(%s, run(%s, %s));" % (cstr(e if e is not None else "REFUSED"), cstr(f), cstr(v)))
        o.append("}")
        o.append("")
    finish(o, names, "test_lot94_bgval.c")
    write_accept([e for f, v, e in cases if f == "grad" and e is not None])
    return len(cases)


def split_args(normal):
    """the top level arguments of a written gradient"""
    body = normal[normal.index("(") + 1:-1]
    out, depth, cur = [], 0, ""
    for ch in body:
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
            continue
        depth += ch == "("
        depth -= ch == ")"
        cur += ch
    out.append(cur.strip())
    return out


def angle_degrees(text):
    for unit in ("turn", "grad", "deg"):
        if text.endswith(unit):
            return M.decimal_degrees(text[:-len(unit)], unit)
    return None


SIDES = {"top": "WE_GRAD_TOP", "right": "WE_GRAD_RIGHT", "bottom": "WE_GRAD_BOTTOM", "left": "WE_GRAD_LEFT"}
QUARTERS = ["WE_GRAD_TOP", "WE_GRAD_RIGHT", "WE_GRAD_BOTTOM", "WE_GRAD_LEFT"]


def engine_reading(normal):
    """(dir, angle, corner, stops) the engine keeps for a written value"""
    args = split_args(normal)
    conic = normal.startswith("conic")
    first = args[0]
    if conic:
        frm = 0
        if first.startswith("from ") or first.startswith("at "):
            w = first.split()
            if w[0] == "from":
                frm = angle_degrees(w[1]) % 360
            return "WE_GRAD_CONIC", frm, 0, len(args) - 1
        return "WE_GRAD_CONIC", 0, 0, len(args)
    if first.startswith("to "):
        w = first.split()[1:]
        if len(w) == 1:
            return SIDES[w[0]], 0, 0, len(args) - 1
        v = [x for x in w if x in ("top", "bottom")][0]
        h = [x for x in w if x in ("left", "right")][0]
        return "WE_GRAD_ANGLE", 0, 1 + (h == "left") + 2 * (v == "bottom"), len(args) - 1
    d = angle_degrees(first)
    if d is None:
        return "WE_GRAD_BOTTOM", 0, 0, len(args)
    if d % 90 == 0:
        return QUARTERS[(d // 90) % 4], 0, 0, len(args) - 1
    return "WE_GRAD_ANGLE", d % 360, 0, len(args) - 1


