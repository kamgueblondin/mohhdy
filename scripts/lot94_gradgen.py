def named_stops(rng, conic=False):
    n = rng.choice([2, 2, 3, 4])
    texts, model = [], []
    for _ in range(n):
        if rng.random() < 0.5:
            name = rng.choice(list(NAMED))
            t, v = name, NAMED[name]
        else:
            t, v = hex_colour(rng)
        pos = None
        r = rng.random()
        if r < 0.2:
            pc = rng.randrange(101)
            t += " %d%%" % pc
            pos = pc * 100
        elif conic and r < 0.4:
            d = rng.randrange(361)
            t += " %ddeg" % d
            pos = M.conic_stop_pos(d)
        texts.append(t)
        model.append((v, pos))
    return texts, model


def sheet_case(rng):
    w, h = rng.randrange(4, 120), rng.randrange(4, 60)
    o = c = (0, 0, w, h)
    k = rng.randrange(5)
    reg = ""
    while True:
        if k == 0:
            # radians: the reader writes whole degrees
            body = "%d.%04d" % (rng.randrange(0, 13), rng.randrange(10000))
            if rng.random() < 0.3:
                body = "-" + body
            d = M.rad_whole_degrees(body)
            if d is None or d % 90 == 0:
                continue
            first = body + "rad"
            pfun = (lambda d: lambda cell: M.linear_p(o, cell, angle=d))(d)
            kind = "linear"
        elif k == 1:
            v = rng.randrange(-720, 721)
            if v % 90 == 0:
                continue
            first = "%ddeg" % v
            pfun = (lambda v: lambda cell: M.linear_p(o, cell, angle=v))(v)
            kind = "linear"
        elif k == 2:
            vv, hh = rng.choice(CORNERS)
            first = "to %s %s" % (vv, hh) if rng.random() < 0.5 else "to %s %s" % (hh, vv)
            pfun = (lambda vv, hh: lambda cell: M.linear_p(o, cell, corner=(vv, hh)))(vv, hh)
            kind = "linear"
        elif k == 3:
            # a registered angle computed by the reader (whole degrees)
            a, b = rng.randrange(-300, 301), rng.randrange(-300, 301)
            if (a + b) % 90 == 0:
                continue
            reg = "@property --a { syntax: '<angle>'; inherits: false; initial-value: 0deg } "
            first = "var(--a)"
            regval = "calc(%ddeg + %ddeg)" % (a, b)
            pfun = (lambda d: lambda cell: M.linear_p(o, cell, angle=d))(a + b)
            kind = "linear"
        else:
            frm = rng.randrange(0, 360)
            x, y = rng.randrange(101), rng.randrange(101)
            first = "from %ddeg at %d%% %d%%" % (frm, x, y)
            kind = "conic"
        break
    texts, stops = named_stops(rng, conic=(kind == "conic"))
    if kind == "conic":
        try:
            items = conic_paint(o, c, stops, frm, ((x, 1), (y, 1)))
        except M.Ambiguous:
            STATS["ambiguous"] += 1
            return None
    else:
        items = paint(o, c, stops, pfun)
    g = "%s-gradient(%s)" % (kind, ", ".join([first] + texts))
    prop = rng.choice(["background-image", "background"])
    css = reg + "#t { %s%s: %s }" % ("--a: %s; " % regval if k == 3 else "", prop, g)
    return css, w, h, items


