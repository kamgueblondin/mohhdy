def model(fn, *args):
    try:
        return ("ok", fn(*args))
    except T.Unsure:
        return None


# ------------------------------------------------------------- none colours
def maybe_none(rng, t, p):
    return "none" if rng.random() < p else t


def alpha_none(rng, p=0.5):
    if rng.random() < 0.55:
        return ""
    a = "none" if rng.random() < p else G100.alpha_text(rng)
    return rng.choice([" / ", "/", " /"]) + a


def rgb_comp(rng):
    k = rng.randrange(4)
    if k == 0:
        return str(rng.randrange(0, 256))
    if k == 1:
        return dec(rng, 0, 255, 2)
    if k == 2:
        return str(rng.randrange(0, 101)) + "%"
    return rng.choice(["0", "255", "300", "-10", "50%", "100%"])


def none_text(rng, good=True):
    """a colour function with at least one none component (most of the
    time)"""
    k = rng.randrange(7)
    p = rng.choice([0.3, 0.5, 0.7])
    if k == 0:
        fn = rng.choice(["rgb", "rgba", "rgb", "RGB"])
        args = [maybe_none(rng, rgb_comp(rng), p) for _ in range(3)]
        t = "%s(%s%s)" % (fn, " ".join(args), alpha_none(rng))
    elif k == 1:
        fn = rng.choice(["hsl", "hsla", "hsl"])
        args = [maybe_none(rng, G98.hue_text(rng), p), maybe_none(rng, G98.sl_text(rng), p),
                maybe_none(rng, G98.sl_text(rng), p)]
        t = "%s(%s%s)" % (fn, " ".join(args), alpha_none(rng))
    elif k == 2:
        args = [maybe_none(rng, G98.hue_text(rng), p),
                maybe_none(rng, str(rng.randrange(0, 101)) + rng.choice(["%", ""]), p),
                maybe_none(rng, str(rng.randrange(0, 101)) + rng.choice(["%", ""]), p)]
        t = "hwb(%s%s)" % (" ".join(args), alpha_none(rng))
    elif k in (3, 4):
        base = G101.lab_text(rng)
        head, _, rest = base.partition("(")
        got = M98.colour_args(rest[:-1])
        if got is None or got[1]:
            return none_text(rng, good)
        toks = [maybe_none(rng, x, p) for x in got[0][:3]]
        t = "%s(%s%s)" % (head, " ".join(toks), alpha_none(rng))
    else:
        sp = rng.choice(SPACES)
        comps = [maybe_none(rng, G101.pct_or(rng, -1, 2, -20, 120) if rng.random() < 0.3 else dec(rng, 0, 1), p)
                 for _ in range(3)]
        t = "color(%s %s%s)" % (sp, " ".join(comps), alpha_none(rng))
    if "none" not in t.lower() and rng.random() < 0.8:
        t = t.replace("(", "(none ", 1)
    if not good:
        t = rng.choice(["rgb(none, 0, 0)", "rgba(10, none, 0, 0.5)", "hsl(none, 10%, 20%)", "hsla(120, 50%, 50%, none)",
             "rgb(none 0)", "rgb(nonee 0 0)", "lab(50 none)", "color(none 1 0 0)",
             "rgb(none 0 0 none)", "hwb(none, 10%, 10%)", "oklch(none none none none)", "color(srgb none none)",
             "rgb(none 0 0 / none / 1)", "hsl(nonedeg 10% 10%)"])
    return t


def any_colour(rng):
    k = rng.randrange(10)
    if k < 6:
        return none_text(rng)
    if k < 8:
        return G100.simple_colour(rng)
    if k == 8:
        return G101.new_colour(rng)
    return none_text(rng, False)


def mix_none(rng, depth=0):
    def item():
        c = mix_none(rng, depth + 1) if depth < 1 and rng.random() < 0.15 else any_colour(rng)
        if rng.random() < 0.3:
            pc = G100.pct_text(rng)
            return c + " " + pc if rng.random() < 0.5 else pc + " " + c
        return c
    return "color-mix(in srgb, %s, %s)" % (item(), item())


def reg_none(rng):
    k = rng.randrange(10)
    if k < 6:
        return none_text(rng).lower()
    if k < 8:
        return mix_none(rng).lower()
    return G100.reg_colour(rng)


def write_none():
    rng = random.Random(10201)
    cases, seen = [], set()
    fixed = ["rgb(none 0 0)", "rgb(none none none)", "rgb(0 0 0 / none)", "rgba(none 128 255 / 50%)",
             "hsl(none 100% 50%)", "hsl(120 none 50%)", "hsl(120 100% none)", "hsla(none none none / none)",
             "hwb(none 0% 0%)", "hwb(0 none none)", "lab(none 0 0)", "lab(50 none none)", "lch(50 30 none)",
             "oklab(none 0 0)", "oklch(0.7 none 120)", "oklch(0.7 0.1 none)", "color(srgb none 1 0)",
             "color(display-p3 none 0.5 0.5)", "color(xyz none none none)", "color(srgb-linear 1 none 1 / none)",
             "rgb(none, 0, 0)", "hsl(none, 10%, 10%)", "hsla(10, 10%, 10%, none)", "rgb(0 0 0 none)",
             "NONE", "rgb(NONE 0 0)", "color-mix(in srgb, rgb(none 0 0), red)",
             "color-mix(in srgb, rgb(none 0 0), rgb(none 255 0))", "color-mix(in srgb, rgb(0 0 0 / none), blue 30%)",
             "color-mix(in srgb, rgb(0 0 0 / none), rgb(9 9 9 / none))",
             "color-mix(in srgb, color-mix(in srgb, rgb(none 0 0), rgb(none 0 0)), red)"]
    for t in fixed:
        m = model(L.reader, t)
        assert m is not None, t
        seen.add(t)
        cases.append(["TEST_ASSERT_EQUAL_STRING(%s, rc(%s));" % (cstr(G100.rc_str(m[1])), cstr(t))])
    while len(cases) < 480:
        k = rng.randrange(10)
        if k < 6:
            t = none_text(rng, rng.random() < 0.9)
        elif k < 9:
            t = mix_none(rng)
        else:
            t = rng.choice([" ", ""]) + none_text(rng) + rng.choice(["", " ", ";", " !important", " x", ")"])
        if t in seen or len(t) > 200:
            continue
        seen.add(t)
        m = model(L.reader, t)
        if m is None:
            continue
        cases.append(["TEST_ASSERT_EQUAL_STRING(%s, rc(%s));" % (cstr(G100.rc_str(m[1])), cstr(t))])
    alts = L.ALTS

    def ok(v):
        m = model(A.colour_match, v)
        return m is not None and m[1] and len(v) < 128
    fixed_ip = [("rgb(none 0 0)", "rgb(255 255 255)"), ("rgb(255 255 255)", "rgb(none 0 0)"),
                ("rgb(none 0 0)", "rgb(none 255 0)"), ("rgb(0 0 0 / none)", "rgb(255 0 0 / 50%)"),
                ("rgb(10 20 30 / none)", "rgb(0 0 0 / none)"), ("hsl(none 100% 50%)", "blue"),
                ("color(srgb none 0 0)", "red"), ("color(display-p3 none 0 0)", "lime"), ("lab(none 0 0)", "white"),
                ("color-mix(in srgb, rgb(none 0 0), rgb(none 0 0))", "red")]
    for a, b in fixed_ip:
        m = model(A.interp, alts, a, b, 5000)
        assert m is not None and ok(a) and ok(b), (a, b)
        r, c = m[1]
        cases.append(["TEST_ASSERT_EQUAL_STRING(%s, ip(%s, %s, %d, %d));" % (cstr(r), cstr(a), cstr(b), 5000, c)])
    while len(cases) < 760:
        a, b = reg_none(rng), reg_none(rng)
        if rng.random() < 0.5:
            a, b = b, a
        if not (ok(a) and ok(b)):
            continue
        tt = rng.choice([5000, rng.randrange(1, S), rng.randrange(1, S), 1, 9999, 2500])
        m = model(A.interp, alts, a, b, tt)
        if m is None or m[1][0] is None or len(m[1][0]) >= 160:
            continue
        r, c = m[1]
        cases.append(["TEST_ASSERT_EQUAL_STRING(%s, ip(%s, %s, %d, %d));" % (cstr(r), cstr(a), cstr(b), tt, c)])
    while len(cases) < 860:
        a, b = reg_none(rng), reg_none(rng)
        if not (ok(a) and ok(b)):
            continue
        m = model(M98.add, alts, a, b)
        if m is None or m[1][0] is None or len(m[1][0]) >= 160:
            continue
        r, c = m[1]
        cases.append(["TEST_ASSERT_EQUAL_STRING(%s, ad(%s, %s, %d));" % (cstr(r), cstr(a), cstr(b), c)])
    seen = set()
    while len(cases) < 1000:
        v = (none_text(rng, rng.random() < 0.75) if rng.random() < 0.8 else mix_none(rng)).lower()
        if v in seen or len(v) >= 128:
            continue
        seen.add(v)
        m = model(A.colour_match, v)
        if m is None:
            continue
        cases.append(["TEST_ASSERT_EQUAL(%d, mt(%s));" % (int(bool(m[1])), cstr(v))])
    o = [HEADER % "Lot 102: the none keyword in the reader colour and in registered <color> values"] + \
        G98.IP_C + [
        "/* the reader colour of v as \"#rrggbb alpha\", \"-\" when it is not one */",
        "static const char *rc(const char *v) {",
        "    static char b[64];",
        "    unsigned int c = 0xdeadbeefu;",
        "    int a = -7, r = wf_cssprop_color(v, (int)strlen(v), &c, &a);",
        "    if (!r) return c == 0xdeadbeefu && a == -7 ? \"-\" : \"WRITTEN\";",
        "    if (r != 1 || c > 0xffffffu || a < 0 || a > 255) return \"BAD CODE\";",
        "    snprintf(b, sizeof(b), \"#%06x %d\", c, a);",
        "    return b;",
        "}", "",
        "static const char *ip(const char *a, const char *b, int t, int code) {",
        "    if (!syn(\"'<color>'\")) return \"BAD SYNTAX\";",
        "    if (wf_cssprop_interp(&g_p, a, b, t, g_o, (int)sizeof(g_o)) != code) return \"BAD CODE\";",
        "    return g_o;",
        "}", "",
        "static const char *ad(const char *under, const char *v, int code) {",
        "    if (!syn(\"'<color>'\")) return \"BAD SYNTAX\";",
        "    if (wf_cssprop_add(&g_p, under, v, g_o, (int)sizeof(g_o)) != code) return \"BAD CODE\";",
        "    return g_o;",
        "}", "",
        "static int mt(const char *v) {",
        "    if (!syn(\"'<color>'\")) return -1;",
        "    return wf_cssprop_match_prop(&g_p, v) != 0;",
        "}", ""]
    o.insert(3, "#include <stdio.h>")
    names = chunks(o, "test_l102_none", cases, 12)
    finish(o, names, "test_lot102_none.c")
    return len(cases)


