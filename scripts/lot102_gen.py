def kf_value(rng):
    k = rng.randrange(10)
    if k < 4:
        return none_text(rng).lower()
    if k < 7:
        return G100.simple_colour(rng)
    if k == 7:
        return mix_none(rng).lower()
    if k == 8:
        return "currentcolor"
    return G100.reg_colour(rng)


def keyframes(rng, name):
    offs = sorted(set(rng.sample([0, 2500, 5000, 7500, 10000, 3333, 6000], rng.randrange(1, 4))))
    if rng.random() < 0.4:
        offs = [o for o in offs if o not in (0, S)] or [5000]
    blocks, frames = [], {p: [] for p in PROPS}
    for o in offs:
        decls = []
        for p in PROPS:
            if rng.random() < 0.65 or (p == "background-color" and not decls):
                v = kf_value(rng)
                if not G100.css_ok(v):
                    v = "red"
                decls.append((p, v))
        blocks.append("%s { %s }" % (G98.offset_sel(rng, o), "; ".join("%s: %s" % d for d in decls)))
        for p, v in decls:
            L.CUR = L.BLACK
            m = model(A.colour_match, v)
            L.CUR = None
            if m is None:
                return None
            if m[1] and len(v) < 128:
                frames[p].append((o, v, None, None))
    return "@keyframes %s { %s }" % (name, " ".join(blocks)), frames


def range_decls(rng):
    k = rng.randrange(6)
    if k == 0:
        return []
    if k < 3:
        return [("animation-range", range_list(rng, True, rng.random() < 0.9))]
    if k < 5:
        d = []
        if rng.random() < 0.8:
            d.append(("animation-range-start", range_list(rng, False, rng.random() < 0.9)))
        if rng.random() < 0.8:
            d.append(("animation-range-end", range_list(rng, False, rng.random() < 0.9)))
        return d
    return [("animation-range", rng.choice(["initial", "unset", "normal", "10% 90%", "25%", "entry", "50% 50%",
                                             "60% 40%", "-50% 50%", "0% 200%"]))]


def anim_decls(rng):
    out = []
    items = []
    for _ in range(rng.choice([1, 1, 2])):
        it = "%s %s" % (rng.choice(["k", "k", "j"]), rng.choice(["1000ms", "2s", "1s", "1000ms", "500ms"]))
        if rng.random() < 0.6:
            it += " linear"
        if rng.random() < 0.3:
            it += " " + rng.choice(["500ms", "-500ms", "1s", "250ms"])
        if rng.random() < 0.2:
            it += " " + rng.choice(["2", "infinite", "0.5", "3"])
        if rng.random() < 0.3:
            it += " " + rng.choice(["both", "forwards", "backwards", "both"])
        if rng.random() < 0.15:
            it += " " + rng.choice(["reverse", "alternate"])
        items.append(it)
    pre = range_decls(rng) if rng.random() < 0.15 else []
    out += pre
    out.append(("animation", ", ".join(items)))
    tl = [rng.choice(ANIM_TL) for _ in range(rng.choice([1, 1, 2]))]
    out.append(("animation-timeline", ", ".join(tl)))
    out += range_decls(rng)
    if rng.random() < 0.2:
        out.append(("animation-composition", rng.choice(["add", "accumulate", "replace"])))
    return out


def scope_decls(rng, p):
    return [("timeline-scope", rng.choice(SCOPES))] if rng.random() < p else []


def sheet_case(rng):
    els = ["html", "body", "#o", "#i", "#q"]
    parents = [-1, 0, 1, 2, 1]
    tags = ["html", "body", "div", "p", "p"]
    decls = {}
    decls["html"] = (G101.tl_decls(rng, True) if rng.random() < 0.85 else []) + scope_decls(rng, 0.1)
    decls["body"] = (G101.tl_decls(rng, False) if rng.random() < 0.2 else []) + scope_decls(rng, 0.4)
    decls["#o"] = (G101.tl_decls(rng, False) if rng.random() < 0.2 else []) + scope_decls(rng, 0.3)
    decls["#q"] = G101.tl_decls(rng, False) if rng.random() < 0.45 else []
    decls["#i"] = G101.tl_decls(rng, False) if rng.random() < 0.1 else []
    for el in els:
        if rng.random() < 0.2:
            rng.shuffle(decls[el])
    nodes = [{"parent": parents[k], "tag": tags[k], "tl": M.tl_cascade(decls[els[k]])} for k in range(5)]
    kfs = {p: {} for p in PROPS}
    kf_rules = []
    for name in (("k", "j") if rng.random() < 0.35 else ("k",)):
        got = keyframes(rng, name)
        if got is None:
            return None
        text, fr = got
        kf_rules.append(text)
        for p in PROPS:
            kfs[p][name] = fr[p]
    own = {}
    for p in PROPS:
        if rng.random() < 0.45:
            v = none_text(rng).lower() if rng.random() < 0.4 else G100.simple_colour(rng)
            if G100.css_ok(v) and v != "transparent":
                own[p] = v
    adecls = anim_decls(rng)
    anims = M.coord(M.anim_cascade([(100, adecls)]))
    ms = rng.choice([0, 0, 500, 1500])
    pm = rng.choice([0, S, 5000, 2500, 7500, rng.randrange(0, S + 1), rng.randrange(0, 101) * 100])
    try:
        L.CUR = L.BLACK
        out, n_anim, n_comp = [], 0, 0
        for p in PROPS:
            town = L.paint_text(own[p]) if p in own else None
            base = town if town is not None else "#000000" if p == "color" else "transparent"
            cur, animated, composed = M.stack(L.ALTS, anims, kfs[p], base, ms, nodes, 3, pm)
            n_comp += int(composed)
            final = town
            if animated:
                n_anim += 1
                t = L.paint_text(cur)
                if t:
                    final = t
            if final:
                out.append("%s:%s" % (p, final))
            if p == "color":
                L.CUR = G100.cur_of(final) if final else L.BLACK
        n_sc, n_idle = M.counts(anims, set(kfs["color"]), nodes, 3, ms, pm)
    except T.Unsure:
        return None
    finally:
        L.CUR = None
    decls["#i"] = [(p, v) for p, v in own.items()] + decls["#i"] + adecls
    # a registered property makes the reader count the idle animations
    css = PROP + " ".join(kf_rules) + " " + " ".join("%s { %s }" % (el, "; ".join("%s: %s" % x for x in decls[el]))
                                                     for el in els if decls[el])
    style = ' style="%s"' % ";".join(out) if out else ""
    return css, ms, pm, style, n_anim, n_comp, n_sc, n_idle


