#!/usr/bin/env python3
"""Lot 102 test generator: the none keyword in colours (reader colour,
registered <color> values, color-mix(), interpolation and addition),
scroll() and view() in animation-timeline, animation-range and
timeline-scope (the API and the reader sheet).

Expectations come from scripts/lot102_model.py (written from the rules in
docs/lot102_plan.md, CSS Color 4 and CSS Scroll-driven Animations 1) with
the lot 97 to 101 models, not from the C sources. A colour the float model
cannot place on one side of a rounding boundary (lot101_colormodel.Unsure)
is left out.

* test_lot102_none.c: wf_cssprop_color, wf_cssprop_match_prop,
  wf_cssprop_interp and wf_cssprop_add with none components;
* test_lot102_range.c: wf_cssanim_long on animation-timeline (scroll(),
  view()) and animation-range-start / -end, wf_cssanim_range,
  wf_cssanim_range_text, wf_cssanim_range_ms and wf_cssanim_coord with
  the twelve longhands;
* test_lot102_scope.c: wf_csstl_parse(WF_CSSTL_SCOPE) and
  wf_csstl_scoped;
* test_lot102_sheet.c: wf_site_prepare_ext after wf_site_set_time and
  wf_site_set_scroll: colour keyframes on #i driven by scroll(), view()
  and named timelines with timeline-scope and animation-range in a tree
  (the written style, col_animated, prop_composed, anim_scroll,
  anim_idle).

Run: python3 scripts/lot102_gen.py
"""
