        "}", "",
        "static const char *tlv(const wf_cssanim_t *a) {",
        "    if (a->timeline >= WF_CSSANIM_TL_SCROLL) snprintf(g_t, sizeof(g_t), \"%d %d %d\", a->timeline, a->tlsrc, a->tlaxis);",
        "    else snprintf(g_t, sizeof(g_t), \"%d - -\", a->timeline);",
        "    return g_t;",
        "}", "",
        "static const char *tlf(int j) { return tlv(&g_a[j]); }", "",
        "/* animation-range-start (end 0) or -end; items past the count stay\n * untouched */",
        "static int rl(int end, const char *v) {",
        "    int n, k;",
        "    memset(g_a, 0x5a, sizeof(g_a));",
        "    n = wf_cssanim_long(end ? WF_CSSANIM_L_RANGE_END : WF_CSSANIM_L_RANGE_START, v, g_a, WF_CSSANIM_MAX);",
        "    for (k = n < 0 ? 4 : n; k < 8; k++) if (g_a[k].rs != 0x5a || g_a[k].re != 0x5a) return -9;",
        "    return n;",
        "}", "",
        "static const char *rf(int j, int end) {",
        "    snprintf(g_t, sizeof(g_t), \"%d %d\", end ? g_a[j].re : g_a[j].rs, end ? g_a[j].rep : g_a[j].rsp);",
        "    return g_t;",
        "}", "",
        "static int g_n;",
        "static int rs(const char *v) {",
