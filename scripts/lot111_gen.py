def blen_case(rng):
    hd, bd = [("overflow", rng.choice(["hidden", "auto", "clip hidden"]))], []
    hh = rng.choice(BH_HTML) if rng.random() < 0.85 else None
    hw = rng.choice(BW_HTML) if rng.random() < 0.85 else None
    fs = rng.choice(["20px", "10px"]) if rng.random() < 0.3 else None
    if hh:
        hd.append(("height", hh))
    if hw:
        hd.append(("width", hw))
    if fs:
        hd.append(("font-size", fs))
    bd.append(("overflow", rng.choice(["auto", "scroll", "auto"])))
    bh = rng.choice(BH_BODY) if rng.random() < 0.8 else None
    bw = rng.choice(BW_BODY) if rng.random() < 0.8 else None
    bmw = rng.choice(["50%", "300px", "90%"]) if rng.random() < 0.25 else None
    for p, v in (("height", bh), ("width", bw), ("max-width", bmw)):
        if v:
            bd.append((p, v))
    css = "@keyframes k { from { color: #000000 } to { color: #ffffff } } html { %s } body { %s } " \
          "#i { animation: k 1s linear; animation-timeline: scroll(nearest) } " \
          "#j { animation: k 1s linear; animation-timeline: scroll(nearest x) }" % (
              "; ".join("%s: %s" % d for d in hd), "; ".join("%s: %s" % d for d in bd))
    em = M._F(fs[:-2]) if fs else 16

    def slot(v):
        if v is None:
            return None
        got = M7.height_val(v, False)
        return None if got is None else got

    def body_val(v, html_v, basis):
        if v is None:
            return "-"
        if not v.endswith("%"):
            return v
        hv = M.html_len(slot(html_v), em, em, basis) if html_v else None
        if html_v in (None, "auto") and basis == M.VW:
            hv = M.VW       # Lot 112: html's width auto is the viewport's (CSS 2, 10.3.3)
        pc = int(v[:-1].split(".")[0])
        if hv is None:
            return "%d%%" % pc
        return "%dpx" % min(min(hv, M.HMAX) * pc // 100, M.HMAX)
    h = body_val(bh, hh, 480)
    w = body_val(bw, hw, M.VW) if bh or bw or bmw else "-"
    mw = body_val(bmw, hw, M.VW)
    if not bh:
        h = "-"
    if not (bw or bmw):
        w = mw = "-"
    return css, h, w, mw


