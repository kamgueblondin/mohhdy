"""Lot 111 test generator: relative colours with missing origin
components, opacity in math functions, var() and the all shorthand and
revert, lh against the element's line-height, and the body's percentage
sizes against html's.

Expectations come from scripts/lot111_model.py (written from CSS Color 5
4.1 and 4.2, CSS Color 4 3.2 and 12.2, CSS Values 4 and 5, CSS Cascade
5, CSS Inline 3 and CSS 2 10.5 and 10.8) with the lot 97 to 110 models,
not from the C sources. A value the exact model cannot place (Unsure of
any model) is left out. The suites are kept small: each case is one new
behaviour.

* test_lot111_rel.c: relative colours whose origin has missing
  components, alone and in color-mix() (where a missing component takes
  the other colour's);
* test_lot111_op.c: opacity with calc(), var() (sheet and element
  custom properties), all and revert, revert-layer;
* test_lot111_lh.c: box scroller lengths in lh against the element's
  line-height (inherited numbers, lengths and percentages);
* test_lot111_blen.c: the body box scroller's percentage height against
  an html height given as an expression, and its percentage width
  against html's width;
* test_lot111_pad.c: view timeline insets from scroll-padding with a
  percentage inside a math function;
* test_lot111_mix.c and test_lot111_mflow.c: box lengths with mixed
  min()/max()/clamp() nested or inside a sum or a product, as
  wf_css_math_box writes them and as the engine lays them out.

Run: python3 scripts/lot111_gen.py
"""
