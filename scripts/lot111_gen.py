def lh_case(rng):
    """(css, expected lh of body, #o, #i (px thousandths + 1, 0 normal),
    #o's height or -1)"""
    els = {"html": [], "body": [], "#o": [], "#i": []}
    if rng.random() < 0.3:
        els["html"].append(("font-size", rng.choice(FS_HTML)))
    for el in ("body", "#o", "#i"):
        if rng.random() < 0.35:
            els[el].append(("font-size", rng.choice(FS_EL)))
    for el in ("html", "body", "#o", "#i"):
        if rng.random() < (0.3 if el == "html" else 0.55):
            for _ in range(rng.choice([1, 1, 2])):
                els[el].append(("line-height", rng.choice(LH_VALS)))
    els["#o"] += [("overflow", "auto"), ("height", rng.choice(LH_H))]
    rules = [k for k in els if els[k]]
    rng.shuffle(rules)
    css = "@keyframes k { from { color: #000000 } to { color: #ffffff } } " + " ".join(
        "%s { %s }" % (el, "; ".join("%s: %s" % d for d in els[el])) for el in rules)
    css += " #i { animation: k 1s linear; animation-timeline: scroll(nearest) }"
    # the model
    fsz, comp, out = {}, {}, {}
    parent = {"html": None, "body": "html", "#o": "body", "#i": "#o"}
    root = 16000
    for el in ("html", "body", "#o", "#i"):
        pf = fsz[parent[el]] if parent[el] else 16000
        f = pf
        for p, v in els[el]:
            if p == "font-size":
                f = int(M._F(v[:-2]) * 1000) if v.endswith("px") else int(M._F(v[:-2]) * pf)
        fsz[el] = f
        if el == "html":
            root = f
        decl = None
        for p, v in els[el]:
            if p == "line-height":
                d = M.lh_decl(v)
                if d is not None:
                    decl = d
        pc = comp[parent[el]] if parent[el] else None
        comp[el] = M.lh_comp(decl, f, root, pc, fsz[parent[el]] if parent[el] else 16000)
        out[el] = M.lh_px(comp[el], f) + 1 if comp[el][0] else 0
    lh_o = out["#o"] - 1 if out["#o"] else None
    h = M.box_len_lh(dict(els["#o"])["height"], fsz["#o"], root, lh_o)
    hv = -1 if h is None else min(max(h, 0) // 1000, M5.HMAX)
    return css, out["body"], out["#o"], out["#i"], hv


