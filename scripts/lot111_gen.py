# ------------------------------------------------------------- mixed math
MIX_K = ["2", "0.5", "-1", "3", "1.5", "-2", "4", "0.25"]


def mix_lin(rng):
    """a linear argument, mostly with whole px and percentages"""
    k = rng.randrange(6)
    if k == 0:
        return "%d%%" % rng.randrange(0, 101)
    if k == 1:
        return "%dpx" % rng.randrange(0, 300)
    if k == 2:
        return "calc(%d%% %s %dpx)" % (rng.randrange(0, 101), rng.choice("+-"), rng.randrange(0, 200))
    if k == 3:
        return "%s%s" % (G9.num(rng, 0.2), rng.choice(["em", "lh", "ch", "ex", "rem", "vh"]))
    return G9.lin(rng) if k == 4 else "%d%%" % rng.randrange(0, 101)


def mix_fn(rng, depth):
    f = rng.choice(["min", "max", "min", "max", "clamp"])
    n = 3 if f == "clamp" else rng.choice([2, 2, 3])
    return "%s(%s)" % (f, ", ".join(mix_val(rng, depth + 1) for _ in range(n)))


def mix_val(rng, depth=0):
    """an argument or a value: linear, a min()/max()/clamp(), or one of
    those in a sum or a product"""
    k = rng.random()
    if depth >= 2 or k < 0.45:
        return mix_lin(rng)
    if k < 0.7:
        return mix_fn(rng, depth)
    if k < 0.85:
        return "calc(%s %s %s)" % (mix_fn(rng, depth), rng.choice("+-"), mix_val(rng, depth + 1))
    if rng.random() < 0.5:
        return "calc(%s * %s)" % (mix_fn(rng, depth), rng.choice(MIX_K))
    return "calc(%s / %s)" % (mix_fn(rng, depth), rng.choice(["2", "4", "-2", "0.5"]))


def mix_value(rng):
    """a whole box value (a math function), some refused"""
    if rng.random() < 0.08:
        return rng.choice(["calc(1 / min(10%, 1px))", "calc(min(10%, 1px) * 2%)", "calc(min(10%, 1px) * min(2%, 1px))",
                           "calc(min(10%, 1px) + 1)", "min(10%, 2, 1px)", "clamp(min(10%, 1px), 2px)",
                           "calc(min(10%, 1px) / 0)", "calc(min(10%, 1px)+1px)", "min(1%, 1px, 2%, 2px, 3%, 3px, 4%, 4px, 5%)"])
    while True:
        v = mix_val(rng)
        if v.startswith(("calc(", "min(", "max(", "clamp(")):
            return v


def mix_check(s, text, em, rem):
    """the written expression laid out against a few bases is what the
    value is (CSS Values 4 10), when every literal came out whole (the
    engine cuts each percentage toward zero, so the floor)"""
    import re
    if "-" in text or "." in s or "/" in s or any(u != "px" for u in re.findall(r"\d([a-z]+)", s)):
        return
    for basis in (0, 37, 100, 333, 640):
        try:
            t = M.pct_at(s, M9.F(em), M9.F(rem), M9.F(basis))
        except UNSURE:
            return
        if t is None:
            return
        want = max(0, M7.math_floor(t)) if t >= 0 else 0
        got = M9.engine_px(text, basis)
        assert got == want, (s, text, basis, got, want)


