@contextlib.contextmanager
def reuse(mod, seed, fname, title, old, new, patches, keep=None):
    """run an older writer of module mod with seed, its file fname, its
    header title and its test names old* renamed new*, the first keep
    cases only, with the module attributes in patches replaced meanwhile
    (lot109_gen.reuse with this file's header)"""
    class _R:
        Random = staticmethod(lambda _seed: random.Random(seed))
    saved = {k: getattr(mod, k) for k in list(patches) + ["random", "finish", "chunks"]}

    def fin(o, names, _f):
        o[0] = HEADER % title
        finish(o, names, fname)
    for k, v in patches.items():
        setattr(mod, k, v)
    mod.random, mod.finish = _R, fin
    mod.chunks = lambda o, prefix, cases, per: chunks(o, prefix.replace(old, new), cases[:keep], per)
    try:
        yield
    finally:
        for k, v in saved.items():
            setattr(mod, k, v)


