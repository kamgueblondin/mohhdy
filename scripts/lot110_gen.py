OP_VALS = ["0", "1", "0.5", ".25", "0.75", "1.5", "-0.2", "+0.3", "50%", "12.5%", "150%", "-10%", "0.12345",
           "33.333%", "0.1", "0.9", "2", "100%", "0%", "0.0001", "0.99999"]
OP_BAD = ["calc(0.5)", "0.5px", "1e-1", "5.", "half", "50 %", "none", "revert", "0.5 0.5", "--x", "var(--o)"]


def op_value(rng):
    k = rng.random()
    if k < 0.08:
        return rng.choice(OP_BAD)
    if k < 0.14:
        return rng.choice(["initial", "unset"])
    if k < 0.4:
        return "%d.%d" % (rng.randrange(0, 2), rng.randrange(0, 10000))
    if k < 0.55:
        return "%d%%" % rng.randrange(0, 120)
    return rng.choice(OP_VALS)


def op_keyframes(rng, name):
    offs = sorted(set(rng.sample([0, 2500, 5000, 7500, 10000, 3333, 6000], rng.randrange(1, 4))))
    if rng.random() < 0.4:
        offs = [o for o in offs if o not in (0, S)] or [5000]
    blocks, frames = [], []
    for o in offs:
        v = op_value(rng) if rng.random() < 0.9 else "inherit"
        decls = ["opacity: %s" % v]
        fe = fc = None
        if rng.random() < 0.15:
            ft = rng.choice(["linear", "ease-in", "steps(2)"])
            fe = A.ease_parse(ft)
            decls.append("animation-timing-function: %s" % ft)
        if rng.random() < 0.2:
            fc = rng.choice(M98.COMPS)
            decls.append("animation-composition: %s" % fc)
        rng.shuffle(decls)
        blocks.append("%s { %s }" % (G98.offset_sel(rng, o), "; ".join(decls)))
        n = M.op_kf(v.strip().lower())     # Lot 112: math too (was op_num)
        if n is not None:
            frames.append((o, M.op_text(n), fe, fc))
    return "@keyframes %s { %s }" % (name, " ".join(blocks)), frames


def op_trans_decls(rng):
    decls = []
    if rng.random() < 0.5:
        decls.append(("transition", rng.choice(["opacity 1000ms linear", "all 400ms", "none", "--x 1s, opacity 2s ease-in",
                                                "opacity 1s allow-discrete", "color 2s linear",
                                                "color 1s, opacity 500ms linear", "all 2s 500ms linear"])))
    else:
        decls.append(("transition-property", rng.choice(["opacity", "all", "color", "--x, opacity", "none"])))
        decls.append(("transition-duration", rng.choice(["1000ms", "2s", "400ms, 1s", "0s", "1s, 0s"])))
        if rng.random() < 0.6:
            decls.append(("transition-timing-function", rng.choice(["linear", "ease-in", "steps(3)", "linear, ease"])))
        if rng.random() < 0.3:
            decls.append(("transition-delay", rng.choice(["200ms", "-500ms", "0s, 1s"])))
    return decls


def op_case(rng):
    rules, odecls, idecls = [], [], []
    order = 0
    for _ in range(rng.choice([0, 1, 1, 2])):
        order += 1
        v = op_value(rng)
        imp = rng.random() < 0.12
        odecls.append(((int(imp), order), v.strip().lower(), imp, "opacity: %s%s" % (v, " !important" if imp else "")))
    if rng.random() < 0.4:
        v = rng.choice(["inherit", "inherit", "0.5", "initial", "20%"])
        idecls.append("opacity: %s" % v)
        iown = M.op_cascade([((0, 1), v, False)])
    else:
        iown = (0, 10000, False)
    kfs = {}
    use_anim = rng.random() < 0.7
    adecls, tdecls, start = [], [], None
    if use_anim:
        for name in ("k", "j") if rng.random() < 0.35 else ("k",):
            text, fr = op_keyframes(rng, name)
            kfs[name] = fr
            rules.append(text)
        adecls = G99.anim_decls(rng)
    if not use_anim or rng.random() < 0.3:
        tdecls = op_trans_decls(rng)
        sv = rng.choice(["0", "1", "0.5", "25%", "initial", "inherit", "0.3333"])
        rules.append("@starting-style { #o { opacity: %s } }" % sv)
        d = M.op_decl(sv)
        if d is not None and d[0] != 3:
            start = d[1]
    anims = M99.coord(G99.cascade([(100, adecls)])) if adecls else []
    tl = M98.coord(False, G98.cascade(False, [(100, tdecls)])) if tdecls else []
    ms = rng.choice([0, rng.randrange(0, 2500), rng.randrange(0, 1200), 250, 500, 750, 1500])
    body = [x[3] for x in odecls] + ["%s: %s" % d for d in adecls + tdecls]
    css = "%s #o { %s }" % (" ".join(rules), "; ".join(body))
    if idecls:
        css += " #i { %s }" % "; ".join(idecls)
    try:
        own = M.op_cascade([(x[0], x[1], x[2]) for x in odecls])
        fo, an, tr, cp = M.op_final(own, None, anims, kfs, ms, start, tl)
        fi = M.op_final(iown, fo, [], {}, ms)[0]
    except UNSURE:
        return None
    so = ' style="opacity:%d%%"' % (fo // 100) if fo is not None else ""
    si = ' style="opacity:%d%%"' % (fi // 100) if fi is not None else ""
    return css, ms, so, si, int(an), int(tr), int(cp)


