def body_rules(rng):
    """the scroller rules with html and body biased to scroll"""
    rules = []
    if rng.random() < 0.95:
        d = [("overflow" if rng.random() < 0.7 else rng.choice(["overflow-x", "overflow-y"]), rng.choice(HTML_OV))]
        if rng.random() < 0.5:
            d.append(("height", rng.choice(HTML_H)))
        rules.append(("html", G5.imp(rng, d)))
    if rng.random() < 0.92:
        d = [("overflow" if rng.random() < 0.7 else rng.choice(["overflow-x", "overflow-y"]), rng.choice(BODY_OV))]
        if rng.random() < 0.9:
            d.append(("height", rng.choice(BODY_H)))
        if rng.random() < 0.15:
            d.append(("max-height", rng.choice(["200px", "50%", "none", "40vh"])))
        rules.append(("body", G5.imp(rng, d)))
    for el in ("#o", "#b"):
        if rng.random() < 0.3:
            rules.append((el, G5.imp(rng, G5.sc_decls(rng, 1.0))))
    rng.shuffle(rules)
    ranked = {k: [] for k in range(len(ELS))}
    order = 0
    for sel, decls in rules:
        for p, v in decls:
            order += 1
            im = v.endswith(" !important")
            vv = v[:-len(" !important")] if im else v
            k = ELS.index(sel)
            spec = (1, 0, 0) if sel.startswith("#") else (0, 0, 1)
            ranked[k].append(((int(im), spec, order), p, vv))
    return rules, ranked


ANIM_TL = ["scroll(nearest)", "scroll(nearest)", "scroll(nearest)", "scroll(nearest)", "scroll()", "scroll(self)",
           "scroll(root)", "--b", "--b",
           "view()", "view()", "view(block)", "view(y)", "--t", "--t", "--u", "--b", "--b", "auto", "none"]


def tl_rules(rng):
    d = {el: [] for el in ELS}
    if rng.random() < 0.5:
        d["body"].append(("scroll-timeline", rng.choice(["--b", "--b block", "--b y", "--t", "--b inline"])))
    if rng.random() < 0.3:
        d["html"].append(("scroll-timeline", rng.choice(["--b", "--t", "--u"])))
    if rng.random() < 0.3:
        d["body"] += G4.view_tl_decls(rng)
    for el in ("#o", "#b"):
        if rng.random() < 0.3:
            d[el] += G4.view_tl_decls(rng)
    return d


def anim_decls(rng):
    out = G5.anim_decls(rng)
    out[1] = ("animation-timeline", ", ".join(rng.choice(ANIM_TL) for _ in range(rng.choice([1, 1, 2]))))
    return out


def body_rec(rng, rgy, scroller):
    b = G6.body_box(rng, rgy)
    if scroller and rng.random() < 0.85 or rng.random() < 0.05:
        b["sv"] = 1
        b["s_vp"] = rng.choice([300, 200, 240, 480])
        b["s_rg"] = rng.choice([0, 100, 700, 1200, rng.randrange(0, 1500)])
        b["s_sc"] = rng.choice([0, b["s_rg"], b["s_rg"] // 2, rng.randrange(0, b["s_rg"] + 1)])
    return b


def rand_box(rng, k, nodes, rgy):
    """G5.rand_box with the Lot 110 scrollers and the body's mark"""
    b = G5.rand_box(rng, k, nodes, rgy)
    s = M5.scroller_of(nodes, k)
    if s >= 0 and rng.random() < 0.85:
        b["root"], b["sm"] = 0, M.sm_of(nodes, s)
    elif s >= 0 and rng.random() < 0.5:
        b["sm"] = s + 1
    return b


def sm_arg(sm):
    """the C value of a model sm (SM_BODY stays)"""
    return sm if sm == M.SM_BODY else ci(sm - 1) + 1


def body_case(rng):
    rules, ranked = body_rules(rng)
    tld = tl_rules(rng)
    try:
        tl = [M4.tl_cascade(tld[el]) for el in ELS]
        nodes = G5.sc_nodes(ranked, tl)
    except UNSURE:
        return None
    target = 4 if rng.random() < 0.7 else 1
    kfs = {p: {} for p in G102.PROPS}
    kf_rules = []
    got = G102.keyframes(rng, "k")
    if got is None:
        return None
    kf_rules.append(got[0])
    for p in G102.PROPS:
        kfs[p]["k"] = got[1][p]
    adecls = anim_decls(rng)
    anims = L102.coord(L102.anim_cascade([(100, adecls)]))
    ms = rng.choice([0, 0, 500])
    pm = rng.choice([0, S, 5000, rng.randrange(0, S + 1)])
    gui = rng.random() < 0.3
    geom = None
    if rng.random() < 0.92:
        rgy = rng.choice([0, 400, 1000, rng.randrange(0, 3000)])
        geom = {"rg_y": rgy, "sc_y": rng.choice([0, rgy, rgy // 2, rng.randrange(0, rgy + 1)]), "box": {}}
        if rng.random() < 0.9:
            geom["body"] = body_rec(rng, rgy, M.box_scroller(nodes, 1) != 0)
        for k in (0, 2, 3, 4):
            if rng.random() < 0.65:
                geom["box"][k] = rand_box(rng, k, nodes, rgy)
    c = M5.Ctx(geom, pm, gui)
    try:
        L.CUR = L.BLACK
        out, n_anim = [], 0
        for p in G102.PROPS:
            base = "#000000" if p == "color" else "transparent"
            cur, animated, _ = M7.stack(L.ALTS, anims, kfs[p], base, ms, nodes, target, c)
            final = None
            if animated:
                n_anim += 1
                final = L.paint_text(cur)
            if final:
                out.append("%s:%s" % (p, final))
            if p == "color":
                L.CUR = G100.cur_of(final) if final else L.BLACK
        n_sc, n_vw, n_bx, n_idle = M7.counts(anims, set(kfs["color"]), nodes, target, ms, c)
    except UNSURE:
        return None
    finally:
        L.CUR = None
    flagged = c.need | c.scr
    need = len(flagged) + int(c.root)
    used = sum(1 for q in flagged if M.box_of(nodes, q, geom))
    el = ELS[target]
    tld[el] = tld[el] + adecls
    css = G102.PROP + " ".join(kf_rules) + " " + G5.rules_css(rules) + " " + " ".join(
        "%s { %s }" % (e, "; ".join("%s: %s" % x for x in tld[e])) for e in ELS if tld[e])
    styles = {}
    for k in (1, 2, 3, 4):
        sty = list(out) if k == target else []
        t = M8.passed(nodes, k, c.scr) if k in c.scr else ""
        if t:
            sty.append(t)
        styles[k] = ' style="%s"' % ";".join(sty) if sty else ""
    return {"css": css, "ms": ms, "pm": pm, "gui": int(gui), "geom": geom, "styles": styles,
            "sc": (M.box_scroller(nodes, 1), ci(M5.scroller_of(nodes, 4))),
            "counts": (n_anim, n_sc, n_vw, n_bx, n_idle, need, used, int(c.live)),
            "flags": "".join("%d%d" % (int(k in c.need), int(k in c.scr)) for k in range(5))}


