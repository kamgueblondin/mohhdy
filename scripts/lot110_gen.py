def blen_case(rng):
    rules = []
    hd = [("overflow", rng.choice(["hidden", "auto", "clip", "visible", "scroll", "hidden visible"]))]
    if rng.random() < 0.85:
        hd.append(("height", rng.choice(BL_HTML)))
    rules.append(("html", hd))
    bd = [("overflow", rng.choice(["auto", "scroll", "hidden", "auto", "visible"]))]
    for prop in ("height", "max-height", "min-height"):
        if rng.random() < (0.85 if prop == "height" else 0.3):
            bd.append((prop, rng.choice(BL_H + (["none"] if prop == "max-height" else []))))
    if rng.random() < 0.3:
        bd.append(("font-size", rng.choice(["20px", "10px"])))
    rules.append(("body", bd))
    ranked = {k: [] for k in range(len(ELS))}
    order = 0
    for sel, decls in rules:
        for p, v in decls:
            order += 1
            if p != "font-size":
                ranked[ELS.index(sel)].append(((0, (0, 0, 1), order), p, v))
    try:
        nodes = G5.sc_nodes(ranked)
        fs = 16
        for p, v in bd:
            if p == "font-size":
                fs = int(v[:-2])
        nodes[1]["fs"] = fs
        scr = set()
        s = M5.scroller_of(nodes, 4)
        if s >= 0:
            scr.add(s)
        t = M8.passed(nodes, 1, scr)
    except UNSURE:
        return None
    css = "@keyframes k { to { color: #ffffff } } " + G5.rules_css(rules) + \
        " #i { animation: k 1s linear; animation-timeline: scroll(nearest) }"
    lines = ["prep(%s, 0);" % cstr(css),
             "TEST_ASSERT_EQUAL(%d, wf_site_box_scroller(&g_d, 2));" % M.box_scroller(nodes, 1),
             "TEST_ASSERT_EQUAL(%d, wf_site_scroller_of(&g_d, 5));" % ci(M5.scroller_of(nodes, 4)),
             "TEST_ASSERT_EQUAL_STRING(%s, style_of(\"body\"));" % cstr(
                 ' style="%s"' % ";".join(([] if fs == 16 else ["font-size:%dpx" % fs]) + ([t] if t else []))
                 if t or fs != 16 else "")]
    return css, lines


