#!/usr/bin/env python3
"""Lot 72: writes tests/unit/userspace/wf_aead_vectors.h, AEAD vectors made
with the Python 'cryptography' package (OpenSSL) for the freestanding
wf_aead.c. Deterministic (fixed seed). Not needed to build or run the tests:
the generated header is committed."""
import os
import random
import sys
from cryptography.hazmat.primitives.ciphers.aead import AESGCM, ChaCha20Poly1305

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests", "unit", "userspace", "wf_aead_vectors.h")


def carr(b):
    return "{" + ",".join("0x%02x" % x for x in b) + "}" if b else "{0}"


def main():
    rnd = random.Random(72)
    rows = []
    lens = [(0, 0), (1, 0), (15, 13), (16, 5), (17, 0), (63, 20), (64, 13), (65, 1), (300, 13), (1000, 17)]
    for alg, klen in ((1, 16), (2, 32), (3, 32)):
        for pl, al in lens:
            key = bytes(rnd.getrandbits(8) for _ in range(klen))
            nonce = bytes(rnd.getrandbits(8) for _ in range(12))
            aad = bytes(rnd.getrandbits(8) for _ in range(al))
            pt = bytes(rnd.getrandbits(8) for _ in range(pl))
            c = ChaCha20Poly1305(key) if alg == 3 else AESGCM(key)
            out = c.encrypt(nonce, pt, aad)
            rows.append((alg, key, nonce, aad, pt, out[:-16], out[-16:]))
    lines = ["/* Generated by scripts/gen_aead_vectors.py (Python cryptography %s). Do not edit. */" % __import__("cryptography").__version__,
             "typedef struct { int alg; int kl, al, pl; uint8_t key[32], nonce[12], aad[32], pt[1000], ct[1000], tag[16]; } aead_vec_t;",
             "static const aead_vec_t AEAD_VECS[] = {"]
    for alg, key, nonce, aad, pt, ct, tag in rows:
        lines.append("  {%d, %d, %d, %d, %s, %s, %s, %s, %s, %s}," % (alg, len(key), len(aad), len(pt), carr(key), carr(nonce), carr(aad), carr(pt), carr(ct), carr(tag)))
    lines.append("};")
    open(OUT, "w").write("\n".join(lines) + "\n")
    print("wrote %d vectors to %s" % (len(rows), OUT))


if __name__ == "__main__":
    sys.exit(main())
