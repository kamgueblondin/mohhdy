        "    g_o[0] = 0;",
        "    for (i = 0; i < g_d.nnodes; i++)",
        "        if (!strcmp(g_d.node[i].tag, tag)) wf_site_style_attr(&g_d, g_d.node[i].start, g_o, (int)sizeof(g_o));",
        "    return g_o;",
