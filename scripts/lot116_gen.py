def un_valid(good, bad):
    def ok(t):
        if t in good:
            return True
        if t in bad:
            return False
        raise M7.Unsure("not curated: %s" % t)
    return ok


def unset_case(rng):
    prop, good, bad, earlier = rng.choice(UN_PROPS)
    env, defs_b, defs_o = {}, [], []
    if rng.random() < 0.5:
        v = rng.choice(good + bad)
        defs_b.append(("--x", v))
        env["--x"] = v
    if rng.random() < 0.5:
        v = rng.choice(good + bad)
        defs_o.append(("--y", v))
        env["--y"] = v
    ref = rng.choice(["var(--x)", "var(--y)", "var(--z)", "var(--z, %s)" % rng.choice(good + bad), "var(--x, var(--y))",
                      "var(--z, var(--x))", "var(--y, %s)" % rng.choice(good)])
    own = [(prop, rng.choice(earlier))] if rng.random() < 0.7 else []
    got = M.unset_or_value(ref, env, un_valid(good, bad))
    anim = prop.startswith("animation")
    target = "#i" if anim else "#o"

    def sheet(last):
        t = "#o { overflow: auto; height: 90px; width: 300px } "
        if defs_b:
            t += "#b { %s } " % "; ".join("%s: %s" % d for d in defs_b)
        od = defs_o if not anim else []
        idl = defs_o if anim else []
        if od or not anim:
            t += "#o { %s } " % "; ".join(["%s: %s" % d for d in od] + (
                ["%s: %s" % d for d in own] + ["%s: %s" % (prop, last)] if not anim else []))
        t += "#i { animation: k 1s linear; animation-timeline: scroll(nearest)%s }" % "".join(
            "; %s: %s" % d for d in idl + (own + [(prop, last)] if anim else []))
        return t
    return sheet(ref), sheet(got), got, target


