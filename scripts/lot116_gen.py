# ------------------------------------------------ font-relative units
UNITS = ["cap", "ic", "rex", "rch", "rcap", "ric", "ex", "ch"]
U_NUM = ["1", "2", "3", "0.5", "1.5", "2.25", "4", "0.125", "10", "6.5"]
U_FONT = [None, "8px", "10px", "12px", "16px", "18px", "20px", "24px", "30px", "32px", "40px", "64px", "13px"]


def units_case(rng):
    """a sheet with a font-relative unit, the same sheet with the px the
    model gives (the reader must treat both alike) and the sheet without
    the declaration (which must differ: the unit is read)"""
    root = rng.choice(U_FONT)
    rem = M.milli(root[:-2]) if root else 16000
    par = rng.choice(U_FONT)
    pf = M.milli(par[:-2]) if par else rem
    u, n = rng.choice(UNITS), rng.choice(U_NUM)
    where = rng.choice(["height", "height", "font", "lh", "mix", "rootfont", "minh"])
    head = "html { font-size: %s } " % root if root and where != "rootfont" else ""
    pre = "#b { font-size: %s } " % par if par else ""
    if where == "rootfont":
        # the root's own font-size: its units are of the initial 16px
        m = M.len_milli(n + u, 16000, 16000)
        if not 1 <= m <= 96000 or m % 10 or m == 16000:      # the plain px takes two decimals
            raise M.Unsure("bounds")
        return ("html { font-size: %s%s } " % (n, u) + pre, "html { font-size: %s } " % M.px_text(m) + pre, pre, u)
    if where == "font":
        # font-size: units of the parent's font (CSS Values 4 6.1.1)
        m = M.len_milli(n + u, pf, rem)
        if not 1 <= m <= 96000 or m % 10:
            raise M.Unsure("bounds")
        return (head + pre + "#o { font-size: %s%s }" % (n, u), head + pre + "#o { font-size: %s }" % M.px_text(m),
                head + pre, u)
    own = rng.choice(U_FONT[1:])
    f = M.milli(own[:-2])
    m = M.len_milli(n + u, f, rem)
    body = head + pre + "#o { font-size: %s; " % own
    if where == "lh":
        return (body + "line-height: %s%s }" % (n, u), body + "line-height: %s }" % M.px_text(m), body + "}", u)
    tl = " #i { animation: k 1s linear; animation-timeline: scroll(nearest) }"
    if where == "mix":
        return (body + "overflow: auto; height: calc(%s%s + 10%%) }%s" % (n, u, tl),
                body + "overflow: auto; height: calc(%s + 10%%) }%s" % (M.px_text(m), tl),
                body + "overflow: auto }" + tl, u)
    prop = "min-height" if where == "minh" else "height"
    extra = "height: 5px; " if where == "minh" else ""
    if where == "minh" and m <= 5000:
        raise M.Unsure("no effect")
    return (body + "overflow: auto; %s%s: %s%s }%s" % (extra, prop, n, u, tl),
            body + "overflow: auto; %s%s: %s }%s" % (extra, prop, M.px_text(m), tl),
            body + "overflow: auto; %s}%s" % (extra, tl), u)


