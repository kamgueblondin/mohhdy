# ------------------------------------------------------------ engine math
def em_leaf(rng):
    k = rng.random()
    if k < 0.4:
        return "%dpx" % rng.randrange(0, 120)
    if k < 0.7:
        return "%d%%" % rng.randrange(0, 101)
    if k < 0.75:
        return "-%dpx" % rng.randrange(1, 50)
    if k < 0.8:
        return rng.choice(["2000px", "2001px", "1999%", "2001%", "0px"])
    return "%dpx" % rng.randrange(0, 40)


def em_val(rng, depth, budget):
    """a length expression of the engine's grammar near its bounds"""
    k = rng.random()
    if depth >= budget or k < 0.3:
        return em_leaf(rng)
    if k < 0.55:
        f = rng.choice(["min", "max"])
        n = rng.choice([1, 2, 3, 4, 5, 6, 7, 8, 8, 9, 10])
        return "%s(%s)" % (f, rng.choice([",", ", "]).join(em_val(rng, depth + 1, budget) for _ in range(n)))
    if k < 0.65:
        return "clamp(%s)" % ", ".join(em_val(rng, depth + 1, budget) for _ in range(3))
    if k < 0.75:
        return "calc(%s)" % em_val(rng, depth + 1, budget)
    if k < 0.82:
        return "(%s)" % em_val(rng, depth + 1, budget)
    if k < 0.92:
        n = rng.randrange(2, 9)
        return " ".join(sum(([em_val(rng, depth + 1, budget), rng.choice("+-")] for _ in range(n)), [])[:-1])
    if rng.random() < 0.6:
        return "%s * %d" % (em_val(rng, depth + 1, budget), rng.choice([2, 3, 0, 1000, 600]))
    return "%s / %d" % (em_val(rng, depth + 1, budget), rng.choice([2, 3, 0, 7]))


def em_value(rng):
    k = rng.random()
    if k < 0.15:
        # a flat sum near the node bound: n literals take 2n - 1 nodes
        n = rng.randrange(14, 19)
        return "calc(%s)" % " + ".join("%dpx" % rng.randrange(0, 9) for _ in range(n))
    if k < 0.3:
        # nested near the depth bound
        d = rng.randrange(6, 11)
        v = em_leaf(rng)
        for _ in range(d):
            v = rng.choice(["calc(%s)", "min(%s, 300px)", "max(%s, 1px)", "(%s)"]) % v
        return v if v.startswith(("calc(", "min(", "max(")) else "calc(%s)" % v
    if k < 0.45:
        # arguments near the argument bound
        n = rng.randrange(6, 11)
        return "%s(%s)" % (rng.choice(["min", "max"]), ", ".join(em_leaf(rng) for _ in range(n)))
    while True:
        v = em_val(rng, 0, rng.randrange(2, 6))
        if v.startswith(("calc(", "min(", "max(", "clamp(")):
            return v


def write_emath():
    rng = random.Random(11602)
    cases, seen, took = [], set(), 0
