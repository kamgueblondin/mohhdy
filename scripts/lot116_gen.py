def write_bflow():
    rng = random.Random(11604)
    cases = []
    while len(cases) < 100:
        outer = rng.choice(G9.OUTER)
        basis = M7.math_floor(M9.math_box(outer)[1])
        decls = [("height", big_value(rng))]
        if rng.random() < 0.25:
            decls.append(("max-height", big_value(rng)))
        if rng.random() < 0.25:
            decls.append(("min-height", big_value(rng)))
        try:
            with _same():
                got = [(p, M7.height_val(v, p == "max-height")) for p, v in decls]
                got = [(p, M7.box_len(hv, 16, 16) if hv else None) for p, hv in got]
                with M.bounds_lot112():
                    old = [(p, M7.box_len(M7.height_val(v, p == "max-height"), 16, 16)) for p, v in decls]
        except UNSURE:
            continue
        if got[0][1] is None or got[0][1][1] != "expr" or got == old:
            continue            # nothing new
        txt = {p: M7.box_text(r) for p, r in got if r is not None}
        h = M9.engine_px(txt["height"], basis)
        if "max-height" in txt:
            h = min(h, M9.engine_px(txt["max-height"], basis))
        if "min-height" in txt:
            h = max(h, M9.engine_px(txt["min-height"], basis))
        if h > 2000:
            continue
        sty = "overflow-y:auto" + "".join(";%s:%s" % (p, txt[p]) for p in ("height", "max-height", "min-height")
                                          if p in txt)
        css = "#p { overflow: auto; height: %s } #o { overflow: auto; %s }" % (outer, "; ".join(
            "%s: %s" % d for d in decls))
        if len(css) > 600 or len(sty) > 500:
            continue
        cases.append(["flow(%s);" % cstr(css), "TEST_ASSERT_EQUAL_STRING(%s, g_o);" % cstr(sty),
                      "TEST_ASSERT_EQUAL(%d, sh(0));" % basis, "TEST_ASSERT_EQUAL(%d, sh(1));" % h])
    o = [HEADER % "Lot 116: mixed values past the Lot 112 bounds laid out by the engine"] + G9.FLOW_C.split("\n")
    names = chunks(o, "test_l116_bflow", cases, 8)
    finish(o, names, "test_lot116_bflow.c")
    return len(cases)


