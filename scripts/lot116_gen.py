# ------------------------------------------------- mixed values, bigger
def big_lin(rng):
    k = rng.randrange(5)
    if k == 0:
        return "%d%%" % rng.randrange(0, 101)
    if k == 1:
        return "%dpx" % rng.randrange(0, 300)
    return "calc(%d%% %s %dpx)" % (rng.randrange(0, 101), rng.choice("+-"), rng.randrange(0, 200))


def big_val(rng, depth, deep):
    k = rng.random()
    if depth >= deep or k < 0.35:
        return big_lin(rng)
    if k < 0.8:
        f = rng.choice(["min", "max", "min", "max", "clamp"])
        n = 3 if f == "clamp" else rng.choice([2, 3, 4, 5, 6, 7, 8])
        return "%s(%s)" % (f, ", ".join(big_val(rng, depth + 1, deep) for _ in range(n)))
    if k < 0.9:
        return "calc(%s + %s)" % (big_val(rng, depth + 1, deep), big_lin(rng))
    return "calc(%s * %s)" % (big_val(rng, depth + 1, deep), rng.choice(["2", "0.5", "-1", "3"]))


def big_value(rng):
    while True:
        v = big_val(rng, 0, rng.choice([2, 3, 4, 5, 6]))
        if v.startswith(("min(", "max(", "clamp(", "calc(")) and len(v) <= 120:
            return v


