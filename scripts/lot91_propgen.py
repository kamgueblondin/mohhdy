#!/usr/bin/env python3
"""Lot 91 test generator: @property syntax with alternatives, lists and
keywords; calc(), min(), max() and clamp() type checking.

Expectations come from this file, not from the C sources:
* a syntax string is built from a list of alternatives (type name or
  keyword, multiplier) and a known fault or none; the expected code and
  alternatives follow from that list.
* a math expression is built as a tree; its type is computed on the tree
  with the CSS Values 4 rules (+ and - need the same type, a length and a
  percentage give a length-percentage; * needs a number on one side; /
  needs a number on the right; min/max fold their arguments like +; clamp
  takes three). The text is written from the tree, with a known spacing
  fault (no white space around + or -) when one is planted.
* a value is a list of items, each made for a type (or a math tree); the
  model says which types an item satisfies, splits the value as each
  alternative's multiplier says (spaces for '+', commas for '#', never
  inside parentheses) and tries the alternatives in order.

Codes (wf_cssprop.h): BAD 0, ANY 1, LENGTH 2, PERCENT 3, LENPCT 4,
NUMBER 5, INTEGER 6, COLOR 7, ANGLE 8, TIME 9, CIDENT 10, KEYWORD 11,
COMPLEX 12; multipliers ONE 0, PLUS 1, HASH 2.

Run: python3 scripts/lot91_propgen.py
"""
import os
import random
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "tests", "unit", "userspace")
HEADER = "/* %s (generated by scripts/lot91_propgen.py; expectations from that model). */\n"
SEED_SYNTAX = 9111
SEED_MATH = 9112
SEED_MATCH = 9113
SEED_RULE = 9114

BAD, ANY, LENGTH, PERCENT, LENPCT, NUMBER, INTEGER, COLOR, ANGLE, TIME, CIDENT, KEYWORD, COMPLEX = range(13)
CNAME = {BAD: "WF_CSSPROP_BAD", ANY: "WF_CSSPROP_ANY", LENGTH: "WF_CSSPROP_LENGTH", PERCENT: "WF_CSSPROP_PERCENT",
         LENPCT: "WF_CSSPROP_LENPCT", NUMBER: "WF_CSSPROP_NUMBER", INTEGER: "WF_CSSPROP_INTEGER",
         COLOR: "WF_CSSPROP_COLOR", ANGLE: "WF_CSSPROP_ANGLE", TIME: "WF_CSSPROP_TIME", CIDENT: "WF_CSSPROP_CIDENT",
         KEYWORD: "WF_CSSPROP_KEYWORD", COMPLEX: "WF_CSSPROP_COMPLEX"}
TYPE_NAMES = {LENGTH: "<length>", PERCENT: "<percentage>", LENPCT: "<length-percentage>", NUMBER: "<number>",
              INTEGER: "<integer>", COLOR: "<color>", ANGLE: "<angle>", TIME: "<time>", CIDENT: "<custom-ident>"}
ONE, PLUS, HASH = 0, 1, 2
RESERVED = ["initial", "inherit", "unset", "revert", "revert-layer", "default"]
KEYWORDS = ["auto", "none", "small", "big", "x", "left-side", "_under", "-moz-thing", "a1", "stretch", "thin", "red"]
LEN_UNITS = ["px", "em", "rem", "ex", "ch", "vw", "vh", "vmin", "vmax", "pt", "pc", "cm", "mm", "in", "q"]
ANG_UNITS = ["deg", "grad", "rad", "turn"]
TIME_UNITS = ["s", "ms"]
COLOR_NAMES = ["black", "white", "red", "green", "blue", "yellow", "gray", "grey", "silver", "maroon", "purple",
               "fuchsia", "lime", "olive", "navy", "teal", "aqua", "orange", "transparent", "currentcolor"]


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def rcase(rng, s):
    m = rng.randrange(3)
    if m == 0:
        return s
    if m == 1:
        return s.upper()
    return "".join(c.upper() if rng.random() < 0.3 else c for c in s)


def emit_main(o, names):
    o += ["int main(void) {", "    unity_init();"]
    o += ["    RUN_TEST(%s);" % n for n in names]
    o += ["    unity_print_results();", "    unity_cleanup();", "    return unity_stats.tests_failed == 0 ? 0 : 1;", "}", ""]


# ======================================================== syntax strings
def syntax_case(rng):
    """(text, expected code, alternatives [(type, mult, ident)] or None)"""
    if rng.random() < 0.06:
        q = rng.choice(["'", '"'])
        return q + rng.choice(["*", " * ", "*"]) + q, ANY, []
    n = rng.choice([1, 1, 1, 2, 2, 3, 4, 5])
    alts = []
    for _ in range(n):
        if rng.random() < 0.65:
            t = rng.choice(sorted(TYPE_NAMES))
            alts.append((t, rng.choice([ONE, ONE, PLUS, HASH]), ""))
        else:
            alts.append((KEYWORD, rng.choice([ONE, ONE, ONE, PLUS, HASH]), rng.choice(KEYWORDS)))
    valid = n <= 4
    texts = []
    for t, m, ident in alts:
        w = rcase(rng, TYPE_NAMES[t]) if t != KEYWORD else rcase(rng, ident)
        texts.append(w + ("" if m == ONE else "+" if m == PLUS else "#"))
    fault = rng.random()
    q = rng.choice(["'", '"'])
    if fault < 0.05:
        k = rng.randrange(n)
        texts[k] = rcase(rng, rng.choice(RESERVED))
        valid = False
    elif fault < 0.09:
        k = rng.randrange(n)
        texts[k] = rng.choice(["1abc", "-1x", "a.b", "<resolution>", "<transform-list>", "<url>", "-", "*", "a#b"])
        valid = False
    elif fault < 0.12:
        k = rng.randrange(n)
        texts[k] = "abcdefghijklmnop"                       # 16 bytes: longer than WF_CSSPROP_IDENT - 1
        valid = False
    elif fault < 0.15:
        k = rng.randrange(n)
        texts[k] = texts[k] + rng.choice(["+#", "#+", "++"])
        valid = False
    elif fault < 0.18:
        k = rng.randrange(n)
        texts[k] = texts[k] + " " + rng.choice(["+", "#"])  # space before the multiplier
        valid = False
    elif fault < 0.21:
        texts.append("")                                     # a trailing or empty alternative
        valid = False
    elif fault < 0.23:
        q2 = "'" if q == '"' else '"'
        body = " | ".join(texts)
        return q + body + q2, BAD, None
    elif fault < 0.25:
        return " | ".join(texts), BAD, None                  # no quotes
    elif fault < 0.27:
        k = rng.randrange(n)
        texts[k] = "< length >"
        valid = False
    seps = [rng.choice(["|", " | ", "  |", "| ", "\t|\t"]) for _ in range(len(texts) - 1)]
    body = texts[0]
    for k in range(1, len(texts)):
        body += seps[k - 1] + texts[k]
    text = q + rng.choice(["", " "]) + body + rng.choice(["", " "]) + q
    if not valid:
        return text, BAD, None
    if n == 1 and alts[0][1] == ONE and alts[0][0] != KEYWORD:
        return text, alts[0][0], alts
    return text, COMPLEX, alts


