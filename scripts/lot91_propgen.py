def independent(v):
    if re.search(r"(^|[^a-z0-9_-])var\(", v):
        return False
    for m in re.finditer(r"[0-9.]+([a-z]*)", v):
        start = m.start()
        if start > 0 and re.match(r"[a-z_]", v[start - 1]):
            continue
        if m.group(1) in ("em", "rem", "ex", "ch"):
            return False
    return True


