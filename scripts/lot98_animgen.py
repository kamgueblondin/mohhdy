# ------------------------------------------------------------- hsl
def hue_text(rng):
    k = rng.randrange(5)
    if k == 0:
        return str(rng.randrange(0, 361))
    if k == 1:
        return dec(rng, -720, 720)
    if k == 2:
        return dec(rng, -400, 800) + "deg"
    if k == 3:
        return rng.choice(["0", "60", "120", "180", "240", "300", "360", "-60deg", "720deg", "30", "90deg"])
    return str(rng.randrange(0, 12) * 30 + rng.choice([0, 1, -1]))


def sl_text(rng, pct=True):
    v = rng.choice([dec(rng, 0, 100, 4), dec(rng, 0, 100, 1), str(rng.randrange(0, 101)), dec(rng, -20, 130, 2),
                    rng.choice(["0", "100", "50"])])
    return v + "%" if pct else v


def hsl_text(rng, good=True):
    h = hue_text(rng)
    form = rng.randrange(6)
    if form <= 1:
        args = [h, sl_text(rng), sl_text(rng)]
        if form == 1:
            args.append(rng.choice([dec(rng, 0, 1, 2), str(rng.randrange(0, 101)) + "%", dec(rng, -1, 2, 1)]))
        f = "hsla" if form == 1 and rng.random() < 0.7 else "hsl"
        sep = rng.choice([", ", ",", " , "])
        t = f + "(" + sep.join(args) + ")"
    else:
        pct = rng.random() < 0.6
        args = [h, sl_text(rng, pct), sl_text(rng, pct or rng.random() < 0.5)]
        t = ("hsla" if rng.random() < 0.2 else "hsl") + "(" + " ".join(args)
        if form >= 4:
            t += rng.choice([" / ", "/", " /"]) + rng.choice([dec(rng, 0, 1, 2), str(rng.randrange(0, 101)) + "%"])
        t += ")"
    if not good:
        j = rng.randrange(7)
        if j == 0:
            t = "hsl(%s, %s, %s)" % (h, sl_text(rng, False), sl_text(rng))
        elif j == 1:
            t = "hsl(%s, %s)" % (h, sl_text(rng))
        elif j == 2:
            t = "hsl(%s, %s, %s / 0.5)" % (h, sl_text(rng), sl_text(rng))
        elif j == 3:
            t = "hsl(%s %s %s %s)" % (h, sl_text(rng), sl_text(rng), sl_text(rng))
        elif j == 4:
            t = "hsl(%s%%, %s, %s)" % (dec(rng, 0, 100), sl_text(rng), sl_text(rng))
        elif j == 5:
            t = "hsl(%s, %s, %s, 0.5, 1)" % (h, sl_text(rng), sl_text(rng))
        else:
            t = "hsl(%s %s, %s)" % (h, sl_text(rng), sl_text(rng))
    return t


def boundary_hsl(rng, mode):
    """an hsl() text one of whose exact channels, in 1/10000 of 0..255,
    sits within 1/2 of a unit below an integer channel + 1/2: rounding the
    channel half away from zero to 1/10000 gives the next integer
    (mode "up") where a floor would not"""
    while True:
        h = rng.randrange(0, 360)
        s = rng.randrange(0, 1000001)
        l = rng.randrange(0, 1000001)
        st, lt = "%d.%04d%%" % divmod(s, 10000), "%d.%04d%%" % divmod(l, 10000)
        hs, ls = F(s, 1000000), F(l, 1000000)
        a = hs * min(ls, 1 - ls)
        for n in (0, 8, 4):
            k = (n + F(h, 30)) % 12
            c = (ls - a * max(-1, min(k - 3, 9 - k, 1))) * 255 * S
            fr = c - (c // S) * S
            if F(9999, 2) <= fr < 5000:
                return "hsl(%d, %s, %s)" % (h, st, lt)


def write_hsl():
    rng = random.Random(9801)
    cases = []
    for _ in range(12):
        h = boundary_hsl(rng, "up")
        r = A.interp([("<color>", "", None)], h, h, 5000)[0]
        cases.append(["TEST_ASSERT_EQUAL_STRING(%s, ip(%s, %s, 5000, 2));" % (cstr(r), cstr(h), cstr(h))])
    while len(cases) < 480:
        good = rng.random() < 0.85
        a = hsl_text(rng, good)
        k = rng.randrange(4)
        b = a if k == 0 else hsl_text(rng) if k == 1 else G.colour_text(rng)
        if rng.random() < 0.5:
            a, b = b, a
        tt = rng.choice([5000, 5000, rng.randrange(1, S), rng.randrange(1, S), 1, 9999])
        alts = [("<color>", "", None)]
        if not (A.colour_match(a) and A.colour_match(b)):
            continue
        r, c = A.interp(alts, a, b, tt)
        if r is None:
            continue
        cases.append(["TEST_ASSERT_EQUAL_STRING(%s, ip(%s, %s, %d, %d));" % (cstr(r), cstr(a), cstr(b), tt, c)])
    o = [HEADER % "Lot 98: hsl() and hsla() colours interpolated in sRGB (wf_cssprop_interp)"] + IP_C + [
        "/* the interpolated text of two colours; the return code is checked */",
        "static const char *ip(const char *a, const char *b, int t, int code) {",
        "    if (!syn(\"'<color>'\")) return \"BAD SYNTAX\";",
        "    if (wf_cssprop_interp(&g_p, a, b, t, g_o, (int)sizeof(g_o)) != code) return \"BAD CODE\";",
        "    return g_o;",
        "}", ""]
    names = chunks(o, "test_l98_hsl", cases, 12)
    finish(o, names, "test_lot98_hsl.c")
    return len(cases)


# ------------------------------------------------------------- add
def write_add():
    rng = random.Random(9802)
    cases = []
    types = list(G.TYPE_KIND)
    while len(cases) < 560:
        t = rng.choice(types)
        m = rng.choice(["", "", "", "+", "#"])
        alts = [(t, m)]
        if rng.random() < 0.2:
            t2 = rng.choice(types)
            if t2 != t:
                alts.append((t2, ""))
        text = "'" + " | ".join(x + y for x, y in alts) + "'"
        if rng.random() < 0.04:
            text = "'*'"
        code, parsed = P.parse_syntax(text)
        if not parsed and text != "'*'":
            continue

        def val():
            ty, mm = rng.choice(alts)
            if ty == "<color>" and rng.random() < 0.3:
                one = lambda: hsl_text(rng)  # noqa: E731
            else:
                one = lambda: G.value_of(rng, ty)  # noqa: E731
            if mm:
                n = rng.randrange(1, 4)
                return (", " if mm == "#" else " ").join(one() for _ in range(n))
            return one()
        a = val()
        b = val()
        if rng.random() < 0.3 and m:
            b = a.replace("1", "2", 1)
        r, c = M.add(None if text == "'*'" else parsed, a, b)
        if r is None or len(r) >= 150:
            continue
        cases.append(["TEST_ASSERT_EQUAL_STRING(%s, ad(%s, %s, %s, %d));" % (cstr(r), cstr(text), cstr(a), cstr(b), c)])
    o = [HEADER % "Lot 98: a value composited on the value below (wf_cssprop_add)"] + IP_C + [
        "/* the sum text; the return code is checked against code */",
        "static const char *ad(const char *s, const char *under, const char *v, int code) {",
        "    if (!syn(s)) return \"BAD SYNTAX\";",
        "    if (wf_cssprop_add(&g_p, under, v, g_o, (int)sizeof(g_o)) != code) return \"BAD CODE\";",
        "    return g_o;",
        "}", ""]
    names = chunks(o, "test_l98_add", cases, 10)
    finish(o, names, "test_lot98_add.c")
    return len(cases)


