def anim_tok(rng, k, good=True):
    if not good:
        if rng.random() < 0.3:
            return rng.choice(GENERIC_BAD)
        if k == 2:
            return G.ease_text(rng, False)
        return rng.choice(ANIM_BAD[k])
    if k == 0:
        return rng.choice(["k", "j", "slide", "none", "_x", "fade-in", "a" * 31, "q", "--n", "ease", "z"])
    if k in (1, 3):
        return rng.choice([G.time_text(rng, k == 3), "auto" if k == 1 else "0s", "0ms"])
    if k == 2:
        return G.ease_text(rng)
    if k == 4:
        return rng.choice(["infinite", "0", "1", "2.5", "100000", "0.0001", dec(rng, 0, 10)])
    return rng.choice({5: M.DIRS, 6: M.FILLS, 7: ["running", "paused"], 8: M.COMPS}[k])


def trans_tok(rng, k, good=True):
    if not good:
        if rng.random() < 0.3:
            return rng.choice(GENERIC_BAD)
        if k == 2:
            return G.ease_text(rng, False)
        return rng.choice(TRANS_BAD[k])
    if k == 0:
        return rng.choice(["--p", "--x", "all", "color", "none" if rng.random() < 0.3 else "--q", "a" * 31])
    if k in (1, 3):
        return rng.choice([G.time_text(rng, k == 3), "0s"])
    if k == 2:
        return G.ease_text(rng)
    return rng.choice(["allow-discrete", "normal"])


def ease_c(e):
    return G.ease_fields(e)


def afield(a):
    return "%s %d %d %d %d %d %d %d %s" % (a["name"] or "-", a["dur"], a["delay"], a["iters"], G.DIRS[a["dir"]],
                                           G.FILLS[a["fill"]], int(a["paused"]), M.COMPS.index(a["comp"]),
                                           ease_c(a["ease"]))


def tfield(t):
    return "%s %d %d %d %s" % (t["prop"] or "-", t["dur"], t["delay"], int(t["discrete"]), ease_c(t["ease"]))


def long_field(anim, k, v):
    if anim:
        if k == 0:
            return v or "-"
        if k == 2:
            return ease_c(v)
        if k == 5:
            return str(G.DIRS[v])
        if k == 6:
            return str(G.FILLS[v])
        if k == 8:
            return str(M.COMPS.index(v))
        return str(int(v))
    if k == 0:
        return "-" if v == "NONE" else v
    if k == 2:
        return ease_c(v)
    return str(int(v))


def long_list_text(rng, anim, k, good):
    n = rng.choice([1, 1, 2, 3, 4, 5] if not good else [1, 1, 2, 3, 4])
    tok = anim_tok if anim else trans_tok
    bad = -1 if good else rng.randrange(n)
    toks = [tok(rng, k, j != bad) for j in range(n)]
    sep = rng.choice([", ", ",", " , "])
    v = sep.join(toks)
    if not good and rng.random() < 0.1:
        v = rng.choice([v + ",", ", " + v, v.replace(",", ",,", 1) if "," in v else v + ",, k", ""])
    return v


def slot_text(rng, anim, k):
    """("sh", shorthand text) or ("long", longhand text) or None"""
    r = rng.random()
    if r < 0.35:
        return None
    if r < 0.5 and k < (8 if anim else 5):
        return ("sh", None)
    return ("long", long_list_text(rng, anim, k, rng.random() < 0.85))


def write_longs():
    rng = random.Random(9803)
    cases = []
    while len(cases) < 360:
        anim = rng.random() < 0.6
        k = rng.randrange(9 if anim else 5)
        good = rng.random() < 0.6
        v = long_list_text(rng, anim, k, good)
        got = M.long_list(anim, k, v)
        fn = "along" if anim else "tlong"
        lines = ["TEST_ASSERT_EQUAL(%d, %s(%d, %s));" % (-1 if got is None else len(got), fn, k, cstr(v))]
        for j, x in enumerate(got or []):
            lines.append("TEST_ASSERT_EQUAL_STRING(%s, %sf(%d, %d));" % (cstr(long_field(anim, k, x)), fn, k, j))
        cases.append(lines)
    while len(cases) < 580:
        anim = rng.random() < 0.6
        nl = 9 if anim else 5
        slots = [slot_text(rng, anim, k) for k in range(nl)]
        sh = None
        if any(s and s[0] == "sh" for s in slots):
            n = rng.choice([1, 1, 2, 3])
            sh = ", ".join((G.anim_item if anim else G.trans_item)(rng, rng.random() < 0.9) for _ in range(n))
            slots = [("sh", sh) if s and s[0] == "sh" else s for s in slots]
