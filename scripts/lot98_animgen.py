SHEET_TYPES = ["<length>", "<number>", "<percentage>", "<color>", "<angle>", "<integer>", "<length-percentage>",
               "<custom-ident>", "<length>+", "<color>#"]


def sheet_value(rng, t):
    if t.endswith("+") or t.endswith("#"):
        return (", " if t.endswith("#") else " ").join(sheet_value(rng, t[:-1]) for _ in range(2))
    if t == "<color>" and rng.random() < 0.3:
        return hsl_text(rng)
    v = G.value_of(rng, t)
    if t == "<color>" and v.startswith(("hsl", "currentcolor")):
        v = "red"
    return v


def computed(alts, v):
    c = P.compute(alts, v, (640, 480))
    return v if c is None else c


def offset_sel(rng, o):
    if o == 0 and rng.random() < 0.5:
        return "from"
    if o == S and rng.random() < 0.5:
        return "to"
    return "%d%%" % (o // 100) if o % 100 == 0 else "%d.%02d%%" % (o // 100, o % 100)


def keyframes(rng, t, alts, name):
    """the rule text and its model frames"""
    offs = sorted(rng.sample([0, 2500, 5000, 7500, 10000, 3333, 6000], rng.randrange(1, 4)))
    blocks, frames = [], []
    for o in offs:
        v = sheet_value(rng, t)
        body = "--p: %s" % v
        fe = fc = None
        if rng.random() < 0.15:
            ft = rng.choice(["linear", "ease-in", "steps(2)"])
            fe = A.ease_parse(ft)
            body += "; animation-timing-function: %s" % ft
        if rng.random() < 0.25:
            fc = rng.choice(M.COMPS)
            body += "; animation-composition: %s" % fc.upper() if rng.random() < 0.2 else \
                "; animation-composition: %s" % fc
        blocks.append("%s { %s }" % (offset_sel(rng, o), body))
        frames.append((o, computed(alts, v), fe, fc))
    return "@keyframes %s { %s }" % (name, " ".join(blocks)), frames


def anim_decls(rng):
    """declarations setting the animation longhands: [(property, value)]"""
    out = []
    if rng.random() < 0.5:
        n = rng.choice([1, 1, 2])
        items = []
        for _ in range(n):
            nm = rng.choice(["k", "k", "j", "none"])
            items.append("%s %dms%s" % (nm, rng.choice([1000, 2000, 500]),
                                        rng.choice(["", " linear", " ease-in-out", " steps(4)"])))
        out.append(("animation", ", ".join(items)))
    ks = rng.sample(range(9), rng.randrange(1, 6))
    if 8 not in ks and rng.random() < 0.5:
        ks.append(8)
    if not out:
        for k in (0, 1):
            if k not in ks and rng.random() < 0.85:
                ks.insert(0, k)
    for k in ks:
        if k == 0 and rng.random() < 0.7:
            v = rng.choice(["k", "k, j", "j, k", "none, k", "k, k", "j"])
        elif k == 1:
            v = rng.choice(["1000ms", "2s", "500ms, 3000ms", "1s, 2s", "auto, 1s"])
        elif k == 8:
            v = rng.choice(["add", "accumulate", "replace", "add, replace", "replace, accumulate", "ADD"])
        elif k == 4:
            v = rng.choice(["infinite", "2", "1.5", "1, 2", "0.5"])
        else:
            v = long_list_text(rng, True, k, rng.random() < 0.85)
        if rng.random() < 0.05:
            v = rng.choice(["initial", "unset", "inherit"])
        out.append((M.ANIM_LONGS[k], v))
    return out


def cascade(anim, rules):
    """rules: [(specificity, [(property, value)])] in source order: the
    winning slots"""
    names = M.ANIM_LONGS if anim else M.TRANS_LONGS
    short = "animation" if anim else "transition"
    nsh = 8 if anim else 5
    best = [None] * len(names)
    order = 0
    for spec, decls in rules:
        for prop, val in decls:
            val = val.strip().lower()
            order += 1
            if len(val) >= 128:
                continue        # a declaration value over 127 bytes is dropped (Lot 90)
            setv = None
            if prop == short:
                if val in ("initial", "unset") or (anim and val == "none"):
                    setv = [(k, None) for k in range(nsh)]
                elif (A.anim_parse if anim else A.trans_parse)(val):
                    setv = [(k, ("sh", val)) for k in range(nsh)]
            elif prop in names:
                k = names.index(prop)
                if val in ("initial", "unset"):
                    setv = [(k, None)]
                elif M.long_list(anim, k, val) is not None:
                    setv = [(k, ("long", val))]
            for k, s in setv or []:
                if best[k] is None or (spec, order) >= best[k][0]:
                    best[k] = ((spec, order), s)
    return [b[1] if b else None for b in best]


def wrap_scope(rng, rule):
    k = rng.randrange(4)
    if k == 0:
        return "@scope (#o) { %s }" % rule
    if k == 1:
        return "@scope { @scope (div) { %s } }" % rule
    return rule


def kf_case(rng):
    t = rng.choice(SHEET_TYPES)
    syn = "'%s'" % t
    _, alts = P.parse_syntax(syn)
    inherits = rng.random() < 0.5
    init = computed(alts, sheet_value(rng, t))
    own = sheet_value(rng, t) if rng.random() < 0.6 else None
    under = computed(alts, own) if own is not None else init
    kfs, rules = {}, []
    scoped = 0
    for name in ("k", "j") if rng.random() < 0.5 else ("k",):
        text, fr = keyframes(rng, t, alts, name)
        kfs[name] = fr
        if rng.random() < 0.4:
            text = wrap_scope(rng, text)
            scoped += text.startswith("@scope")
        rules.append(text)
    decls = anim_decls(rng)
    weak = anim_decls(rng) if rng.random() < 0.3 else []
    slots = cascade(True, [(100, decls), (1, weak)] if weak else [(100, decls)])
    anims = M.coord(True, slots)
    ms = rng.choice([0, rng.randrange(0, 5000), rng.randrange(0, 1500), rng.randrange(0, 1500), 500, 250])
    o_val, animated, composed = M.stack(alts, anims, kfs, under, ms)
    i_val = o_val if inherits else init
    body = "; ".join("%s: %s" % d for d in decls) + ("; --p: %s" % own if own is not None else "")
    css = "@property --p { syntax: %s; inherits: %s; initial-value: %s } %s #o { %s }" % (
        syn, "true" if inherits else "false", init, " ".join(rules), body)
    if weak:
        css += " div { %s }" % "; ".join("%s: %s" % d for d in weak)
    return css, ms, o_val, i_val, int(animated), int(composed)


def trans_case(rng):
    t = rng.choice(SHEET_TYPES)
    syn = "'%s'" % t
    _, alts = P.parse_syntax(syn)
    init = computed(alts, sheet_value(rng, t))
    start = sheet_value(rng, t)
    end = sheet_value(rng, t) if rng.random() < 0.9 else start
    decls = []
    if rng.random() < 0.4:
        decls.append(("transition", rng.choice(["--p 1000ms linear", "all 400ms", "none", "--x 1s, --p 2s ease-in",
                                                "--p 1s allow-discrete"])))
    for k in rng.sample(range(5), rng.randrange(1, 5)):
        if k == 0:
            v = rng.choice(["--p", "all", "--x, --p", "--p, --x", "none", "--x"])
        elif k == 1:
            v = rng.choice(["1000ms", "2s", "400ms, 1s", "0s", "1s, 0s"])
        else:
            v = long_list_text(rng, False, k, rng.random() < 0.9)
        decls.append((M.TRANS_LONGS[k], v))
    rng.shuffle(decls)
    slots = cascade(False, [(100, decls)])
    tl = M.coord(False, slots)
    ms = rng.choice([0, rng.randrange(0, 3000), rng.randrange(0, 3000), 150])
    s_c, e_c = computed(alts, start), computed(alts, end)
    tr = None
    for x in tl:
        if x["prop"] in ("all", "--p"):
            tr = x
    val, ran = e_c, 0
    if tr is not None and s_c != e_c and (A.interp(alts, s_c, e_c, 5000)[1] == 2 or tr["discrete"]):
        e = ms - tr["delay"]
        if e < tr["dur"]:
            ran = 1
            val = s_c if e < 0 else A.interp(alts, s_c, e_c, A.ease_at(tr["ease"], e * S // tr["dur"]))[0]
    css = "@property --p { syntax: %s; inherits: true; initial-value: %s } #o { --p: %s; %s } " \
          "@starting-style { #o { --p: %s } }" % (syn, init, end, "; ".join("%s: %s" % d for d in decls), start)
    return css, ms, val, val, ran, 0


