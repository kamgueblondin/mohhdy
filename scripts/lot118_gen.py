"""Lot 118: writes tests/unit/userspace/test_lot118_math.c, the generated
table of CSS math expressions (lot118_exprs) with the values of the integer
model (lot118_model) read through we_math_milli.

    python3 scripts/lot118_gen.py [count]

The rows are deterministic (seeded); about a fifth are mangled (most of
them refused). A row's expectation is the first type of number, length,
angle that parses, as we_math_milli tries them."""
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lot118_exprs as X  # noqa: E402
import lot118_model as M  # noqa: E402

CONTEXTS = ((640, 480, 0), (1000, 500, 0), (320, 900, 1), (1024, 768, 1))
FONTS = (1600, 1250, 2000, 800)
BASES = (0, 100, 333, 640, 1000, -1)


def expect(basis, vw, vh, vert, font, s):
    ctx = M.Ctx(font100=font, root100=1600, lh100=1000, rlh100=1000, vw=vw, vh=vh, vertical=bool(vert))
    for typ, code in ((M.NUMBER, 0), (M.LENGTH, 1), (M.ANGLE, 2)):
        try:
            r = M.parse(s, ctx, typ)
        except M.Refused:
            continue
        if M.has_pct(r) and basis < 0:
            return -1, 0
        try:
            return code, M.used(M.evaluate(r, basis)[0])
        except M.Refused:
            return -1, 0
    return -1, 0


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def rows(count, seed=1180):
    rng = random.Random(seed)
    seen, out = set(), []
    while len(out) < count:
        typ = rng.choice(["length", "number", "angle"])
        s = X.top(rng, typ)
        if rng.random() < 0.2:
            s = X.mangle(rng, s)
        if len(s) > 200 or s in seen:
            continue
        seen.add(s)
        basis = rng.choice(BASES) if rng.random() < 0.8 else 0
        vw, vh, vert = rng.choice(CONTEXTS)
        font = rng.choice(FONTS)
        t, v = expect(basis, vw, vh, vert, font, s)
        out.append((basis, vw, vh, vert, font, s, t, v))
    return out


def main():
    count = int(sys.argv[1]) if len(sys.argv) > 1 else 800
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tests", "unit", "userspace",
                        "test_lot118_math.c")
    lines = ["/* Lot 118: GENERATED by scripts/lot118_gen.py (do not edit): CSS math",
             " * expressions through we_math_milli, the values of scripts/lot118_model.py",
             " * (the integer model of webeng_math.inc). */",
             "#include \"framework/unity.h\"",
             "#include \"userspace/webeng.h\"",
             "#include <stdio.h>",
             "#include <string.h>",
             "",
             "typedef struct { short basis, vw, vh, vertical, font100; const char *expr; int type, milli; } row_t;",
             "",
             "static const row_t rows[] = {"]
    for r in rows(count):
        lines.append("    { %d, %d, %d, %d, %d, %s, %d, %d }," % (r[0], r[1], r[2], r[3], r[4], c_string(r[5]), r[6], r[7]))
    lines += ["};",
              "",
              "static void run_rows(int first, int last) {",
              "    int k;",
              "    for (k = first; k < last; k++) {",
              "        const row_t *r = &rows[k];",
              "        we_unit_ctx_t c;",
              "        int type = -9, milli = 0, rc, ok;",
              "        memset(&c, 0, sizeof(c));",
              "        c.font100 = r->font100; c.root100 = 1600; c.vw = r->vw; c.vh = r->vh; c.vertical = r->vertical;",
              "        rc = we_math_milli(r->expr, (int)strlen(r->expr), &c, r->basis, &type, &milli);",
              "        ok = r->type < 0 ? rc == -1 : rc == 0 && type == r->type && milli == r->milli;",
              "        if (!ok) printf(\"  row %d: %s: rc %d type %d milli %d\\n\", k, r->expr, rc, type, milli);",
              "        TEST_ASSERT_TRUE(ok);",
              "    }",
              "}",
              ""]
    n = count
    parts = 4
    for p in range(parts):
        lines += ["static void test_l118_math_part%d(void) { run_rows(%d, %d); }" % (p, p * n // parts, (p + 1) * n // parts)]
    lines += ["",
              "int main(void) {",
              "    unity_init();"]
    for p in range(parts):
        lines.append("    RUN_TEST(test_l118_math_part%d);" % p)
    lines += ["    unity_print_results();",
              "    unity_cleanup();",
              "    return unity_stats.tests_failed == 0 ? 0 : 1;",
              "}"]
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", path, count, "rows")


if __name__ == "__main__":
    main()
