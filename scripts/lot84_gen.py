#!/usr/bin/env python3
"""Lot 84 test generator.

Expectations come from this file, not from userspace/webeng.c. The placement
rules match the CSS subset the engine implements:

* masonry-auto-flow definite-first places items with an explicit line start
  on the grid axis first (column start for masonry rows, row start for
  masonry columns), then the others. pack picks the shortest window; next
  continues a cursor and wraps. The cursor survives the two passes.
* a percentage or min()/max()/clamp()/calc() border width resolves against
  the containing block width with integer arithmetic, then clamps to 0..8
  (the existing per-side paint cap).
* masonry rows plus grid-auto-flow:column still pack into the declared
  columns. The used height is the tallest column, not one column per item.
* an absolute child's percentage inset resolves against the masonry grid's
  padding box (width for left/right, height for top/bottom).

Run: python3 scripts/lot84_gen.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "tests", "unit", "userspace")


def ev(e, basis):
    k = e[0]
    if k == "px":
        return e[1]
    if k == "pct":
        return basis * e[1] // 100
    if k == "min":
        return min(ev(e[1], basis), ev(e[2], basis))
    if k == "max":
        return max(ev(e[1], basis), ev(e[2], basis))
    if k == "add":
        return ev(e[1], basis) + ev(e[2], basis)
    if k == "sub":
        return ev(e[1], basis) - ev(e[2], basis)
    if k == "clamp":
        a, b, c = ev(e[1], basis), ev(e[2], basis), ev(e[3], basis)
        v = b if b < c else c
        if v < a:
            v = a
        return v
    raise AssertionError(e)


def css_of(e):
    k = e[0]
    if k == "px":
        return "%dpx" % e[1]
    if k == "pct":
        return "%d%%" % e[1]
    if k == "min":
        return "min(%s, %s)" % (css_of(e[1]), css_of(e[2]))
    if k == "max":
        return "max(%s, %s)" % (css_of(e[1]), css_of(e[2]))
    if k == "add":
        return "calc(%s + %s)" % (css_of(e[1]), css_of(e[2]))
    if k == "sub":
        return "calc(%s - %s)" % (css_of(e[1]), css_of(e[2]))
    if k == "clamp":
        return "clamp(%s, %s, %s)" % (css_of(e[1]), css_of(e[2]), css_of(e[3]))
    raise AssertionError(e)


def border_px(e, basis):
    v = ev(e, basis)
    if v < 0:
        v = 0
    if v > 64:
        v = 64
    return v


def place(items, ntracks, gap, nxt, definite):
    """items: dicts with size, span, start (1-based, 0 = auto)."""
    running = [0] * ntracks
    cursor = 0
    order = list(range(len(items)))
    if definite:
        order = [i for i in order if items[i]["start"]] + [i for i in order if not items[i]["start"]]
    pos = [None] * len(items)
    for i in order:
        it = items[i]
        span = it["span"] if it["span"] < ntracks else ntracks
        if span < 1:
            span = 1
        start = it["start"]
        if start and start - 1 + span <= ntracks:
            best = start - 1
            top = max(running[best:best + span])
        elif nxt:
            best = cursor if cursor + span <= ntracks else 0
            top = max(running[best:best + span])
        else:
            best, top = 0, None
            for c in range(ntracks - span + 1):
                edge = max(running[c:c + span])
                if top is None or edge < top:
                    top, best = edge, c
            if top is None:
                top = 0
        cursor = 0 if best + span >= ntracks else best + span
        pos[i] = (best, top, span)
        for j in range(best, best + span):
            running[j] = top + it["size"] + gap
    return pos


def emit_header(title):
    return "/* Lot 84: %s (generated by scripts/lot84_gen.py; expectations from that model). */\n" % title


def write(name, body):
    path = os.path.join(OUT, name)
    with open(path, "w") as fh:
        fh.write(body)
    lines = body.count("\n")
    print("%s %d lines" % (name, lines))
    return lines


def gen_defrow():
    """Masonry rows: explicit column starts go first when definite-first is set."""
    heights = [
        [20, 5, 5, 5],
        [8, 12, 3, 6, 9],
        [4, 10, 6, 2],
        [30, 2, 2, 2, 2, 2, 2],
        [7, 7, 7, 1],
        [15, 4, 9, 4, 11],
    ]
    cols_set = [(30, 30, 30), (40, 20), (20, 20, 20, 20)]
    gaps = [(0, 0), (5, 3), (8, 0)]
    flows = [(0, 0), (1, 0), (0, 1), (1, 1)]  # next, definite
    lines = [emit_header("definite-first masonry rows")]
    names = []
    n = 0
    for cols in cols_set:
        for hs in heights:
            if len(hs) < 3:
                continue
            for cg, rg in gaps:
                for nxt, definite in flows:
                    # give the 0th and 2nd items explicit columns that differ
                    starts = [0] * len(hs)
                    starts[0] = 2 if len(cols) >= 2 else 1
                    starts[2] = 1
                    items = []
                    for i, h in enumerate(hs):
                        items.append({"size": h, "span": 1, "start": starts[i]})
                    pos = place(items, len(cols), rg, nxt, definite)
                    widths = list(cols)
                    xs = []
                    x = 0
                    for c, w in enumerate(widths):
                        xs.append(x)
                        x += w + (cg if c + 1 < len(widths) else 0)
                    bottom = 0
                    boxes = []
                    for i, (best, top, span) in enumerate(pos):
                        boxes.append((xs[best], top, widths[best], hs[i]))
                        if top + hs[i] > bottom:
                            bottom = top + hs[i]
                    flow = []
                    if definite:
                        flow.append("definite-first")
                    flow.append("next" if nxt else "pack")
                    colcss = " ".join("%dpx" % c for c in cols)
                    divs = []
                    for i, h in enumerate(hs):
                        extra = ""
                        if starts[i]:
                            extra = ";grid-column:%d" % starts[i]
                        divs.append("<div id=c%d style='height:%dpx%s'></div>" % (i, h, extra))
                    html = ("<body style='margin:0'><div id=g style='display:grid;width:%dpx;"
                            "column-gap:%dpx;row-gap:%dpx;grid-template-columns:%s;"
                            "grid-template-rows:masonry;masonry-auto-flow:%s'>%s</div></body>"
                            % (x if x > 40 else 200, cg, rg, colcss, " ".join(flow), "".join(divs)))
                    fn = "test_l84_drow_%d" % n
                    names.append(fn)
                    n += 1
                    bits = ["static void %s(void) {" % fn,
                            '    lot52_render("%s", 480);' % html]
                    for i, (xx, yy, ww, hh) in enumerate(boxes):
                        bits.append('    TEST_ASSERT_EQUAL(%d, lot52_node("c%d")->x);' % (xx, i))
                        bits.append('    TEST_ASSERT_EQUAL(%d, lot52_node("c%d")->y);' % (yy, i))
                        bits.append('    TEST_ASSERT_EQUAL(%d, lot52_node("c%d")->w);' % (ww, i))
                        bits.append('    TEST_ASSERT_EQUAL(%d, lot52_node("c%d")->h);' % (hh, i))
                    bits.append('    TEST_ASSERT_EQUAL(%d, lot52_node("g")->h);' % bottom)
                    bits.append('    TEST_ASSERT_EQUAL(1, lot52_node("g")->masonry);')
                    bits.append('    TEST_ASSERT_EQUAL(%d, lot52_node("g")->masonry_next);' % nxt)
                    bits.append('    TEST_ASSERT_EQUAL(%d, lot52_node("g")->masonry_definite);' % definite)
                    bits.append('    TEST_ASSERT_EQUAL(0, g_doc.ndiag);')
                    bits.append("}")
                    bits.append("")
                    lines.append("\n".join(bits))
    lines.append("static void lot84_drow_run(void) {")
    for fn in names:
        lines.append("    RUN_TEST(%s);" % fn)
    lines.append("}")
    lines.append("")
    return write("webeng_lot84_drow.inc", "\n".join(lines))


def gen_defcol():
    rows_set = [(None, None), (None, None, None), (6, 6, 6, 6), (5, 5, 5)]
    widths = [
        [30, 20, 10],
        [40, 10, 25, 15],
        [20, 20, 20, 9],
        [12, 28, 8, 16, 6],
        [50, 5, 5, 30, 8],
    ]
    gaps = [(0, 0), (4, 2), (3, 3)]
    flows = [(0, 0), (1, 0), (0, 1), (1, 1)]
    lines = [emit_header("definite-first masonry columns")]
    names = []
    n = 0
    for rows in rows_set:
        for ws in widths:
            for cg, rg in gaps:
                for nxt, definite in flows:
                    starts = [0] * len(ws)
                    starts[0] = 2 if len(rows) >= 2 else 1
                    if len(ws) > 2:
                        starts[2] = 1
                    items = []
                    for i, w in enumerate(ws):
                        items.append({"size": w, "span": 1, "start": starts[i], "h": 4 + (i % 3)})
                    pos = place(items, len(rows), cg, nxt, definite)
                    fixed = [r is not None for r in rows]
                    heights = [r if r is not None else 0 for r in rows]
                    for i, (best, left, span) in enumerate(pos):
                        h = items[i]["h"]
                        if span == 1 and not fixed[best] and h > heights[best]:
                            heights[best] = h
                    ys = []
                    y = 0
                    for r, h in enumerate(heights):
                        ys.append(y)
                        y += h + (rg if r + 1 < len(rows) else 0)
                    flow = []
                    if definite:
                        flow.append("definite-first")
                    flow.append("next" if nxt else "pack")
                    rowcss = " ".join("auto" if r is None else "%dpx" % r for r in rows)
                    divs = []
                    for i, w in enumerate(ws):
                        extra = ""
                        if starts[i]:
                            extra = ";grid-row:%d" % starts[i]
                        divs.append("<div id=c%d style='width:%dpx;height:%dpx%s'></div>" % (i, w, items[i]["h"], extra))
                    html = ("<body style='margin:0'><div id=g style='display:grid;width:200px;"
                            "column-gap:%dpx;row-gap:%dpx;grid-template-columns:masonry;"
                            "masonry-auto-flow:%s;grid-template-rows:%s'>%s</div></body>"
                            % (cg, rg, " ".join(flow), rowcss, "".join(divs)))
                    fn = "test_l84_dcol_%d" % n
                    names.append(fn)
                    n += 1
                    bits = ["static void %s(void) {" % fn,
                            '    lot52_render("%s", 480);' % html]
                    for i, (best, left, span) in enumerate(pos):
                        bits.append('    TEST_ASSERT_EQUAL(%d, lot52_node("c%d")->x);' % (left, i))
                        bits.append('    TEST_ASSERT_EQUAL(%d, lot52_node("c%d")->y);' % (ys[best], i))
                        bits.append('    TEST_ASSERT_EQUAL(%d, lot52_node("c%d")->w);' % (ws[i], i))
                        bits.append('    TEST_ASSERT_EQUAL(%d, lot52_node("c%d")->h);' % (items[i]["h"], i))
                    bits.append('    TEST_ASSERT_EQUAL(%d, lot52_node("g")->h);' % y)
                    bits.append('    TEST_ASSERT_EQUAL(2, lot52_node("g")->masonry);')
                    bits.append('    TEST_ASSERT_EQUAL(%d, lot52_node("g")->masonry_next);' % nxt)
                    bits.append('    TEST_ASSERT_EQUAL(%d, lot52_node("g")->masonry_definite);' % definite)
                    bits.append('    TEST_ASSERT_EQUAL(0, g_doc.ndiag);')
                    bits.append("}")
                    bits.append("")
                    lines.append("\n".join(bits))
    lines.append("static void lot84_dcol_run(void) {")
    for fn in names:
        lines.append("    RUN_TEST(%s);" % fn)
    lines.append("}")
    lines.append("")
    return write("webeng_lot84_dcol.inc", "\n".join(lines))


def gen_border():
    exprs = []
    for pct in (1, 2, 3, 4, 5, 8, 10, 20, 40, 50):
        for px in (0, 1, 2, 3, 4, 6, 8, 12):
            exprs.append(("min", ("pct", pct), ("px", px)))
            exprs.append(("max", ("pct", pct), ("px", px)))
    for pct in (1, 2, 5, 10, 25):
        for a in (0, 1, 2):
            for c in (3, 4, 6, 8):
                exprs.append(("clamp", ("px", a), ("pct", pct), ("px", c)))
    for pct in (1, 2, 5, 10):
        for px in (0, 1, 2, 4):
            exprs.append(("add", ("pct", pct), ("px", px)))
            exprs.append(("sub", ("pct", pct), ("px", px)))
    bases = (100, 160, 200, 240)
    # side patterns: left, top, left+right, four values
    sides = ("left", "top", "x", "box")
    lines = [emit_header("percentage math in border widths, clamped to 0..64")]
    names = []
    n = 0
    for e in exprs:
        for basis in bases:
            for side in sides:
                b = border_px(e, basis)
                # skip a deterministic slice so the file stays large but bounded
                if (n + basis) % 2 != 0:
                    n += 1
                    continue
                css = css_of(e)
                if side == "left":
                    decl = "border-left-width:%s;border-style:solid" % css
                    bx, by, bw = b, 0, basis - b
                elif side == "top":
                    decl = "border-top-width:%s;border-style:solid" % css
                    bx, by, bw = 0, b, basis
                elif side == "x":
                    decl = "border-left-width:%s;border-right-width:%s;border-style:solid" % (css, css)
                    bx, by, bw = b, 0, basis - 2 * b
                    # The engine never lays out a content box narrower than one glyph.
                    if bw < 8:
                        bw = 8
                else:
                    decl = "border-width:%s;border-style:solid" % css
                    bx, by, bw = b, b, basis - 2 * b
                    if bw < 8:
                        bw = 8
                html = ("<body style='margin:0'><div style='width:%dpx'><div id=a style='%s'>"
                        "<div id=b style='height:2px'></div></div></div></body>" % (basis, decl))
                fn = "test_l84_bor_%d" % len(names)
                names.append(fn)
                bits = ["static void %s(void) {" % fn,
                        '    lot52_render("%s", 480);' % html,
                        '    TEST_ASSERT_EQUAL(%d, lot52_node("b")->x);' % bx,
                        '    TEST_ASSERT_EQUAL(%d, lot52_node("b")->y);' % by,
                        '    TEST_ASSERT_EQUAL(%d, lot52_node("b")->w);' % bw,
                        '    TEST_ASSERT_EQUAL(2, lot52_node("b")->h);',
                        '    TEST_ASSERT_EQUAL(0, g_doc.ndiag);',
                        "}", ""]
                lines.append("\n".join(bits))
                n += 1
    # grid area is the percentage basis, not the grid box
    for col, pct, px in ((50, 10, 3), (80, 20, 6), (100, 5, 8), (40, 50, 4), (120, 2, 1), (60, 8, 12)):
        e = ("min", ("pct", pct), ("px", px))
        b = border_px(e, col)
        css = css_of(e)
        html = ("<body style='margin:0'><div style='display:grid;width:400px;grid-template-columns:%dpx 20px'>"
                "<div id=a style='border-left-width:%s;border-style:solid'><div id=b style='height:2px'></div></div>"
                "<div id=c style='height:2px'></div></div></body>" % (col, css))
        fn = "test_l84_borg_%d" % len(names)
        names.append(fn)
        lines.append("\n".join([
            "static void %s(void) {" % fn,
            '    lot52_render("%s", 480);' % html,
            '    TEST_ASSERT_EQUAL(%d, lot52_node("b")->x);' % b,
            '    TEST_ASSERT_EQUAL(%d, lot52_node("b")->w);' % (col - b),
            '    TEST_ASSERT_EQUAL(%d, lot52_node("c")->x);' % col,
            '    TEST_ASSERT_EQUAL(0, g_doc.ndiag);',
            "}", ""]))
    lines.append("static void lot84_bor_run(void) {")
    for fn in names:
        lines.append("    RUN_TEST(%s);" % fn)
    lines.append("}")
    lines.append("")
    return write("webeng_lot84_border.inc", "\n".join(lines))


def gen_height():
    """Packed height of masonry rows, including grid-auto-flow:column."""
    sets = [
        [10, 10, 10, 10],
        [20, 5, 5, 5],
        [8, 12, 3, 6, 9],
        [4, 10, 6, 2],
        [15, 4, 9, 4],
        [7, 1, 7, 1, 7],
        [30, 2, 2, 2],
        [6, 6, 6, 18],
    ]
    cols_set = [(30, 30), (30, 30, 30), (40, 20)]
    gaps = [0, 3, 5]
    modes = ["pack", "next", "definite-first next"]
    lines = [emit_header("masonry row intrinsic height, including column auto-flow")]
    names = []
    for cols in cols_set:
        for hs in sets:
            for gap in gaps:
                for mode in modes:
                    for flow_col in (0, 1):
                        nxt = 1 if "next" in mode else 0
                        definite = 1 if "definite-first" in mode else 0
                        starts = [0] * len(hs)
                        if definite and len(hs) >= 3 and len(cols) >= 2:
                            starts[0] = len(cols)
                            starts[2] = 1
                        items = [{"size": h, "span": 1, "start": starts[i]} for i, h in enumerate(hs)]
                        pos = place(items, len(cols), gap, nxt, definite)
                        widths = list(cols)
                        xs = []
                        x = 0
                        cg = 0
                        for c, w in enumerate(widths):
                            xs.append(x)
                            x += w + (cg if c + 1 < len(widths) else 0)
                        bottom = 0
                        boxes = []
                        for i, (best, top, span) in enumerate(pos):
                            boxes.append((xs[best], top, widths[best], hs[i]))
                            if top + hs[i] > bottom:
                                bottom = top + hs[i]
                        colcss = " ".join("%dpx" % c for c in cols)
                        divs = []
                        for i, h in enumerate(hs):
                            extra = (";grid-column:%d" % starts[i]) if starts[i] else ""
                            divs.append("<div id=c%d style='height:%dpx%s'></div>" % (i, h, extra))
                        flow = "grid-auto-flow:column;" if flow_col else ""
                        kind = "min-content" if (len(names) % 2 == 0) else "max-content"
                        html = ("<body style='margin:0'><div id=g style='display:grid;width:%dpx;%s"
                                "row-gap:%dpx;grid-template-columns:%s;grid-template-rows:masonry;"
                                "masonry-auto-flow:%s;height:%s'>%s</div></body>"
                                % (max(x, 40), flow, gap, colcss, mode, kind, "".join(divs)))
                        fn = "test_l84_hgt_%d" % len(names)
                        names.append(fn)
                        bits = ["static void %s(void) {" % fn,
                                '    lot52_render("%s", 480);' % html]
                        for i, (xx, yy, ww, hh) in enumerate(boxes):
                            bits.append('    TEST_ASSERT_EQUAL(%d, lot52_node("c%d")->x);' % (xx, i))
                            bits.append('    TEST_ASSERT_EQUAL(%d, lot52_node("c%d")->y);' % (yy, i))
                            bits.append('    TEST_ASSERT_EQUAL(%d, lot52_node("c%d")->h);' % (hh, i))
                        bits.append('    TEST_ASSERT_EQUAL(%d, lot52_node("g")->h);' % bottom)
                        bits.append('    TEST_ASSERT_EQUAL(%d, lot52_node("g")->height_intrinsic);' % (1 if kind == "min-content" else 2))
                        bits.append('    TEST_ASSERT_EQUAL(%d, lot52_node("g")->masonry_definite);' % definite)
                        bits.append('    TEST_ASSERT_EQUAL(0, g_doc.ndiag);')
                        bits.append("}")
                        bits.append("")
                        lines.append("\n".join(bits))
    lines.append("static void lot84_hgt_run(void) {")
    for fn in names:
        lines.append("    RUN_TEST(%s);" % fn)
    lines.append("}")
    lines.append("")
    return write("webeng_lot84_height.inc", "\n".join(lines))


def gen_inset():
    exprs = []
    for pct in (1, 2, 5, 10, 20, 25, 40):
        for px in (2, 4, 8, 12, 30):
            exprs.append(("min", ("pct", pct), ("px", px)))
            exprs.append(("max", ("pct", pct), ("px", px)))
    for pct in (5, 10, 20):
        exprs.append(("clamp", ("px", 1), ("pct", pct), ("px", 16)))
        exprs.append(("add", ("pct", pct), ("px", 2)))
        exprs.append(("sub", ("pct", pct), ("px", 1)))
    boxes = [(200, 80), (160, 40), (120, 100), (240, 60), (100, 50)]
    lines = [emit_header("percentage math in absolute insets of masonry items")]
    names = []
    n = 0
    for e in exprs:
        for gw, gh in boxes:
            for axis in ("left", "top", "right", "bottom"):
                if n % 3:
                    n += 1
                    continue
                basis = gw if axis in ("left", "right") else gh
                v = ev(e, basis)
                if v < -2000:
                    v = -2000
                if v > 2000:
                    v = 2000
                css = css_of(e)
                # a 10px in-flow item keeps the grid masonry; the absolute is taken out
                html = ("<body style='margin:0'><div id=g style='position:relative;display:grid;"
                        "width:%dpx;height:%dpx;grid-template-columns:50px 50px;grid-template-rows:masonry'>"
                        "<div id=a style='position:absolute;%s:%s;width:8px;height:8px'></div>"
                        "<div id=c style='height:10px'></div></div></body>"
                        % (gw, gh, axis, css))
                if axis == "left":
                    ax, ay = v, 0
                elif axis == "top":
                    ax, ay = 0, v
                elif axis == "right":
                    ax, ay = gw - v - 8, 0
                else:
                    ax, ay = 0, gh - v - 8
                fn = "test_l84_ins_%d" % len(names)
                names.append(fn)
                lines.append("\n".join([
                    "static void %s(void) {" % fn,
                    '    lot52_render("%s", 480);' % html,
                    '    TEST_ASSERT_EQUAL(%d, lot52_node("a")->x);' % ax,
                    '    TEST_ASSERT_EQUAL(%d, lot52_node("a")->y);' % ay,
                    '    TEST_ASSERT_EQUAL(8, lot52_node("a")->w);',
                    '    TEST_ASSERT_EQUAL(8, lot52_node("a")->h);',
                    '    TEST_ASSERT_EQUAL(0, lot52_node("c")->x);',
                    '    TEST_ASSERT_EQUAL(0, lot52_node("c")->y);',
                    '    TEST_ASSERT_EQUAL(10, lot52_node("c")->h);',
                    '    TEST_ASSERT_EQUAL(1, lot52_node("g")->masonry);',
                    '    TEST_ASSERT_EQUAL(0, g_doc.ndiag);',
                    "}", ""]))
                n += 1
    lines.append("static void lot84_ins_run(void) {")
    for fn in names:
        lines.append("    RUN_TEST(%s);" % fn)
    lines.append("}")
    lines.append("")
    return write("webeng_lot84_inset.inc", "\n".join(lines))


def main():
    total = 0
    total += gen_defrow()
    total += gen_defcol()
    total += gen_border()
    total += gen_height()
    total += gen_inset()
    print("total lines %d" % total)


if __name__ == "__main__":
    main()
