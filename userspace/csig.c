#define CAP 136
typedef struct { uint32_t l[CAP]; bigint_t b; } num_t;
static num_t P, G, Q;
static int g_ready;

static void num(num_t* n) { bigint_init(&n->b, n->l, CAP); }
static void load(num_t* n, const uint8_t* be, int len) { num(n); bigint_from_be(&n->b, be, (uint16_t)len); }
static void setup(void) {
    if (g_ready) return;
    load(&P, k_p, 128); load(&G, k_g, 128); load(&Q, k_q, 20);
    g_ready = 1;
}
static int is_zero(const num_t* n) { int i; for (i = 0; i < n->b.length; i++) if (n->b.limbs[i]) return 0; return 1; }
static void hash_mod_q(const uint8_t* a, int alen, const uint8_t* m, int mlen, num_t* out) {
    sha256_ctx_t h; uint8_t d[32]; num_t t;
    sha256_init(&h); sha256_update(&h, a, (uint32_t)alen); sha256_update(&h, m, (uint32_t)mlen); sha256_final(&h, d);
    load(&t, d, 32); num(out); bigint_mod_reduce(&out->b, &t.b, &Q.b);
}
/* Montgomery arithmetic (CIOS), ~60x faster than the generic shift-add
 * reduction; only 32x32->64 products, no division. One context per
 * modulus: p of the 1024-bit signature group (32 limbs) and, since lot 9,
 * p of the 2048-bit proof group (64 limbs). */
#define ML 64
typedef struct { int nl, ready; uint32_t pl[ML], pinv, r2[ML], one[ML]; } mont_t;
static mont_t g_m1024, g_m2048;
static int geq(const mont_t* m, const uint32_t* a) { int i; for (i = m->nl - 1; i >= 0; i--) { if (a[i] != m->pl[i]) return a[i] > m->pl[i]; } return 1; }
static void subp(const mont_t* m, uint32_t* a) { uint64_t br = 0; int i; for (i = 0; i < m->nl; i++) { uint64_t d = (uint64_t)a[i] - m->pl[i] - br; a[i] = (uint32_t)d; br = (d >> 63) & 1U; } }
static void mont_mul(const mont_t* M, uint32_t* out, const uint32_t* a, const uint32_t* b) {
    uint32_t t[ML + 2];
    int i, j, nl = M->nl;
    for (i = 0; i < nl + 2; i++) t[i] = 0;
    for (i = 0; i < nl; i++) {
        uint64_t c = 0, m;
        for (j = 0; j < nl; j++) { c += (uint64_t)t[j] + (uint64_t)a[j] * b[i]; t[j] = (uint32_t)c; c >>= 32; }
        c += t[nl]; t[nl] = (uint32_t)c; t[nl + 1] = (uint32_t)(c >> 32);
        m = (uint32_t)(t[0] * M->pinv);
        c = (uint64_t)t[0] + m * M->pl[0]; c >>= 32;
        for (j = 1; j < nl; j++) { c += (uint64_t)t[j] + m * M->pl[j]; t[j - 1] = (uint32_t)c; c >>= 32; }
        c += t[nl]; t[nl - 1] = (uint32_t)c; c >>= 32;
        t[nl] = t[nl + 1] + (uint32_t)c; t[nl + 1] = 0;
    }
    if (t[nl] || geq(M, t)) subp(M, t);
    for (i = 0; i < nl; i++) out[i] = t[i];
}
static void to_limbs(const mont_t* M, const num_t* n, uint32_t* l) { int i; for (i = 0; i < M->nl; i++) l[i] = i < n->b.length ? n->b.limbs[i] : 0; }
static void from_limbs(const mont_t* M, num_t* n, const uint32_t* l) {
    uint8_t be[4 * ML]; int i, nl = M->nl;
    for (i = 0; i < nl; i++) { uint32_t v = l[nl - 1 - i]; be[4 * i] = (uint8_t)(v >> 24); be[4 * i + 1] = (uint8_t)(v >> 16); be[4 * i + 2] = (uint8_t)(v >> 8); be[4 * i + 3] = (uint8_t)v; }
    load(n, be, 4 * nl);
}
static void mont_setup(mont_t* M, const num_t* P_, int nl) {
    uint32_t inv = 1, x[ML];
    int i, bits = 32 * nl;
    if (M->ready) return;
    M->nl = nl;
    to_limbs(M, P_, M->pl);
    for (i = 0; i < 5; i++) inv *= 2U - M->pl[0] * inv;   /* p^-1 mod 2^32 */
    M->pinv = (uint32_t)(0U - inv);
    /* R mod p = 2^bits mod p, then R^2 by more modular doublings */
    for (i = 0; i < nl; i++) x[i] = 0;
    x[0] = 1;
    for (i = 0; i < 2 * bits; i++) {
        uint32_t carry = 0; int j;
        for (j = 0; j < nl; j++) { uint32_t v = x[j]; x[j] = (v << 1) | carry; carry = v >> 31; }
        if (carry || geq(M, x)) subp(M, x);
        if (i == bits - 1) for (j = 0; j < nl; j++) M->one[j] = x[j];
    }
    for (i = 0; i < nl; i++) M->r2[i] = x[i];
    M->ready = 1;
}
static int modexp_m(const mont_t* M, const num_t* Pm, num_t* out, const num_t* base, const num_t* e) {
    uint32_t b[ML], acc[ML], one[ML];
    int i, bits;
    num_t red;
    num(&red);
    if (bigint_mod_reduce(&red.b, &base->b, &Pm->b) != 0) return -1;
    to_limbs(M, &red, b);
    mont_mul(M, b, b, M->r2);                 /* to Montgomery form */
    for (i = 0; i < M->nl; i++) acc[i] = M->one[i];
    bits = e->b.length * 32;
    for (i = bits - 1; i >= 0; i--) {
        mont_mul(M, acc, acc, acc);
        if ((e->b.limbs[i / 32] >> (i % 32)) & 1U) mont_mul(M, acc, acc, b);
    }
    for (i = 0; i < M->nl; i++) one[i] = 0;
    one[0] = 1;
    mont_mul(M, acc, acc, one);               /* out of Montgomery form */
    from_limbs(M, out, acc);
    return 0;
}
static int modexp(num_t* out, const num_t* base, const num_t* e) {
    mont_setup(&g_m1024, &P, 32);
    return modexp_m(&g_m1024, &P, out, base, e);
}

int csig_keypair(const uint8_t seed[32], uint8_t sk[CSIG_SK], uint8_t pk[CSIG_PK]) {
    num_t x, y;
    setup();
    hash_mod_q((const uint8_t*)"mohhdy-collab-key", 17, seed, 32, &x);
    if (is_zero(&x)) return -1;
    if (modexp(&y, &G, &x) != 0) return -1;
    bigint_to_be(&x.b, sk, CSIG_SK); bigint_to_be(&y.b, pk, CSIG_PK);
    return 0;
}

int csig_sign(const uint8_t sk[CSIG_SK], const uint8_t* msg, int len, uint8_t sig[CSIG_SIG]) {
    num_t x, k, r, e, xe, s, tmp;
    uint8_t rb[128];
    setup();
    load(&x, sk, CSIG_SK);
    hash_mod_q(sk, CSIG_SK, msg, len, &k);
    if (is_zero(&k)) return -1;
    if (modexp(&r, &G, &k) != 0) return -1;
    bigint_to_be(&r.b, rb, 128);
    hash_mod_q(rb, 128, msg, len, &e);
    num(&xe); num(&tmp); num(&s);
    if (bigint_mod_multiply(&xe.b, &x.b, &e.b, &Q.b, &tmp.b) != 0) return -1;
    /* s = k - xe mod q = k + (q - xe) mod q */
    num(&tmp);
    if (is_zero(&xe)) { bigint_mod_reduce(&s.b, &k.b, &Q.b); }
    else { bigint_subtract(&tmp.b, &Q.b, &xe.b); bigint_mod_add(&s.b, &k.b, &tmp.b, &Q.b); }
    bigint_to_be(&e.b, sig, 20); bigint_to_be(&s.b, sig + 20, 20);
    return 0;
}

int csig_pk_valid(const uint8_t pk[CSIG_PK]) {
    num_t y, t, one;
    uint8_t ob = 1;
    setup();
    load(&y, pk, CSIG_PK); load(&one, &ob, 1);
    if (bigint_compare(&y.b, &one.b) <= 0 || bigint_compare(&y.b, &P.b) >= 0) return 0;
    if (modexp(&t, &y, &Q) != 0) return 0;
    return bigint_compare(&t.b, &one.b) == 0;
}

int csig_verify(const uint8_t pk[CSIG_PK], const uint8_t* msg, int len, const uint8_t sig[CSIG_SIG]) {
    num_t y, e, s, a, b, r, tmp, e2;
    uint8_t rb[128];
    setup();
    load(&y, pk, CSIG_PK); load(&e, sig, 20); load(&s, sig + 20, 20);
    if (bigint_compare(&e.b, &Q.b) >= 0 || bigint_compare(&s.b, &Q.b) >= 0) return 0;
    if (bigint_compare(&y.b, &P.b) >= 0 || is_zero(&y)) return 0;
    if (modexp(&a, &G, &s) != 0 || modexp(&b, &y, &e) != 0) return 0;
    num(&r); num(&tmp);
    if (bigint_mod_multiply(&r.b, &a.b, &b.b, &P.b, &tmp.b) != 0) return 0;
    bigint_to_be(&r.b, rb, 128);
    hash_mod_q(rb, 128, msg, len, &e2);
    return bigint_compare(&e2.b, &e.b) == 0;
}

/* ---------------------------------------------------------------- lot 9
 * US-103: Schnorr zero-knowledge proof of knowledge of x with y = g^x in a
 * 2048-bit group with a 256-bit prime-order subgroup (generated by
 * scripts/gen_zk_group.py, about 112-bit security like RFC 5114 2.3).
 * Non-interactive by Fiat-Shamir:
 *   k = H512("zk2-k" || x || msg) mod q, t = g^k,
 *   c = H512("zk2-c" || g || y || t || msg) mod q, s = k + c*x mod q,
 *   verify: 1 < y,t < p, y^q = 1, s < q, g^s = t * y^c mod p.
 * Deterministic nonce, not constant time. */
static num_t ZP, ZG, ZQ;
static int g_zready;
static void zsetup(void) {
    if (g_zready) return;
    load(&ZP, k_zp, 256); load(&ZG, k_zg, 256); load(&ZQ, k_zq, 32);
    mont_setup(&g_m2048, &ZP, 64);
    g_zready = 1;
}
static int zexp(num_t* out, const num_t* base, const num_t* e) { zsetup(); return modexp_m(&g_m2048, &ZP, out, base, e); }
/* 512-bit hash of the parts, reduced mod q (bias below 2^-256) */
static void zhash(const char* tag, const uint8_t* a, int alen, const uint8_t* b, int blen,
                  const uint8_t* c, int clen, const uint8_t* m, int mlen, num_t* out) {
    uint8_t d[64];
    num_t t;
    int half;
    for (half = 0; half < 2; half++) {
        sha256_ctx_t h;
        uint8_t ctr = (uint8_t)half;
        int tl = 0;
        while (tag[tl]) tl++;
        sha256_init(&h);
        sha256_update(&h, &ctr, 1);
        sha256_update(&h, (const uint8_t*)tag, (uint32_t)tl);
        if (alen) sha256_update(&h, a, (uint32_t)alen);
        if (blen) sha256_update(&h, b, (uint32_t)blen);
        if (clen) sha256_update(&h, c, (uint32_t)clen);
        if (mlen) sha256_update(&h, m, (uint32_t)mlen);
        sha256_final(&h, d + 32 * half);
    }
    load(&t, d, 64);
    num(out);
    bigint_mod_reduce(&out->b, &t.b, &ZQ.b);
}
/* a*b mod p through Montgomery: (a*b/R) * R^2 / R */
static void zmulmod(num_t* out, const num_t* a, const num_t* b) {
    uint32_t x[ML], y[ML];
    to_limbs(&g_m2048, a, x); to_limbs(&g_m2048, b, y);
    mont_mul(&g_m2048, x, x, y);
    mont_mul(&g_m2048, x, x, g_m2048.r2);
    from_limbs(&g_m2048, out, x);
}

int csig_zk_group_check(void) {
    num_t pm1, one, r, two, t;
    uint8_t ob = 1, tb = 2;
    zsetup();
    load(&one, &ob, 1); load(&two, &tb, 1);
    num(&pm1); num(&r);
    if (bigint_subtract(&pm1.b, &ZP.b, &one.b) != 0) return 0;
    if (bigint_mod_reduce(&r.b, &pm1.b, &ZQ.b) != 0 || !is_zero(&r)) return 0;       /* q | p-1 */
    if (zexp(&t, &ZG, &ZQ) != 0 || bigint_compare(&t.b, &one.b) != 0) return 0;     /* g^q = 1 */
    if (bigint_compare(&ZG.b, &one.b) <= 0) return 0;                                /* g != 1 */
    if (zexp(&t, &two, &pm1) != 0 || bigint_compare(&t.b, &one.b) != 0) return 0;   /* Fermat on p */
    return 1;
}

int csig_zk_keypair(const uint8_t seed[32], uint8_t sk[CSIG_ZK_SK], uint8_t pk[CSIG_ZK_PK]) {
    num_t x, y;
    zsetup();
    zhash("zk2-key", seed, 32, 0, 0, 0, 0, 0, 0, &x);
    if (is_zero(&x)) return -1;
    if (zexp(&y, &ZG, &x) != 0) return -1;
    bigint_to_be(&x.b, sk, CSIG_ZK_SK); bigint_to_be(&y.b, pk, CSIG_ZK_PK);
    return 0;
}

int csig_zk_prove(const uint8_t sk[CSIG_ZK_SK], const uint8_t* msg, int len, uint8_t proof[CSIG_ZK_PROOF]) {
    num_t x, y, k, t, c, cx, s, tmp;
    uint8_t yb[256], tb[256], gb[256];
    zsetup();
    load(&x, sk, CSIG_ZK_SK);
    if (is_zero(&x) || bigint_compare(&x.b, &ZQ.b) >= 0) return -1;
    if (zexp(&y, &ZG, &x) != 0) return -1;
    zhash("zk2-k", sk, CSIG_ZK_SK, 0, 0, 0, 0, msg, len, &k);
    if (is_zero(&k)) return -1;
    if (zexp(&t, &ZG, &k) != 0) return -1;
    bigint_to_be(&ZG.b, gb, 256); bigint_to_be(&y.b, yb, 256); bigint_to_be(&t.b, tb, 256);
    zhash("zk2-c", gb, 256, yb, 256, tb, 256, msg, len, &c);
    num(&cx); num(&tmp); num(&s);
    if (bigint_mod_multiply(&cx.b, &c.b, &x.b, &ZQ.b, &tmp.b) != 0) return -1;
    if (bigint_mod_add(&s.b, &k.b, &cx.b, &ZQ.b) != 0) return -1;
    bigint_to_be(&t.b, proof, 256); bigint_to_be(&s.b, proof + 256, 32);
    return 0;
}

int csig_zk_verify(const uint8_t pk[CSIG_ZK_PK], const uint8_t* msg, int len, const uint8_t proof[CSIG_ZK_PROOF]) {
    num_t y, t, s, c, one, a, b, r, chk;
    uint8_t ob = 1, gb[256];
    zsetup();
    load(&y, pk, CSIG_ZK_PK); load(&t, proof, 256); load(&s, proof + 256, 32); load(&one, &ob, 1);
    if (bigint_compare(&y.b, &one.b) <= 0 || bigint_compare(&y.b, &ZP.b) >= 0) return 0;
    if (bigint_compare(&t.b, &one.b) <= 0 || bigint_compare(&t.b, &ZP.b) >= 0) return 0;
    if (bigint_compare(&s.b, &ZQ.b) >= 0) return 0;
    if (zexp(&chk, &y, &ZQ) != 0 || bigint_compare(&chk.b, &one.b) != 0) return 0;   /* y in the subgroup */
    bigint_to_be(&ZG.b, gb, 256);
    zhash("zk2-c", gb, 256, pk, 256, proof, 256, msg, len, &c);
    if (zexp(&a, &ZG, &s) != 0 || zexp(&b, &y, &c) != 0) return 0;
    zmulmod(&r, &t, &b);
    return bigint_compare(&r.b, &a.b) == 0;
}
